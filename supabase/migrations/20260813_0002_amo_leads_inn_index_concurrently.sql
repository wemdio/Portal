-- Индекс под поиск сделки по ИНН плательщика. Функции `norm_inn` и
-- `amo_custom_field_value`, на которых он построен, заводит миграция
-- 20260812_0004 — она обязана примениться раньше, и по имени файла так и есть.
--
-- Почему индекс нужен: поиск сделки по ИНН идёт по каждому платежу окна. Без
-- индекса это последовательный скан amo_leads с разбором jsonb на каждой
-- строке на каждый запрос дашборда.
--
-- Почему `concurrently` и отдельным файлом: обычный `create index` держит на
-- таблице SHARE-блокировку всё время сборки и блокирует запись. В `amo_leads`
-- непрерывно пишет синк AMO (145k чтений, 23k записей по счётчикам), поэтому
-- обычная сборка упирается в lock_timeout и роняет деплой — это уже случилось
-- на билде 7d0a938a. `concurrently` внутри транзакции Postgres запрещает,
-- отсюда маркер выше; а маркер требует файла без долларовых кавычек, поэтому
-- индекс и уехал из 20260812_0004, где лежат тела функций.
--
-- Почему сначала drop: упавшая сборка `concurrently` оставляет невалидный
-- индекс. Повторный `create index concurrently if not exists` увидел бы имя
-- занятым и молча ничего не сделал — в базе навсегда остался бы индекс,
-- которым планировщик не пользуется. На первом прогоне эта строка no-op, на
-- повторном — уборка за собой.

drop index concurrently if exists public.idx_amo_leads_inn;

create index concurrently if not exists idx_amo_leads_inn
  on public.amo_leads (public.norm_inn(public.amo_custom_field_value(raw, 'ИНН')))
  where public.norm_inn(public.amo_custom_field_value(raw, 'ИНН')) is not null;
