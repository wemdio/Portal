-- Ручной скоринг: флаг «лить ли результат в Instantly».
--
-- Тест-режим: по умолчанию ручной прогон обрабатывается ПОЛНОСТЬЮ (скоринг,
-- скрейп, валидация почт, чистка названий, CSV-выгрузки по бакетам), но в
-- Instantly-кампании НЕ льётся. Это даёт безопасный «тестовый прогон» —
-- перепрогнать файлы и проверить корректность обработки, ничего не отправив.
--
-- Дефолт false (безопасно): routing включается ЯВНО (true) для боевого ручного
-- долива. Раньше routing гейтился только наличием кампаний — после их создания
-- ЛЮБОЙ ручной прогон автоматически уходил в работу; этот флаг возвращает
-- контроль.

ALTER TABLE public.client_manual_score_runs
  ADD COLUMN IF NOT EXISTS route_to_instantly boolean NOT NULL DEFAULT false;

COMMENT ON COLUMN public.client_manual_score_runs.route_to_instantly IS
  'true → готовые контакты (score≥порог) льются в Instantly-кампании по бакетам. false (дефолт) → тест-режим: всё обрабатывается, но в Instantly не уходит.';
