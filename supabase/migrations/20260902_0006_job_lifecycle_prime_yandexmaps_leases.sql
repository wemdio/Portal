-- Выдать аренду задачам Яндекс.Карт, которые уже висят в работе на момент
-- переезда воркера на единый жизненный цикл (companion к 20260902_0001,
-- продолжение 20260902_0003, 20260902_0004 и 20260902_0005;
-- spec: docs/superpowers/specs/2026-09-02-job-lifecycle-design.md).
--
-- Отдельным файлом, а не дописыванием в 0005: применённые миграции трекаются
-- по ИМЕНИ файла, без контрольной суммы (app/scripts/db/ensureDatabase.js).
-- На базе, где 0005 уже применена, дописанные в неё строки просто никогда не
-- выполнятся, и никто об этом не сообщит. Своя миграция на фазу — это правило
-- записано в самой 0003.
--
-- Зачем: захват «истёкшей» аренды считает lease_until is null свободной
-- строкой. Значит, любая задача, оставленная в работе СТАРЫМ контейнером
-- (у неё аренды нет вовсе), станет добычей первой же новой реплики на первом
-- же опросе. Ограждение жетоном не даст испортить строку задачи, но цена
-- реальная и специфическая для этого парсера: два тела на одной задаче — это
-- два потока запросов к Яндексу через один и тот же пул прокси, а Яндекс
-- банит по IP. То есть перехват не просто оплачивается заново, он вдобавок
-- сжигает прокси и роняет обе половины работы в yandex_blocked. Плюс
-- переигранный сбор ссылок и повторный обход карточек на медленных каналах.
--
-- Пять минут — с запасом больше дефолтной аренды воркера
-- (YANDEXMAPS_LEASE_SECONDS, 180 с): живой исполнитель успеет продлить её на
-- ближайшем тике продления (аренда/3 = 60 с), а брошенная строка истечёт сама
-- и будет подобрана штатно.
--
-- Идемпотентно: only where lease_until is null — повторный прогон миграции
-- не сдвигает аренду, которую уже держит живой исполнитель.
update public.yandex_maps_jobs
   set lease_until = now() + interval '5 minutes'
 where status = 'running'
   and lease_until is null;
