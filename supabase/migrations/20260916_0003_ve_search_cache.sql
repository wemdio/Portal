-- Общий кэш поисков Serper для движка вертикалей.
--
-- Поиск «найди официальный сайт компании» стоит кредит и делается по одному на
-- каждую строку, у которой домен из каталога не подтвердился. Запрос строится
-- детерминированно из ИНН либо названия с адресом, поэтому одна и та же
-- компания в двух проектах — это буквально один и тот же запрос, оплаченный
-- дважды. Перезапуск этапа сборки базы (16.09.2026 их было по пять на базу)
-- переспрашивал уже оплаченное по тому же кругу.
--
-- 16.09.2026: 39 093 поиска за сутки против 3 930 накануне, баланс Serper
-- выжжен почти полностью за день. Кэш общий на все проекты и базы намеренно:
-- сайт компании не меняется от того, в чьём проекте её проверяют.
--
-- Кладём только удачные ответы. Таймаут или отказ провайдера ответом не
-- является и кэшироваться не должен — иначе разовый сбой сети превратится
-- в «у этой компании нет сайта» на месяц вперёд.

create table if not exists public.ve_search_cache (
  query_hash    text primary key,
  -- Начало запроса для ручного разбора; ключ считается по полному тексту.
  query_preview text not null,
  -- Ответ Serper в том виде, в каком его читает движок (organic items).
  results       jsonb not null,
  created_at    timestamptz not null default now(),
  last_used_at  timestamptz not null default now(),
  hits          integer not null default 0
);

comment on table public.ve_search_cache is
  'Общий кэш успешных поисков Serper (VE2 relevance). Ключ — sha256 текста запроса. Записываются только удачные ответы.';
comment on column public.ve_search_cache.hits is
  'Сколько раз ответ отдан из кэша вместо оплаченного запроса — прямая мера экономии.';

-- Чистка по возрасту: записи старше TTL перестают отдаваться кодом, но строки
-- нужно и физически удалять, иначе таблица растёт вечно.
create index if not exists ve_search_cache_created_idx
  on public.ve_search_cache (created_at);

grant all on public.ve_search_cache to service_role;
