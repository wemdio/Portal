-- Кто рассылает базу: выбранные оператором аккаунты кампании.
--
-- До этой колонки первую очередь базы брали все активные аккаунты кампании —
-- партию из 36 аккаунтов нельзя было развести по разным гипотезам, все шляпались
-- по одной и той же очереди. Теперь базе можно назначить подмножество аккаунтов:
-- оператор отмечает галочками, кто шлёт именно её, а лимиты и тайминги остаются
-- общими настройками кампании.
--
-- Пустой массив = все аккаунты кампании (поведение до фичи): существующие базы
-- продолжают рассылаться всеми. Массив, а не связующая таблица: список всегда
-- редактируется целиком и читается раз в круг воркером, реляционная связка тут
-- ничего не даёт.

alter table public.tg_outreach_bases
  add column if not exists sending_account_ids uuid[] not null default '{}';

comment on column public.tg_outreach_bases.sending_account_ids is
  'Аккаунты кампании, которые рассылают эту базу (первые касания). Пустой массив — все активные аккаунты кампании-владельца. Ответы в уже открытых диалогах остаются за аккаунтом-владельцем диалога.';
