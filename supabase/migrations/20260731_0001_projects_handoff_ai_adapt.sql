-- Пер-проектный тумблер «ИИ-адаптация текста передачи лида».
-- Жалобы разделились: части спецов ИИ-адаптация была удобна, части — нет
-- («пишет широко, консультирует»). OFF (дефолт): легенда проекта уходит лиду
-- ДОСЛОВНО (полный контроль текста). ON: ИИ адаптирует легенду под контекст
-- ответа лида, как было до 31.07.2026.
ALTER TABLE public.projects
  ADD COLUMN IF NOT EXISTS handoff_ai_adapt boolean NOT NULL DEFAULT false;

COMMENT ON COLUMN public.projects.handoff_ai_adapt IS
  'ON: ИИ адаптирует легенду передачи под ответ лида. OFF (дефолт): легенда уходит лиду дословно.';
