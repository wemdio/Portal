-- Выдать аренду задачам валидации почт, которые уже висят в работе на момент
-- переезда воркера на единый жизненный цикл (companion к 20260902_0001,
-- продолжение 20260902_0003 … 20260903_0006;
-- spec: docs/superpowers/specs/2026-09-02-job-lifecycle-design.md).
--
-- Отдельным файлом, а не дописыванием в предыдущую: применённые миграции
-- трекаются по ИМЕНИ файла, без контрольной суммы (app/scripts/db/
-- ensureDatabase.js). На базе, где 20260903_0006 уже применена, дописанные в
-- неё строки просто никогда не выполнятся, и никто об этом не сообщит. Своя
-- миграция на фазу — это правило записано в самой 20260902_0003.
--
-- Зачем: захват «истёкшей» аренды считает lease_until is null свободной
-- строкой. Значит, любая задача, оставленная в работе СТАРЫМ контейнером
-- (у неё аренды нет вовсе), станет добычей первой же новой реплики на первом
-- же опросе. У worker-emailvalidation реплика одна, и штатный деплой её сперва
-- гасит — отбирать не у кого; но одиночный рестарт или частичный recreate
-- оставляет рядом живого исполнителя. Ограждение жетоном не даст испортить
-- строку задачи, но цена реальная: строки очереди, взятые прежним владельцем
-- в processing, второй исполнитель проверит заново — это платные SMTP-пробы
-- через прокси и лишний трафик к чужим почтовым серверам.
--
-- ВНИМАНИЕ: статус выполнения в этой таблице — 'running' (check-констрейнт
-- миграции 20260221_0001: pending/running/completed/failed/cancelled).
--
-- Пять минут — с запасом больше дефолтной аренды валидации
-- (EMAIL_VALIDATION_LEASE_SECONDS, 180 с): живой исполнитель успеет продлить её
-- на ближайшем тике продления (аренда/3 = 60 с), а брошенная строка истечёт
-- сама и будет подобрана штатно.
--
-- Идемпотентно: only where lease_until is null — повторный прогон миграции
-- не сдвигает аренду, которую уже держит живой исполнитель.
update public.email_validation_jobs
   set lease_until = now() + interval '5 minutes'
 where status = 'running'
   and lease_until is null;
