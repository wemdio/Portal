-- Выдать аренду задачам крипто-приходов, которые уже висят в работе на момент
-- переезда очереди на единый жизненный цикл (companion к 20260902_0001,
-- продолжение 20260902_0003 … 20260903_0008;
-- spec: docs/superpowers/specs/2026-09-02-job-lifecycle-design.md).
--
-- Отдельным файлом, а не дописыванием в предыдущую: применённые миграции
-- трекаются по ИМЕНИ файла, без контрольной суммы (app/scripts/db/
-- ensureDatabase.js). На базе, где 20260903_0008 уже применена, дописанные в
-- неё строки просто никогда не выполнятся, и никто об этом не сообщит.
--
-- Зачем: захват «истёкшей» аренды считает lease_until is null свободной
-- строкой. Значит, любая задача, оставленная в работе СТАРЫМ контейнером
-- (у неё аренды нет вовсе), станет добычей первой же новой реплики на первом же
-- опросе. У воркера обогащения таких реплик девять, и деплой поднимает их не
-- одновременно — то есть новая реплика почти наверняка застанет рядом живого
-- исполнителя. Ограждение жетоном не даст испортить строку задачи, но цена
-- реальная: второй исполнитель заново обошёл бы те же сайты (до семи страниц на
-- сайт) и, что хуже, оба владельца писали бы checked_count и matches — итог
-- задачи стал бы зависеть от того, чья запись легла последней.
--
-- ВНИМАНИЕ: статус выполнения в этой таблице — 'running', отказ называется
-- 'error', а остановка пользователем — 'stopped' (check-констрейнт миграции
-- 20260402_0001: pending/running/completed/stopped/error). Праймим только
-- 'running': ни одну из остальных исполнитель не захватывает.
--
-- Пять минут — с запасом больше дефолтной аренды крипто-приходов
-- (CRYPTO_PAYMENTS_LEASE_SECONDS, 180 с): живой исполнитель успеет продлить её
-- на ближайшем тике продления (аренда/3 = 60 с), а брошенная строка истечёт
-- сама и будет подобрана штатно.
--
-- Идемпотентно: only where lease_until is null — повторный прогон миграции не
-- сдвигает аренду, которую уже держит живой исполнитель.
update public.crypto_payment_jobs
   set lease_until = now() + interval '5 minutes'
 where status = 'running'
   and lease_until is null;
