-- Выдать аренду задачам очереди parser_jobs (HH-вакансии, ATS-компании,
-- ENG-найм), которые уже висят в работе на момент переезда воркеров worker-hh и
-- worker-eng-hiring на единый жизненный цикл (companion к 20260902_0001,
-- продолжение 20260902_0003 … 20260902_0007;
-- spec: docs/superpowers/specs/2026-09-02-job-lifecycle-design.md).
--
-- Отдельным файлом, а не дописыванием в 0007: применённые миграции трекаются
-- по ИМЕНИ файла, без контрольной суммы (app/scripts/db/ensureDatabase.js). На
-- базе, где 0007 уже применена, дописанные в неё строки просто никогда не
-- выполнятся, и никто об этом не сообщит. Своя миграция на фазу — это правило
-- записано в самой 0003.
--
-- Зачем: захват «истёкшей» аренды считает lease_until is null свободной
-- строкой. Значит, любая задача, оставленная в работе СТАРЫМ контейнером (у неё
-- аренды нет вовсе), стала бы добычей первой же новой реплики на первом же
-- опросе. Ограждение жетоном не даст испортить строку, но работа переигралась
-- бы ЦЕЛИКОМ: у этой очереди нет курсора — ни один из трёх парсеров не умеет
-- продолжить с середины. Цена перезапуска — тысячи внешних запросов: обход
-- бордов Greenhouse/Lever/Ashby, выдача HH API, обогащение доменов через
-- Clearbit. Пять минут аренды дают живому исполнителю продлить её на ближайшем
-- тике (аренда/3 = 60 с), а брошенная строка истечёт сама и будет подобрана
-- штатно.
--
-- ВНИМАНИЕ: в отличие от 20260902_0007, статус выполнения здесь — 'running'
-- (check-констрейнт миграции 20260128_0001: pending/running/completed/failed).
-- Никакого 'processing' в этой таблице нет; условие по нему не нашло бы ни
-- одной строки и тихо ничего не сделало бы.
--
-- Идемпотентно: only where lease_until is null — повторный прогон не сдвигает
-- аренду, которую уже держит живой исполнитель.
update public.parser_jobs
   set lease_until = now() + interval '5 minutes'
 where status = 'running'
   and lease_until is null;
