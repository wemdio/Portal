-- Плательщик ручной траты — сразу человеческое название, а не служебный ключ.
--
-- Почему название, а не ключ: колонка `manual_expenses.payer` никогда не была
-- справочником. Это свободный текст без CHECK, без внешнего ключа и без
-- таблицы-словаря, так что «ключ» `ceo_personal_card` был здесь чистой
-- условностью — расшифровка к нему жила только на фронте. При этом витрина
-- `expenses_v` подставляет `payer` в `counterparty` наравне с настоящими
-- контрагентами банка, и служебная строка была видна и в разбивке по сервисам,
-- и в очереди разметки. Починить это в интерфейсе нечем: в то же поле рядом
-- приходят уже человеческие названия из выписок.
--
-- Раз справочника нет, то и ключ не нужен: храним то, что должно быть на
-- экране.

alter table public.manual_expenses
  alter column payer set default 'Личная карта CEO';

-- В проде таблица пустая, переносить нечего. Апдейт оставлен ради копий и
-- дев-баз, где ручные траты успели завестись со старым дефолтом: иначе они
-- продолжили бы показывать служебную строку уже без всякой расшифровки.
update public.manual_expenses
   set payer = 'Личная карта CEO'
 where payer = 'ceo_personal_card';

comment on column public.manual_expenses.payer is
  'Человеческое название плательщика («Личная карта CEO», «карта партнёра») — оно же уходит в counterparty витрины expenses_v. Справочника нет, это свободный текст; служебных ключей здесь быть не должно.';
