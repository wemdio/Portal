-- Проверка аккаунта на запущенной кампании — через очередь, а не напрямую.
--
-- Кнопка «Проверить» подключается к Telegram из приложения портала. Пока
-- кампания работает, ту же сессию держит воркер, и второе подключение даёт
-- AUTH_KEY_DUPLICATED: Telegram выключает аккаунт. Поэтому проверка была
-- доступна только на остановленной кампании — а останавливать её ради того,
-- чтобы посмотреть, жив ли аккаунт, оператор, разумеется, не станет. В
-- результате «жив/не жив» на экране устаревал на недели.
--
-- Теперь нажатие на работающей кампании не подключается никуда, а ставит
-- отметку в этой колонке. Воркер, дойдя до аккаунта в своём круге, выполняет
-- проверку СВОИМ соединением — тем самым, что уже открыто, — записывает итог в
-- check_status/check_detail/checked_at и гасит отметку.
--
-- NULL = проверка не запрошена. Время нужно, чтобы интерфейс мог показать
-- «стоит в очереди с 14:32», а не безликое «ожидает».

alter table public.tg_outreach_accounts
  add column if not exists check_requested_at timestamptz,
  -- Кто нажал — в интерфейс и в журнал: инструмент командный, и «проверку
  -- заказал кто-то» помогает меньше, чем «проверку заказал Егор».
  add column if not exists check_requested_by_name text;

comment on column public.tg_outreach_accounts.check_requested_at is
  'Оператор заказал проверку на работающей кампании. Воркер выполнит её своим соединением в ближайшем круге и обнулит поле. NULL = не запрошена.';
comment on column public.tg_outreach_accounts.check_requested_by_name is
  'Имя того, кто заказал проверку. Показывается в строке аккаунта, пока проверка ждёт круга.';

-- Воркер спрашивает «есть ли заказы по этой кампании» каждый круг: частичный
-- индекс держит этот запрос дешёвым независимо от размера пула аккаунтов.
create index if not exists tg_outreach_accounts_check_requested_idx
  on public.tg_outreach_accounts (campaign_id)
  where check_requested_at is not null;
