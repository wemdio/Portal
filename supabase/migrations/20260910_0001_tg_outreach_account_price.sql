-- Цена аккаунта: сколько заплатили за конкретный номер.
--
-- Аккаунты покупают партиями у разных поставщиков и по разной цене, а живут
-- они по-разному: одна партия отдаёт тридцать писем и уходит в заморозку,
-- другая работает месяц. Без цены сравнивать партии нечем — «дорогие живут
-- дольше» остаётся ощущением, а не цифрой.
--
-- Поле nullable, а не default 0: «цену не указали» и «аккаунт достался
-- бесплатно» — разные вещи, и складывать их в один ноль значит занижать
-- стоимость партии молча. Экран показывает прочерк, суммы считаются только по
-- заполненным.
--
-- Валюта не хранится: закупка идёт в рублях, а множить сущности ради гипотезы
-- «а вдруг доллары» рано — при появлении валютных партий добавим отдельным
-- полем, а не задним числом переинтерпретируем существующие числа.
alter table public.tg_outreach_accounts
  add column if not exists price numeric(12,2);

comment on column public.tg_outreach_accounts.price is
  'Цена аккаунта в рублях. NULL — цена не указана (это не ноль).';
