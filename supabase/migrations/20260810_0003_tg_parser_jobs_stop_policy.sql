-- Парсер TG: разрешить владельцу останавливать свою задачу.
--
-- У tg_parser_jobs были политики на insert, delete и select — а на update не
-- было ни одной. Кнопка «Остановить» шлёт update статуса из-под пользователя,
-- он молча затрагивал ноль строк, и API отвечал «Задача уже завершилась», хотя
-- задача продолжала работать. 10.08.2026 так и не удалось остановить задачу,
-- висевшую полтора часа.
--
-- Право даём только владельцу: остановка чужого запуска — не то, что должно
-- получаться случайным нажатием. Удалять свою задачу владелец и так мог, так
-- что новых возможностей это не открывает.

create policy tg_parser_jobs_update_own on public.tg_parser_jobs
  for update to authenticated
  using (auth.uid() = user_id)
  with check (auth.uid() = user_id);

grant update on public.tg_parser_jobs to authenticated;
