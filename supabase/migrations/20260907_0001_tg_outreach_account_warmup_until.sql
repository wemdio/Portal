-- До какого момента аккаунт греется и не участвует в боевой рассылке.
--
-- Прогрев и рассылка были взаимоисключающими на уровне всей кампании: запуск
-- прогрева переводил её статус в `warming`, боевой круг останавливался у всех
-- аккаунтов разом, а по окончании кампания оставалась `stopped` и поднималась
-- руками. Оба цикла брали один и тот же набор — `campaign_id + is_active`.
--
-- Практический итог: прогревом не пользовались. У ATOL-1 один запуск за всё
-- время (04.08.2026), у Polza — ни одного. Останавливать рассылку клиенту ради
-- того, чтобы погрелась новая партия, никто не станет — и новые аккаунты шли в
-- бой с первого дня, где живут около тридцати писем.
--
-- Теперь прогрев — свойство аккаунта, а не кампании. Кампания продолжает
-- рассылать теми, кто готов, пока новички греются рядом.
--
-- Срок, а не флаг: «греется до четверга» сам заканчивается и переводит аккаунт
-- в бой. Флаг пришлось бы снимать руками, а значит партия грелась бы, пока о
-- ней не вспомнят.
--
-- NULL = аккаунт боевой. Прошедшая дата = прогрев закончился, аккаунт боевой.

alter table public.tg_outreach_accounts
  add column if not exists warmup_until timestamptz;

comment on column public.tg_outreach_accounts.warmup_until is
  'До этого момента аккаунт только греется и в боевую рассылку не берётся. NULL или прошедшая дата — аккаунт боевой.';

-- Оба круга спрашивают «кто сейчас греется» на каждом проходе.
create index if not exists tg_outreach_accounts_warmup_until_idx
  on public.tg_outreach_accounts (campaign_id, warmup_until)
  where warmup_until is not null;
