-- ENG («Движок вертикалей», he_*): сухая вертикаль перестаёт получать ночной
-- слот добора — видимо для клиента и обратимо им же.
--
-- ЗАЧЕМ. Ночной добор (worker/heAutoPipelineCron.ts → lib/hypothesisEngine/
-- autoPipeline.ts) каждую ночь ставит refill-сборку по вертикалям с запущенной
-- кампанией. Сборка ПЛАТНАЯ (план источников, релевант-гейт, краул сайтов и
-- SMTP-проба каждого адреса в конструкторе), а её результат может быть нулевым:
-- срез исчерпан или даёт компании без единого отправляемого адреса. Такая
-- вертикаль ночь за ночью тратит проход и не добавляет ни одного контакта.
-- Правило: N подряд ночей без единого добавленного контакта — вертикаль слот
-- больше не получает, пока клиент не вернёт её сам.
--
-- ПОЧЕМУ КОЛОНКИ У he_verticals, А НЕ ОТДЕЛЬНАЯ ТАБЛИЦА. Пометка — свойство
-- ВЕРТИКАЛИ и должна доехать до кабинета. Деталка проекта читает вертикали
-- `select('*')` (lib/hypothesisEngine/projectDetail.ts) и режет состав ответа
-- белым списком проекции (clientEngProjection.ts, VERTICAL_FIELDS) — отдельная
-- таблица потребовала бы ещё одного чтения и джойна в общем со staff-загрузчике
-- ради двух скаляров. Форма скопирована с соседнего трио той же таблицы
-- (actual_reply_pct/actual_sent/actual_measured_at, 20260806_0001): значение +
-- счётчик + штамп.
--
-- ЧТО ЗНАЧИТ КАЖДАЯ КОЛОНКА.
--   * refill_dry_since — момент, когда ночной проход ПРИНЯЛ решение. NOT NULL
--     ⇒ вертикаль ночной слот не получает. Это единственный признак пометки:
--     кабинет рисует её ровно по нему.
--   * refill_dry_nights — сколько подряд ночей без добавленного контакта
--     насчитал проход в момент решения. Нужен клиентской фразе («N daily
--     refills in a row brought no new contacts», EngStepVerticals.tsx): без
--     него пометка не объясняет себя.
--   * refill_resumed_at — когда КЛИЕНТ снял пометку (POST
--     /api/client/eng/verticals/[id]/refill). Это не аудит: серия считается
--     ТОЛЬКО по прогонам, завершённым позже этого штампа, иначе снятая пометка
--     возвращалась бы следующей же ночью — история-то прежняя, — и кнопка
--     «Resume» была бы враньём.
--
-- ЧЕГО ЗДЕСЬ НЕТ И ПОЧЕМУ. Самой СЕРИИ здесь нет: её считает проход по
-- he_auto_pipeline_runs (status='no_new' подряд, см. autoPipeline.ts). Хранить
-- счётчик рядом с журналом значило бы завести второй источник одного факта,
-- который умеет разъехаться с первым.
--
-- ПОРОГ N — В КОНФИГЕ ПРОЕКТА, А НЕ В КОДЕ. he_auto_pipeline_configs пуст,
-- ночной добор в production не запускался ни разу, истории для калибровки
-- НЕТ — поэтому N вынесен в he_auto_pipeline_configs.dry_nights_limit с
-- консервативным дефолтом 7 (неделя наблюдений). Самo правило вдобавок
-- выключено флагом окружения HE_VERTICAL_DRY_STOP: без него проход только
-- СЧИТАЕТ серию в ночной лог (это и есть материал для калибровки порога) и
-- снимает чужие пометки, но ни одной вертикали слот не отнимает.
--
-- БЕЗ МИГРАЦИИ КОД НЕ ПАДАЕТ: чтение вертикалей идёт `select('*')`, запись
-- пометки — best-effort (ошибка апдейта = решение не принято, вертикаль
-- собирается как раньше), чтение конфига переживает отсутствие колонки
-- (дефолт из кода). Но пометка без колонки не сохранится, а значит правило не
-- заработает — порядок выката прежний: СНАЧАЛА миграция, ПОТОМ код.
--
-- ПРАВ МИГРАЦИЯ НЕ МЕНЯЕТ: новых таблиц и функций она не создаёт, а колонка
-- наследует табличные гранты своей таблицы. he_verticals и
-- he_auto_pipeline_configs запечатаны своими миграциями (20260724_0001,
-- 20260804_0005) и поимённым отзывом anon/authenticated
-- (20260920_0001_he_rls_lockdown.sql); allowlist от этого файла не растёт.

alter table public.he_verticals
  add column if not exists refill_dry_since timestamptz;

alter table public.he_verticals
  add column if not exists refill_dry_nights integer;

alter table public.he_verticals
  add column if not exists refill_resumed_at timestamptz;

comment on column public.he_verticals.refill_dry_since is
  'ENG: когда ночной проход снял вертикаль с добора как сухую (N подряд ночей без добавленного контакта). NOT NULL = слот не выдаётся; снимает клиент из кабинета.';
comment on column public.he_verticals.refill_dry_nights is
  'ENG: длина серии ночей без добавленного контакта на момент решения — число из клиентской фразы о пометке.';
comment on column public.he_verticals.refill_resumed_at is
  'ENG: когда клиент вернул вертикаль в ночной добор. Серия считается только по прогонам, завершённым ПОЗЖЕ этого штампа.';

-- ─── Порог правила: N ночей ──────────────────────────────────────────────
-- На ПРОЕКТ, рядом с остальными настройками добора (daily_leads_cap,
-- verticals_per_run). not null default 7: конфигов в таблице нет ни одного,
-- поэтому дефолт — это и есть значение для первого клиента, и он обязан быть
-- консервативным. Зеркало дефолта в коде — HE_AUTO_DEFAULT_DRY_NIGHTS_LIMIT
-- (lib/hypothesisEngine/autoPipeline.ts); правится в обоих местах сразу.
-- Ноль и отрицательные значения запрещены проверкой: «правило выключено» — это
-- флаг окружения, а не порог 0, который прочитался бы как «снимать вертикаль
-- после нуля пустых ночей», то есть сразу.

alter table public.he_auto_pipeline_configs
  add column if not exists dry_nights_limit integer not null default 7;

do $$ begin
  if not exists (
    select 1 from pg_constraint
    where conname = 'he_auto_pipeline_configs_dry_nights_limit_positive'
  ) then
    alter table public.he_auto_pipeline_configs
      add constraint he_auto_pipeline_configs_dry_nights_limit_positive
      check (dry_nights_limit > 0);
  end if;
end $$;

comment on column public.he_auto_pipeline_configs.dry_nights_limit is
  'ENG: сколько подряд ночей без добавленного контакта снимают вертикаль с ночного добора. Правило вдобавок включается флагом HE_VERTICAL_DRY_STOP.';
