-- Выдать аренду прогонам ручного скоринга, которые уже висят в работе на момент
-- переезда очереди на единый жизненный цикл (companion к 20260902_0001,
-- продолжение 20260902_0003 … 20260903_0009;
-- spec: docs/superpowers/specs/2026-09-02-job-lifecycle-design.md).
--
-- Отдельным файлом, а не дописыванием в предыдущую: применённые миграции
-- трекаются по ИМЕНИ файла, без контрольной суммы (app/scripts/db/
-- ensureDatabase.js). На базе, где 20260903_0009 уже применена, дописанные в
-- неё строки просто никогда не выполнятся, и никто об этом не сообщит.
--
-- ВНИМАНИЕ: активный статус в этой таблице называется 'processing', а не
-- 'running' (check-констрейнт миграции 20260526_0013:
-- pending/processing/completed/failed/cancelled). Праймить по аналогии с
-- остальными очередями здесь нельзя — 'running' не выбрал бы ни одной строки,
-- и миграция молча не сделала бы ничего.
--
-- Зачем: захват «истёкшей» аренды считает lease_until is null свободной
-- строкой. Значит, любой прогон, оставленный в работе СТАРЫМ контейнером
-- (у него аренды нет вовсе), станет добычей первой же новой реплики на первом
-- же опросе. Реплика у ручного скоринга одна, и штатный деплой её сперва
-- гасит — отбирать не у кого; но одиночный рестарт или частичный recreate
-- оставляет рядом живого исполнителя. Ограждение жетоном не даст испортить
-- строку прогона, но цена реальная: второй владелец заново обошёл бы те же
-- сайты (до пяти страниц на домен), заново проверил бы почты по SMTP и заново
-- потратил бы токены суточного бюджета Mailganer, общего со всеми прочими
-- путями к нему.
--
-- Пять минут — с запасом больше дефолтной аренды ручного скоринга
-- (MANUAL_SCORING_LEASE_SECONDS, 180 с): живой исполнитель успеет продлить её
-- на ближайшем тике продления (аренда/3 = 60 с), а брошенный прогон истечёт
-- сам и будет подобран штатно.
--
-- Цена честно: прогон, который был в работе В МОМЕНТ деплоя, простоит эти пять
-- минут (новый контейнер не имеет права его трогать, аренда выглядит живой), а
-- потом будет перехвачен по истёкшей аренде — то есть как потеря, с тратой
-- одной попытки из пяти. Это разовая цена одного деплоя, дальше аренду ведёт
-- сам воркер.
--
-- Идемпотентно: only where lease_until is null — повторный прогон миграции не
-- сдвигает аренду, которую уже держит живой исполнитель.
update public.client_manual_score_runs
   set lease_until = now() + interval '5 minutes'
 where status = 'processing'
   and lease_until is null;
