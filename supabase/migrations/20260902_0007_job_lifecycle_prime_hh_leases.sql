-- Выдать аренду задачам архива вакансий HH и Яндекс.Директа, которые уже висят
-- в работе на момент переезда воркера worker-hh на единый жизненный цикл
-- (companion к 20260902_0001, продолжение 20260902_0003 … 20260902_0006;
-- spec: docs/superpowers/specs/2026-09-02-job-lifecycle-design.md).
--
-- Отдельным файлом, а не дописыванием в 0006: применённые миграции трекаются
-- по ИМЕНИ файла, без контрольной суммы (app/scripts/db/ensureDatabase.js). На
-- базе, где 0006 уже применена, дописанные в неё строки просто никогда не
-- выполнятся, и никто об этом не сообщит. Своя миграция на фазу — это правило
-- записано в самой 0003.
--
-- Зачем: захват «истёкшей» аренды считает lease_until is null свободной
-- строкой. Значит, любая задача, оставленная в работе СТАРЫМ контейнером
-- (у неё аренды нет вовсе), станет добычей первой же новой реплики на первом же
-- опросе. Ограждение жетоном не даст испортить строку, но работа переигралась
-- бы: у архива — весь текущий поисковый чанк (листание hh_vacancies батчами по
-- 1000), у Директа — до десяти платных запросов к XMLStock, который считает
-- лимит по аккаунту. Пять минут аренды дают живому исполнителю продлить её на
-- ближайшем тике (аренда/3 = 60 с), а брошенная строка истечёт сама и будет
-- подобрана штатно.
--
-- ВНИМАНИЕ: у обеих таблиц статус выполнения — 'processing', а не 'running'
-- (check-констрейнты миграций 20260516_0001 и 20260517_0001). Условие по
-- 'running' здесь не нашло бы ни одной строки и тихо ничего не сделало бы.
--
-- Идемпотентно: only where lease_until is null — повторный прогон не сдвигает
-- аренду, которую уже держит живой исполнитель.
update public.hh_archive_jobs
   set lease_until = now() + interval '5 minutes'
 where status = 'processing'
   and lease_until is null;

update public.yandex_direct_jobs
   set lease_until = now() + interval '5 minutes'
 where status = 'processing'
   and lease_until is null;
