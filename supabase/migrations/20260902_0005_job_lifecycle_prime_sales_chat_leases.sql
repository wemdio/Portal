-- Выдать аренду запускам синхронизации сейлз-переписок, которые уже висят в
-- работе на момент переезда воркера на единый жизненный цикл (companion к
-- 20260902_0001, продолжение 20260902_0003 и 20260902_0004;
-- spec: docs/superpowers/specs/2026-09-02-job-lifecycle-design.md).
--
-- Отдельным файлом, а не дописыванием в 0004: применённые миграции трекаются
-- по ИМЕНИ файла, без контрольной суммы (app/scripts/db/ensureDatabase.js).
-- На базе, где 0004 уже применена, дописанные в неё строки просто никогда не
-- выполнятся, и никто об этом не сообщит. Своя миграция на фазу — это правило
-- записано в самой 0003.
--
-- Зачем: захват «истёкшей» аренды считает lease_until is null свободной
-- строкой. Значит, любой запуск, оставленный в работе СТАРЫМ контейнером
-- (у него аренды нет вовсе), станет добычей первой же новой реплики на первом
-- же опросе. Ограждение жетоном не даст испортить строку самого запуска, но
-- цена реальная и специфическая: тело синка подключается к Telegram теми же
-- sales-chat-сессиями, и второе соединение поверх живого — это
-- AUTH_KEY_DUPLICATED и сожжённая сессия аккаунта (lib/tgParser/
-- accountConflict.ts), то есть ручной перезалив tdata, а не просто лишняя
-- работа. Плюс переигранная выгрузка тысяч диалогов и вложений в S3.
--
-- Пять минут — с запасом больше дефолтной аренды синка (SALES_CHAT_LEASE_
-- SECONDS, 180 с): живой исполнитель успеет продлить её на ближайшем тике
-- продления (аренда/3 = 60 с), а брошенная строка истечёт сама и будет
-- подобрана штатно.
--
-- Идемпотентно: only where lease_until is null — повторный прогон миграции
-- не сдвигает аренду, которую уже держит живой исполнитель.
update public.sales_chat_sync_runs
   set lease_until = now() + interval '5 minutes'
 where status = 'running'
   and lease_until is null;
