-- Выдать аренду поисковым задачам, которые уже висят в работе на момент
-- переезда парсера поиска на единый жизненный цикл (companion к 20260902_0001,
-- продолжение 20260902_0003; spec: docs/superpowers/specs/2026-09-02-job-lifecycle-design.md).
--
-- Отдельным файлом, а не дописыванием в 0003: применённые миграции трекаются
-- по ИМЕНИ файла, без контрольной суммы (app/scripts/db/ensureDatabase.js).
-- На базе, где 0003 уже применена, дописанные в неё строки просто никогда не
-- выполнятся, и никто об этом не сообщит. Своя миграция на фазу — это правило
-- записано в самой 0003 («Каждая следующая фаза прайминг своих таблиц делает
-- своей миграцией, когда её воркер переезжает»).
--
-- Зачем: захват «истёкшей» аренды считает lease_until is null свободной
-- строкой. Значит, любая задача, оставленная в работе СТАРЫМ контейнером
-- (у неё аренды нет вовсе), станет добычей первой же новой реплики на первом
-- же опросе. У worker-search реплика одна, и штатный деплой её сперва гасит —
-- отбирать не у кого; но одиночный рестарт или частичный recreate оставляет
-- рядом живого исполнителя. Ограждение жетоном не даст испортить строку
-- задачи, но цена реальная: заново оплаченный скрейпинг и обход каталогов,
-- а результаты пишутся в search_results без уникального ключа — то есть
-- дублями в выгрузке.
--
-- Пять минут — с запасом больше дефолтной аренды поиска (SEARCH_LEASE_SECONDS,
-- 180 с): живой исполнитель успеет продлить её на ближайшем тике продления
-- (аренда/3 = 60 с), а брошенная строка истечёт сама и будет подобрана штатно.
--
-- Идемпотентно: only where lease_until is null — повторный прогон миграции
-- не сдвигает аренду, которую уже держит живой исполнитель.
update public.search_parser_jobs
   set lease_until = now() + interval '5 minutes'
 where status = 'running'
   and lease_until is null;
