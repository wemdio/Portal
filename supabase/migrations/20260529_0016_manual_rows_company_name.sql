-- Ручной скоринг: храним название компании для активных строк.
--
-- Требование: у каждого готового контакта (и в ручном режиме тоже) есть
-- email + название + сайт, причём название ПОЧИЩЕНО тем же AI, что кнопка
-- «Очистить названия». Название резолвится из кэша mailganer_domain_scores
-- (его наполняет фоновый BoB-скорер из базы ФНС), чистится и пишется сюда.
-- Пустая строка '' = «резолв выполнен, имени нет» (маркер идемпотентности,
-- чтобы повторный прогон не дублировал резолв/маршрутизацию).

ALTER TABLE public.client_manual_score_rows
  ADD COLUMN IF NOT EXISTS company_name text;

COMMENT ON COLUMN public.client_manual_score_rows.company_name IS
  'Очищенное (AI, как кнопка «Очистить названия») название компании для активных строк. NULL = ещё не резолвили; '''' = резолвили, имени нет.';
