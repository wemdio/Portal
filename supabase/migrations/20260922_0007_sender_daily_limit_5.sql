-- Дневной лимит кампаний на ящик: 5 вместо 15.
--
-- Решение владельца 22.09.2026: выход на боевые отправки начинаем
-- консервативно — 5 холодных писем в день на ящик. Применяется и к новым
-- ящикам (дефолт колонки), и ко всем уже подключённым. Правится по мере
-- прогрева вручную на карточке ящика (поле «Лимит/день»).

alter table public.sender_mailboxes
  alter column daily_campaign_limit set default 5;

update public.sender_mailboxes
   set daily_campaign_limit = 5;

comment on column public.sender_mailboxes.daily_campaign_limit is
  'Холодных кампанийных писем в день с ящика. Дефолт 5 (решение 22.09.2026, старт с консервативного темпа); поднимается вручную по мере прогрева.';
