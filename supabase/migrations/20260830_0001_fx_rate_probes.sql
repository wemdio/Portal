-- Память о том, за какие даты курс у ЦБ уже спрашивали.
--
-- Зачем. fx_cbr решал «нужен ли курс за дату» по окну: если для валюты есть
-- любой курс не старше 10 дней — дата считается закрытой и в ЦБ за ней не
-- ходят. Окно защищало от бесконечного долбления в выходные (за субботу ЦБ
-- отдаёт пятничный курс под пятничной датой, и точного совпадения rate_date
-- = суббота не будет никогда), но заодно закрывало и обычные будни: 13.08
-- не запрашивали, потому что уже лежал курс за 12.08. В результате валютные
-- суммы считались по курсу давностью до 10 дней. Замеры на боевых данных
-- 30.08.2026: приход 13.08 посчитан по курсу 12.08 (82,3742 вместо 82,9977
-- — на 510 USDT это 318 ₽), худший случай в базе — операция 10.08 по курсу
-- 31.07, отставание ровно 10 дней.
--
-- Как чинится. Правило «спросить, если нет ТОЧНОГО курса за эту дату»
-- корректно, но само по себе зациклилось бы на выходных. Поэтому факт
-- запроса запоминается здесь: каждая дата спрашивается у ЦБ ровно один раз.
-- Выходные после первого же запроса перестают попадать в выборку, а будни
-- получают свой собственный курс, а не соседний.
--
-- Почему отдельная таблица, а не строка в fx_rates. fx_rates обязана
-- оставаться тем, что ЦБ действительно опубликовал: положить туда пятничный
-- курс под субботней датой — значит выдумать публикацию, которой не было, и
-- потерять возможность отличить настоящий курс дня от перенесённого.

create table if not exists public.fx_rate_probes (
  -- Дата, за которую ходили в ЦБ (date_req), а НЕ дата публикации ответа.
  rate_date    date        primary key,
  probed_at    timestamptz not null default now(),
  -- Что ЦБ ответил в атрибуте Date. Для будней совпадает с rate_date, для
  -- выходных и праздников указывает на предыдущий рабочий день. Хранится
  -- ради диагностики: по нему видно, почему за дату нет своей строки в
  -- fx_rates, без повторного похода в ЦБ.
  published_on date
);

comment on table public.fx_rate_probes is
  'Даты, за которые курс у ЦБ уже спрашивали. Нужна, чтобы выходные и '
  'праздники (ЦБ отдаёт за них курс предыдущего рабочего дня) не '
  'запрашивались каждую ночь вечно. См. services/portal-external-sync/sources/fx_cbr.py';

-- Права — как у fx_rates рядом (20260730_0001_expenses_core.sql): таблицу
-- пишет синк курсов, который ходит в базу напрямую, и читает он же. Отдельной
-- роли под неё не заводим — где живут курсы, там же живёт и память о запросах.
grant all on public.fx_rate_probes to service_role, postgres;
