-- Прочитано ли собеседником наше последнее сообщение в диалоге.
--
-- Telegram отдаёт это в списке диалогов (readOutboxMaxId): воркер и так
-- запрашивает список каждый круг, поэтому отдельных запросов не нужно.
--
-- null — не знаем или последнее сообщение не наше (тогда галочек не показываем).
-- true — собеседник прочитал наше последнее сообщение; false — ещё нет.
--
-- Колонка заполняется воркером, а портал сбрасывает её в false при отправке
-- нового сообщения, чтобы не показать «прочитано» на только что ушедшее.

alter table public.tg_outreach_dialogs
  add column if not exists out_read boolean;

comment on column public.tg_outreach_dialogs.out_read is
  'Прочитал ли собеседник наше последнее сообщение: true/false, null — неизвестно или последнее сообщение не наше. Пишет воркер по readOutboxMaxId.';
