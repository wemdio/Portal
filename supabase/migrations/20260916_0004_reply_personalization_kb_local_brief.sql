-- Бриф, введённый прямо в базе знаний инструмента «Персонализированные ответы».
--
-- 15.09.2026 колонку `brief` отсюда удалили (миграция 20260915_0003) с расчётом,
-- что к запуску кампании бриф уже заполнен в карточке проекта и дублировать его
-- незачем. На практике карточка часто пуста, а ответы лидам нужны сейчас: идти
-- заполнять карточку ради одной генерации никто не станет, и специалист упирался
-- в read-only поле без единого способа продолжить.
--
-- Поэтому возвращаем, но с другой ролью и другим именем. Это не копия брифа и не
-- замена карточке: карточка остаётся источником истины и имеет приоритет, а это
-- поле используется, только пока `projects.brief_text` пуст. Пометка «в карточке
-- проекта нет брифа» в модалке остаётся намеренно — она напоминает, где бриф
-- должен жить постоянно, и не даёт локальному полю тихо стать основным местом.
--
-- Запись сюда НИКОГДА не пишет в карточку проекта: инструмент не имеет права
-- задним числом менять бриф, который ведут менеджеры проекта.

alter table public.reply_personalization_kb
  add column if not exists local_brief text not null default '';

comment on column public.reply_personalization_kb.local_brief is
  'Бриф, введённый в самой модалке базы знаний. Запасной источник: используется только когда projects.brief_text пуст, и никогда не пишется обратно в карточку проекта.';

comment on table public.reply_personalization_kb is
  'Карточка знаний проекта для генератора персонализированных ответов на входящие: факты о продукте, тон, пример письма и запасной бриф (основной — живьём из projects.brief_text). Одна строка на проект.';
