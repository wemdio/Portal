-- Колонка прогресса и аренда для кампаний TG-аутрича, переезжающих на единый
-- жизненный цикл задач (companion к 20260902_0001, продолжение
-- 20260902_0003 … 20260903_0004;
-- spec: docs/superpowers/specs/2026-09-02-job-lifecycle-design.md).
--
-- Отдельным файлом, а не дописыванием в предыдущую: применённые миграции
-- трекаются по ИМЕНИ файла, без контрольной суммы (app/scripts/db/
-- ensureDatabase.js). На базе, где 20260903_0004 уже применена, дописанные в
-- неё строки просто никогда не выполнятся, и никто об этом не сообщит. Своя
-- миграция на фазу — это правило записано в самой 20260902_0003.

-- 1. Колонка прогресса.
--
-- Аренду продлевает независимый таймер, поэтому здоровый процесс с намертво
-- зависшим циклом кампании продлевал бы её вечно, и кампанию не подобрал бы
-- никто. Признак «работа движется» обязан быть отдельным от признака «процесс
-- жив» — им и становится эта отметка.
--
-- Почему НОВАЯ колонка, а не существующая. Скалярных кандидатов в этой таблице
-- два, и оба не годятся. `updated_at` пишется на смене статуса и служит
-- человеку отметкой «когда кампанию трогали в последний раз» — механизм аренды
-- обязан её не трогать (ловушка, сработавшая в этом проекте трижды). Счётчиков
-- отправленного у кампании нет вовсе: отправки живут построчно в
-- tg_outreach_dialogs и tg_outreach_base_contacts, а jsonb-колонки библиотека
-- прямо запрещает — сравнение по !== на каждый раз новом объекте всегда даёт
-- «движение» и молча выключает и детектор простоя, и предел попыток.
--
-- Что именно отмечается. Не отправка, а ПРОДВИЖЕНИЕ ЦИКЛА: верх круга, переход
-- к аккаунту, каждый контакт первого касания, конец паузы — те же горячие
-- точки, что раньше кормили сторожевой таймер в памяти воркера. Так и нужно:
-- кампания законно может не отправить ничего часами (пустая очередь, «тихий
-- час», все диалоги прочитаны), и порог по отправкам глушил бы исправную
-- работу. Ловим мы другое — цикл, повисший внутри сетевого вызова gramJS.
--
-- Пишется не чаще раза в минуту (PROGRESS_WRITE_INTERVAL_MS в
-- app/worker/tgOutreach.ts) и ограждается жетоном аренды, поэтому индекса не
-- требует: читают её по первичному ключу.
alter table public.tg_outreach_campaigns
  add column if not exists progress_at timestamptz;

comment on column public.tg_outreach_campaigns.progress_at is
  'Когда цикл кампании последний раз продвинулся (не отправка, а шаг круга). Колонка прогресса для lib/jobs/lifecycle.ts: стоит дольше порога — аренда не продлевается, кампанию подбирает другой исполнитель.';

-- 2. Прайминг аренд.
--
-- Захват «истёкшей» аренды считает lease_until is null свободной строкой.
-- Кампания, оставленная в работе СТАРЫМ контейнером (аренды у него нет вовсе),
-- стала бы добычей первой же новой реплики на первом же опросе. И вот здесь
-- цена выше, чем у любой очереди, переведённой до этого: новый исполнитель
-- подключил бы ТЕ ЖЕ сессии MTProto, что ещё держит старый, получил бы
-- AUTH_KEY_DUPLICATED, и после трёх таких подряд аккаунт выключается насовсем —
-- восстановление только руками, с перевыпуском сессии с телефона.
--
-- Пять минут — заведомо больше аренды кампании (TG_OUTREACH_LEASE_SECONDS,
-- 180 с): живой исполнитель успеет продлить её на ближайшем тике продления
-- (аренда/3 = 60 с), а брошенная кампания истечёт сама и будет подобрана
-- штатно. Старый контейнер к этому моменту давно остановлен: деплой сначала
-- гасит воркеры (`docker compose stop --timeout 15`) и только потом поднимает
-- новые.
--
-- ВНИМАНИЕ: статус выполнения в этой таблице — 'running' (check-констрейнт
-- миграции 20260804_0001: stopped/running/paused/error/warming). Отдельного
-- статуса «ожидает» здесь нет вовсе: кнопка «Запустить» пишет сразу 'running',
-- и очередь выражена отсутствием аренды, а не статусом. Греющиеся кампании
-- (`warming`) под условие не подпадают — и не должны: их ведёт раннер прогрева
-- по своей таблице, а боевой цикл на них не запускается вовсе.
--
-- Идемпотентно: only where lease_until is null — повторный прогон не сдвигает
-- аренду, которую уже держит живой исполнитель.
update public.tg_outreach_campaigns
   set lease_until = now() + interval '5 minutes'
 where status = 'running'
   and lease_until is null;
