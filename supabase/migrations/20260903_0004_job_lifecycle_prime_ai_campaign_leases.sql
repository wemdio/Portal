-- Выдать аренду кампаниям обзвона, которые уже идут на момент переезда воркера
-- portal-worker-aicaller на единый жизненный цикл (companion к 20260902_0001,
-- продолжение 20260902_0003 … 20260903_0001;
-- spec: docs/superpowers/specs/2026-09-02-job-lifecycle-design.md).
--
-- Отдельным файлом, а не дописыванием в предыдущую: применённые миграции
-- трекаются по ИМЕНИ файла, без контрольной суммы (app/scripts/db/
-- ensureDatabase.js). На базе, где 20260903_0001 уже применена, дописанные в
-- неё строки просто никогда не выполнятся, и никто об этом не сообщит. Своя
-- миграция на фазу — это правило записано в самой 20260902_0003.
--
-- Зачем: захват «истёкшей» аренды считает lease_until is null свободной
-- строкой. Кампания, оставленная в работе СТАРЫМ контейнером (аренды у него
-- нет вовсе), стала бы добычей первой же новой реплики на первом же опросе.
-- Ограждение жетоном не даст испортить саму строку кампании, но цена здесь не в
-- переигранной работе: новый исполнитель начал бы обзванивать контакты
-- параллельно с ещё живым старым. Захват контакта теперь атомарный и от
-- ДВОЙНОГО набора одного человека защищает сам по себе, но два цикла на одной
-- кампании всё равно вдвое ускоряют исходящие звонки против настроек и путают
-- счётчики; пять минут тишины стоят дешевле.
--
-- Пять минут — с запасом больше аренды обзвона (AI_CALLER_LEASE_SECONDS, 180 с):
-- живой исполнитель успеет продлить её на ближайшем тике продления
-- (аренда/3 = 60 с), а брошенная кампания истечёт сама и будет подобрана
-- штатно.
--
-- ВНИМАНИЕ: статус выполнения в этой таблице — 'running' (check-констрейнт
-- миграции 20260325_0000: draft/running/paused/completed). Отдельного статуса
-- «ожидает» здесь нет вовсе: кнопка «Запустить» пишет сразу 'running', и
-- очередь выражена отсутствием аренды, а не статусом. Терминал успеха
-- называется 'completed'.
--
-- Идемпотентно: only where lease_until is null — повторный прогон не сдвигает
-- аренду, которую уже держит живой исполнитель.
update public.ai_campaigns
   set lease_until = now() + interval '5 minutes'
 where status = 'running'
   and lease_until is null;
