-- Кто сделал диалог лидом: ИИ по положительному триггеру или сотрудник руками.
--
-- Статус «Лид» ставят три пути: ИИ по положительному триггеру, кнопка
-- «Передать лида» и кнопка статуса «Лид» на карточке. На экране все три
-- выглядели одинаково. Метка автопересылки и плашка «Передан: лид» есть
-- только там, где у кампании задан чат пересылки, а у «АИ МОП» его нет, и
-- лид от ИИ ничем не отличался от лида, отмеченного оператором. Кто именно
-- нажал кнопку, не было видно и с чатом: имя оставалось только в журнале.
-- 08.10.2026 операторы попросили видеть «какие лиды переданы мною».
--
-- Поля описывают последнее действие «это лид»: ИИ или сотрудник, кто и когда.
-- При смене статуса с «Лид» на другой их не стираем: экран и фильтр смотрят
-- на них только у диалогов в статусе «Лид».
--
-- Старые лиды не размечаем — решение пользователя: метка только у тех, кто
-- станет лидом после выкладки. У прежних поля остаются пустыми.

alter table public.tg_outreach_dialogs
  add column if not exists lead_source text check (lead_source in ('ai', 'manual')),
  add column if not exists lead_marked_by uuid,
  add column if not exists lead_marked_by_name text,
  add column if not exists lead_marked_at timestamptz;

comment on column public.tg_outreach_dialogs.lead_source is
  'Кто сделал диалог лидом: ai — ИИ по положительному триггеру, manual — сотрудник (кнопка «Лид» или «Передать лида»). NULL — лид отмечен до 08.10.2026, метки нет.';
comment on column public.tg_outreach_dialogs.lead_marked_by is
  'Сотрудник портала (auth.users.id), отметивший лида руками. NULL у лидов от ИИ.';
comment on column public.tg_outreach_dialogs.lead_marked_by_name is
  'Имя сотрудника на момент действия — подпись на экране без лишнего запроса к профилям.';
comment on column public.tg_outreach_dialogs.lead_marked_at is
  'Когда диалог сделали лидом.';
