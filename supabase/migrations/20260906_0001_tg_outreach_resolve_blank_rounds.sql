-- Сколько кругов подряд аккаунт не смог найти ни одного ника из порции.
--
-- Telegram умеет «замораживать» аккаунт молча: юзернеймы перестают
-- резолвиться, а в ответ приходит обычное «нет такого пользователя». @SpamBot
-- про это молчит — он отвечает только про спам-блок, — кода ошибки нет, флага
-- в профиле нет. Отличить такой аккаунт от невезения с мёртвыми никами можно
-- только по истории: у исправного номера часть порции уходит, у замороженного
-- не находится ничего и так круг за кругом.
--
-- Счётчик такой истории уже был, но жил в памяти круга кампании. Круг
-- перезапускается — от штатной остановки, от передеплоя, от переподключения
-- аккаунтов, — и вместе с ним обнулялся счётчик. За 30 часов 06.09.2026 круг
-- ATOL-1 стартовал трижды, а до отдельного аккаунта доходил один-два раза за
-- запуск: порога в два пустых круга подряд не достигал никто. В результате
-- одиннадцать замороженных аккаунтов кампании неделями числились исправными,
-- на экране показывали безмолвное «молчит 4 дня» без причины и каждый круг
-- тратили время на заведомо безнадёжный резолв.
--
-- Поэтому счётчик переезжает в строку аккаунта: он про сам аккаунт, а не про
-- конкретный запуск воркера, и обязан переживать перезапуск.
--
-- 0 = последний круг с резолвом удался (или их ещё не было). Обнуляется при
-- первой же успешной отправке — она доказывает, что резолв работает.

alter table public.tg_outreach_accounts
  add column if not exists resolve_blank_rounds smallint not null default 0;

comment on column public.tg_outreach_accounts.resolve_blank_rounds is
  'Кругов подряд, где ни один ник порции не нашёлся, а @SpamBot ограничений не подтвердил. Признак тихой заморозки Telegram: на пороге аккаунт уходит на паузу с диагнозом. Обнуляется первой успешной отправкой.';
