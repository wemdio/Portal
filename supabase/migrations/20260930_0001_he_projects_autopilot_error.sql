-- ENG (Движок вертикалей, he_*): причина, по которой автопилот НЕ повёл
-- конвейер дальше, становится данными на строке проекта.
--
-- ЗАЧЕМ. Координатор автопилота (app/src/lib/hypothesisEngine/autopilotNext.ts)
-- различал ровно два исхода — «поставил» и «не понадобилось». Сбой ЧТЕНИЯ
-- состояния выглядел как второе: проект переставал двигаться, а в данных не
-- оставалось ничего, за что мог бы зацепиться автоматический реконсилер
-- (lib/hypothesisEngine/autopilotReconcile.ts) и чем кабинет мог бы объяснить
-- клиенту паузу. Теперь причина пишется сюда, и её снимает тот, кто доставит
-- пропущенную стадию.
--
-- КТО ИМЕННО СНИМАЕТ — НЕ РАСПИСАНИЕ, А НАСТРОЙКА УСТАНОВКИ. Ночной проход
-- (runHeAutopilotReconcilePass) идёт ТОЛЬКО там, где выставлен
-- HE_AUTOPILOT_RECONCILE; по умолчанию флаг не выставлен, и прохода нет вовсе.
-- На такой установке причину снимают ровно два события, и оба — не по
-- расписанию: нажатие клиентом «Start outreach» в кабинете (тот же
-- reconcileHeAutopilotProject, режим client — он и пишет причину, и снимает её)
-- и следующая успешная джоба chain или base_analyze, после которой координатор
-- воркера (enqueueAutopilotFollowups) перезаписывает колонку итогом дочейна.
-- Текст кабинета поэтому зовёт нажать кнопку и НЕ обещает возврата сам собой;
-- та же оговорка стоит в каждом файле волны, который упоминает ночной проход.
--
-- ЧТО В КОЛОНКЕ. ТОЛЬКО машинный токен из закрытого списка
-- HE_AUTOPILOT_PAUSE_REASONS: 'read_failed' (состояние не прочиталось),
-- 'enqueue_failed' (постановка отвергнута БД), 'letters_exhausted' (платные
-- прогоны генерации писем на это поколение анализа исчерпаны), 'stage_failed'
-- (оплаченная стадия упала, автоматически за неё не платим), 'setup_incomplete'
-- (вести нечего). Русской прозы, текста Postgres и имён таблиц здесь нет и быть
-- не должно: значение уезжает в английский кабинет проекцией, и текст ошибки в
-- такой колонке означал бы утечку кухни студии — ту самую, ради которой
-- he_projects.error в кабинет не отдаётся вовсе.
--
-- ПОЧЕМУ БЕЗ CHECK-ОГРАНИЧЕНИЯ. Список токенов живёт в коде и будет
-- пополняться раньше, чем сюда доедет следующая миграция; отвергнутая запись
-- при этом молча стоила бы кабинету сигнала (запись причины намеренно не
-- бросает ошибку — см. recordHeAutopilotPause). Неизвестный токен наружу не
-- уедет: читает колонку одна функция (toHeAutopilotPause), и всё, чего нет в
-- закрытом списке, она отбрасывает.
--
-- ПРАВА. Новых ОБЪЕКТОВ (таблиц, функций) миграция не создаёт — только
-- колонки, а они наследуют права своих таблиц (тот же довод, что в
-- 20260926_0001_he_emails_per_company.sql). Поэтому ни `grant`, ни поимённого
-- `revoke` здесь нет: правилам app/src/lib/migrationLint.ts проверять в этом
-- файле нечего. Сама he_projects заперта от anon/authenticated в
-- 20260920_0001_he_rls_lockdown.sql и остаётся запертой.
--
-- NULL = поведение до этой миграции: паузы нет. Ни один существующий проект,
-- база или запущенная кампания не меняются; ручной RU-инструмент специалиста
-- /tools/hypothesis-engine колонку не читает и не пишет.
--
-- Миграция идемпотентна: `add column if not exists` можно гонять повторно.

alter table public.he_projects
  add column if not exists autopilot_error text;

alter table public.he_projects
  add column if not exists autopilot_error_at timestamptz;

comment on column public.he_projects.autopilot_error is
  'ENG: машинный токен причины, по которой автопилот не повёл конвейер дальше (NULL = паузы нет). Закрытый список — HE_AUTOPILOT_PAUSE_REASONS в app/src/lib/hypothesisEngine/autopilotNext.ts.';
comment on column public.he_projects.autopilot_error_at is
  'ENG: когда записана текущая причина паузы автопилота (NULL = паузы нет).';
