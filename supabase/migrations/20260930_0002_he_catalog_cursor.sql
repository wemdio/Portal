-- ENG («Движок вертикалей», he_*): место, до которого вертикаль разобрала свой
-- срез каталога, и план источников, которому эти закладки принадлежат.
--
-- ЗАЧЕМ. Ночной добор ENG (worker/heAutoPipelineCron.ts → стадия base_collect с
-- payload.refill) заводит на каждую ночь НОВУЮ строку he_bases с пустым
-- collect_info. Отсюда два следствия, которые эта таблица и снимает:
--   1. каждая ночь читала срез С ПЕРВОЙ СТРОКИ, набирала те же компании и
--      выбрасывала их на мёрдже как уже собранные — ноль новых компаний при
--      полностью потраченном проходе;
--   2. каждая ночь заново строила план источников, а это платный вызов модели
--      (роль bulk) плюс проба среза (роль gate).
--
-- ПОЧЕМУ НЕ КОЛОНКА В he_bases И НЕ ПОЛЕ В collect_info. У V2 задача сбора
-- переоткрывается внутри ТОЙ ЖЕ базы, поэтому там закладка живёт в состоянии
-- задачи. У V1 задача диспатчится один раз за базу, а добор заводит новую базу:
-- закладка в collect_info не имела бы ни писателя (базу больше не трогают), ни
-- читателя (следующая база её не видит). Ключ поэтому — ВЕРТИКАЛЬ, а строка
-- переживает любое число баз.
--
-- ПОЧЕМУ ПЛАН И ЗАКЛАДКИ В ОДНОЙ СТРОКЕ. Ключ закладки — источник + хеш ЕГО
-- фильтров (app/src/lib/hypothesisEngine/catalogCursor.ts, heCatalogSliceKey),
-- а фильтры приходят из плана. Пока план каждую ночь новый, хеш каждую ночь
-- другой, и ни одна закладка не совпадает — стор был бы бесполезен. План и его
-- закладки поэтому неразделимы: сменился вход планировщика — план перестроен, и
-- закладки чужих срезов выброшены ТОЙ ЖЕ записью.
--
-- ЧТО В bookmarks. jsonb-карта «<источник>:<хеш фильтров>» → {id, inserted_at?,
-- at}. Закладку между сборками стадия держит ТОЛЬКО у pdl_companies:
--   * pdl_companies — одноразовый bulk-дамп (19,5 млн строк), id text, выдача
--     RPC строго order by id, строки на месте не переписываются → закладка по
--     id;
--   * funded_companies и eng_hiring_cache — живые фиды, и их строки
--     переписываются НА МЕСТЕ с прежним created_at (poll-sec-daily и
--     обогащение из PDL у funded, ночной ingest jobhive у eng_hiring).
--     Закладка по времени вставки перешагивала бы строку, которую фильтр среза
--     в ту ночь не вернул, и после переписывания её не прочитал бы уже никто.
--     Поэтому закладки между сборками у них нет: каждая сборка читает срез с
--     начала, уже собранные компании отсеиваются на выборке (stages/
--     baseCollect.ts, «ЧТЕНИЕ КАТАЛОГА С ЗАКЛАДКОЙ»). Ключи этих источников,
--     записанные прежним кодом, стадия не читает.
-- Значения карты пишет и читает только стадия; схемы у jsonb нет намеренно —
-- набор ключей закладки зависит от источника и будет пополняться.
--
-- КУДА ЗАКЛАДКА ДВИГАЕТСЯ — записано в коде (блок «ЧТЕНИЕ КАТАЛОГА С
-- ЗАКЛАДКОЙ» в stages/baseCollect.ts), здесь только следствие для данных:
-- закладка отмечает конец префикса строк, с которыми у проекта ПОКОНЧЕНО, а не
-- конец прочитанного. Поэтому она может отставать от последней прочитанной
-- строки, и это нормальное состояние, а не рассинхрон.
--
-- КОНКУРЕНЦИЯ. Писателей на строку не больше одного по построению: partial
-- unique index he_bases_one_collecting_per_vertical
-- (20260730_0005_he_bases_collecting_unique.sql) допускает одну собирающуюся
-- базу на вертикаль, а закладки пишет только собирающаяся база. Поэтому
-- read-modify-write карты закладок здесь безопасен без блокировок.
--
-- БЕЗ МИГРАЦИИ СБОРКА НЕ ПАДАЕТ, НО ЧИТАЕТ УЖЕ ПО-НОВОМУ — и это разные вещи.
-- Отказ чтения стора трактуется как «закладок нет»: запись не делается, в лог
-- стадии уходит строка с причиной, сборка идёт дальше. Однако РЕЖИМ чтения
-- каталога стадия выбирает по РЫНКУ, а не по доступности стора: при
-- market='us' funded всё равно читается keyset'ом по времени вставки внутри
-- прогона (eng_hiring — свежими вакансиями вперёд и только по
-- source='jobhive'), просто с первой строки. Поэтому порядок выката
-- обязателен: СНАЧАЛА эта миграция, ПОТОМ код.
--
-- ПОДДЕРЖИВАЮЩИЙ ИНДЕКС funded (ниже) — ровно та причина, по которой порядок
-- обязателен: keyset по времени вставки без него уводит страницу в сортировку
-- всей отфильтрованной выборки (тот же класс отказа, из-за которого для pdl
-- завели RPC search_pdl_companies — 58s+ и 504 у Kong). Под eng_hiring индекса
-- здесь нет: его ENG-чтение по времени вставки не сортирует (блок индекса
-- ниже).
-- Индекс на СПРАВОЧНОЙ таблице (не he_*), своих прав не имеет и живёт правами
-- своей таблицы; новых ОБЪЕКТОВ, требующих grant/revoke по правилам
-- app/src/lib/migrationLint.ts, кроме he_catalog_cursors, миграция не создаёт.
-- Построение берёт короткий SHARE-лок на запись в funded_companies: её пишут
-- ingest-скрипты (поштучно), читатели не задеваются.
-- Если к моменту применения таблица вырастет настолько, что пауза записи станет
-- заметна, индекс можно собрать вручную с `concurrently` ДО деплоя — тогда
-- `if not exists` здесь просто ничего не сделает.

create table if not exists public.he_catalog_cursors (
  vertical_id     uuid primary key references public.he_verticals(id) on delete cascade,
  -- Рынок, для которого построен план: промпты планировщика RU и EN разные, и
  -- один план на два рынка невозможен. Хранится для прямых запросов staff —
  -- код сверяет рынок хешем plan_key, в который market входит.
  market          text not null,
  -- Переиспользуемый план источников (HeSourcePlan) и хеш ВХОДА планировщика,
  -- по которому он построен. Не совпал хеш — план строится заново за деньги.
  plan            jsonb,
  plan_key        text,
  plan_at         timestamptz,
  -- Когда ПЛАТНОЕ расширение плана последний раз ничего не дало. Живёт рядом с
  -- планом, а не в базе: базы у каждой ночи свои, и запись «не получилось» в
  -- collect_info одной базы не мешает следующей ночи купить тот же отказ снова.
  widen_failed_at timestamptz,
  -- Закладки срезов: {"<source>:<filters_hash>": {id, inserted_at?, at}}.
  bookmarks       jsonb not null default '{}'::jsonb,
  created_at      timestamptz not null default now(),
  updated_at      timestamptz not null default now()
);

comment on table public.he_catalog_cursors is
  'ENG: план источников вертикали + закладки её срезов каталога (между сборками их держит только pdl). Одна строка на вертикаль; пишет только собирающаяся база.';
comment on column public.he_catalog_cursors.bookmarks is
  'Карта «источник:хеш фильтров» → закладка {id, inserted_at?, at}. Отмечает конец префикса строк, с которыми у проекта покончено, а НЕ конец прочитанного.';
comment on column public.he_catalog_cursors.widen_failed_at is
  'Время последнего БЕЗРЕЗУЛЬТАТНОГО платного расширения плана. Пока оно моложе окна остывания, расширение не покупается снова.';
comment on column public.he_catalog_cursors.plan_key is
  'Хеш входа планировщика (имя/описание вертикали, синонимы, отобранные гипотезы, типы компаний, рынок). Совпал — план берётся отсюда вместо платного вызова модели.';

-- ─── Права ───────────────────────────────────────────────────────────────
-- Движковые таблицы (he_*/ve_*) браузер напрямую не читает — только API и
-- воркер под service_role. ALTER DEFAULT PRIVILEGES выдаёт anon/authenticated
-- права на каждую новую таблицу раннера миграций, поэтому отзываем их
-- ПОИМЁННО (20260920_0001_he_rls_lockdown.sql, линт app/tests/migrations/
-- grants.test.ts).

alter table public.he_catalog_cursors enable row level security;
revoke all privileges on table public.he_catalog_cursors from public, anon, authenticated;
grant all on table public.he_catalog_cursors to service_role, postgres;

do $$ begin
  if exists (select 1 from pg_catalog.pg_roles where rolname = 'readonly') then
    execute 'grant select on public.he_catalog_cursors to readonly';
  end if;
end $$;

-- ─── Поддерживающий индекс справочника ───────────────────────────────────
-- Keyset по времени вставки: '(created_at, id) > курсор' + order by
-- created_at, id — у funded это курсор страниц ВНУТРИ одного прогона.
-- Столбцы фильтров у среза разные (source/country/industry выбирает
-- планировщик), поэтому индекс по ключу СОРТИРОВКИ, а не составной с
-- фильтрами: он даёт упорядоченный проход, а фильтр отсеивает на лету.
--
-- eng_hiring_cache здесь индекса не получает: ENG-чтение eng_hiring по времени
-- вставки не сортирует — оно идёт свежими вакансиями вперёд (order by
-- published_at desc, id; фильтры source/country_code/published_at — столбцы
-- индекса из 20260617_0001_eng_hiring_cache_filter_index.sql). Индекс по
-- created_at читателя не имел бы, а ночной upsert jobhive переписывает каждую
-- строку фида (cache_fetched_at индексирован, HOT-обновления нет) и платил бы
-- за него вставкой в индекс на каждую строку каждую ночь.

create index if not exists idx_funded_created_id
  on public.funded_companies (created_at, id);
