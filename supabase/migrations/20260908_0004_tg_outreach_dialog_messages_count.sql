-- Число сообщений в диалоге отдельной колонкой — чтобы по нему можно было
-- фильтровать.
--
-- Список диалогов показывает «1 сообщ.» / «6 сообщ.», считая длину `messages`
-- уже на экране. Отобрать по этому числу так нельзя: фильтр применяется к
-- странице выборки, а не ко всей кампании, и «покажи диалоги с ответом» на
-- третьей странице выдало бы не то.
--
-- Оператору нужны ровно два случая: «мы написали и тишина» (одно сообщение) и
-- «завязался разговор» (два и больше). Первых накапливаются сотни, и они
-- прячут те немногие, ради которых экран и открывают.
--
-- Колонка вычисляемая, а не заполняемая приложением: значение обязано совпадать
-- с содержимым `messages` всегда, а любое место, где мы пишем диалог и забыли
-- обновить счётчик, породило бы тихое расхождение. Таблица маленькая (около
-- четырёх тысяч строк), перезапись при добавлении мгновенна.

alter table public.tg_outreach_dialogs
  add column if not exists messages_count integer
    generated always as (coalesce(jsonb_array_length(messages), 0)) stored;

comment on column public.tg_outreach_dialogs.messages_count is
  'Сколько сообщений в переписке. Вычисляется из messages, вручную не пишется. Кормит фильтр «1 сообщение / 2 и больше» на вкладке «Диалоги».';

-- Фильтр всегда идёт вместе с кампанией, поэтому индекс составной.
create index if not exists tg_outreach_dialogs_messages_count_idx
  on public.tg_outreach_dialogs (campaign_id, messages_count);
