-- Отметка о том, что контакт уже ушёл менеджеру сам, по положительному триггеру.
--
-- Триггерная фраза в ответе модели пересылает переписку в чат менеджера, ставит
-- диалогу статус «Лид» и выключает отправку. В интерфейсе от всего этого
-- оставался только статус «Лид» — а его точно так же ставит оператор руками.
-- Отличить «человека уже отдали» от «кто-то отметил статус» было нельзя, и
-- второй разговор о том же человеке начинался ровно отсюда.
--
-- Плашка ручной передачи не помогала: она живёт на строках
-- `tg_outreach_lead_forwards`, а их создаёт только кнопка. Автопересылка следа
-- в базе не оставляла вовсе.
--
-- Поля кладём в сам диалог, а не в `tg_outreach_lead_forwards`. Та таблица —
-- очередь ручной передачи с правилом «одна передача на диалог»; запись туда
-- погасила бы кнопки. А гасить их не нужно: автопересылка отправляет голую
-- переписку, без карточки «кто это, из какой базы и по какому офферу пришёл,
-- каким аккаунтом вели», и досылать менеджеру контекст иногда требуется.
-- Оператор просто должен знать, что контакт уже у адресата.
--
-- Отмечаем только положительный триггер. Отрицательный тоже пересылает, но в
-- другой чат и по другому поводу — отметка «ушёл менеджеру» про него солгала бы.

alter table public.tg_outreach_dialogs
  add column if not exists auto_forwarded_at timestamptz,
  add column if not exists auto_forward_chat text,
  add column if not exists auto_forward_error text;

comment on column public.tg_outreach_dialogs.auto_forwarded_at is
  'Когда переписка ушла менеджеру автоматически, по положительному триггеру. NULL — не уходила.';
comment on column public.tg_outreach_dialogs.auto_forward_chat is
  'Куда ушла автопересылка. Снимок настройки на момент отправки: смена чата в кампании не переписывает историю.';
comment on column public.tg_outreach_dialogs.auto_forward_error is
  'Причина, по которой автопересылка не ушла. Раньше сбой оседал строкой в журнале кампании, а диалог снаружи выглядел успешным.';

-- Старые диалоги не трогаем.
--
-- Отметить их можно было бы только реконструкцией по косвенным признакам —
-- статус `lead` плюс триггерная фраза в ответе бота. Но это догадка, а не
-- факт: если чат пересылки завели уже после того, как триггер отработал,
-- диалог оказался бы помечен ушедшим, никуда не уходив. Пустая отметка честнее
-- правдоподобной выдумки: про диалоги до этой миграции портал просто не знает,
-- уходили они менеджеру или нет.
