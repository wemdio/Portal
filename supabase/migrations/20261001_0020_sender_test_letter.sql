-- Тестовое письмо себе из формы кампании «Рассылки» (01.10.2026).
--
-- Проверить письмо до запуска можно было только предпросмотром на экране — а
-- увидеть, как оно выглядит в почте (ссылки, переносы, подпись, спам-папка),
-- было негде.
--
-- Тест — то же произвольное письмо с ящика кампании, что и ручной ответ
-- оператора (миграция 20260922_0005), но без переписки: кампании может ещё не
-- быть (письмо проверяют до создания), и получателя в базе нет. Заводить под
-- это вторую очередь незачем — у sender_manual_messages уже есть и claim по
-- адресу отправки, и ретраи, и статусы, а SMTP всё равно обязан ходить только
-- с sender-хоста, не из API-процесса портала. Поэтому привязки к кампании и
-- получателю становятся необязательными.
--
-- Экран переписки и разбор по шагам читают эту таблицу только с фильтром по
-- recipient_id, поэтому строки теста им не видны.

alter table public.sender_manual_messages
  alter column campaign_id drop not null,
  alter column recipient_id drop not null;

comment on column public.sender_manual_messages.recipient_id is
  'Null for test letters: the operator checks a campaign letter on their own address, outside any thread.';
