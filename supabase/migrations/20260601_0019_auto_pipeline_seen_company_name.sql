-- Авто-пайплайн: храним ОЧИЩЕННОЕ название компании в seen-строках.
--
-- Требование: у каждого готового к аутричу контакта есть email + название +
-- сайт, причём название ПОЧИЩЕНО тем же AI, что кнопка «Очистить названия».
-- Раньше чистка шла только на этапе отправки в кампанию (боевой запуск), и в
-- dry-run в seen лежало сырое hh_employer_name (ООО "..." с кавычками). Теперь
-- чистка идёт ПРЯМО в чанк-цикле для would-be-ready строк (валидная почта +
-- имя + сайт) — и в dry-run, и в боевом — и результат пишется сюда. Это даёт
-- честное измерение качества в dry-run: дашборд/выгрузка показывают готовое имя.
--
-- hh_employer_name остаётся СЫРЫМ (исходное имя из ФНS/HH) для справки.
-- NULL в company_name = строка не готова (нет валидной почты/сайта) либо AI
-- недоступен (cleanCompanyNames при сбое отдаёт исходное, но мы кладём NULL
-- только для не-ready строк).

ALTER TABLE public.client_auto_pipeline_seen_employers
  ADD COLUMN IF NOT EXISTS company_name text;

COMMENT ON COLUMN public.client_auto_pipeline_seen_employers.company_name IS
  'Очищенное (AI, как кнопка «Очистить названия») название для would-be-ready строк (валидная почта + имя + сайт). Заполняется и в dry-run, и в боевом. NULL = строка не готова. hh_employer_name остаётся сырым.';
