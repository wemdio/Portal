-- Страна аккаунта, названная при загрузке партии.
--
-- Страну аккаунта видно по телефону, но телефона у залитых tdata нет до первого
-- подключения к Telegram. А подключаться положено через прокси той же страны —
-- иначе Telegram видит несовпадение гео. Получался круг: чтобы узнать страну,
-- нужен прокси, а чтобы выбрать прокси, нужна страна.
--
-- Круг разрывается там, где он и не должен был возникнуть: оператор знает
-- страну при покупке — он выбирает её в объявлении («+998 Узбекистан»).
-- Портал просто не спрашивал.
--
-- Поле подсказочное. Как только настоящий телефон прочитан, страна считается по
-- нему: сказанное при загрузке — заявление продавца, а номер — факт.

alter table public.tg_outreach_accounts
  add column if not exists country_code text;

comment on column public.tg_outreach_accounts.country_code is
  'Страна партии, названная оператором при загрузке (ISO-код, например UZ). Нужна, чтобы подобрать прокси до первого подключения. После чтения телефона страна берётся из номера.';
