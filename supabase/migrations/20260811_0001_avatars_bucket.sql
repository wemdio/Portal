-- Бакет `avatars` — публичное хранилище аватарок аккаунтов TG Outreach и пула.
--
-- Бакет был заведён руками в облачном Supabase и в репозитории никогда не
-- описывался, поэтому при переезде на self-hosted 22-23.07.2026 он не приехал:
-- storage API на проде отвечает «Bucket not found» ровно так же, как на любое
-- выдуманное имя. Из-за этого загрузка аватарки молча падала, а в аккаунт
-- писалась пустая ссылка — оператор видел «в Telegram нет аватарки» у аккаунтов
-- с фото.
--
-- Пишут в бакет только серверные ручки служебным ключом (он обходит RLS),
-- поэтому политик на запись здесь нет: публичным нужно быть только чтению —
-- ссылка на картинку идёт прямо в <img> в списке аккаунтов.
insert into storage.buckets (id, name, public)
values ('avatars', 'avatars', true)
on conflict (id) do update set public = excluded.public;
