-- Когда круг рассылки в последний раз брал аккаунт в работу.
--
-- 28.08.2026 воркер tg-outreach падал по три раза за день, а анти-флуд пауза
-- между аккаунтами доходит до десяти минут. Круг всегда начинался с начала
-- списка, поэтому каждый новый процесс успевал обработать два-три аккаунта и
-- умирал. Хвост списка не работал ни разу: у ATOL-1 из двенадцати аккаунтов
-- писали двое, а свежая база на триста контактов сутки простояла с нулём
-- отправок.
--
-- Эта метка и есть позиция в круге. Отдельного «указателя» не заводим: «когда
-- до аккаунта дошли в последний раз» переживает перезапуск, переезд на другой
-- воркер и добавление аккаунтов в середину списка, а указатель на индекс — нет.
--
-- NULL = до аккаунта не доходили ни разу; такие идут первыми, что верно и по
-- смыслу, и для только что загруженной партии.

alter table public.tg_outreach_accounts
  add column if not exists last_cycle_at timestamptz;

comment on column public.tg_outreach_accounts.last_cycle_at is
  'Когда боевой круг в последний раз брал аккаунт в работу. Задаёт порядок обхода: первым идёт тот, до кого дольше всех не доходили. NULL — не брали ни разу.';

-- Воркер сортирует по этой колонке на каждом круге и пишет её после каждого
-- аккаунта. Частичного индекса достаточно: выборка всегда ограничена одной
-- кампанией и только включёнными аккаунтами.
create index if not exists tg_outreach_accounts_cycle_order_idx
  on public.tg_outreach_accounts (campaign_id, last_cycle_at nulls first)
  where is_active;
