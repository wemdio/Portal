-- Чаты-источники гипотезы: откуда для этой базы собирали контакты.
--
-- Отчёт по договору спрашивает «Кол-во обработанных чатов» и «Канал/чат» по
-- каждому офферу. Портал не мог ответить ни на то, ни на другое: в файле базы,
-- который реально загружают, всего две колонки — юзернейм и текст сообщения, —
-- и откуда взят человек, там не написано (у всех 600 контактов ATOL поле `raw`
-- пустое). Обе колонки отчёта заполнялись руками, а «обработанные чаты» портал
-- и вовсе брал из задач парсера, не привязанных к кампании: у специалиста,
-- ведущего двух клиентов, чаты одного попадали в отчёт другому.
--
-- Просить колонку в файле на каждую строку — лишняя работа: чатов на гипотезу
-- три-четыре, а контактов триста. Поэтому список живёт у базы: ввели один раз
-- при заведении гипотезы, и обе колонки отчёта считаются сами.
--
-- Текст, а не массив: оператор вставляет ссылки списком, по одной в строке,
-- ровно как копирует их из парсера. Разбор — на стороне приложения, там же, где
-- нормализация «t.me/x» и «@x» к одному чату.

alter table public.tg_outreach_bases
  add column if not exists source_chats text not null default '';

comment on column public.tg_outreach_bases.source_chats is
  'Чаты, из которых собраны контакты этой базы: по одной ссылке в строке. Кормит «Кол-во обработанных чатов» и «Канал/чат» в отчёте по договору.';
