-- Сводка обновлений портала показывается внутри портала, а не только в телеграме.
--
-- Сами сводки уже копятся в changelog_digests — их пишет сервис changelog-bot
-- (services/changelog-bot), он же создаёт таблицу. Здесь мы её не заводим, а
-- только связываем с уведомлениями портала.
--
-- Отдельной таблицы «кто что прочитал» намеренно нет. Прочитанность уже есть у
-- уведомлений, и заводить рядом второй такой же признак значит получить два
-- источника правды, которые разойдутся: человек закрыл модалку, а колокольчик
-- всё ещё считает сводку непрочитанной.
alter table public.notifications
  add column if not exists changelog_digest_id bigint;

-- Одному человеку — одна запись на сводку. Уведомления заводятся лениво, при
-- заходе на портал, поэтому без уникальности повторный заход плодил бы дубли.
--
-- Индекс намеренно НЕ частичный, хотя колонка пустая у всех остальных
-- уведомлений. Postgres не считает NULL равными друг другу, так что обычные
-- уведомления такому индексу не мешают; а вот с частичным индексом вставка
-- «добавь, если ещё нет» не работает — ON CONFLICT требует индекс без условия.
create unique index if not exists idx_notifications_changelog_unique
  on public.notifications (user_id, changelog_digest_id);

comment on column public.notifications.changelog_digest_id is
  'Сводка обновлений портала (changelog_digests.id), из которой сделано уведомление. NULL у всех остальных уведомлений.';
