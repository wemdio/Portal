-- Отлёжка после смены имени или ника — своим полем, а не общим кулдауном.
--
-- Правило из руководства TgNinja: после смены имени или аватарки дать аккаунту
-- отлежаться. Для Telegram свежепереименованный аккаунт, тут же ушедший писать
-- незнакомым, — характерный признак подготовки к рассылке, и платим за это тем
-- самым бюджетом в тридцать писем на аккаунт.
--
-- Почему не `cooldown_until`. Тот означает «Telegram нас ограничил, аккаунт
-- трогать нельзя» и останавливает любую активность. Здесь смысл другой:
-- аккаунту нельзя в БОЕВУЮ рассылку, а греться между своими — можно и нужно,
-- именно этим отлёжка и наполняется. Свалив их в одно поле, мы бы запретили
-- ровно то поведение, ради которого пауза и делается.
--
-- NULL или прошедшая дата — аккаунт свободен.

alter table public.tg_outreach_accounts
  add column if not exists profile_rest_until timestamptz;

comment on column public.tg_outreach_accounts.profile_rest_until is
  'До этого момента аккаунт не берётся в боевую рассылку после смены имени или ника. Прогрев между своими аккаунтами при этом разрешён. NULL — свободен.';

create index if not exists tg_outreach_accounts_profile_rest_idx
  on public.tg_outreach_accounts (campaign_id, profile_rest_until)
  where profile_rest_until is not null;
