-- Индекс под поиск курса из витрины expenses_v.
--
-- Первичный ключ fx_rates идёт (rate_date, currency), а витрина ищет
-- «последний курс этой валюты не позже даты операции»: равенство по currency
-- плюс диапазон по rate_date. С порядком колонок в PK равенство по currency
-- не становится индексным условием. Здесь порядок обратный, под этот запрос.

create index if not exists idx_fx_rates_currency_date
  on public.fx_rates (currency, rate_date desc);

-- ЗАМЕЧЕНО ПРИ РЕВЬЮ, НЕ ЛЕЧИТСЯ ИНДЕКСОМ.
--
-- Витрина отдаёт occurred_on_msk = (occurred_at at time zone 'Europe/Moscow')::date,
-- и дашборд фильтрует период именно по нему. Функциональный индекс на это
-- выражение создать нельзя: AT TIME ZONE над timestamptz помечен STABLE, а не
-- IMMUTABLE, и Postgres такой индекс отвергает.
--
-- Следствие: фильтр по периоду идёт построчно. На ожидаемых объёмах (тысячи
