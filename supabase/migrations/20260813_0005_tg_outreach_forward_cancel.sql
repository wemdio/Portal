-- Отмена передачи, пока она не ушла.
--
-- Кнопка в интерфейсе не отправляет, а ставит задачу: живое соединение с
-- Telegram есть только у воркера, и он заберёт её, когда дойдёт до аккаунта в
-- круге. Между нажатием и отправкой проходят часы — всё это время ошибочную
-- задачу ещё можно остановить, но снять её из портала было нечем.
--
-- Инцидент 13.08.2026: шесть лидов поставили в очередь по ошибке, и снимать их
-- пришлось запросом в базу на проде, пока кампания стояла остановленной.
--
-- Почему отдельный статус, а не 'failed': сорвавшаяся передача — поломка,
-- которую чинят и повторяют, снятая — осознанное решение человека. Свалить их
-- в одну кучу значит показывать оператору «не отправлено: отменил Егор» как
-- аварию и считать отменённые в статистике сбоев.
--
-- Новый статус безопасен для всего, что уже написано: и уникальный индекс
-- «одна передача на диалог», и воронка дашборда, и очередь воркера перечисляют
-- активные статусы поимённо ('pending', 'sent'), поэтому снятая передача нигде
-- не считается живой — и не мешает передать этот диалог заново.

alter table public.tg_outreach_lead_forwards
  drop constraint if exists tg_outreach_lead_forwards_status_check;

alter table public.tg_outreach_lead_forwards
  add constraint tg_outreach_lead_forwards_status_check
  check (status in ('pending', 'sent', 'failed', 'cancelled'));
