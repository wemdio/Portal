-- OutreachOS: источник SuperJob убран целиком.
--
-- SuperJob заблокировал наше API-приложение на своей стороне: любой запрос с
-- ключом, включая публичный /catalogues/, отвечает
-- `403 {"error":{"code":403,"message":"Ваше приложение API заблокировано!"}}`.
-- Проверено 15.08.2026 с прод-сервера ключом самого воркера; тот же запрос без
-- ключа получает обычное «передайте ключ приложения», то есть ни IP, ни сеть ни
-- при чём — заблокировано именно приложение. Ключ валиден по формату и на месте.
-- Кодом это не лечится, а источник был fail-open (ошибка → строка INFO в логе и
-- продолжаем на одном HH), поэтому три прогона подряд молча шли без него.
--
-- Снятие колонок безопасно и для ещё не обновлённого образа: loadOutreachOsConfig
-- читает конфиг через `select('*')` и трактует поле как `row.superjob_enabled
-- === true`. Отсутствующая колонка даёт undefined → false → источник выключен.
-- Отдельная мутация «выключить флаг» поэтому не нужна: миграция выключает его
-- по построению, в каком бы порядке ни встали миграции и новый образ.
--
-- Если SuperJob когда-нибудь разблокирует приложение, интеграция поднимается из
-- истории: код источника жил в app/src/lib/outreachos/superjobSource.ts, колонки
-- заводила миграция 20260806_0003_outreachos_superjob.sql.
ALTER TABLE public.outreachos_pipeline_config
  DROP COLUMN IF EXISTS superjob_enabled,
  DROP COLUMN IF EXISTS superjob_catalogues;

NOTIFY pgrst, 'reload schema';
