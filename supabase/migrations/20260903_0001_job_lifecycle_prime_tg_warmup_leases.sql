-- Выдать аренду прогонам прогрева Telegram, которые уже идут на момент переезда
-- воркера portal-worker-tg-outreach на единый жизненный цикл (companion к
-- 20260902_0001, продолжение 20260902_0003 … 20260902_0008;
-- spec: docs/superpowers/specs/2026-09-02-job-lifecycle-design.md).
--
-- Отдельным файлом, а не дописыванием в 0008: применённые миграции трекаются
-- по ИМЕНИ файла, без контрольной суммы (app/scripts/db/ensureDatabase.js). На
-- базе, где 0008 уже применена, дописанные в неё строки просто никогда не
-- выполнятся, и никто об этом не сообщит. Своя миграция на фазу — это правило
-- записано в самой 0003.
--
-- Зачем: захват «истёкшей» аренды считает lease_until is null свободной
-- строкой. Значит, прогон, оставленный в работе СТАРЫМ контейнером (у него
-- аренды нет вовсе), стал бы добычей первой же новой реплики на первом же
-- опросе. Ограждение жетоном не даст испортить саму строку прогона, но цена
-- здесь не в переигранной работе: тело прогрева подключает к Telegram все
-- аккаунты кампании (до дюжины MTProto-сессий), и второе соединение поверх
-- живого — это AUTH_KEY_DUPLICATED; три подряд, и gramClient.ts выключает
-- аккаунт насовсем (is_active = false), а восстановление — только ручным
-- перевыпуском сессии с телефона. Плюс дубли переписок: оба исполнителя вели
-- бы один и тот же диалог теми же двумя аккаунтами.
--
-- Пять минут — с запасом больше аренды прогрева (TG_WARMUP_LEASE_SECONDS,
-- 180 с): живой исполнитель успеет продлить её на ближайшем тике продления
-- (аренда/3 = 60 с), а брошенный прогон истечёт сам и будет подобран штатно.
--
-- ВНИМАНИЕ: статус выполнения в этой таблице — 'running' (check-констрейнт
-- миграции 20260803_0006: pending/running/finished/stopped/failed). Терминал
-- успеха здесь называется 'finished', а не 'completed'/'done'; условие по ним
-- не нашло бы ни одной строки и тихо ничего не сделало бы.
--
-- Строки в 'pending' намеренно не трогаем: у них нет исполнителя, их берут
-- обычным путём захвата по статусу, и аренда им только помешала бы.
--
-- Идемпотентно: only where lease_until is null — повторный прогон не сдвигает
-- аренду, которую уже держит живой исполнитель.
update public.tg_outreach_warmup_runs
   set lease_until = now() + interval '5 minutes'
 where status = 'running'
   and lease_until is null;
