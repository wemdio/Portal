-- Системный промпт генератора персонализированных ответов — в глобальных
-- настройках, а не только в коде.
--
-- Правила ответа (как разбирать реплику лида, структура письма, длина, что
-- нельзя) жили в lib/replyPersonalization/promptRules.ts, и любая правка
-- формулировки шла через разработчика и деплой. Теперь админ правит их на
-- экране «Глобальные настройки ответов».
--
-- Пустая строка = стандартные правила из кода (UNIVERSAL_REPLY_RULES): так
-- улучшения в коде продолжают доезжать до всех, пока админ не задал своё.
-- Читать и менять поле может только роль admin — проверка в API-роуте.

alter table public.reply_personalization_global_kb
  add column if not exists system_prompt text not null default '';

comment on column public.reply_personalization_global_kb.system_prompt is
  'Системный промпт генератора ответов (правила письма). Пусто — стандартный из кода (promptRules.ts). Правит только admin.';
