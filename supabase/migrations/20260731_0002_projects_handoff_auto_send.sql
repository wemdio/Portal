-- Пер-проектный тумблер «автопередача без подтверждения в TG».
-- Кнопка «Передать клиенту» в TG-чате была временным контролем текстов ИИ.
-- После введения легенды-дословно и минимальной адаптации с запретами часть
-- проектов готова к полному авто: лид и клиент получают письмо сразу при
-- квалификации, без нажатия кнопки спецом. OFF (дефолт) — как было: карточка
-- с кнопкой, отправка только ответственным спецом.
ALTER TABLE public.projects
  ADD COLUMN IF NOT EXISTS handoff_auto_send boolean NOT NULL DEFAULT false;

COMMENT ON COLUMN public.projects.handoff_auto_send IS
  'ON: передача лида клиенту отправляется автоматически без кнопки-подтверждения спеца в TG. OFF (дефолт): требуется нажатие кнопки ответственным спецом.';
