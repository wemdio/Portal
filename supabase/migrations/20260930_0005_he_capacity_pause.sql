-- ENG («Движок вертикалей», he_*): переполненный воркспейс рассыльщика
-- durable-останавливает ночной добор ПРОЕКТА, и вернуть его может только
-- человек — явной кнопкой в staff-инструменте.
--
-- ЗАЧЕМ. Ночной добор (worker/heAutoPipelineCron.ts → lib/hypothesisEngine/
-- autoPipeline.ts) каждую ночь ставит платную refill-сборку: план источников,
-- релевант-гейт, краул сайтов, SMTP-проба каждого адреса. Отправить собранное
-- некуда, если у воркспейса Instantly кончилось место под контакты. До этой
-- миграции такое знание жило РОВНО ОДНУ НОЧЬ:
--   * предполёт ёмкости (autoPipeline.ts) спрашивает /workspace-billing/
--     plan-details и при нуле остатка сборку не ставит — но только пока ключ
--     ИМЕЕТ право читать биллинг. Без права (403) ответ «не знаем», и предполёт
--     молчит;
--   * тогда переполнение обнаруживает САМ ДОЛИВ, отказом провайдера на
--     /leads/add (stages/baseCollectRefill.ts, error_kind='instantly_capacity')
--     — то есть ПОСЛЕ оплаченной сборки. Этот факт нигде не сохранялся, и
--     следующая ночь покупала ту же сборку заново. Каждую ночь, пока место не
--     освободится.
-- Колонки ниже — место, где факт живёт дольше ночи.
--
-- ПОЧЕМУ КОЛОНКИ У he_auto_pipeline_configs, А НЕ У he_auto_pipeline_runs.
-- Строка прогона — это ночь; пауза обязана пережить ночь, иначе она не пауза.
-- Конфиг — единственная строка проекта, которая живёт между ночами
-- (project_id unique, 20260804_0005), и он же — то, что читает тик крона ДО
-- любых денег. Состояния «решили не собирать» в he_auto_pipeline_runs.status
-- нет, и заводить его значило бы объявлять намеренную экономию прогоном.
--
-- СЧЁТЧИК ЁМКОСТИ — ВОРКСПЕЙСНЫЙ, И ЭТО ГЛАВНОЕ О ЧЁМ МОЛЧАТЬ НЕЛЬЗЯ.
-- total_lead_limit/current_lead_count у Instantly считаются на ВЕСЬ воркспейс
-- аккаунта, а не на кампанию и не на клиента: лиды RU-клиентов, сидящих в том
-- же instantly-аккаунте, входят в тот же знаменатель. Поэтому ENG-проект может
-- быть поставлен на паузу из-за нагрузки, которую он не создавал. Текст
-- причины (refill_pause_reason) обязан называть это вслух — его читает
-- сотрудник, который решает, чистить воркспейс или возобновлять.
--
-- ЧТО ЗНАЧИТ КАЖДАЯ КОЛОНКА.
--   * refill_paused_at — момент, когда добор остановлен. NOT NULL ⇒ тик крона
--     проекту сборку НЕ ставит (ни одной вертикали: воркспейс у них общий).
--     Это единственный признак паузы.
--   * refill_pause_reason — человеческий текст для сотрудника: что произошло,
--     что счётчик общий на воркспейс, и кто именно записал паузу (ночной
--     предполёт или долив конкретной базы). Не машинный код: ветки по нему нет
--     ни одной, решение бинарное — пауза стоит или не стоит.
--   * refill_resumed_at — когда сотрудник вернул проект в добор
--     (POST /api/tools/hypothesis-engine/projects/[id]/refill-pause). Штамп
--     нужен не для аудита: без него «возобновили вчера» и «никогда не
--     паузили» выглядят одинаково, а первая из этих ночей — единственная,
--     по которой видно, что кнопка работает.
--
-- ЧЕГО ЗДЕСЬ НЕТ И ПОЧЕМУ.
--   * Нет автоснятия по таймеру. Пункт ровно об ЯВНОМ возобновлении: пауза,
--     которая снимается сама, вернёт добор в тот же переполненный воркспейс и
--     купит ту же сборку заново — то есть не починит ничего, а человек об этом
--     так и не узнает.
--   * Нет счётчика ночей паузы. Ночь под паузой не собирается и не
--     отправляется, строки прогона у неё нет, и считать в ней нечего; «сколько
--     ночей стоим» читается из refill_paused_at вычитанием.
--   * Нет отдельной таблицы истории пауз. Пауза — состояние проекта, а не
--     событие: второй паузы поверх стоящей не бывает (запись идёт только при
--     refill_paused_at is null), а хронология её постановок и снятий и так
--     оседает в ночном логе крона.
--
-- ЭТО НЕ ВЫКЛЮЧАТЕЛЬ enabled. enabled=false — «клиент/студия не хотят ночного
-- добора»; пауза — «добор хотим, но сейчас физически некуда». Смешивать их
-- нельзя: снятие паузы не должно включать добор тому, кто его выключил сам, а
-- включение добора не должно стирать паузу, которую никто не разбирал.
--
-- БЕЗ МИГРАЦИИ КОД НЕ ПАДАЕТ: тик крона читает эти колонки ОПЦИОНАЛЬНО (42703
-- → повтор запроса без них, см. loadConfigs), запись паузы best-effort
-- (ошибка = паузы нет, проект собирается как раньше), staff-роут отвечает
-- «пауза не поддержана окружением». Но без колонок механизм не работает, а
-- значит порядок выката прежний: СНАЧАЛА миграция, ПОТОМ код.
--
-- ПРАВ МИГРАЦИЯ НЕ МЕНЯЕТ: новых таблиц и функций она не создаёт, колонки
-- наследуют гранты своей таблицы. he_auto_pipeline_configs запечатана своей
-- миграцией (20260804_0005) и поимённым отзывом anon/authenticated
-- (20260920_0001_he_rls_lockdown.sql); allowlist от этого файла не растёт.

