-- he_hypotheses.fit_rationale: обязательное обоснование «почему это рынок
-- для клиента» (Hypothesis Engine, Движок вертикалей).
--
-- Отличие от соседних полей:
-- - description — кто такой сегмент (описание рынка);
-- - fit_rationale — цепочка фита: кто клиент сегмента (ЛПР) → его цель →
--   его боль, которую снимает продукт клиента → конкретный оффер клиента.
-- Жалоба владельца: карточка вертикали доказывала существование сегмента,
-- но не доказывала, что КЛИЕНТ может в него продавать — связка фита теперь
-- явная и обязательная у новых кандидатов (zod-схема: min(1), см.
-- app/src/lib/hypothesisEngine/schemas.ts).
--
-- Колонка nullable: легаси-строки (прогоны до этой миграции) без неё.
-- Grants не нужны: добавление колонки наследует права таблицы he_hypotheses
-- (см. 20260724_0001_create_hypothesis_engine.sql).

alter table public.he_hypotheses
  add column if not exists fit_rationale text;

comment on column public.he_hypotheses.fit_rationale is
  '«Почему это рынок для клиента»: цепочка ЛПР сегмента → его цель → его боль, которую снимает продукт клиента → конкретный оффер клиента. Обязательна для новых гипотез (zod min(1)); NULL у легаси-строк.';
