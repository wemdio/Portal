-- Захват контакта первого касания в БАЗЕ, а не в памяти процесса.
--
-- Зачем. До сих пор порция первого касания отбиралась обычным
-- `select ... where status = 'pending'` со смещением по аккаунту, а от двойной
-- отправки одному человеку защищал только `Set` в памяти круга кампании
-- (claimedContacts в lib/tgOutreach/campaignLoop.ts). Пока исполнитель у
-- кампании был ровно один, этого хватало.
--
-- С переездом TG-аутрича на единый жизненный цикл задач
-- (app/src/lib/jobs/lifecycle.ts) исполнителей может быть двое одновременно:
-- библиотека намеренно допускает короткое окно, когда уходящий владелец ещё
-- дорабатывает, а сосед уже захватил строку кампании. Два множества в двух
-- разных процессах друг о друге не знают — и один и тот же человек получил бы
-- два первых сообщения с двух номеров. Для холодного аутрича это худший из
-- возможных видов брака: так выглядит бот, и второй раз этому лиду уже не
-- написать.
--
-- Как. Две колонки-замка и CAS-UPDATE поверх отобранных id (см.
-- claimContacts в lib/tgOutreach/firstTouch/db.ts): захват получает та реплика,
-- для которой строка на момент записи ещё `pending` и не захвачена. Postgres
-- сериализует конкурирующие UPDATE по строке и перечитывает условие после
-- снятия блокировки, поэтому второй писатель уходит ни с чем — без RPC и без
-- транзакций на стороне приложения.
--
-- Почему замок с СРОКОМ, а не «захвачен навсегда». Контакт, у которого отправка
-- не удалась, остаётся `pending` намеренно (сбой мог быть сетевым, попытки
-- считаются отдельно в attempts). Вечный замок означал бы, что такой контакт
-- больше не возьмёт никто — очередь молча протухала бы. Срок замка держит код
-- (CONTACT_CLAIM_TTL_MS, 10 минут): он заведомо больше самой долгой отправки
-- (резолв 60 с + отправка 120 с) и заведомо меньше паузы между кругами
-- кампании, так что нормальный ритм повторов не меняется.
--
-- Отдельного индекса нет намеренно: кандидаты по-прежнему отбираются по
-- (base_id, status) существующим индексом, а CAS бьёт по первичному ключу —
-- список id известен заранее. Индекс по claimed_at не ускорил бы ни один
-- сегодняшний запрос, а стоил бы записи на каждый захват.

alter table public.tg_outreach_base_contacts
  add column if not exists claimed_by uuid,
  add column if not exists claimed_at timestamptz;

comment on column public.tg_outreach_base_contacts.claimed_by is
  'Аккаунт, взявший контакт в работу (uuid из tg_outreach_accounts). Внешнего ключа намеренно нет: это отметка замка, а не связь — удалённый аккаунт не должен мешать снять замок.';
comment on column public.tg_outreach_base_contacts.claimed_at is
  'Когда контакт захвачен. Замок протухает по сроку из кода (CONTACT_CLAIM_TTL_MS): иначе контакт, у которого отправка не удалась, не взял бы больше никто.';
