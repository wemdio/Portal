#!/usr/bin/env node
/**
 * Reads app/src/lib/globalTranslations.ts and produces a SQL seed file at
 *   supabase/migrations/20260520_0004_seed_portal_translations.sql
 * that inserts every RU→EN pair into `portal_translations` with source='human'.
 *
 * These pairs were hand-curated over many months — when the new on-the-fly
 * translator runs against EN, it'll find the blessed translation in the cache
 * instead of paying an LLM round-trip. The 'human' source flag also protects
 * them from being overwritten by machine output (see lib/portalTranslate).
 *
 * Re-run after editing globalTranslations.ts to refresh the seed.
 */

import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const __filename = fileURLToPath(import.meta.url);
const __dirname = dirname(__filename);
const REPO_ROOT = join(__dirname, '..', '..');
const SOURCE_PATH = join(REPO_ROOT, 'app', 'src', 'lib', 'globalTranslations.ts');
const OUT_PATH = join(REPO_ROOT, 'supabase', 'migrations', '20260520_0004_seed_portal_translations.sql');

const src = readFileSync(SOURCE_PATH, 'utf8');

// PAIRS lines look like:
//   ['Source RU', 'English'],
//   ["...", "..."],
// They may use single or double quotes; the file's own conventions are
// single-quoted with \u escapes for tricky chars. We tolerate either by
// pulling the array literal as a TS expression and `eval`-ing it inside a
// sandboxed Function. That's safer than a homebrew regex for 2.4k entries.

const start = src.indexOf('const PAIRS');
if (start === -1) throw new Error('Could not find PAIRS in globalTranslations.ts');
// Skip past the TypeScript type annotation (`: Array<[string, string]>`) by
// anchoring on `=` first; otherwise our bracket scanner picks up the type
// parameter brackets before the actual array literal.
const eqAt = src.indexOf('=', start);
if (eqAt === -1) throw new Error('Could not find PAIRS assignment');
const openBracket = src.indexOf('[', eqAt);
if (openBracket === -1) throw new Error('Could not find PAIRS array opener');

// Find the matching closing bracket. Brackets only appear in string content
// when escaped — the file convention uses single-quoted strings — so a
// simple depth counter that ignores string contents is sufficient.
let depth = 0;
let i = openBracket;
let inString = null; // null | "'" | '"' | '`'
for (; i < src.length; i += 1) {
  const c = src[i];
  if (inString) {
    if (c === '\\') { i += 1; continue; }
    if (c === inString) inString = null;
    continue;
  }
  if (c === "'" || c === '"' || c === '`') { inString = c; continue; }
  if (c === '[') depth += 1;
  else if (c === ']') {
    depth -= 1;
    if (depth === 0) break;
  }
}
if (depth !== 0) throw new Error('Unbalanced brackets in PAIRS');
const arrayLiteral = src.slice(openBracket, i + 1);

// Evaluate as plain JS (the literal is valid JS — no TS syntax inside).
const pairs = new Function(`return (${arrayLiteral});`)();
if (!Array.isArray(pairs)) throw new Error('PAIRS did not evaluate to an array');

const seen = new Set();
const rows = [];
for (const entry of pairs) {
  if (!Array.isArray(entry) || entry.length !== 2) continue;
  const [ru, en] = entry;
  if (typeof ru !== 'string' || typeof en !== 'string') continue;
  const ruTrim = ru.trim();
  const enTrim = en.trim();
  if (!ruTrim || !enTrim) continue;
  const key = ruTrim;
  if (seen.has(key)) continue;
  seen.add(key);
  rows.push([ruTrim, enTrim]);
}

const escape = (s) => s.replace(/'/g, "''");

const header = [
  '-- Portal i18n: seed portal_translations with the hand-curated RU->EN pairs',
  '-- formerly stored in app/src/lib/globalTranslations.ts. Generated by',
  '-- app/scripts/generate-translations-seed.mjs - DO NOT edit by hand. Re-run',
  '-- the script after changing the source file.',
  '--',
  "-- These rows are marked source='human' so the runtime LLM translator never",
  '-- overwrites them (see lib/portalTranslate.writeCache). Idempotent: an',
  '-- ON CONFLICT clause leaves existing rows untouched.',
  '',
  '',
].join('\n');

const chunkSize = 500;
const chunks = [];
for (let k = 0; k < rows.length; k += chunkSize) {
  const slice = rows.slice(k, k + chunkSize);
  const values = slice
    .map(([ru, en]) => `('${escape(ru)}', 'en', '${escape(en)}', 'ru', 'human')`)
    .join(',\n  ');
  chunks.push(
    `insert into public.portal_translations (source_text, target_lang, translated_text, source_lang, source) values\n  ${values}\non conflict (source_text, target_lang) do nothing;`,
  );
}

const sql = header + chunks.join('\n\n') + '\n';
writeFileSync(OUT_PATH, sql, 'utf8');
console.log(`Wrote ${rows.length} rows in ${chunks.length} INSERT batches to ${OUT_PATH}`);
