def classify_rubrics(subcats):
    """Набор подрубрик компании -> (tier, t1_hits, t2_hits, b2c_hits)."""
    t1 = subcats & TIER1
    t2 = subcats & TIER2
    b2c = subcats & B2C_MICRO
    if t1:
        tier = 1
    elif t2:
        tier = 2
    else:
        tier = 3
    return tier, t1, t2, b2c


def city_score(cities):
    if cities & CITY_TIER1:
        return 2
    if cities & CITY_TIER2:
        return 1
    return 0
