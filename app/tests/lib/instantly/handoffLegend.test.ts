/** @jest-environment node */

import { substituteHandoffLegend } from '@/lib/instantly/handoffLegend';

describe('substituteHandoffLegend', () => {
  it('подставляет имя в «[Имя, если есть]»', () => {
    expect(
      substituteHandoffLegend('Добрый день, [Имя, если есть]. Благодарю за ответ.', 'Венера'),
    ).toBe('Добрый день, Венера. Благодарю за ответ.');
  });

  it('подставляет имя в «[Имя]» (любой регистр)', () => {
    expect(substituteHandoffLegend('Здравствуйте, [ИМЯ]!', 'Пётр')).toBe('Здравствуйте, Пётр!');
  });

  it('имени нет — плейсхолдер срезается с запятой, висячей пунктуации не остаётся', () => {
    expect(substituteHandoffLegend('Добрый день, [Имя, если есть]. Благодарю.', null)).toBe(
      'Добрый день. Благодарю.',
    );
  });

  it('имени нет — плейсхолдер без запятой срезается целиком', () => {
    expect(substituteHandoffLegend('Приветствую [Имя], спасибо за ответ', '  ')).toBe(
      'Приветствую , спасибо за ответ',
    );
  });

  it('несколько плейсхолдеров в одном тексте', () => {
    expect(
      substituteHandoffLegend('[Имя], добрый день. [Имя], передаю вас коллеге.', 'Ольга'),
    ).toBe('Ольга, добрый день. Ольга, передаю вас коллеге.');
  });

  it('текст без плейсхолдеров не меняется', () => {
    const t = 'Добавил в копию свою основную почту, чтобы не потерять.';
    expect(substituteHandoffLegend(t, 'Кто-то')).toBe(t);
  });
});
