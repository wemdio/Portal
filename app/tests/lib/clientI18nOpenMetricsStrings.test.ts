/** @jest-environment node */

/**
 * Строки, которые поменялись вместе с уходом открытий из клиентской
 * статистики, должны переводиться на en/es.
 *
 * Кабинет переводит текст по ТОЧНОМУ совпадению узла с каталогом
 * (getClientTranslation), а неизвестный узел оставляет на русском. Когда
 * 74aec1b87 разрезал «писем, открыли» на «писем» + условное «, открыли», а
 * 97840c682 переписал подсказку «Воронки базы», английский клиент увидел
 * «Campaign sent 1,234 писем, answered 5%.». Тест держит все такие узлы — и
 * новые заметки карточки переписки — в каталоге.
 */

import { getClientTranslation } from '@/lib/clientI18n';

const STRINGS = [
  // /client/campaigns/[id]: «Кампания отправила N писем, ответили X%.»
  'писем',
  // …и в auto-режиме (Mailganer) — «, открыли X%» между ними
  ', открыли',
  // /client: пустое состояние
  'Запустите первую — мы покажем здесь её метрики (отправки, ответы, лиды) в реальном времени.',
  // /client/reports: подсказка
  'Отправки, ответы и лиды смотрите в разделе',
  // ExpandedThread: отложенная история
  'Показываем последнее письмо — остальная переписка догрузится через несколько секунд.',
  'Обновляем переписку — новые письма появятся через несколько секунд.',
  'Переписку сейчас не удалось загрузить полностью — повторите через минуту.',
];

describe('каталог переводов — строки без «открытий»', () => {
  it.each(STRINGS)('en и es есть для «%s»', (source) => {
    expect(getClientTranslation(source, 'en')).toEqual(expect.any(String));
    expect(getClientTranslation(source, 'es')).toEqual(expect.any(String));
  });

  it('узел с пробелами по краям тоже переводится (края сохраняются)', () => {
    expect(getClientTranslation(' писем ', 'en')).toBe(' letters ');
  });

  it('в переводах нет следов открытий (кроме auto-режима, где открытия показываются)', () => {
    for (const source of STRINGS.filter((s) => s !== ', открыли')) {
      expect(getClientTranslation(source, 'en')).not.toMatch(/open/i);
      expect(getClientTranslation(source, 'es')).not.toMatch(/apertur/i);
    }
  });
});
