/** @jest-environment node */

/**
 * Порядок обхода аккаунтов в круге рассылки.
 *
 * Регрессия 28.08.2026: воркер падал трижды за день, круг каждый раз начинался
 * с начала списка, а пауза между аккаунтами доходит до десяти минут. Процесс
 * успевал обработать два-три аккаунта и умирал — хвост списка не работал ни
 * разу. У ATOL-1 из двенадцати аккаунтов реально писали двое, а свежая база на
 * триста контактов сутки простояла с нулём отправок.
 *
 * Поэтому проверяем именно то, ради чего сортировка и появилась: после обрыва
 * очередь продолжается с места остановки, а не с начала.
 */

import { orderByStaleness } from '@/lib/tgOutreach/accountRotation';

const acc = (id: string, lastCycleAt: string | null, createdAt = '2026-08-01T00:00:00.000Z') => ({
  id,
  last_cycle_at: lastCycleAt,
  created_at: createdAt,
});

describe('orderByStaleness', () => {
  it('первым идёт тот, до кого дольше всех не доходили', () => {
    const order = orderByStaleness([
      acc('свежий', '2026-08-28T12:00:00.000Z'),
      acc('давний', '2026-08-28T09:00:00.000Z'),
      acc('средний', '2026-08-28T11:00:00.000Z'),
    ]).map((a) => a.id);

    expect(order).toEqual(['давний', 'средний', 'свежий']);
  });

  it('после обрыва круг продолжается с места остановки', () => {
    /**
     * Три аккаунта обработаны, до четвёртого и пятого не дошли — процесс умер.
     * Новый запуск обязан начать с них, а не с первого.
     */
    const order = orderByStaleness([
      acc('1', '2026-08-28T12:00:00.000Z'),
      acc('2', '2026-08-28T12:10:00.000Z'),
      acc('3', '2026-08-28T12:20:00.000Z'),
      acc('4', null),
      acc('5', null),
    ]).map((a) => a.id);

    expect(order.slice(0, 2)).toEqual(['4', '5']);
    // И только потом — по второму разу, снова начиная с самого давнего.
    expect(order.slice(2)).toEqual(['1', '2', '3']);
  });

  it('не бравшиеся ни разу идут перед всеми, даже перед очень давними', () => {
    const order = orderByStaleness([
      acc('брали год назад', '2025-08-28T00:00:00.000Z'),
      acc('не брали', null),
    ]).map((a) => a.id);

    expect(order).toEqual(['не брали', 'брали год назад']);
  });

  it('новые аккаунты идут в порядке загрузки, а не вперемешку', () => {
    // Партию заливают пачкой, и оператор ожидает увидеть её в том же порядке,
    // в каком грузил, — иначе непонятно, дошла очередь до неё или нет.
    const order = orderByStaleness([
      acc('третий', null, '2026-08-28T10:03:00.000Z'),
      acc('первый', null, '2026-08-28T10:01:00.000Z'),
      acc('второй', null, '2026-08-28T10:02:00.000Z'),
    ]).map((a) => a.id);

    expect(order).toEqual(['первый', 'второй', 'третий']);
  });

  it('одинаковое время обхода разводится датой добавления', () => {
    const same = '2026-08-28T12:00:00.000Z';
    const order = orderByStaleness([
      acc('поздний', same, '2026-08-02T00:00:00.000Z'),
      acc('ранний', same, '2026-08-01T00:00:00.000Z'),
    ]).map((a) => a.id);

    expect(order).toEqual(['ранний', 'поздний']);
  });

  it('исходный список не меняется', () => {
    // Он используется дальше и для других целей — сверки своих tg_user_id и
    // счётчиков. Молча переставить его под ними значит получить неочевидную
    // ошибку через полгода.
    const input = [acc('b', '2026-08-28T12:00:00.000Z'), acc('a', null)];
    const before = input.map((a) => a.id);
    orderByStaleness(input);
    expect(input.map((a) => a.id)).toEqual(before);
  });

  it('битая метка времени не ломает сортировку', () => {
    const order = orderByStaleness([
      acc('нормальный', '2026-08-28T12:00:00.000Z'),
      acc('битый', 'не дата'),
    ]).map((a) => a.id);

    // Нечитаемая метка равна её отсутствию: аккаунт считается не бравшимся.
    expect(order).toEqual(['битый', 'нормальный']);
  });

  it('пустой список остаётся пустым', () => {
    expect(orderByStaleness([])).toEqual([]);
  });
});
