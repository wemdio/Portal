function escapeRegExp(value: string): string {
  return value.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
}

const CYR = 'А-Яа-яЁё';
const seen = new Set<string>();
const DEDUPED: Array<[string, string]> = [];
for (const [from, to] of PAIRS) {
  if (!seen.has(from)) { seen.add(from); DEDUPED.push([from, to]); }
}

const SORTED_PAIRS = DEDUPED.sort((a, b) => b[0].length - a[0].length);
const SORTED_RULES = SORTED_PAIRS.map(([from, to]) => ({
  from,
  to,
  regex: new RegExp(`(?<![${CYR}])${escapeRegExp(from)}(?![${CYR}])`, 'g'),
}));

export function translateKnownRuToEn(text: string): string {
  if (!text) return text;
  if (!/[А-Яа-яЁё]/.test(text)) return text;

  let output = text;
  for (const rule of SORTED_RULES) {
    output = output.replace(rule.regex, rule.to);
  }
  return output;
}
