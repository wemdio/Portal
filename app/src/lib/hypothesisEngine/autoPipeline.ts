/**
 * Колонки вертикали со стороны правила сухости. Отдельной строкой, потому что
 * при отсутствующей миграции запрос с ними падает целиком (PostgREST 42703), а
 * это стоило бы НОЧИ ВСЕМ проектам ради выключенного по умолчанию правила —
 * см. loadVerticals.
 */
const VERTICAL_DRY_COLUMNS = 'refill_dry_since, refill_dry_nights, refill_resumed_at';

/**
 * Колонки конфига, которых может не быть на окружении (та же причина, см.
 * loadConfigs): порог сухости (20260930_0003) и пауза по ёмкости
 * (20260930_0005).
 *
 * Группа ОДНА на обе миграции осознанно. Читать их двумя независимыми
 * запросами значило бы удвоить чтение конфигов ради окна в несколько минут
 * между двумя накатами, а исход у обеих недостающих колонок один и тот же —
 * прежнее поведение: без dry_nights_limit порог берётся из кода, без
 * refill_paused_at паузы просто нет. Обе стороны безопасны: непрочитанная
 * пауза = проект собирается, как собирался до неё.
 */
const CONFIG_OPTIONAL_COLUMNS = 'dry_nights_limit, refill_paused_at, refill_pause_reason';

/**
 * Ошибка PostgREST «колонки нет» (Postgres 42703). Ровно она отделяет
 * «миграция ещё не прокатана» от настоящего сбоя БД, и только её мы глушим.
 */
function isMissingColumnError(error: { code?: string } | null): boolean {
  return error?.code === '42703';
}

function asNumberOrNull(value: unknown): number | null {
  return typeof value === 'number' && Number.isFinite(value) ? value : null;
}

function asStringOrNull(value: unknown): string | null {
  return typeof value === 'string' && value.length > 0 ? value : null;
}

function asString(value: unknown): string {
  return typeof value === 'string' ? value : '';
}

/** Куда доливать вертикаль: кампания и пресет её последнего запуска. */
interface VerticalLaunchTarget {
  campaignId: string;
  /**
   * Пресет запуска: через него (client_user_id → instantly_account_id) ведёт
   * единственный путь к воркспейсу, в который долив реально пишет, — тот же,
   * что резолвит appendLeadsToClientCampaign. Предполёт ёмкости обязан спросить
   * ИМЕННО его, иначе он мерил бы чужой (дефолтный) воркспейс.
   */
  presetId: string;
  /**
   * Шаблон этого запуска: его желание клиента (he_eng_launch_sending — пауза
   * клиента ставится на шаблон) читает проверка «кампании запуска
   * отправляют?» (createHeRefillSendGate).
   */
  templateId: string;
}

/**
 * Карта «вертикаль → кампания и пресет» по шаблонам с launch_info: на вертикаль —
 * ПОСЛЕДНИЙ по дате запуска (force-перезапуск перезаписывает launch_info;
 * доливать надо в актуальную кампанию).
 */
function latestCampaignByVertical(
  templateRows: Array<Record<string, unknown>>,
): Map<string, VerticalLaunchTarget> {
  const best = new Map<string, VerticalLaunchTarget & { ts: number }>();
  for (const row of templateRows) {
    const launch = parseLaunchInfo(row.launch_info);
    if (!launch) continue;
    const verticalId = asString(row.vertical_id);
    if (!verticalId) continue;
    const ts =
      Date.parse(launch.created_at) ||
      Date.parse(asString(row.created_at)) ||
      0;
    // При сплите запуска по сегментам цель ночи — основная кампания
    // (segment=null): по ней тик находит шаблон для гейта писем (основные
    // тексты) и пресет для предполёта ёмкости воркспейса. Строки
    // сегментов по сегментным кампаниям того же запуска раскладывает уже сам
    // долив (stages/baseCollectRefill.ts, routeHeRefillSegments, только 'us');
    // сплит без основной кампании вертикаль пропускает — строкам без сегмента
    // лечь некуда (pickRefillTemplate тоже вернёт null).
    const campaignId = heRefillMainCampaignId(launch);
    if (!campaignId) continue;
    const current = best.get(verticalId);
    if (!current || ts >= current.ts) {
      best.set(verticalId, { campaignId, presetId: launch.preset_id, templateId: asString(row.id), ts });
    }
  }
  return new Map(
    [...best.entries()].map(([k, v]) => [
      k,
      { campaignId: v.campaignId, presetId: v.presetId, templateId: v.templateId },
    ]),
  );
}

/**
 * Вертикали, чью ночь отбор долива снял бы целиком (шаг 3a-- в шапке):
 * вертикаль → причина. Шаблон ночи долив выбирает по кампании, в которую
 * доливает (pickRefillTemplate: шаблон, чей запуск несёт этот campaign_id),
 * поэтому сверяются ВСЕ запущенные шаблоны вертикали с этой кампанией, и
 * вертикаль попадает сюда, только если снят был бы каждый: какой из них
 * возьмёт долив, тик не знает. Обычно такой шаблон один.
 *
 * `project` — сайт, бриф и признак владельца проекта для проверки чужой
 * компании в письмах (heRefillBrandHoldEveryRow); null — тик их не читал (в
 * письмах нет ни одного проверяемого слова), и этой причины нет.
 */
function lettersHeldByVertical(
  templateRows: Array<Record<string, unknown>>,
  campaignByVertical: ReadonlyMap<string, VerticalLaunchTarget>,
  project: HeBrandProject | null,
): Map<string, string> {
  const held = new Map<string, string>();
  const sendable = new Set<string>();
  for (const row of templateRows) {
    const verticalId = asString(row.vertical_id);
    const target = campaignByVertical.get(verticalId);
    const launch = parseLaunchInfo(row.launch_info);
    if (!target || !launch || sendable.has(verticalId)) continue;
    const carriesCampaign =
      launch.campaign_id === target.campaignId ||
      (launch.campaigns ?? []).some((c) => c.campaign_id === target.campaignId);
    if (!carriesCampaign) continue;
    const reason =
      heRefillLettersHoldEveryRow({
        letters: row.letters,
        personalization_plan: row.personalization_plan,
      }) ?? (project ? heRefillBrandHoldEveryRow(row.letters, project) : null);
    if (reason === null) {
      sendable.add(verticalId);
      held.delete(verticalId);
    } else if (!held.has(verticalId)) {
      held.set(verticalId, reason);
    }
  }
  return held;
}

/**
 * Сколько контактов ещё принимает воркспейс рассыльщика: число — точный
 * остаток, null — «не знаем».
 */
type HeWorkspaceCapacityProbe = (presetId: string) => Promise<number | null>;

/**
 * Предполёт ёмкости на один тик.
 *
 * Запрос к рассыльщику — ОДИН на воркспейс за тик (мемоизация по аккаунту), а
 * не один на вертикаль: все вертикали одного проекта живут в воркспейсе своего
 * клиента (пресет — один на client_user_id), и переспрашивать то же самое
 * значило бы тратить общий rate-limit ради одинакового ответа.
 *
 * null — «не знаем», и это ОБЯЗАТЕЛЬНО не «ноль»: ключ без права читать биллинг
 * воркспейса, таймаут, 429/5xx у провайдера, нечитаемый ответ, ненайденный
 * пресет и отсутствующая instantly-БД дают именно null, после чего тик работает
 * как до этой правки. Предполёт, который угадывает ноль, останавливает продукт;
 * предполёт, который угадывает «место есть», в худшем случае возвращает нас к
 * прежнему поведению (отказ на доливе, где его уже умеют ставить на паузу).
 */
function createHeWorkspaceCapacityProbe(): HeWorkspaceCapacityProbe {
  const optionsByPreset = new Map<string, Promise<InstantlyRequestOptions | null>>();
  const remainingByAccount = new Map<string, Promise<number | null>>();

  const optionsFor = (presetId: string): Promise<InstantlyRequestOptions | null> => {
    const cached = optionsByPreset.get(presetId);
    if (cached) return cached;
    const pending = (async () => {
      if (!supabaseInstantly) return null;
      const { data, error } = await supabaseInstantly
        .from('client_campaign_presets')
        .select('client_user_id')
        .eq('id', presetId)
        .maybeSingle();
      if (error) throw new Error(`client_campaign_presets read: ${error.message}`);
      const userId = (data as { client_user_id?: unknown } | null)?.client_user_id;
      if (typeof userId !== 'string' || !userId) return null;
      // Тот же резолв, которым долив выбирает аккаунт (DRY, по client_user_id).
      return resolveClientInstantlyRequestOptions(userId);
    })();
    optionsByPreset.set(presetId, pending);
    return pending;
  };

  return async (presetId) => {
    if (!presetId) return null;
    try {
      const options = await optionsFor(presetId);
      if (!options) return null;
      const accountKey = options.accountId ?? '';
      const cached = remainingByAccount.get(accountKey);
      if (cached) return await cached;
      const pending = getWorkspaceContactCapacity(options).then((c) => c?.remaining ?? null);
      remainingByAccount.set(accountKey, pending);
      return await pending;
    } catch {
      // Любая неопределённость — «не знаем». Текст ошибки не логируем здесь:
      // вызывающий и без него работает как раньше, а шумная строка каждую ночь
      // у клиентов без права на биллинг-чтение прятала бы настоящие отказы.
      return null;
    }
  };
}

/**
 * Вертикали проекта. Колонки пометки читаются ОПЦИОНАЛЬНО: воркер может уехать
 * раньше миграции 20260930_0003, и тогда запрос с ними отвечает 42703 — а это
 * уронило бы весь ночной тик (ошибка чтения = фейл обхода конфига) ради
 * правила, которое по умолчанию выключено. Без колонок пометки просто нет:
 * вертикаль считается непомеченной, серия всё равно считается, а записать
 * решение не выйдет (writeDryMark вернёт false и слот будет выдан).
 */
async function loadVerticals(
  supabase: SupabaseClient,
  projectId: string,
): Promise<VerticalRow[]> {
  const base = 'id, name, created_at';
  let rows: Array<Record<string, unknown>> | null = null;
  const first = await supabase
    .from('he_verticals')
    .select(`${base}, ${VERTICAL_DRY_COLUMNS}`)
    .eq('project_id', projectId);
  if (first.error && !isMissingColumnError(first.error)) {
    throw new Error(`he_verticals read: ${first.error.message}`);
  }
  if (first.error) {
    const retry = await supabase.from('he_verticals').select(base).eq('project_id', projectId);
    if (retry.error) throw new Error(`he_verticals read: ${retry.error.message}`);
    rows = (retry.data ?? []) as Array<Record<string, unknown>>;
  } else {
    rows = (first.data ?? []) as Array<Record<string, unknown>>;
  }
  return rows.map((row) => ({
    id: asString(row.id),
    name: asString(row.name),
    created_at: asStringOrNull(row.created_at),
    refill_dry_since: asStringOrNull(row.refill_dry_since),
    refill_dry_nights: asNumberOrNull(row.refill_dry_nights),
    refill_resumed_at: asStringOrNull(row.refill_resumed_at),
  }));
}

/**
 * Сколько ЗАВЕРШЁННЫХ refill-прогонов вертикали подряд не добавили ни одного
 * контакта. Полный разбор состояний — в блоке «СУХАЯ ВЕРТИКАЛЬ» выше.
 *
 * Окно чтения — `limit + 1` строк: решение бинарное («серия достигла порога или
 * нет»), а лишняя строка отличает «ровно на пороге» от «длиннее» в логе.
 * Возвращаемое число поэтому НИКОГДА не больше limit + 1, и это не длина всей
 * истории. Тот же приём, что у refillFailStreak (stages/baseCollectRefill.ts).
 *
 * `resumedAt` — момент, с которого клиент попросил считать заново: прогоны
 * старше него в окно не идут, иначе снятая пометка вернулась бы той же ночью.
 *
 * НИКОГДА НЕ БРОСАЕТ: непрочитанная история = null («не знаем»), и вызывающий
 * трактует это как «серии нет». Из двух исходов этот обратимый — лишняя ночь
 * сбора против вертикали, заглушенной нашим же сбоем чтения.
 */
async function readDryNightStreak(
  supabase: SupabaseClient,
  vertical: VerticalRow,
  limit: number,
): Promise<number | null> {
  try {
    let query = supabase
      .from('he_auto_pipeline_runs')
      .select('status, stats')
      .eq('vertical_id', vertical.id)
      // Отбор делает запрос, а не JS: пропускаемые строки (отказы постановки
      // без base_id, незавершённые 'collecting') иначе занимали бы место в
      // окне и серия читалась бы короче, чем она есть.
      .not('base_id', 'is', null)
      .neq('status', 'collecting')
      .not('completed_at', 'is', null);
    if (vertical.refill_resumed_at) {
      query = query.gt('completed_at', vertical.refill_resumed_at);
    }
    const { data, error } = await query
      .order('completed_at', { ascending: false })
      .limit(limit + 1);
    if (error) throw new Error(error.message);
    let streak = 0;
    for (const row of (data ?? []) as Array<{ status?: unknown; stats?: unknown }>) {
      // Любой исход, кроме 'no_new', серию обрывает — включая 'failed'
      // (наш сбой) и 'appended' с нулём (наш кап, блок-лист клиента либо
      // строки, снятые из-за писем кампании — held_unfilled).
      if (row.status !== 'no_new') break;
      // ...и 'no_new' ночи, у которой каталог остался недочитанным: её ноль
      // про наш предохранитель, а не про источник.
      const stats = row.stats as { scan_complete?: unknown } | null | undefined;
      if (stats?.scan_complete !== true) break;
      streak += 1;
    }
    return streak;
  } catch {
    return null;
  }
}

/**
 * Записать или снять пометку сухой вертикали. Возвращает false, если записать
 * не удалось (нет колонок, сбой БД).
 *
 * ПОЧЕМУ ЭТО ВАЖНО ИМЕННО РЕЗУЛЬТАТОМ. Пропуск, о котором не осталось следа в
 * he_verticals, — это молча пропавший добор: в кабинете ничего, у клиента
 * никакой кнопки, у поддержки никакого объяснения. Поэтому не записалось —
 * значит решение не принято, и вертикаль идёт в сборку как раньше.
 */
async function writeDryMark(
  supabase: SupabaseClient,
  verticalId: string,
  patch: Record<string, unknown>,
): Promise<boolean> {
  const { error } = await supabase.from('he_verticals').update(patch).eq('id', verticalId);
  return !error;
}

/**
 * Вернуть вертикаль в ночной добор: снять пометку и открыть НОВОЕ окно серии.
 *
 * Единственный способ отменить решение правила, и он же — обработчик кнопки
 * кабинета (POST /api/client/eng/verticals/[id]/refill). `refill_resumed_at`
 * обязателен: без него следующая же ночь прочитала бы ту же самую историю из N
 * пустых прогонов и поставила пометку обратно, то есть кнопка ничего бы не
 * меняла.
 *
 * Рынок и владелец здесь НЕ проверяются: это делает вызывающий роут
 * (requireEngMarket + loadClientHeVertical).
 */
export async function resumeHeVerticalNightlyRefill(
  supabase: SupabaseClient,
  verticalId: string,
  opts: { now?: Date } = {},
): Promise<void> {
  const now = (opts.now ?? new Date()).toISOString();
  const { error } = await supabase
    .from('he_verticals')
    .update({ refill_dry_since: null, refill_dry_nights: null, refill_resumed_at: now })
    .eq('id', verticalId);
  if (error) throw new Error(`he_verticals refill resume: ${error.message}`);
}

/**
 * Сколько лидов дневной бюджет проекта ещё разрешает отправить СЕГОДНЯ (UTC).
 *
 * Источник — брони (`he_refill_daily_budgets` + `he_refill_daily_reservations`,
 * миграция 20260930_0004), то есть ровно тот же учёт, которым долив режет
 * отправку (reserveRefillDailyBudget в stages/baseCollectRefill.ts): открытая
 * бронь занимает весь свой объём, завершённая — фактический расход. Второго
 * определения «потрачено» тут не заводится.
 *
 * ВОЗРАСТ БРОНИ ЗДЕСЬ НЕ УЧИТЫВАЕТСЯ, и это совпадает с доливом: перехватить
 * зависшую бронь имеет право только СВОЯ ЖЕ база (окно в два часа), а для
 * суммы проекта такая бронь занята до конца суток. Иначе тик покупал бы сборку
 * под объём, который долив всё равно не выдаст.
 *
 * Зачем тику знать остаток. Платит СБОРКА (план источников, гейт, краул сайтов,
 * SMTP-проба каждого адреса), а бюджет режет уже ОТПРАВКУ: поставить сборку
 * проекту, чей день выбран, значит заплатить за компании, строки которых
 * бюджет выбросит, и выжечь эти компании из будущих сборок. На обычном ночном
 * тике этого не бывает — в 03:20 броней нет. Второй за сутки прогон крона
 * останавливает раньше правило суток (shouldRunConfigToday); эта проверка
 * остаётся для ручного `--force` и для конфига, чья метка last_run_at не
 * легла. Она закрывает только день, который брони УЖЕ выбрали целиком: ночь,
 * отправившая меньше капа (или вовсе не дошедшая до брони — 'no_new', отказ
 * до долива), оставляет остаток, и по нему сборки покупаются снова.
 *
 * `null` — «не знаем, считаем что бюджет цел», и это ЕДИНСТВЕННОЕ значение для
 * всех неопределённостей: миграции нет, прав нет, сбой чтения, а также штатное
 * «сегодня ещё не бронировали» (строки капа за этот день нет). Все они обязаны
 * вести к прежнему поведению: предполёт, угадавший ноль, останавливает продукт.
 */
async function readRefillDayRemaining(
  supabase: SupabaseClient,
  projectId: string,
  now: Date,
): Promise<number | null> {
  const day = now.toISOString().slice(0, 10);
  try {
    const budget = await supabase
      .from('he_refill_daily_budgets')
      .select('daily_cap')
      .eq('project_id', projectId)
      .eq('budget_date', day)
      .maybeSingle();
    if (budget.error) throw new Error(budget.error.message);
    const cap = asNumberOrNull((budget.data as { daily_cap?: unknown } | null)?.daily_cap);
    // Кап дня не заморожен — значит сегодня не было ни одной брони, тратить
    // нечего. Это не «не знаем», но исход тот же: бюджет цел.
    if (cap === null) return null;
    const reservations = await supabase
      .from('he_refill_daily_reservations')
      .select('reserved_count, consumed_count, finalized_at')
      .eq('project_id', projectId)
      .eq('budget_date', day);
    if (reservations.error) throw new Error(reservations.error.message);
    let spent = 0;
    for (const row of (reservations.data ?? []) as Array<Record<string, unknown>>) {
      const open = asStringOrNull(row.finalized_at) === null;
      const amount = asNumberOrNull(open ? row.reserved_count : row.consumed_count);
      if (amount !== null) spent += amount;
    }
    return Math.max(0, cap - spent);
  } catch {
    return null;
  }
}

/**
 * ПЕРЕНОС: сколько перенесённых компаний (he_refill_carryover, 'pending', срок
 * не вышел, без пометки «ждёт писем») ждёт у каждой вертикали проекта — для
 * шага 3a- тика.
 *
 * Зачем тику. Ночь вертикали с очередью сначала отправляет очередь (стадия
 * долива, блок «ПЕРЕНОС» в stages/baseCollectRefill.ts), и если очереди
 * проекта хватает на остаток дня, сборка ЛЮБОЙ другой вертикали этой ночью
 * кончится 'cap_exhausted': её компании вернутся в пул, и следующая сборка
 * купит их заново. Не ставить такую сборку — это и есть «ничего не покупать
 * дважды» на уровне проекта.
 *
 * ОЧЕРЕДЬ ВЕРТИКАЛИ СЧИТАЕТСЯ, только если её последняя РЕШАЮЩАЯ ночь —
 * 'appended'. Иначе одна сломанная вертикаль (пропал пресет, снята кампания) с
 * непустой очередью каждую ночь отнимала бы день у здоровых, а её очередь всё
 * равно не уходила бы — проект стоял бы до конца срока очереди (7 суток). С
 * этим правилом сломанная вертикаль перестаёт закрывать день после первой же
 * неудачной ночи: её ночь падает на шаге кампании/пресета, до брони, и строка
 * прогона — обычный 'failed'.
 *
 * Вертикаль, чья база застряла в сборке, решающей ночи не получает вовсе
 * (строка прогона так и стоит 'collecting'), и это правило её не отсеет. Её
 * отсеивает тик: очередь считается закрывающей день, только когда ночь
 * вертикали этим тиком действительно поставлена (carryRunning в
 * runForConfig), а 'existing' — не поставлена.
 *
 * Не решают (пропускаются, как и в серии отказов refillStreakVerdict): ночь без
 * бюджета ('failed' с budget_outcome 'cap_exhausted'), повтор прогона той же
 * базы ('already_reserved'), отмена клиентом (stats.cancelled) и пропуск долива,
 * потому что кампании запуска не отправляли (stats.sending_skip). Ночь без
 * бюджета ПЕРЕНОСИТ свои компании (решение владельца 04.10.2026), и именно у
 * её вертикали очередь самая большая; считать её «сломанной» значило бы
 * оставить эту очередь без ночи, пока она не истечёт. Решающей ночи в окне
 * нет вовсе (у вертикали только ночи без бюджета) — очередь считается: каждая
 * такая ночь дошла до брони, то есть кампания и пресет у вертикали живы.
 *
 * `null` — «не знаем» (нет миграции 20261004_0001, сбой чтения): тик ведёт себя
 * как до переноса. Читается обычным клиентом тика; RU сюда не доходит — тик
 * берёт только market='us'.
 */
async function readCarryoverByVertical(
  supabase: SupabaseClient,
  projectId: string,
  now: Date,
): Promise<Map<string, { companies: number; oldestMs: number }> | null> {
  try {
    const { data, error } = await supabase
      .from('he_refill_carryover')
      .select('vertical_id, prepared_at')
      .eq('project_id', projectId)
      .eq('status', 'pending')
      .gt('expires_at', now.toISOString())
      // Без пометки «ждёт писем» (HE_REFILL_CARRY_HELD_REASON в
      // stages/baseCollectRefill.ts — у 'pending' settle_reason бывает только
      // NULL или она): такую компанию письмо кампании вчера не взяло бы, и
      // день она не закрывает. Её ночь вертикали всё равно перепроверит.
      .is('settle_reason', null)
      .limit(5000);
    if (error) return null;
    const queues = new Map<string, { companies: number; oldestMs: number }>();
    for (const row of (data ?? []) as Array<{ vertical_id?: unknown; prepared_at?: unknown }>) {
      const verticalId = asString(row.vertical_id);
      if (!verticalId) continue;
      const preparedMs = Date.parse(asString(row.prepared_at));
      const queue = queues.get(verticalId) ?? { companies: 0, oldestMs: Number.POSITIVE_INFINITY };
      queue.companies += 1;
      if (Number.isFinite(preparedMs)) queue.oldestMs = Math.min(queue.oldestMs, preparedMs);
      queues.set(verticalId, queue);
    }
    if (queues.size === 0) return queues;
    const { data: runs, error: runsErr } = await supabase
      .from('he_auto_pipeline_runs')
      .select('vertical_id, status, stats')
      .eq('project_id', projectId)
      .in('vertical_id', [...queues.keys()])
      .not('base_id', 'is', null)
      .neq('status', 'collecting')
      .order('created_at', { ascending: false })
      .limit(200);
    if (runsErr) return null;
    const decisive = new Map<string, string>();
    for (const run of (runs ?? []) as Array<{ vertical_id?: unknown; status?: unknown; stats?: unknown }>) {
      const verticalId = asString(run.vertical_id);
      if (!verticalId || decisive.has(verticalId)) continue;
      const status = asString(run.status);
      const stats = (run.stats && typeof run.stats === 'object' ? run.stats : {}) as {
        budget_outcome?: unknown;
        cancelled?: unknown;
        sending_skip?: unknown;
      };
      // Пропуск долива, потому что кампании запуска не отправляли
      // (stats.sending_skip, stages/baseCollectRefill.ts, шаг 4c), тоже не
      // решает: о вертикали он не говорит ничего, а её компании ушли в ту же
      // очередь переноса.
      const undecided =
        status === 'failed'
        && (stats.cancelled === true
          || typeof stats.sending_skip === 'string'
          || stats.budget_outcome === 'cap_exhausted'
          || stats.budget_outcome === 'already_reserved');
      if (!undecided) decisive.set(verticalId, status);
    }
    for (const verticalId of [...queues.keys()]) {
      const last = decisive.get(verticalId);
      if (last !== undefined && last !== 'appended') queues.delete(verticalId);
    }
    return queues;
  } catch {
    return null;
  }
}

/* ─── ПОРЯДОК ВЕРТИКАЛЕЙ НОЧИ (P-B-refill-ranking-no-starvation) ──────────
 *
 * Слоты verticals_per_run раздаются в порядке compareHeRefillVerticalOrder.
 * Раньше порядок был по he_verticals.created_at, и первые verticals_per_run
 * вертикалей проекта забирали слоты каждую ночь: кампании остальных вертикалей
 * не доливались никогда.
 *
 * КОМПАРАТОР — ключи по очереди, следующий решает только при равенстве:
 *   1. UTC-день последней ночи, в которую вертикаль ПОЛУЧИЛА СЛОТ, — раньше
 *      идёт первой; нет такой ночи в окне чтения (ни разу, либо старше всего
 *      окна) — первее всех. Слот = строка he_auto_pipeline_runs с base_id: её
 *      пишет постановка сборки (и ночь только из переноса), финал пишет стадия.
 *      Отказы постановки без base_id (нет места у рассыльщика, письма, сбой
 *      enqueue) и пропуски без строки ('existing', 'no_campaign', 'dry',
 *      'carry_covers', пауза, бюджет) слота не тратят — и вертикаль остаётся
 *      впереди. Получившая слот уходит в конец: вертикали, которые слоты
 *      расходуют, идут по кругу;
 *   2. в один день — вертикаль с очередью переноса раньше, старейшая очередь
 *      первой (её компании уже оплачены и ждут не дольше срока очереди);
 *   3. меньше лидов, принятых рассыльщиком за последние
 *      HE_REFILL_RANK_RECENT_DAYS суток (сумма stats.appended строк окна), —
 *      раньше: отстающая вертикаль идёт перед той, что недавно получила больше;
 *   4. точное время той же строки (created_at) — раньше: из получивших слот в
 *      один день первой идёт та, что тогда стояла в очереди раньше. Без этого
 *      ключа ничьи по 1–3 решал бы created_at, и одна и та же старейшая
 *      вертикаль выигрывала бы каждую ничью;
 *   5. he_verticals.created_at (старше — раньше); 6. id — полный порядок.
 *
 * ПОЧЕМУ ПЕРЕНОС НЕ ПЕРВЫЙ КЛЮЧ. Очередь пополняет только ночь самой
 * вертикали: компании с адресом, которым кап не дал письма (а ночь, которой
 * бюджет дня не дал ни строки, — все свои компании с адресом). Пол сборки
 * (HE_REFILL_MIN_COMPANIES = 100 компаний, stages/baseCollectRefill.ts) больше
 * дефолтного капа (50 лидов на проект за сутки), и этот кап делят до
 * verticals_per_run ночей. «Очередь первой» отдавала бы слоты тем вертикалям,
 * что получили их вчера, — то же голодание, что у created_at, а при
 * verticals_per_run = 1 сколько угодно долго. Там, где очередь действительно
 * решает — очередей проекта хватает на остаток дня, — порядок прежний и стоит
 * выше компаратора: очереди первыми, от старейшей (шаг 3a- в шапке, tickOrder).
 *
 * Всё, что читает компаратор, лежит в БД и переживает ночь: строки журнала
 * (base_id, created_at, stats.appended), he_refill_carryover (prepared_at) и
 * he_verticals (created_at, id). В памяти процесса между ночами — ничего.
 *
 * Журнал не прочитался — ключи 1–4 молчат у всех, и порядок сводится к
 * прежнему created_at (fail-open: сбой чтения не должен ни останавливать ночь,
 * ни менять её объём — количество сборок за ночь компаратор не меняет).
 */

/** Окно ключа 3 компаратора: сколько суток назад считаются «недавние» лиды. */
export const HE_REFILL_RANK_RECENT_DAYS = 7;
/**
 * Сколько свежих строк журнала проекта читает порядок за обход. Вертикаль,
 * чьей строки в окне нет, получила последний слот раньше любой строки окна
 * (или ни разу) — для ключа 1 это и есть «раньше всех», так что обрезка его
 * не искажает. Ключ 3 считается по строкам окна: сумма неполная, только если у
 * проекта больше 500 слотов за HE_REFILL_RANK_RECENT_DAYS суток.
 */
const HE_REFILL_RANK_RUNS_LIMIT = 500;

/** Что журнал прогонов говорит о вертикали для порядка ночи. */
interface HeRefillRankFacts {
  /** UTC-день (YYYY-MM-DD) последней строки с base_id. */
  lastSlotDay: string;
  /** created_at той же строки (мс). */
  lastSlotMs: number;
  /** Сумма stats.appended строк за последние HE_REFILL_RANK_RECENT_DAYS суток. */
  appendedRecent: number;
}

/** Ключи компаратора одной вертикали (см. блок «ПОРЯДОК ВЕРТИКАЛЕЙ НОЧИ»). */
export interface HeRefillOrderKey {
  id: string;
  /** Ключ 1; null — слота в окне журнала нет (или журнал не прочитан). */
  lastSlotDay: string | null;
  /** Ключ 2: prepared_at старейшей компании очереди (мс); null — очереди нет. */
  carryOldestMs: number | null;
  /** Ключ 3. */
  appendedRecent: number;
  /** Ключ 4: created_at строки последнего слота (мс); null — вместе с lastSlotDay. */
  lastSlotMs: number | null;
  /** Ключ 5: he_verticals.created_at (мс); NaN — нечитаемо, такая идёт последней. */
  createdAtMs: number;
}

/** Порядок ночи — см. блок «ПОРЯДОК ВЕРТИКАЛЕЙ НОЧИ». Отрицательное — `a` раньше. */
export function compareHeRefillVerticalOrder(a: HeRefillOrderKey, b: HeRefillOrderKey): number {
  if (a.lastSlotDay !== b.lastSlotDay) {
    if (a.lastSlotDay === null) return -1;
    if (b.lastSlotDay === null) return 1;
    return a.lastSlotDay < b.lastSlotDay ? -1 : 1;
  }
  if (a.carryOldestMs !== b.carryOldestMs) {
    if (a.carryOldestMs === null) return 1;
    if (b.carryOldestMs === null) return -1;
    return a.carryOldestMs < b.carryOldestMs ? -1 : 1;
  }
  if (a.appendedRecent !== b.appendedRecent) return a.appendedRecent < b.appendedRecent ? -1 : 1;
  // Ключ 1 равен, значит lastSlotMs у обоих null либо у обоих число.
  if (a.lastSlotMs !== null && b.lastSlotMs !== null && a.lastSlotMs !== b.lastSlotMs) {
    return a.lastSlotMs < b.lastSlotMs ? -1 : 1;
  }
  const aCreated = Number.isFinite(a.createdAtMs) ? a.createdAtMs : Number.POSITIVE_INFINITY;
  const bCreated = Number.isFinite(b.createdAtMs) ? b.createdAtMs : Number.POSITIVE_INFINITY;
  if (aCreated !== bCreated) return aCreated < bCreated ? -1 : 1;
  return a.id < b.id ? -1 : a.id > b.id ? 1 : 0;
}

/** Порядок ночи одной строкой для лога крона: вертикали с их ключами. */
function describeHeRefillVerticalOrder(
  keys: HeRefillOrderKey[],
  carryCompaniesOf: Map<string, number>,
  historyRead: boolean,
  carryCoversDay: boolean,
): string {
  const parts = keys.map((k) => {
    const queue = carryCompaniesOf.get(k.id);
    return (
      `${k.id} (last slot ${k.lastSlotDay ?? 'never'}` +
      (queue === undefined ? '' : `, carried ${queue}`) +
      `, accepted ${HE_REFILL_RANK_RECENT_DAYS}d ${k.appendedRecent})`
    );
  });
  return (
    (carryCoversDay ? 'carried-over queues cover today — queued verticals first, oldest queue first, then: ' : '') +
    (historyRead ? '' : 'run history unread — created_at order: ') +
    parts.join(' > ')
  );
}

/**
 * Ключи 1 и 3 компаратора из журнала прогонов проекта. `null` — журнал не
 * прочитан (сбой, срок): вызывающий берёт прежний порядок по created_at.
 * НИКОГДА НЕ БРОСАЕТ — порядок не повод ронять обход проекта.
 */
async function readRefillRankByVertical(
  supabase: SupabaseClient,
  projectId: string,
  verticalIds: string[],
  now: Date,
): Promise<Map<string, HeRefillRankFacts> | null> {
  try {
    const { data, error } = await supabase
      .from('he_auto_pipeline_runs')
      .select('vertical_id, created_at, stats')
      .eq('project_id', projectId)
      .in('vertical_id', verticalIds)
      .not('base_id', 'is', null)
      .order('created_at', { ascending: false })
      .limit(HE_REFILL_RANK_RUNS_LIMIT);
    if (error) return null;
    const recentFromMs = now.getTime() - HE_REFILL_RANK_RECENT_DAYS * 24 * 60 * 60 * 1000;
    const facts = new Map<string, HeRefillRankFacts>();
    for (const row of (data ?? []) as Array<{ vertical_id?: unknown; created_at?: unknown; stats?: unknown }>) {
      const verticalId = asString(row.vertical_id);
      const createdMs = Date.parse(asString(row.created_at));
      if (!verticalId || !Number.isFinite(createdMs)) continue;
      // Строки идут от свежей к старой: первая встреченная — последний слот.
      const entry = facts.get(verticalId) ?? {
        lastSlotDay: new Date(createdMs).toISOString().slice(0, 10),
        lastSlotMs: createdMs,
        appendedRecent: 0,
      };
      if (createdMs >= recentFromMs) {
        const stats = row.stats && typeof row.stats === 'object' ? (row.stats as { appended?: unknown }) : {};
        const appended = asNumberOrNull(stats.appended);
        if (appended !== null && appended > 0) entry.appendedRecent += appended;
      }
      facts.set(verticalId, entry);
    }
    return facts;
  } catch {
    return null;
  }
}

