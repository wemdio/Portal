/**
 * Enabled-конфиги добора. CONFIG_OPTIONAL_COLUMNS читаются ОПЦИОНАЛЬНО по той
 * же причине, что и колонки пометки у вертикалей (см. loadVerticals): воркер
 * может уехать раньше миграций 20260930_0003/0005, а 42703 здесь уронил бы
 * весь ночной тик. Колонок нет — порог берётся из кода, а паузы по ёмкости
 * просто не существует.
 *
 * `enabled=false` конфиги сюда не попадают вовсе — и паузу им поэтому не
 * ставят и не снимают. Это верно: выключенный добор и без паузы ничего не
 * собирает, а снятие паузы не должно включать добор тому, кто выключил его сам.
 */
async function loadConfigs(supabase: SupabaseClient): Promise<ConfigRow[]> {
  // daily_leads_cap и last_run_at — колонки той же миграции, что и сама
  // таблица (20260804_0005), поэтому в обязательной части выборки.
  const base = 'id, project_id, verticals_per_run, daily_leads_cap, last_run_at';
  let rows: Array<Record<string, unknown>>;
  const first = await supabase
    .from('he_auto_pipeline_configs')
    .select(`${base}, ${CONFIG_OPTIONAL_COLUMNS}`)
    .eq('enabled', true);
  if (first.error && !isMissingColumnError(first.error)) {
    throw new Error(`he_auto_pipeline_configs read: ${first.error.message}`);
  }
  if (first.error) {
    const retry = await supabase.from('he_auto_pipeline_configs').select(base).eq('enabled', true);
    if (retry.error) throw new Error(`he_auto_pipeline_configs read: ${retry.error.message}`);
    rows = (retry.data ?? []) as Array<Record<string, unknown>>;
  } else {
    rows = (first.data ?? []) as Array<Record<string, unknown>>;
  }
  return rows.map((row) => ({
    id: asString(row.id),
    project_id: asString(row.project_id),
    verticals_per_run: asNumberOrNull(row.verticals_per_run),
    last_run_at: asStringOrNull(row.last_run_at),
    daily_leads_cap: asNumberOrNull(row.daily_leads_cap),
    dry_nights_limit: asNumberOrNull(row.dry_nights_limit),
    refill_paused_at: asStringOrNull(row.refill_paused_at),
    refill_pause_reason: asStringOrNull(row.refill_pause_reason),
  }));
}

/**
 * «Тик этот конфиг обошёл»: he_auto_pipeline_configs.last_run_at. Одно
 * определение на все выходы обхода — обычный, ранний (пауза) и упавший после
 * постановки (runForConfig): под паузой добор не идёт, но обход СОСТОЯЛСЯ, и
 * last_run_at, застывший на дате паузы, читался бы как сломавшийся крон.
 * Читатель метки — shouldRunConfigToday: второй за сутки запуск крона конфиг
 * не обходит.
 */
async function touchConfigLastRun(supabase: SupabaseClient, configId: string, now: Date): Promise<void> {
  const { error } = await supabase
    .from('he_auto_pipeline_configs')
    .update({ last_run_at: now.toISOString(), updated_at: now.toISOString() })
    .eq('id', configId);
  if (error) throw new Error(`he_auto_pipeline_configs last_run_at: ${error.message}`);
}

/**
 * Обход одного конфига: ОДИН РАЗ НА UTC-СУТКИ (шаг 1-- в шапке), затем
 * passConfig.
 *
 * ЧТО ДЕРЖИТ СУТКИ. Сам обход пишет last_run_at последним шагом. Упал он
 * посреди — метка пишется, только если этот обход УЖЕ поставил хотя бы одну
 * сборку (`paid.enqueued`): иначе второй запуск крона в те же сутки обошёл бы
 * конфиг заново и купил сборки остальным вертикалям проекта (поставленные
 * вертикали дедуп постановки вернёт 'existing', и слот verticals_per_run они не
 * едят — поэтому и нужны сутки, а не дедуп). Упавший обход, который не
 * поставил ничего, ничего и не оплатил — его повтор в те же сутки и есть
 * починка, метку он не получает.
 *
 * `force` — ручной прогон (`--force` у крона): проверку суток обходит, всё
 * остальное (пауза, дневной бюджет по броням, дедуп постановки) действует.
 */
async function runForConfig(
  supabase: SupabaseClient,
  config: ConfigRow,
  now: Date,
  summary: HeAutoPipelineTickSummary,
  capacityProbe: HeWorkspaceCapacityProbe,
  opts: { force: boolean },
): Promise<void> {
  if (!opts.force && !shouldRunConfigToday(config.last_run_at, now)) {
    summary.alreadyRan += 1;
    summary.details.push({
      configId: config.id,
      projectId: config.project_id,
      status: 'already_ran_today',
      message: `last pass at ${config.last_run_at} — one pass per UTC day, rerun with --force`,
    });
    return;
  }
  const paid = { enqueued: 0 };
  try {
    await passConfig(supabase, config, now, summary, capacityProbe, paid);
  } catch (e) {
    if (paid.enqueued > 0) {
      // Best-effort: исходная ошибка важнее, её и бросаем дальше.
      await touchConfigLastRun(supabase, config.id, now).catch(() => undefined);
    }
    throw e;
  }
}

async function passConfig(
  supabase: SupabaseClient,
  config: ConfigRow,
  now: Date,
  summary: HeAutoPipelineTickSummary,
  capacityProbe: HeWorkspaceCapacityProbe,
  /** Сколько НОВЫХ сборок этот обход уже поставил — читает runForConfig. */
  paid: { enqueued: number },
): Promise<void> {
  const detail = (d: Omit<HeAutoPipelineTickDetail, 'configId' | 'projectId'>) => {
    summary.details.push({ configId: config.id, projectId: config.project_id, ...d });
  };
  const touchLastRun = () => touchConfigLastRun(supabase, config.id, now);

  const dryStopEnabled = heVerticalDryStopEnabled();

  /**
   * Правило сухой вертикали выключено — снимаем пометки СО ВСЕГО ПРОЕКТА, и
   * делаем это РАНЬШЕ проверки паузы.
   *
   * Порядок важен: под паузой по ёмкости мы из функции выходим, и снятие,
   * стоящее после неё, не выполнилось бы НИ РАЗУ, пока проект стоит. Кабинет
   * продолжал бы писать «ночной добор по вертикали остановлен» про правило,
   * которое выключено. Статья расхода — один UPDATE, который в норме не
   * трогает ни строки (фильтр по непустой пометке).
   *
   * Внутри цикла вертикалей этого делать нельзя по отдельной причине: до
   * вертикали можно не дойти (бюджет ночи, пропавшая кампания), и она хранила
   * бы пометку вечно.
   */
  if (!dryStopEnabled) {
    await supabase
      .from('he_verticals')
      .update({ refill_dry_since: null, refill_dry_nights: null })
      .eq('project_id', config.project_id)
      .not('refill_dry_since', 'is', null);
  }

  // ─── ПАУЗА ДОБОРА (раньше всех решений: до чтения вертикалей и
  //     шаблонов, до бюджета, до рассыльщика, до денег) ───
  // Повода три — ёмкость рассыльщика, отмена клиентом и потолок расхода (блок
  // «ПАУЗА ПО ЁМКОСТИ», «ВТОРОЙ ПОВОД», «ТРЕТИЙ ПОВОД»), решение по ним одно.
  // Решение принято раньше и записано в конфиге; перепроверять его
  // сегодняшним запросом к рассыльщику нельзя — ровно этот «автоматический
  // пересмотр» и превратил бы паузу обратно в пропуск одной ночи. Снимает её
  // только сотрудник (resumeHeRefillPause, staff-роут refill-pause).
  // Своей строки he_auto_pipeline_runs пропуск НЕ пишет — та же причина, что у
  // budget_exhausted и dry: в status нет значения «решили не собирать», а
  // 'failed' выдал бы намеренную остановку за сбой. И ровно поэтому ночь под
  // паузой не растит ни серию сухих ночей, ни серию отказов вертикали.
  if (config.refill_paused_at) {
    summary.paused += 1;
    detail({
      status: 'paused',
      message: `nightly refill paused since ${config.refill_paused_at}`
        + (config.refill_pause_reason ? ` — ${config.refill_pause_reason}` : ''),
    });
    // Напоминание команде — раз за ночь, пока пауза стоит: клиент всё это
    // время читает «команда уже работает», а у паузы нет автоснятия. Тик
    // одноразовый и обходит конфиг раз в сутки (shouldRunConfigToday), поэтому
    // «раз за обход» и есть «раз за ночь»; проекты одной ночи opsAlert
    // сворачивает в одно сообщение-список, а отправку списка обеспечивает
    // flushHeOpsAlerts в конце тика. Паузе, записанной ОТМЕНОЙ клиентом,
    // напоминания нет: это не «нет места у рассыльщика», и чинить команде
    // нечего — сотрудник видит её причину в карточке проекта.
    if (!isHeClientCancelPauseReason(config.refill_pause_reason)) {
      // Пауза потолка расхода напоминает о себе своим видом: «освободить место
      // у рассыльщика» про неё было бы неверным советом команде.
      const spendPause = isHeSpendCeilingPauseReason(config.refill_pause_reason);
      await notifyHeClientStop({
        projectId: config.project_id,
        // Тик берёт только market='us' (runHeAutoPipelineTick).
        market: 'us',
        stage: 'refill_paused',
        kind: spendPause ? 'spend_ceiling' : 'capacity_pause',
        provider: spendPause ? 'budget' : 'sending',
        reason:
          `пауза стоит с ${config.refill_paused_at}` +
          (config.refill_pause_reason ? `; ${config.refill_pause_reason}` : ''),
        pauseRecorded: false,
      });
    }
    // Что именно произошло, объясняют строка ночного лога и сама пометка со
    // штампом; last_run_at при этом двигается как у любого обойдённого конфига.
    await touchLastRun();
    return;
  }

  // created_at asc — только исходный порядок списка (и прежний порядок равных
  // очередей переноса ниже). Слоты раздаёт компаратор после переноса
  // (verticalsInOrder, блок «ПОРЯДОК ВЕРТИКАЛЕЙ НОЧИ»).
  const verticals = (await loadVerticals(supabase, config.project_id))
    .slice()
    .sort((a, b) => Date.parse(a.created_at ?? '') - Date.parse(b.created_at ?? ''));

  let campaignByVertical = new Map<string, VerticalLaunchTarget>();
  // Вертикаль → почему её ночь не покупается из-за писем (шаг 3a-- в шапке).
  let heldLetters = new Map<string, string>();
  if (verticals.length > 0) {
    const { data: templateRows, error: tErr } = await supabase
      .from('he_templates')
      .select('vertical_id, launch_info, created_at, letters, personalization_plan')
      .in('vertical_id', verticals.map((v) => v.id))
      .not('launch_info', 'is', null);
    if (tErr) throw new Error(`he_templates read: ${tErr.message}`);
    const launchedTemplates = (templateRows ?? []) as Array<Record<string, unknown>>;
    campaignByVertical = latestCampaignByVertical(launchedTemplates);
    heldLetters = lettersHeldByVertical(launchedTemplates, campaignByVertical);
  }

  const perRun = Math.max(1, config.verticals_per_run ?? HE_AUTO_DEFAULT_VERTICALS_PER_RUN);
  const dryLimit = Math.max(1, config.dry_nights_limit ?? HE_AUTO_DEFAULT_DRY_NIGHTS_LIMIT);
  const dateTag = now.toISOString().slice(0, 10);
  let enqueued = 0;
  // Потолок расхода (шаг 3a-): проверяется один раз за обход, при первой
  // вертикали, которой ночь действительно покупалась бы. Между постановками
  // одного обхода расход не меняется — платит воркер, а он их ещё не взял.
  const spendCaps = readHeSpendCaps();
  let spendChecked = false;
  /** «Расход неизвестен — купили как без потолка»: строка ночного лога. */
  let spendNote: string | null = null;

  // Снятие пометок выключенного правила сухой вертикали стоит ВЫШЕ, до
  // проверки паузы: иначе под паузой оно не выполнялось бы ни разу (см. там же
  // разбор обоих ограничений на его место).

  // ─── ДНЕВНОЙ БЮДЖЕТ ПРОЕКТА (до сухой вертикали, до ёмкости, до денег) ───
  // Кап общий на проект, поэтому и решение общее: выбран — ни одной вертикали
  // сборку не ставим. Проверка идёт ПЕРВОЙ из трёх, потому что она про
  // проект целиком, а две следующие — про вертикаль. Своей строки журнала
  // прогонов пропуск НЕ пишет: в he_auto_pipeline_runs.status нет значения для
  // «решили не собирать», а 'failed' выдал бы намеренную экономию за сбой (та
  // же причина, что у правила сухой вертикали).
  const dayRemaining = verticals.length === 0
    ? null
    : await readRefillDayRemaining(supabase, config.project_id, now);
  const budgetExhausted = dayRemaining === 0;
  if (budgetExhausted) {
    summary.budgetExhausted += 1;
    detail({ status: 'budget_exhausted', message: `daily lead budget for ${dateTag} is fully reserved` });
  }

  // ─── ПЕРЕНОС (шаг 3a- в шапке, после бюджета, до сборок) ───
  // Очередь проекта считается только по вертикалям, которые этой ночью вообще
  // могут отправить: есть кампания и нет пометки сухой вертикали. Остаток дня —
  // по броням, а до первой брони суток (обычный тик в 03:20) — полный кап
  // проекта. Кап не прочитался — правило молчит (прежнее поведение).
  //
  // Хватает очереди на день — ночь получают ТОЛЬКО вертикали с самой старой
  // очередью, по возрастанию её возраста, пока их компаний не хватит на
  // остаток дня. Ночь такой вертикали сборку не покупает (carryOnly в
  // стадии), а остальные — и без очереди, и с более свежей — пропускаются
  // ('carry_covers'): их ночь кончилась бы 'cap_exhausted', то есть строкой
  // отказа и ещё одной вертикалью, которой бюджет не дал ничего. Старые идут
  // первыми, потому что у очереди есть срок: при гонке за бронь случайный
  // победитель оставлял бы старейшие компании ждать до истечения.
  //
  // День закрывает только очередь вертикали, чья ночь ДЕЙСТВИТЕЛЬНО поставлена
  // (carryRunning), а не очередь, которую мы надеялись отправить. Поэтому при
  // покрытом дне вертикали с очередью идут первыми (от старейшей), остальные —
  // следом в порядке компаратора, и решение «пропустить» принимается по уже
  // поставленным ночам. Вертикаль, чья ночь не встала — уже собирается
  // ('existing': база застряла в сборке), сбой постановки, пометка сухой, —
  // день не закрывает: ночь получает следующая по возрасту очередь, а не
  // хватило очередей — и вертикали без очереди. Без этого одна застрявшая
  // вертикаль с самой старой очередью отнимала бы ночь у здоровых до конца
  // срока очереди (до 7 суток).
  const carryByVertical =
    budgetExhausted || verticals.length === 0
      ? null
      : await readCarryoverByVertical(supabase, config.project_id, now);
  const carryCandidates: Array<{ id: string; companies: number; oldestMs: number }> = [];
  for (const vertical of verticals) {
    if (!carryByVertical || !campaignByVertical.has(vertical.id)) continue;
    if (dryStopEnabled && vertical.refill_dry_since) continue;
    // Ночь этой вертикали не ставится (шаг 3a--), а её очередь отбор долива
    // снял бы целиком: день она не закрывает.
    if (heldLetters.has(vertical.id)) continue;
    const queue = carryByVertical.get(vertical.id);
    if (queue && queue.companies > 0) carryCandidates.push({ id: vertical.id, ...queue });
  }
  const projectCarry = carryCandidates.reduce((sum, c) => sum + c.companies, 0);
  const dayLeft = dayRemaining ?? config.daily_leads_cap;
  const carryCoversDay = dayLeft !== null && projectCarry > 0 && projectCarry >= dayLeft;
  const carryQueueOf = new Map(carryCandidates.map((c) => [c.id, c.companies]));
  const verticalById = new Map(verticals.map((v) => [v.id, v]));

  // ─── ПОРЯДОК ВЕРТИКАЛЕЙ (блок «ПОРЯДОК ВЕРТИКАЛЕЙ НОЧИ» выше) ───
  // Ключ 2 — те же очереди, что считает перенос (carryCandidates): только
  // вертикали, которые этой ночью могут отправить. Журнал не прочитался —
  // ключи 1–4 не ставятся никому, и остаётся прежний порядок по created_at.
  const rankFacts =
    budgetExhausted || verticals.length === 0
      ? null
      : await readRefillRankByVertical(supabase, config.project_id, verticals.map((v) => v.id), now);
  const carryOldestOf = new Map(carryCandidates.map((c) => [c.id, c.oldestMs]));
  const orderKeys = verticals
    .map((v): HeRefillOrderKey => {
      const facts = rankFacts?.get(v.id);
      return {
        id: v.id,
        lastSlotDay: facts?.lastSlotDay ?? null,
        carryOldestMs: rankFacts ? (carryOldestOf.get(v.id) ?? null) : null,
        appendedRecent: facts?.appendedRecent ?? 0,
        lastSlotMs: facts?.lastSlotMs ?? null,
        createdAtMs: Date.parse(v.created_at ?? ''),
      };
    })
    .sort(compareHeRefillVerticalOrder);
  const verticalsInOrder = orderKeys
    .map((k) => verticalById.get(k.id))
    .filter((v): v is (typeof verticals)[number] => v !== undefined);
  if (!budgetExhausted && verticals.length > 0) {
    summary.orders.push({
      configId: config.id,
      projectId: config.project_id,
      order: describeHeRefillVerticalOrder(orderKeys, carryQueueOf, rankFacts !== null, carryCoversDay),
    });
  }

  // Очередям хватает на день — они первыми, от старейшей (шаг 3a- в шапке),
  // за ними остальные в порядке компаратора.
  const tickOrder = carryCoversDay
    ? [
        ...carryCandidates
          .slice()
          .sort((a, b) => a.oldestMs - b.oldestMs)
          .map((c) => verticalById.get(c.id))
          .filter((v): v is (typeof verticals)[number] => v !== undefined),
        ...verticalsInOrder.filter((v) => !carryQueueOf.has(v.id)),
      ]
    : verticalsInOrder;
  /** Компании очередей вертикалей, чья ночь этим тиком действительно поставлена. */
  let carryRunning = 0;

  for (const vertical of budgetExhausted ? [] : tickOrder) {
    if (enqueued >= perRun) break;
    const target = campaignByVertical.get(vertical.id);
    if (!target) {
      summary.noCampaign += 1;
      detail({ verticalId: vertical.id, status: 'no_campaign' });
      continue;
    }
    const { campaignId } = target;

    // ─── СУХАЯ ВЕРТИКАЛЬ (до предполёта, до постановки, до денег) ───
    // Правило и разбор состояний — в блоке «СУХАЯ ВЕРТИКАЛЬ» вверху файла.
    // Идёт ПЕРВЫМ из двух отказов: чтение журнала своё и дешёвое, а предполёт
    // ёмкости — запрос к рассыльщику из общего rate-limit, и тратить его на
    // вертикаль, которую мы всё равно не собираем, незачем.
    if (dryStopEnabled && vertical.refill_dry_since) {
      // Решение уже записано — журнал ради него не перечитываем. Пометка это и
      // есть решение со своим числом ночей; отменяет его клиент кнопкой
      // (resumeHeVerticalNightlyRefill), а не следующее чтение истории. Иначе
      // сбой чтения или поднятый порог молча возвращали бы платные ночи, а
      // фраза кабинета («… — N daily refills in a row brought no new
      // contacts», EngStepVerticals.tsx) перестала бы совпадать с тем, что
      // происходит.
      summary.dry += 1;
      detail({
        verticalId: vertical.id,
        status: 'dry',
        ...(vertical.refill_dry_nights === null ? {} : { dryNights: vertical.refill_dry_nights }),
      });
      continue;
    }
    // Пометки выключенного правила сняты выше, разом по проекту: снимать их
    // здесь значило бы не снять у вертикали, до которой цикл не дошёл.
    // Серия считается ВСЕГДА, включая выключённое правило: это единственный
    // материал, по которому порог потом выбирается по факту (см. dryNights в
    // HeAutoPipelineTickDetail).
    const dryStreak = await readDryNightStreak(supabase, vertical, dryLimit);
    const dryNightsDetail = dryStreak === null ? {} : { dryNights: dryStreak };
    if (dryStopEnabled && dryStreak !== null && dryStreak >= dryLimit) {
      // Записать решение обязаны ДО пропуска: пропуск без пометки — это добор,
      // пропавший без объяснения (см. writeDryMark). Не записалось — решения
      // нет, вертикаль идёт в сборку как раньше.
      const marked = await writeDryMark(supabase, vertical.id, {
        refill_dry_since: now.toISOString(),
        refill_dry_nights: dryStreak,
      });
      if (marked) {
        summary.dry += 1;
        detail({ verticalId: vertical.id, status: 'dry', ...dryNightsDetail });
        continue;
      }
    }

    // ─── ПИСЬМА ЗАПУЩЕННОГО ШАБЛОНА (шаг 3a-- в шапке; до переноса, до
    //     предполёта, до постановки, до денег) ───
    // Отбор долива снял бы все строки ночи при любых строках — сборку не
    // ставим, слот не расходуем. Ночь — строкой журнала без base_id, как отказ
    // предполёта ёмкости: дневную бронь она не трогает (бронь берёт только
    // сам долив), в серию сухих ночей и в серию отказов вертикали не входит
    // (обе читают только строки с base_id). Каждую ночь, пока письма не
    // починят: ни пометки, ни паузы здесь нет — пересобранный и запущенный
    // шаблон снимает отказ сам, следующей же ночью (тик сверяет шаблон
    // последнего запуска вертикали).
    const lettersHeld = heldLetters.get(vertical.id);
    if (lettersHeld !== undefined) {
      summary.lettersHeld += 1;
      detail({
        verticalId: vertical.id,
        status: 'letters_held',
        ...dryNightsDetail,
        message: `letters of the launched template would hold every row (${lettersHeld}) — no collection bought`,
      });
      // Тот же алерт, что у долива, снявшего все строки (alertRefillLettersHeld
      // в stages/baseCollectRefill.ts): вид 'letters_held', окно молчания по
      // вертикали. Ждём, а не `void`: крон одноразовый (ожидание ограничено
      // внутри opsAlert). До записи журнала: команде важнее узнать, чем строке лечь.
      await notifyHeClientStop({
        projectId: config.project_id,
        // Тик берёт только market='us' (runHeAutoPipelineTick).
        market: 'us',
        stage: 'refill_preflight',
        kind: 'letters_held',
        provider: 'letters',
        // «Не куплена» — первым: opsAlert режет текст до HE_OPS_REASON_MAX, а
        // причина гейта бывает длиннее (у долива порядок обратный: там сборка
        // куплена, и важнее причина).
        reason: `ночь НЕ куплена, письма сняли бы все строки ещё до сборки (кампания ${campaignId}): ${lettersHeld}`,
        verticalId: vertical.id,
        clientSees: 'строку ленты «refill failed»; вертикаль остаётся «live»',
      });
      await insertRun(supabase, {
        config_id: config.id,
        project_id: config.project_id,
        vertical_id: vertical.id,
        base_id: null,
        status: 'failed',
        stats: { error_kind: 'letters_held' },
        error: `${LETTERS_HELD_ERROR}: ${lettersHeld}`.slice(0, 500),
        completed_at: now.toISOString(),
      });
      continue;
    }

    // ─── ПЕРЕНОС ЗАКРЫВАЕТ ДЕНЬ (до предполёта: запрос к рассыльщику не
    //     тратим на вертикаль, которую не собираем) ───
    // Очереди уже поставленных ночей хватает на остаток дня (carryRunning):
    // их ночь сборку и не купит (carryOnly в стадии), а ночь любой другой
    // кончилась бы 'cap_exhausted' без единого письма. Пока не хватает —
    // ночь получает следующая вертикаль порядка tickOrder. Строки журнала
    // пропуск не пишет — та же причина, что у budget_exhausted и dry.
    if (carryCoversDay && carryRunning >= (dayLeft ?? 0)) {
      summary.carryCovers += 1;
      detail({
        verticalId: vertical.id,
        status: 'carry_covers',
        ...dryNightsDetail,
        message:
          `carried-over companies of the verticals running tonight (${carryRunning}) cover ` +
          `today's lead budget (${dayLeft}) — older queues go first, no run for this vertical tonight`,
      });
      continue;
    }

    // ─── ПОТОЛОК РАСХОДА ПРОЕКТА (шаг 3a- в шапке; до предполёта: запрос к
    //     рассыльщику проекту, которому ночь всё равно не покупаем, незачем) ───
    // ПО УМОЛЧАНИЮ ВЫКЛЮЧЕН — тогда checkHeSpendCeiling отвечает 'off' без
    // единого запроса. 'unknown' (журнал не прочитан, срок, неполное чтение
    // ниже порога) — покупаем как раньше (fail-open), причина — в строку лога.
    if (!spendChecked) {
      spendChecked = true;
      const spend = await checkHeSpendCeiling(supabase, {
        projectId: config.project_id,
        // Тик берёт только market='us' (runHeAutoPipelineTick).
        market: 'us',
        caps: spendCaps,
        now,
      });
      if (spend.verdict.kind === 'over') {
        // Пауза — ДО алерта и без строки he_auto_pipeline_runs: та же причина,
        // что у паузы в начале обхода (в status нет «решили не собирать», а
        // 'failed' выдал бы намеренную остановку за сбой).
        const paused = await pauseHeAutoPipelineRefill(
          supabase,
          config.project_id,
          buildHeSpendCeilingPauseReason(spend),
          { now },
        );
        // Ждём, а не `void`: крон одноразовый (ожидание ограничено в opsAlert).
        await alertHeSpendCeiling({
          projectId: config.project_id,
          check: spend,
          stage: 'refill_preflight',
          path: 'nightly_refill',
          verticalId: vertical.id,
          pauseRecorded: paused,
          clientSees: 'состояние ночного добора «spend_paused»: «The daily refill for this project is on hold…»',
        });
        summary.paused += 1;
        detail({
          verticalId: vertical.id,
          status: 'paused',
          ...dryNightsDetail,
          message:
            `spend ceiling reached (${spend.verdict.cap}: $${spend.verdict.spendUsd.toFixed(2)} ≥ ` +
            `$${spend.verdict.capUsd.toFixed(2)}) — no collection bought, refill pause ` +
            (paused ? 'recorded' : 'NOT recorded (already paused, no config or no columns)'),
        });
        break;
      }
      if (spend.verdict.kind === 'unknown') {
        spendNote = `spend ceiling unknown (${spend.failure ?? spend.verdict.cap}) — bought without it`;
      }
    }

    // ─── ПРЕДПОЛЁТ ЁМКОСТИ ВОРКСПЕЙСА (до постановки, до денег) ───
    // Платит СБОРКА: краул сайтов и SMTP-проба каждого адреса уходят задолго до
    // долива, и раньше «нет места у рассыльщика» обнаруживалось только на
    // append'е — после оплаты и с выжженными компаниями. Ноль остатка — не
    // ставим и не тратим; null («не знаем») — работаем как раньше, отказ поймает
    // пауза долива (stages/baseCollectRefill.ts).
    const remainingCapacity = await capacityProbe(target.presetId);
    if (remainingCapacity === 0) {
      summary.capacityBlocked += 1;
      detail({ verticalId: vertical.id, status: 'capacity_blocked', ...dryNightsDetail });
      // Ноль ДОКАЗАН (число пришло от самого рассыльщика, а не угадано) —
      // записываем durable-паузу проекта, иначе завтрашняя ночь спросит то же
      // самое заново и так каждую ночь, пока место не освободится. null
      // («не знаем») сюда не доходит по условию выше — это ключевое: пауза
      // ставится только по доказанному нулю.
      //
      // Best-effort: не записалось (нет колонок, нет конфига, сбой) — ведём
      // себя как до этой правки, то есть пропускаем ночь и пробуем завтра.
      // Пишем ДО insertRun: строка журнала — объяснение, а деньги экономит
      // пауза, и терять её из-за сбоя вставки журнала незачем.
      const paused = await pauseHeAutoPipelineRefill(
        supabase,
        config.project_id,
        buildHeCapacityPauseReason('ночной предполёт ёмкости (остаток 0)'),
        { now },
      );
      // Команде — в момент паузы, независимо от того, легла ли она (без
      // конфига или колонок кабинет всё равно покажет «команда уже работает»
      // по строке журнала ниже). Ждём, а не `void`: крон одноразовый, и
      // невыжданная отправка умерла бы вместе с процессом; ожидание ограничено
      // 15 с внутри opsAlert.
      await notifyHeClientStop({
        projectId: config.project_id,
        // Тик берёт только market='us' (runHeAutoPipelineTick).
        market: 'us',
        stage: 'refill_preflight',
        kind: 'capacity_pause',
        provider: 'sending',
        reason: CAPACITY_REFUSAL_ERROR,
        pauseRecorded: paused,
      });
      await insertRun(supabase, {
        config_id: config.id,
        project_id: config.project_id,
        vertical_id: vertical.id,
        // base_id NULL — сбора не было. Это же отличает отказ ПОСТАНОВКИ от
        // отказа среза: серию отказов вертикали (refillFailStreak, решает,
        // возвращать ли компании в пул) считают только строки с base_id.
        base_id: null,
        status: 'failed',
        stats: { error_kind: 'instantly_capacity' },
        error: CAPACITY_REFUSAL_ERROR,
        completed_at: now.toISOString(),
      });
      // Остальные вертикали проекта — в том же воркспейсе: пресет один на
      // client_user_id, а все запуски проекта идут от одного клиента. Спрашивать
      // по каждой одно и то же и писать ей такую же строку журнала незачем.
      break;
    }

    // ─── ПАУЗА У САМОЙ ПОСТАНОВКИ (шаг 4- в шапке) ───
    // Конфиг прочитан в начале тика, а до этой строки проходят секунды
    // (журнал, шаблоны, запрос к рассыльщику). Отмена клиентом, нажатая в это
    // окно, иначе получила бы сборку, поставленную уже после её «Cancel»; то
    // же — пауза по ёмкости, записанной доливом соседней вертикали проекта.
    // Пропуск строки журнала не пишет — та же причина, что у паузы в начале
    // обхода.
    const pauseBefore = await readRefillPauseNow(supabase, config.project_id);
    if (pauseBefore) {
      summary.paused += 1;
      detail({
        verticalId: vertical.id,
        status: 'paused',
        ...dryNightsDetail,
        message:
          `nightly refill paused during this pass (since ${pauseBefore.pausedAt})` +
          (pauseBefore.reason ? ` — ${pauseBefore.reason}` : ''),
      });
      break;
    }

    const result = await enqueueHeBaseCollect(supabase, {
      verticalId: vertical.id,
      projectId: config.project_id,
      verticalName: vertical.name,
      limit: HE_AUTO_REFILL_ROWS_LIMIT,
      hypothesisIds: null,
      filename: `auto-refill: ${vertical.name} · ${dateTag}`,
      refill: { campaignId },
    });
    if (!result.ok) {
      summary.failed += 1;
      detail({ verticalId: vertical.id, status: 'failed', message: result.message, ...dryNightsDetail });
      await insertRun(supabase, {
        config_id: config.id,
        project_id: config.project_id,
        vertical_id: vertical.id,
        base_id: null,
        status: 'failed',
        error: result.message.slice(0, 500),
        completed_at: now.toISOString(),
      });
      continue;
    }
    if (!result.created) {
      // Уже собирается (ручной запуск или вчерашний refill) — слот не ест.
      summary.existing += 1;
      detail({
        verticalId: vertical.id,
        baseId: asString(result.base.id) || null,
        status: 'existing',
        ...dryNightsDetail,
      });
      continue;
    }

    const baseId = asString(result.base.id);
    // ─── ОТМЕНА, ЗАПИСАННАЯ МЕЖДУ ЧТЕНИЕМ ПАУЗЫ И ПОСТАНОВКОЙ ───
    // Последнее окно: cancel-роут пишет паузу ДО отмены джоб, поэтому джоба,
    // вставленная после его отмены джоб, здесь уже видит паузу — и отзывается
    // теми же статусами, что пишет роут (см. withdrawRefillAfterClientCancel).
    // Только пауза отмены: пауза по ёмкости — забота предполёта ёмкости
    // самого долива (appendLeadsToClientCampaign), и отзывать по ней уже
    // поставленную сборку этот тик не берётся.
    const pauseAfter = await readRefillPauseNow(supabase, config.project_id);
    if (pauseAfter && isHeClientCancelPauseReason(pauseAfter.reason)) {
      const withdrawn = await withdrawRefillAfterClientCancel(supabase, {
        projectId: config.project_id,
        baseId,
        now,
      });
      summary.paused += 1;
      // Не отозвалась — джоба может исполниться и оплатить сборку: для
      // правила суток это поставленная сборка (runForConfig).
      if (!withdrawn) paid.enqueued += 1;
      detail({
        verticalId: vertical.id,
        baseId,
        status: 'paused',
        ...dryNightsDetail,
        message: withdrawn
          ? 'client cancelled during this pass — the just-enqueued refill was withdrawn before it ran'
          : 'client cancelled during this pass — withdrawing the just-enqueued refill FAILED; ' +
            'its send is stopped by the refill ownership check',
      });
      break;
    }

    enqueued += 1;
    paid.enqueued += 1;
    summary.enqueued += 1;
    // Ночь встала — её очередь (если есть) уйдёт этой ночью и закрывает день.
    carryRunning += carryQueueOf.get(vertical.id) ?? 0;
    await insertRun(supabase, {
      config_id: config.id,
      project_id: config.project_id,
      vertical_id: vertical.id,
      base_id: baseId,
      status: 'collecting',
    });
    detail({
      verticalId: vertical.id,
      baseId,
      status: 'enqueued',
      // Серия пустых ночей на момент постановки: с ней ночной лог отвечает на
      // вопрос «насколько эта вертикаль близка к порогу», не заходя в БД.
      ...dryNightsDetail,
      // Остаток ёмкости в строке журнала крона — доказательство, что предполёт
      // действительно отработал (а не молча деградировал в «не знаем»): для
      // первой ночи под присмотром это единственный способ отличить одно от
      // другого, не заходя в рассыльщик.
      ...(remainingCapacity === null && spendNote === null
        ? {}
        : {
            message: [
              remainingCapacity === null ? null : `workspace capacity ${remainingCapacity}`,
              spendNote,
            ].filter(Boolean).join('; '),
          }),
    });
  }

  // Тик по конфигу отработал (даже без новых постановок и под паузой,
  // замеченной посреди обхода, — тот же исход, что пауза в его начале) —
  // фиксируем.
  await touchLastRun();
}

/**
 * Один тик ENG auto-pipeline. Ошибки чтения конфигов/проектов — фатальны
 * (бросок, крон выйдет с кодом 1); ошибки обхода отдельного конфига изолированы
 * (summary.failed + detail), остальные конфиги продолжаются.
 *
 * `force` — ручной прогон (`--force` у крона): обходит конфиги, уже обойдённые
 * в эти UTC-сутки (shouldRunConfigToday). По умолчанию выключен.
 */
export async function runHeAutoPipelineTick(
  supabase: SupabaseClient,
  opts: { now?: Date; force?: boolean } = {},
): Promise<HeAutoPipelineTickSummary> {
  const now = opts.now ?? new Date();
  const force = opts.force === true;
  const summary: HeAutoPipelineTickSummary = {
    configs: 0,
    alreadyRan: 0,
    enqueued: 0,
    existing: 0,
    noCampaign: 0,
    capacityBlocked: 0,
    budgetExhausted: 0,
    paused: 0,
    dry: 0,
    carryCovers: 0,
    lettersHeld: 0,
    failed: 0,
    details: [],
    orders: [],
  };

  const configs = (await loadConfigs(supabase)).filter((c) => c.id && c.project_id);
  if (configs.length === 0) return summary;

  // Только us-проекты: добор идёт в ENG-кампании (RU-поток покрывает
  // client_auto_pipeline_*).
  const { data: projectRows, error: projectsErr } = await supabase
    .from('he_projects')
    .select('id, market')
    .in('id', configs.map((c) => c.project_id));
  if (projectsErr) throw new Error(`he_projects read: ${projectsErr.message}`);
  const usProjectIds = new Set(
    ((projectRows ?? []) as Array<{ id?: unknown; market?: unknown }>)
      .filter((p) => p.market === 'us')
      .map((p) => asString(p.id)),
  );
  const eligible = configs.filter((c) => usProjectIds.has(c.project_id));
  summary.configs = eligible.length;

  // Предполёт ёмкости — один на тик: мемоизация внутри держит один запрос к
  // рассыльщику на воркспейс, сколько бы конфигов и вертикалей тик ни обошёл.
  const capacityProbe = createHeWorkspaceCapacityProbe();

  try {
    for (const config of eligible) {
      try {
        await runForConfig(supabase, config, now, summary, capacityProbe, { force });
      } catch (e) {
        summary.failed += 1;
        summary.details.push({
          configId: config.id,
          projectId: config.project_id,
          status: 'failed',
          message: e instanceof Error ? e.message : String(e),
        });
      }
    }
  } finally {
    // Крон одноразовый: полный воркспейс останавливает все проекты одной и той
    // же ночью, и opsAlert отправляет сразу только первый из них, а остальные
    // копит на 10 минут в одно сообщение-список. Без этой отправки список
    // умер бы вместе с процессом, и команда узнала бы об одном проекте из
    // многих. Не бросает и ограничен по времени внутри opsAlert.
    await flushHeOpsAlerts();
  }

  return summary;
}
