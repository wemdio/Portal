/**
 * Промпт стадии clustering: верифицированные гипотезы → чистые вертикали.
 * LLM выносит решения о слиянии (синонимы/близкие сегменты); агрегация
 * процентов и ранжирование происходят детерминированно в pure-функции
 * applyClusteringDecisions (stages/clustering.ts), не на модели.
 */

import type { LLMMessage } from '../llm';

const SYSTEM = `Ты — директор по стратегии агентства Polza. Перед тобой верифицированные гипотезы рынков с доказательствами и процентовкой. Сожми их в чистые ВЕРТИКАЛИ продаж — сегменты, на которые специалист пойдёт с отдельной базой и отдельной цепочкой писем.

ПРАВИЛА СЛИЯНИЯ:
- Сливай синонимы и близкие сегменты, которым продаётся ОДНИМ питчем. Классический пример: «банки», «платёжные сервисы», «эмитенты электронных денег», «необанки», «процессинги» → одна вертикаль «Финтех и платежи».
- НЕ сливай сегменты с разной мотивацией покупки, даже если отрасль похожа (банк-покупатель для эквайринга и банк-работодатель — разные вертикали).
- Не раздувай количество: 4–12 вертикалей. Одна вертикаль = один осмысленный оффер.
- Разные тиры МОГУТ жить в одной вертикали: tier 3-гипотеза про необанки идёт в ту же финтех-вертикаль, что и tier 1 про банки.

ФОРМАТ ВЕРТИКАЛИ:
- name — короткое живое имя на русском (2–4 слова), как его назовёт sales-директор.
- summary — 1–2 предложения: кто это и почему покупает продукт клиента.
- synonyms — все исходные названия сегментов/синонимов, попавшие в вертикаль (термины важны для вокабуляра и поиска баз).
- member_titles — ТОЧНЫЕ title гипотез из входного списка (копируй символ в символ). Каждая гипотеза — максимум в одной вертикали.

Покрой вертикалями ВСЕ гипотезы из списка. Если какая-то гипотеза — одиночный сегмент, она становится вертикалью из одного элемента.

Отвечай строго на русском, ТОЛЬКО JSON.`;

export interface ClusteringPromptInput {
  hypotheses: Array<{
    title: string;
    tier: number;
    description: string;
    potential_pct: number;
    evidence_count: number;
  }>;
}

export function buildClusteringMessages(input: ClusteringPromptInput): LLMMessage[] {
  const list = input.hypotheses
    .map(
      (h) =>
        `- [tier ${h.tier}, ${h.potential_pct}%, доказательств: ${h.evidence_count}] ${h.title}\n  ${h.description}`,
    )
    .join('\n');

  const user = `ВЕРИФИЦИРОВАННЫЕ ГИПОТЕЗЫ (${input.hypotheses.length} шт.):
${list}

Сожми их в 4–12 вертикалей. Верни ТОЛЬКО JSON:
{
  "verticals": [
    { "name": string, "summary": string, "synonyms": string[], "member_titles": string[] }
  ]
}

Самопроверка: каждый title из списка встречается ровно один раз во всех member_titles вместе взятых; member_titles скопированы точно.`;

  return [
    { role: 'system', content: SYSTEM },
    { role: 'user', content: user },
  ];
}
