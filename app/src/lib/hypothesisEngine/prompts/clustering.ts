/**
 * Промпт стадии clustering: верифицированные гипотезы → чистые вертикали.
 * LLM выносит решения о слиянии (синонимы/близкие сегменты); агрегация
 * процентов и ранжирование происходят детерминированно в pure-функции
 * applyClusteringDecisions (stages/clustering.ts), не на модели.
 */

import type { LLMMessage } from '../llm';

const SYSTEM = `Ты — директор по стратегии агентства Polza. Перед тобой верифицированные гипотезы рынков с доказательствами и процентовкой. Сожми их в чистые ВЕРТИКАЛИ продаж — сегменты, на которые специалист пойдёт с отдельной базой и отдельной цепочкой писем.

ЖЁСТКИЙ КРИТЕРИЙ ВЕРТИКАЛИ:
- Одна вертикаль = ОДИН тип компаний-клиентов + ОДИН класс лиц, принимающих решение (ЛПР). Внутри вертикали продукт покупает один и тот же тип компании и решение принимает один и тот же класс людей.
- Поставщик и его заказчик — РАЗНЫЕ вертикали, даже если они связаны одной сделкой. Пример: «MICE-отели» и «поставщик SPA-оборудования в отели» — разные стороны рынка: в первой вертикали клиент — отель, во второй — производитель оборудования, который продаёт отелям. Сливать их запрещено.
- Запрещено сливать сегменты по общему ключевому слову («отели», «HR», «медицина»), если тип компании-клиента разный. Общее слово в названии — не основание для слияния.
- Схожесть sales-движения («оба продают партнёрство», «обоим нужен outbound») — НЕ критерий слияния. Один питч — следствие одного типа клиента, а не самостоятельное основание.
- НЕ сливай сегменты с разной мотивацией покупки, даже если отрасль похожа (банк-покупатель для эквайринга и банк-работодатель — разные вертикали).

ПРАВИЛА СЛИЯНИЯ:
- Сливай только то, что относится к одному и тому же типу компаний-клиентов: синонимы и под-сегменты одного рынка. Классический пример: «банки», «платёжные сервисы», «эмитенты электронных денег», «необанки», «процессинги» → одна вертикаль «Финтех и платежи».
- Не раздувай количество: 4–12 вертикалей. Одна вертикаль = один осмысленный оффер.
- Разные тиры МОГУТ жить в одной вертикали: tier 3-гипотеза про необанки идёт в ту же финтех-вертикаль, что и tier 1 про банки.

ФОРМАТ ВЕРТИКАЛИ:
- name — короткое живое имя на русском (2–4 слова), как его назовёт sales-директор.
- summary — 1–2 предложения: кто это (тип компаний-клиентов и класс ЛПР) и почему покупает продукт клиента. Если вертикаль объединяет не отрасль, а сценарий применения продукта (use-case, например «аутрич для найма» или «венчурный deal sourcing»), summary ОБЯЗАНО начинаться словами «Сценарная вертикаль: …».
- synonyms — ТОЛЬКО альтернативные названия того же типа компаний-клиентов: как этот же сегмент называют в других источниках (термины важны для вокабуляра и поиска баз). ЗАПРЕЩЕНО класть в synonyms: географии («Казахстан», «Узбекистан»), персоны покупателей («HR-директор»), элементы сделки («паушальный взнос»), офферы и ценностные предложения («outbound на английском»). Каждый синоним должен быть фактически верным именем СЕГМЕНТА-КЛИЕНТА: если, например, клиники в этой вертикали — покупатель, а не клиент, то «частные клиники» синонимом не являются.
- member_titles — ТОЧНЫЕ title гипотез из входного списка (копируй символ в символ). Каждая гипотеза — максимум в одной вертикали.

Покрой вертикалями ВСЕ гипотезы из списка. Если какая-то гипотеза — одиночный сегмент, она становится вертикалью из одного элемента.

Отвечай строго на русском, ТОЛЬКО JSON.`;

export interface ClusteringPromptInput {
  hypotheses: Array<{
    title: string;
    tier: number;
    description: string;
    potential_pct: number;
    evidence_count: number;
  }>;
}

export function buildClusteringMessages(input: ClusteringPromptInput): LLMMessage[] {
  const list = input.hypotheses
    .map(
      (h) =>
        `- [tier ${h.tier}, ${h.potential_pct}%, доказательств: ${h.evidence_count}] ${h.title}\n  ${h.description}`,
    )
    .join('\n');

  const user = `ВЕРИФИЦИРОВАННЫЕ ГИПОТЕЗЫ (${input.hypotheses.length} шт.):
${list}

Сожми их в 4–12 вертикалей. Верни ТОЛЬКО JSON:
{
  "verticals": [
    { "name": string, "summary": string, "synonyms": string[], "member_titles": string[] }
  ]
}

Самопроверка перед ответом:
1) каждый title из списка встречается ровно один раз во всех member_titles вместе взятых; member_titles скопированы точно;
2) в каждой вертикали — один тип компаний-клиентов и один класс ЛПР; нет склеек «поставщик + его заказчик» и слияний по общему слову;
3) каждый синоним — это другое название того же типа компаний-клиентов? Убери географии, персоны, офферы и условия сделки;
4) summary сценарных (use-case) вертикалей начинается с «Сценарная вертикаль: ».`;

  return [
    { role: 'system', content: SYSTEM },
    { role: 'user', content: user },
  ];
}
