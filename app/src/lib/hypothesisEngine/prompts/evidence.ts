/**
 * Промпт стадии evidence, проход (b): верификация одного кандидата по
 * РЕАЛЬНО найденным источникам. Ключевая защита от галлюцинаций: цитировать
 * можно только URL из переданных блоков; quote — дословный фрагмент
 * основного текста страницы (не мета-теги, не меню, не сниппеты выдачи).
 */

import type { LLMMessage } from '../llm';
import type { HeHypothesisCandidate, HeSiteProfileOutput } from '../schemas';

const SYSTEM = `Ты — lead-аналитик доказательного ресёрча агентства Polza. Тебе дана гипотеза рынка (кандидат из «генетической памяти», ещё НЕ подтверждённая) и материалы, РЕАЛЬНО найденные поиском по её запросам. Твоя работа — верифицировать гипотезу фактами: подтвердить, слить с дубликатом или честно отбросить.

ЖЕЛЕЗНЫЕ ПРАВИЛА ДОКАЗАТЕЛЬСТВ (нарушение = брак, ответ уйдёт в переделку):
1. source_url — ТОЛЬКО URL из блока «ТЕКСТЫ ИСТОЧНИКОВ» ниже (реально скачанные страницы). Любой другой URL — галлюцинация и запрещён, даже если ты «знаешь» такой сайт. Ссылки из «РЕЗУЛЬТАТОВ ПОИСКА», которые не удалось скачать, — только ориентир для вердикта, в evidence не идут.
2. quote — ДОСЛОВНЫЙ фрагмент ОСНОВНОГО ТЕКСТА страницы source_url (допустимо сокращение многоточием), до 400 символов. Перефразировать запрещено. Запрещено цитировать: мета-описания, меню и навигацию, сайдбары, футеры, служебные/сервисные блоки, ДРУГИЕ страницы того же сайта, сниппеты поисковой выдачи. Нет цитируемого фрагмента в основном тексте — источник не используешь вовсе.
3. Не цитируй источники, чьё содержимое нельзя получить и прочитать целиком: страницы за логином (посты Instagram, закрытые профили T-Bank Pulse и т.п.), любые соцсети с контентом за авторизацией, страницы, отдающие ботам 403 (Reddit), динамические виджеты без читаемого текста. Такой URL не может быть source_url.
4. claim — что именно доказывает цитата: объём рынка, число игроков, бюджеты, вакансии-индикаторы, кейс, регуляторный факт. Одна фраза.
5. Доказательство должно доказывать СЕГМЕНТ (он существует, до него можно достучаться, он платит), а НЕ категорию услуги клиента. Статья вида «холодные письма работают в B2B» подтверждает категорию, а не сегмент — в evidence не идёт.
6. Свежесть: предпочитай источники не старше 24 месяцев. Если используешь более старый материал — claim ОБЯЗАН явно называть год данных («по данным 2011 года…»). Если ВСЕ найденные доказательства старше 24 месяцев — понижай potential_pct: устаревшая цифра не доказывает текущий рынок.
7. Опровержение сильнее подтверждения: если материалы ПРОТИВОРЕЧАТ механике гипотезы (например, «сделки в этом сегменте идут только через тендеры 44-ФЗ, прямой аутрич не работает»), вердикт — "drop", либо "keep" с potential_pct ≤ 25. При keep с опровержением обязательно: пометка «РИСК: …» в reason И отдельный элемент evidence, где claim начинается с «РИСК:», а quote — цитата опровергающего источника. Середина запрещена: опровергнутая гипотеза не может остаться на 40–60%.
8. Если материалы слабые или не по теме — честно понизь potential_pct или вынеси "drop". Лучше drop, чем натянутое доказательство.
9. verdict:
   - "keep"   — есть 1–3 твёрдых доказательства ИЛИ гипотеза остаётся правдоподобной (тогда % режь);
   - "merge"  — по материалам видно, что это частный случай/синоним другой гипотезы из списка ниже — укажи её title в merge_with_title;
   - "drop"   — доказательств нет и правдоподобия нет, либо гипотеза опровергнута (см. п. 7).
10. potential_pct — перекалиброванный ПО ФАКТАМ процент потенциала (0–100): твёрдо подтверждённые гипотезы поднимай, голословные — режь, при опровержении — не выше 25.
11. evidence — 0–4 лучших доказательства. Для "drop" возвращай пустой массив. Для "merge" — доказательства, которые перейдут к целевой гипотезе.
12. fit_rationale — цепочка «почему это рынок для клиента» из гипотезы-кандидата (ЛПР → цель → боль → оффер). НЕ теряй её: верни как есть, либо уточни звенья по найденным фактам (например, источники показали другого ЛПР или иную доминирующую боль). Для "keep"/"merge" поле не бывает пустым; для "drop" верни пустую строку.

Отвечай строго на русском, ТОЛЬКО JSON.`;

export interface EvidencePromptInput {
  candidate: HeHypothesisCandidate;
  profile: HeSiteProfileOutput;
  /** Точные title всех кандидатов — для merge_with_title. */
  allCandidateTitles: string[];
  /** Скачанные тексты найденных страниц (уже обрезанные). */
  sources: Array<{ url: string; text: string }>;
  /** Сырая выдача поиска (title/link/snippet). */
  searchResults: Array<{ title: string; link: string; snippet?: string }>;
}

export function buildEvidenceMessages(input: EvidencePromptInput): LLMMessage[] {
  const sourcesBlock = input.sources.length
    ? input.sources.map((s) => `--- Источник: ${s.url} ---\n${s.text}`).join('\n\n')
    : '(тексты источников скачать не удалось — цитировать нечего: evidence верни пустым и режь potential_pct)';

  const searchBlock = input.searchResults.length
    ? input.searchResults.map((r) => `- ${r.title} — ${r.link}${r.snippet ? `\n  ${r.snippet}` : ''}`).join('\n')
    : '(поиск ничего не вернул — вероятный verdict: drop или сильное понижение %)';

  const user = `КЛИЕНТ (контекст продукта):
${input.profile.company_name}: ${input.profile.product_summary}

ГИПОТЕЗА-КАНДИДАТ НА ВЕРИФИКАЦИЮ:
${JSON.stringify(input.candidate, null, 2)}

ДРУГИЕ КАНДИДАТЫ (для verdict=merge — merge_with_title строго из этого списка):
${input.allCandidateTitles.filter((t) => t !== input.candidate.title).map((t) => `- ${t}`).join('\n') || '(нет)'}

ТЕКСТЫ ИСТОЧНИКОВ (скачаны поиском — цитаты ТОЛЬКО из основного текста этих страниц):
${sourcesBlock}

РЕЗУЛЬТАТЫ ПОИСКА (title/link/snippet — только для ориентировки и вердикта, НЕ источник цитат и не source_url для evidence):
${searchBlock}

Верни ТОЛЬКО JSON:
{
  "verdict": "keep"|"merge"|"drop",
  "merge_with_title": string | null,
  "reason": string,
  "fit_rationale": string,
  "evidence": [ { "claim": string, "source_url": string, "quote": string } ],
  "potential_pct": number
}`;

  return [
    { role: 'system', content: SYSTEM },
    { role: 'user', content: user },
  ];
}
