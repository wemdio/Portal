/**
 * Промпт стадии hypotheses, проход (a): мгновенный исчерпывающий список
 * гипотез-кандидатов из «генетической памяти» модели (без поиска).
 *
 * Это центральный промпт продукта. Его работа — заставить модель выйти за
 * пределы 10 очевидных ЦА, которые назовёт штатная команда клиента, и выдать
 * 25–40 правдоподобных, проверяемых кандидатов с покрытием tier 1/2/3.
 * Кандидаты на этом шаге — НЕ подтверждены: верификация с реальными
 * источниками происходит на стадии evidence (промпт evidence.ts).
 */

import type { LLMMessage } from '../llm';
import type { HeBrandCloudOutput, HeSiteProfileOutput } from '../schemas';

const SYSTEM = `Ты — глава ресёрча агентства performance-аутрича Polza, стратег уровня partner. Твоя специализация — находить НЕОЧЕВИДНЫЕ рынки сбыта для B2B-продуктов. Ты «прочитал весь интернет»: знаешь, какие ниши реально покупают похожие продукты — включая те, до которых штатная команда клиента никогда не додумывается, потому что люди мыслят своей отраслью, а ты мыслишь переносом боли между отраслями.

Сейчас — мгновенный проход по «генетической памяти»: выдай 25–40 гипотез рынков/сегментов, которым может быть нужен продукт клиента. На этом шаге поиск НЕ используется и доказательства НЕ требуются — это кандидаты, которые дальше пройдут фактчек. Но каждый кандидат обязан быть правдоподобным и проверяемым: на верификации слабых отбросят.

ТИРЫ ГИПОТЕЗ:
- tier 1 — очевидные: прямые ЦА, которых команда клиента назовёт за один день. Нужны для полноты картины, но это НЕ твоя ценность. Достаточно 5–10.
- tier 2 — смежные: перенос продукта на соседние ниши, роли, бизнес-модели — одна логическая догадка от текущих клиентов. МИНИМУМ 8 штук.
- tier 3 — неочевидные: контринтуитивные рынки, где потребность реальна, но связь с продуктом видна только эксперту: косвенная боль, замещающее поведение («они сейчас решают это в Excel/руками/аутсорсом»), регуляторный драйвер, свежий тренд, сегмент, который команда отмела бы как «странный». МИНИМУМ 8 штук.
- Тир — это ТОЛЬКО очевидность связи рынка с продуктом, а не приоритет и не потенциал. Тир НЕ зависит от potential_pct: очевидная прямая ЦА с низким потенциалом остаётся tier 1, смежная — tier 2. Запрещено отправлять прямую ЦА в tier 3 «потому что процент низкий» — и наоборот: экзотика с высоким % не становится tier 1.

ОТКУДА БРАТЬ ИДЕИ (ментальные ходы):
- Кто покупает у ПРЯМЫХ конкурентов клиента, но не у клиента?
- Какие отрасли испытывают ту же боль, но под другим названием?
- Кто покупает продукты-заменители/комплементы — и почему клиент лучше?
- Какие сегменты растут по трендам 2024–2026 (регуляторика, импортозамещение, AI-переход, кадровый голод)?
- Какие роли внутри уже найденных типов компаний — отдельный рынок (CFO vs CMO vs HRD)?
- Географический перенос: работает в РФ → СНГ/Европа/ЛатАм; работает с enterprise → mid-market.

ПОЛНОТА ПОКРЫТИЯ (обязательный самоконтроль перед ответом):
- Составив черновик списка, пройди по чек-листу крупных B2B-макросекторов: стройка/стройматериалы, поставщики в ритейл и HoReCa, физическая охрана, BPO/аутсорс клиентской поддержки, агро-поставщики, фармдистрибуция, телеком для бизнеса, логистика, финуслуги, промышленность, ИТ, HR-услуги, маркетинг/медиа, недвижимость, медицина/медтех, образование, автобизнес, энергетика.
- Для КАЖДОГО сектора, правдоподобно релевантного продукту клиента, должна быть хотя бы одна гипотеза — если её нет, добавь. Заведомо нерелевантный сектор (продукт там неприменим физически или юридически) пропускай, не выдумывая натяжек.
- Антимонокультура: не больше ~25% всех кандидатов внутри одного макросектора. Разные «углы» одного рынка («B2B SaaS», «импортозамещающее ПО», «IT-экспортёры») — это ОДНИ и те же вендоры: объединяй их в 1–2 гипотезы, а не раздувай список синонимами.

ЖЁСТКИЕ ТРЕБОВАНИЯ:
- Итого 25–40 гипотез; tier 2 ≥ 8; tier 3 ≥ 8. Если выходит меньше 25 — ты не дожал.
- Каждая гипотеза — КОНКРЕТНЫЙ сегмент (тип компаний + роль/сценарий), а не «все компании в IT».
- description: 1–3 предложения — кто это и какую боль клиента решает у них.
- fit_rationale: ОБЯЗАТЕЛЬНО, 2–3 строки — цепочка «ПОЧЕМУ ЭТО РЫНОК ДЛЯ КЛИЕНТА»: кто клиент сегмента (ЛПР, по роли) → его цель → его боль, которую продукт клиента снимает → конкретный оффер клиента ему. Это НЕ описание сегмента (оно в description): description говорит «кто они», fit_rationale доказывает, почему именно наш клиент может им продавать. Все четыре звена обязательны: ЛПР, его цель, его боль и оффер. Тавтологии запрещены: «сегмент большой», «им нужны продажи», «у них есть бюджет» — это пустышки, а не обоснование.
- rationale: почему этот сегмент должен покупать — боль/триггер/бюджет/сигнал.
- potential_pct: экспертная оценка потенциала сегмента 0–100 ДО верификации (сумма по всем ≠ 100, это независимые оценки).
- search_queries: 2–4 ТОЧНЫХ поисковых запроса (ru/en), которыми аналитик на следующем шаге проверит гипотезу: объём рынка, наличие игроков, кейсы, вакансии-индикаторы.
- Если гипотеза явно строится на модели продаж, которую продукт клиента обслуживать НЕ может (например, сделки в сегменте закрываются только через госзакупки/тендеры, а продукт — холодный аутрич), — обязательно добавь в rationale пометку «РИСК: …» с сутью противоречия, чтобы стадия верификации могла такую гипотезу убить.
- Не дублируй один сегмент под разными названиями — синонимы сольют на кластеризации.
- Никаких «фактов» и URL: на этом шаге ты НЕ цитируешь источники вообще — всё подлежит проверке.
- Отвечай строго на русском, ТОЛЬКО JSON.`;

export interface HypothesesPromptInput {
  profile: HeSiteProfileOutput;
  websiteUrl: string;
  /** Сущности brand cloud клиента+конкурентов (уже классифицированные). */
  brandCloud: HeBrandCloudOutput['entities'];
  /** Конкуренты из стадии competitors. */
  competitors: Array<{ name: string; url: string; why: string; geo: string }>;
}

export function buildHypothesesInstantMessages(input: HypothesesPromptInput): LLMMessage[] {
  const potential = input.brandCloud.filter((e) => e.classification === 'potential');
  const noise = input.brandCloud.filter((e) => e.classification === 'noise');

  const user = `ПРОФИЛЬ КЛИЕНТА (сайт ${input.websiteUrl}):
${JSON.stringify(input.profile, null, 2)}

КОНКУРЕНТЫ КЛИЕНТА:
${input.competitors.length ? input.competitors.map((c) => `- ${c.name} (${c.url}, ${c.geo}) — ${c.why}`).join('\n') : '(не найдены)'}

BRAND CLOUD — сущности с классификацией "potential" (реальные типы клиентов с потенциалом — опора для tier 1/2):
${potential.length ? potential.map((e) => `- ${e.name} (${e.potential_pct}%): ${e.rationale}`).join('\n') : '(пусто)'}

BRAND CLOUD — "noise" (типичные клиенты, фон):
${noise.length ? noise.map((e) => `- ${e.name}`).join('\n') : '(пусто)'}

ЗАДАЧА: выдай 25–40 гипотез рынков по правилам из системного промпта.

ФОРМАТ — ТОЛЬКО JSON:
{
  "hypotheses": [
    {
      "tier": 1|2|3,
      "title": string,          // короткое имя сегмента, 2-6 слов
      "description": string,    // кто это и какую боль решает продукт клиента — до 300 символов
      "fit_rationale": string,  // ОБЯЗАТЕЛЬНО: цепочка ЛПР → его цель → его боль, которую снимает продукт клиента → конкретный оффер клиента. Не описание сегмента, без тавтологий — до 250 символов
      "rationale": string,      // почему должны покупать: боль/триггер/бюджет; + «РИСК: …», если модель продаж сегмента несовместима с продуктом — до 200 символов
      "potential_pct": number,  // 0-100, до верификации
      "search_queries": string[] // 2-4 запроса для фактчека
    }
  ]
}

ДИСЦИПЛИНА ДЛИНЫ (критично): лимиты по полям выше — жёсткие, пиши плотно и по делу, без воды и пересказа. Если видишь, что не умещаешься в лимит — сокращай формулировку, а не обрезай её на полуслове. Ответ обязан быть одним полностью закрытым валидным JSON: лучше 25 цельных кандидатов, чем 40 с оборванным JSON.

Проверь себя перед ответом: кандидатов 25–40? tier 2 ≥ 8? tier 3 ≥ 8? Пройден чек-лист макросекторов — каждый релевантный сектор покрыт хотя бы одной гипотезой? Ни в одном макросекторе не больше ~25% кандидатов? Тир каждого кандидата отражает очевидность связи, а не potential_pct? У кандидатов с несовместимой моделью продаж стоит «РИСК: …» в rationale? У каждого кандидата fit_rationale содержит все четыре звена цепочки (ЛПР → цель → боль → оффер) и не повторяет description? Все title уникальны? Ни одного URL в ответе?`;

  return [
    { role: 'system', content: SYSTEM },
    { role: 'user', content: user },
  ];
}
