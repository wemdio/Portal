/**
 * Релевант-гейт строк автосборки «Движка вертикалей». Источники тащат шум. На
 * RU-сборке: hh full-text вернёт любую компанию, чья вакансия упомянула слово;
 * карты — рубричный шум; реестр — самодекларированные ОКВЭД. На market='us':
 * каталоги (pdl, funded) дают грубый industry-ярлык, eng_hiring — работодателя,
 * у которого совпало название вакансии, и отраслевого ярлыка у него нет вовсе
 * (в `category` его строк уезжает обрезанное описание компании из кэша, когда
 * оно там есть, — см. mapEngHiringRow). Строки проверяются дешёвой
 * LLM-проверкой (мини-модель роли 'gate'): «компания ∈ вертикаль?». На
 * EN-пути, ТОЛЬКО при включённом флаге HE_GATE_HYPOTHESIS_SCOPE (по умолчанию
 * выключен, см. heGateHypothesisScopeEnabled) и непустом списке гипотез
 * вертикали от вызывающего, вопрос другой: «может ли компания быть
 * покупателем хотя бы по одной из этих гипотез?» — см. gateScopeEn и
 * buildRelevanceMessages.
 *
 * Где стоит гейт: на ENG-сборке — ДО конструктора, по merged-строкам (одна
 * компания = одна строка), см. judgeRowsBeforeConstruct в stages/baseCollect.ts.
 * Прежний путь «после импорта» остался ровно на четыре случая: RU-сборка
 * legacy-инструмента; ENG-база с пустым merged (судить нечего ни там, ни тут);
 * ENG-база, чья фаза CONSTRUCT началась до переноса гейта; ENG-база, у которой
 * гейт до конструктора вернул ran=false.
 *
 * ЧЕГО ЗДЕСЬ НЕТ — состояния «на пересмотр». Помеченная строка остаётся в базе
 * для прозрачности, но выбрасывается ДВАЖДЫ и молча: из запуска
 * (launchTemplate.ts, фильтр `_low_relevance`) и из ночного долива
 * (stages/baseCollectRefill.ts). Никто её потом не пересматривает, поэтому
 * лишняя пометка = потерянная компания, а недостающая = мусор, который получит
 * письмо с домена клиента. Обе ошибки стоят денег, и ужесточать/смягчать
 * формулировки промпта ниже можно только с осознанной ценой.
 *
 * Never-throw: сбой батча → его строки без пометок; сборка базы гейтом не
 * валится никогда. Идут ли после сбоя остальные батчи — зависит от языка, ниже.
 *
 * УПРАВЛЕНИЕ ПРОХОДОМ У ЯЗЫКОВ РАЗНОЕ, и это не недосмотр.
 *
 * RU (legacy-инструмент /tools/hypothesis-engine, им ежедневно пользуются
 * сотрудники) — ровно то, что было до волны 7, см. judgeBatchRu: батч из 50
 * строк, ОДИН вызов модели; ответ, прошедший схему, — вердикт (в том числе
 * собранный ремонтом усечённого JSON); любой отказ — пропущен этот батч, а
 * следующий идёт как обычно. Повторов, дробления и остановок прохода у RU нет:
 * поведение инструмента специалистов не меняется без отдельного решения
 * владельца. Учёт расхода, строки лога и число вызовов — те же, что тогда.
 *
 * EN (ENG-сборка, market='us') — здесь язык гейта и рынок совпадают, потому
 * что язык выводит из рынка вызывающий (stages/baseCollect.ts передаёт 'en'
 * только проектам 'us', а гейт до конструктора вообще только у 'us'). Это
 * правило гейта, а не писем: язык цепочки и шаблона выбирает сотрудник, и
 * английская цепочка проекта 'ru' бывает — у писем решает рынок
 * (letterChecks.heUsEnglishLetters). Сбой разбирается по классу, потому что все
 * исходы здесь платные, а направление ошибки у этого гейта одно: он падает
 * ОТКРЫТО (нет вердикта → строка остаётся в базе и уходит в запуск). Весь
 * перечень:
 *  - прерывание задачи (отмена клиентом, сторож простоя, рестарт воркера) —
 *    проход ОСТАНАВЛИВАЕТСЯ: следующий батч упрётся в тот же сигнал;
 *  - биллинг / конфигурация (деньги, ключ) — проход ОСТАНАВЛИВАЕТСЯ и пишется
 *    в лог: такой отказ принадлежит ключу, а не батчу, и каждый оставшийся
 *    батч получил бы ровно его же;
 *  - permanent (прочие 4xx; ответ 200, тело которого не конверт чата) —
 *    пропускается ТОЛЬКО этот сегмент: llm.ts назначает этот класс ЗАПРОСУ
 *    («тот же запрос ответит тем же»), а у соседнего батча запрос другой;
 *  - таймаут, 5xx, обрыв сети, 429 — ОДИН повтор того же сегмента в пределах
 *    бюджета повторов (MAX_TRANSPORT_RETRIES); время, ушедшее на такие отказы,
 *    копится, и отказ, которым оно дошло до MAX_TRANSPORT_LOSS_MS,
 *    ОСТАНАВЛИВАЕТ проход;
 *  - тот же 429/5xx, но провайдер попросил Retry-After дольше
 *    MAX_RETRY_WAIT_MS — проход ОСТАНАВЛИВАЕТСЯ вместо ожидания: окно у
 *    провайдера общее для всех сегментов, ждать его по разу на каждый значило
 *    бы простоять окно джобы целиком;
 *  - невалидный ответ (не прошёл схему дважды, приехал усечённым или
 *    собрался только ремонтом усечённого JSON) — сегмент ДРОБИТСЯ
 *    50 → 10 → 1 в пределах бюджета MAX_SPLIT_CALLS;
 *  - всё прочее (ошибка без класса транспорта, например не задан ключ) —
 *    сегмент пропускается;
 *  - и поверх пропусков: MAX_UNANSWERED_IN_A_ROW сегментов ПОДРЯД без ответа
 *    модели (permanent, транспорт после повтора, всё прочее) — проход
 *    ОСТАНАВЛИВАЕТСЯ. Так кончается проход, у которого отказ оказался
 *    свойством провайдера, а не запроса (снятая модель отвечает 404 каждому
 *    батчу, провайдер лежит и отвечает 503 на всё).
 * Пометки «не проверено» у пропущенных строк НЕТ и не будет: один отказ
 * провайдера не имеет права превратиться в пустой запуск. Разрыв покрытия
 * виден вызывающему одним способом — judgedRows < checkedRows.
 */

