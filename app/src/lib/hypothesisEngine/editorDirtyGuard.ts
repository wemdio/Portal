/**
 * Политика защиты НЕСОХРАНЁННЫХ правок инлайн-редактора письма цепочки
 * (hypothesis-engine, шаг 3 «Контент»).
 *
 * Вынесено из Step3Content в чистую функцию по образцу
 * emailSequenceV2/letterDirtyGuard, чтобы:
 *  - все точки выхода (переключение письма, A/B-действия, перегенерация,
 *    уход со шага) шли через ОДНУ политику, а не расходились по хендлерам;
 *  - класс регрессий «новый путь навигации забыл про dirty-флаг» ловился
 *    юнит-тестом, а не только глазами ревьюера.
 *
 * Решение зависит от намерения (intent) и от того, есть ли несохранённые правки.
 */

export type EditorExitIntent =
  /** «✎» на другом письме (или «+ Добавить письмо», открывающее новое) — редактор заменится. */
  | 'switchLetter'
  /** A/B-переключатель или «сделать основным» — показ/серверное состояние писем меняется. */
  | 'swapVariant'
  /** «Сгенерировать / Перегенерировать» цепочку — письма будут заменены целиком. */
  | 'regenerate'
  /** Уход со шага 3 (кнопка «Далее: загрузить базу»). */
  | 'leaveStep';

export interface EditorExitDecision {
  /** Показать window.confirm перед действием (и дать отменить). */
  confirm: boolean;
  /** Сбросить флаг несохранённых правок и закрыть редактор после (подтверждённого) выхода. */
  clear: boolean;
}

/**
 * Матрица решений ПРИ наличии несохранённых правок. В отличие от v2 (где
 * leaveStep — тихий сброс по контракту кнопки «Назад»), здесь ВСЕ интенты
 * спрашивают: правки черновой цепочки делаются вручную и терять их обидно,
 * поэтому подтверждение единообразно на каждом выходе. clear всегда true:
 * подтверждённый выход отменяет правки и закрывает редактор, иначе флаг
 * протухнет и даст ложное предупреждение при следующем открытии.
 */
const POLICY: Record<EditorExitIntent, EditorExitDecision> = {
  switchLetter: { confirm: true, clear: true },
  swapVariant: { confirm: true, clear: true },
  regenerate: { confirm: true, clear: true },
  leaveStep: { confirm: true, clear: true },
};

/** Единый текст подтверждения для всех интентов. */
export const EDITOR_EXIT_MESSAGE = 'Есть несохранённые правки — отменить их?';

/**
 * Что делать при выходе из редактора письма с учётом несохранённых правок.
 * Если несохранённого нет — ничего спрашивать и чистить не нужно.
 */
export function decideEditorExit(
  intent: EditorExitIntent,
  hasUnsaved: boolean,
): EditorExitDecision {
  if (!hasUnsaved) return { confirm: false, clear: false };
  return POLICY[intent];
}
