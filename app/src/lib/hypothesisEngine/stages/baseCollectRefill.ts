/**
 * Сколько компаний вертикали ждёт в очереди (pending, срок не вышел) — плюс те,
 * что уже держит ЭТА база (`baseId`): повтор прогона после смерти воркера
 * должен видеть свой прошлый захват, иначе он решил бы, что очереди нет, и
 * купил бы сборку, которую очередь покрывала. Только для размера сборки:
 * оценка, а не захват. Не бросает: не прочиталось — ноль, то есть размер как
 * до переноса.
 */
export async function countHeRefillCarryover(
  ctx: HeStageContext,
  verticalId: string,
  baseId: string,
): Promise<number> {
  try {
    const { data, error } = await ctx.supabase
      .from('he_refill_carryover')
      .select('status, claimed_base_id')
      .eq('vertical_id', verticalId)
      .in('status', ['pending', 'claimed'])
      .gt('expires_at', new Date().toISOString())
      .limit(HE_REFILL_CARRYOVER_CLAIM_MAX);
    if (error) throw new Error(error.message);
    return ((data ?? []) as Array<{ status?: unknown; claimed_base_id?: unknown }>).filter(
      (row) => row.status === 'pending' || row.claimed_base_id === baseId,
    ).length;
  } catch (e) {
    stageLog(
      ctx,
      `[base_collect] refill: очередь переноса не прочитана ` +
        `(${e instanceof Error ? e.message : String(e)}) — размер сборки как без неё`,
    );
    return 0;
  }
}

interface HeRefillCarryClaim {
  companies: HeRefillCarryCompany[];
  /** id, которые ЭТА база держала ещё до этого прогона (повтор той же базы). */
  heldBefore: Set<string>;
  /** Истёкших переведено в 'released' этим захватом. */
  released: number;
  /** Снято в 'dropped' этим захватом: брошенные чужие захваты и компании ушедшей базы. */
  dropped: number;
}

function parseCarryCompany(raw: unknown): (HeRefillCarryCompany & { status: string; claimedBy: string | null }) | null {
  const r = raw as Record<string, unknown> | null;
  if (!r || typeof r.id !== 'string' || typeof r.source_base_id !== 'string') return null;
  if (typeof r.company_key !== 'string' || !r.company_key) return null;
  if (!Array.isArray(r.lead_rows) || !Array.isArray(r.lead_columns)) return null;
  const rows = r.lead_rows.filter(
    (row): row is HeRefillCarryRow => !!row && typeof row === 'object' && !Array.isArray(row),
  );
  const columns = r.lead_columns.filter((c): c is string => typeof c === 'string');
  return {
    id: r.id,
    sourceBaseId: r.source_base_id,
    companyKey: r.company_key,
    rows,
    columns,
    status: typeof r.status === 'string' ? r.status : '',
    claimedBy: typeof r.claimed_base_id === 'string' ? r.claimed_base_id : null,
  };
}

/**
 * Причины 'dropped', при которых строка очереди ТОЧНО не уходила письмом:
 * снята до отправки (всё в чёрном списке, база-источник ушла в 'failed', её
 * компанию держит другая база). Её копия не мешает той же компании в другой
 * базе — heRefillCarryPeerConflicts. Остальные причины ('fate_unknown',
 * 'claim_abandoned') — «могла уйти».
 */
const HE_REFILL_CARRY_NEVER_SENT_DROPS = new Set(['no_sendable_address', 'source_base_released', 'prepared_elsewhere']);

/**
 * Компании очереди, которые ПАРАЛЛЕЛЬНАЯ база того же проекта подготовила ещё
 * раз (шаг 3 блока «ПЕРЕНОС»): ids кандидатов, которых брать нельзя.
 *
 * ОТКУДА ДВОЙНИК. Исключение сборок читает `data` других баз проекта, а у
 * собирающейся базы `data` пуст до её терминальной записи. Тик крона ставит
 * вертикали проекта одновременно, поэтому две сборки одной ночи не видят
 * строк друг друга, и одна компания может оказаться в двух базах. До переноса
 * это не давало второго письма: проигравшая бронь ночь отправляла ноль и
 * возвращала компании в пул, где их исключала база победителя. Перенос
 * проигравшей ночи держит её копию в очереди — и отправил бы её второй раз.
 *
 * ПРАВИЛО (копия той же компании в чужой не-'failed' базе P, сверка — тем же
 * правилом «та же компания», что у исключения сборок):
 *  - копия P могла уйти письмом (строки очереди нет — её решила ночь P: отправка,
 *    чёрный список, серия; 'sent'; 'dropped' с неизвестной судьбой) → нашу
 *    копию не берём;
 *  - копия P живая в очереди ('pending' со сроком или 'claimed') → остаётся
 *    одна: копия базы с меньшим id. Порядок один для обеих сторон, поэтому
 *    отправит ровно одна, кто бы ни пришёл первым;
 *  - копия P точно не уходила ('released', истёкшая 'pending', 'dropped' без
 *    отправки) → не мешает.
 *
 * ОКНО. Двойником может быть только база, жившая одновременно с источником:
 * созданная до его терминальной записи и закрытая после его создания
 * (created_at ≤ updated_at источника, updated_at ≥ created_at источника).
 * Более ранние базы источник сам исключил на сборке, более поздние исключили
 * его. Окно ограничивает чтение `data` неделей очереди, а не всей историей.
 *
 * Бросает на сбое чтения: захват тогда не берёт очередь этой ночью (компании
 * ждут следующей), потому что без сверки «не знаем» означало бы «может уйти
 * второй раз».
 */
async function heRefillCarryPeerConflicts(
  ctx: HeStageContext,
  input: {
    projectId: string;
    candidates: ReadonlyArray<HeRefillCarryCompany>;
    sources: ReadonlyMap<string, { createdAtMs: number; updatedAtMs: number }>;
    nowMs: number;
  },
): Promise<Set<string>> {
  const conflicts = new Set<string>();
  if (input.candidates.length === 0) return conflicts;
  const windows = [...input.sources.values()];
  let query = ctx.supabase
    .from('he_bases')
    .select('id, columns, data')
    .eq('project_id', input.projectId)
    .neq('status', 'failed');
  if (windows.length > 0 && windows.every((w) => Number.isFinite(w.createdAtMs) && Number.isFinite(w.updatedAtMs))) {
    query = query
      .gte('updated_at', new Date(Math.min(...windows.map((w) => w.createdAtMs))).toISOString())
      .lte('created_at', new Date(Math.max(...windows.map((w) => w.updatedAtMs))).toISOString());
  }
  const { data: bases, error } = await query;
  if (error) throw new Error(`he_bases peers: ${error.message}`);
  const peers = ((bases ?? []) as Array<{ id?: unknown; columns?: unknown; data?: unknown }>).filter(
    (b): b is { id: string; columns?: unknown; data?: unknown } =>
      typeof b.id === 'string' && Array.isArray(b.data) && b.data.length > 0,
  );
  if (peers.length === 0) return conflicts;

  const states = new Map<string, { status: string; reason: string | null; expiresAtMs: number }>();
  for (const ids of chunked(peers.map((p) => p.id), HE_REFILL_CARRYOVER_ID_CHUNK)) {
    const { data, error: qErr } = await ctx.supabase
      .from('he_refill_carryover')
      .select('source_base_id, company_key, status, settle_reason, expires_at')
      .in('source_base_id', ids);
    if (qErr) throw new Error(`he_refill_carryover peers: ${qErr.message}`);
    for (const r of (data ?? []) as Array<Record<string, unknown>>) {
      if (typeof r.source_base_id !== 'string' || typeof r.company_key !== 'string') continue;
      states.set(`${r.source_base_id}\u0000${r.company_key}`, {
        status: typeof r.status === 'string' ? r.status : '',
        reason: typeof r.settle_reason === 'string' ? r.settle_reason : null,
        expiresAtMs: typeof r.expires_at === 'string' ? Date.parse(r.expires_at) : NaN,
      });
    }
  }

  const keyed = peers.map((peer) => {
    const columns = Array.isArray(peer.columns)
      ? peer.columns.filter((c): c is string => typeof c === 'string')
      : [];
    const keyOf = heRefillCarryKeyFn(columns.length > 0 ? columns : [...HE_AUTO_COLLECT_COLUMNS]);
    const blocking: Record<string, unknown>[] = [];
    const queued: Record<string, unknown>[] = [];
    for (const item of peer.data as unknown[]) {
      if (!item || typeof item !== 'object') continue;
      const row = item as Record<string, unknown>;
      const st = states.get(`${peer.id}\u0000${keyOf(row)}`);
      if (!st || st.status === 'sent' || (st.status === 'dropped' && !HE_REFILL_CARRY_NEVER_SENT_DROPS.has(st.reason ?? ''))) {
        blocking.push(row);
      } else if (st.status === 'claimed' || (st.status === 'pending' && st.expiresAtMs > input.nowMs)) {
        queued.push(row);
      }
    }
    return { id: peer.id, blocking: heCarryExclusionKeys(blocking), queued: heCarryExclusionKeys(queued) };
  });

  for (const company of input.candidates) {
    const rows = company.rows as unknown as Array<Record<string, unknown>>;
    const clash = keyed.some(
      (peer) =>
        peer.id !== company.sourceBaseId &&
        rows.some(
          (row) =>
            heCarryRowExcluded(peer.blocking, row) ||
            (peer.id < company.sourceBaseId && heCarryRowExcluded(peer.queued, row)),
        ),
    );
    if (clash) conflicts.add(company.id);
  }
  return conflicts;
}

/**
 * Взять очередь вертикали на отправку этой ночью (шаг 3 блока «ПЕРЕНОС»).
 *
 * Никогда не бросает. Всё, что не удалось, оставляет очередь как была, то есть
 * компании ждут следующей ночи: сбой чтения — пустой захват; сбой посреди
 * захвата — возвращается то, что успели взять (иначе взятое стало бы брошенным
 * и ушло бы в 'dropped' следующей ночью).
 *
 * Работа, а не деньги: все запросы — клиентом стадий.
 */
async function claimHeRefillCarryover(
  ctx: HeStageContext,
  input: { projectId: string; verticalId: string; baseId: string },
): Promise<HeRefillCarryClaim> {
  const nowMs = Date.now();
  const now = new Date(nowMs).toISOString();
  const out: HeRefillCarryClaim = { companies: [], heldBefore: new Set(), released: 0, dropped: 0 };
  const note = (what: string, e: unknown) =>
    stageLog(ctx, `[base_collect] refill: перенос — ${what} (${e instanceof Error ? e.message : String(e)})`);

  // Истёкшие — в 'released'. Только учёт: исключение сборок считает истёкшую
  // 'pending' отпущенной и без этой записи, а захват ниже её не берёт.
  try {
    const { data, error } = await ctx.supabase
      .from('he_refill_carryover')
      .update({ status: 'released', settled_at: now, settle_reason: 'expired', updated_at: now })
      .eq('vertical_id', input.verticalId)
      .eq('status', 'pending')
      .lte('expires_at', now)
      .select('id');
    if (error) throw new Error(error.message);
    out.released = (data ?? []).length;
  } catch (e) {
    note('истёкшие не переведены в released', e);
  }
  // Брошенные чужие захваты — в 'dropped' (почему — шаг 3 блока «ПЕРЕНОС»).
  try {
    const { data, error } = await ctx.supabase
      .from('he_refill_carryover')
      .update({ status: 'dropped', settled_at: now, settle_reason: 'claim_abandoned', updated_at: now })
      .eq('vertical_id', input.verticalId)
      .eq('status', 'claimed')
      .neq('claimed_base_id', input.baseId)
      .select('id');
    if (error) throw new Error(error.message);
    out.dropped += (data ?? []).length;
  } catch (e) {
    note('брошенные захваты не сняты', e);
  }

  let candidates: Array<HeRefillCarryCompany & { status: string; claimedBy: string | null }>;
  const live = new Set<string>();
  /** Компании, которые подготовила ещё и параллельная база проекта. */
  let conflicts = new Set<string>();
  try {
    const { data, error } = await ctx.supabase
      .from('he_refill_carryover')
      .select('id, source_base_id, company_key, lead_rows, lead_columns, status, claimed_base_id')
      .eq('vertical_id', input.verticalId)
      .in('status', ['pending', 'claimed'])
      .gt('expires_at', now)
      .order('prepared_at', { ascending: true })
      .limit(HE_REFILL_CARRYOVER_CLAIM_MAX);
    if (error) throw new Error(error.message);
    candidates = (data ?? [])
      .map(parseCarryCompany)
      .filter((c): c is NonNullable<typeof c> => c !== null)
      // Свой прошлый захват (повтор этой же базы) — берём; чужой сюда попадает,
      // только если его снятие выше не легло, и тогда его не трогаем вовсе.
      .filter((c) => c.status === 'pending' || c.claimedBy === input.baseId);
    // База-источник обязана держать компанию исключённой. Ушла в 'failed' или
    // удалена — компания уже в пуле сборки, и слать её отсюда значило бы
    // готовить её второй раз параллельно с этой очередью.
    const sources = new Map<string, { createdAtMs: number; updatedAtMs: number }>();
    for (const ids of chunked([...new Set(candidates.map((c) => c.sourceBaseId))], HE_REFILL_CARRYOVER_ID_CHUNK)) {
      const { data: bases, error: bErr } = await ctx.supabase
        .from('he_bases')
        .select('id, status, created_at, updated_at')
        .in('id', ids);
      if (bErr) throw new Error(`he_bases: ${bErr.message}`);
      for (const b of (bases ?? []) as Array<Record<string, unknown>>) {
        if (typeof b.id !== 'string' || b.status === 'failed') continue;
        live.add(b.id);
        sources.set(b.id, {
          createdAtMs: typeof b.created_at === 'string' ? Date.parse(b.created_at) : NaN,
          updatedAtMs: typeof b.updated_at === 'string' ? Date.parse(b.updated_at) : NaN,
        });
      }
    }
    // Двойники параллельных баз проекта — до захвата: копию, которая могла
    // уйти письмом из другой базы, брать нельзя (heRefillCarryPeerConflicts).
    conflicts = await heRefillCarryPeerConflicts(ctx, {
      projectId: input.projectId,
      candidates: candidates.filter((c) => live.has(c.sourceBaseId)),
      sources,
      nowMs,
    });
  } catch (e) {
    note('очередь не прочитана, ночь идёт без неё', e);
    return out;
  }

  // Двойник параллельной базы — в 'dropped'. Своя 'pending' копия письмом не
  // уходила ('prepared_elsewhere' — для сверки других баз это «не отправлена»);
  // свой прошлый захват мог уйти у умершего прогона — 'fate_unknown'.
  const clashing = candidates.filter((c) => live.has(c.sourceBaseId) && conflicts.has(c.id));
  for (const [ids, status, reason] of [
    [clashing.filter((c) => c.status === 'pending').map((c) => c.id), 'pending', 'prepared_elsewhere'],
    [clashing.filter((c) => c.status === 'claimed').map((c) => c.id), 'claimed', 'fate_unknown'],
  ] as const) {
    for (const chunk of chunked(ids, HE_REFILL_CARRYOVER_ID_CHUNK)) {
      try {
        const { data, error } = await ctx.supabase
          .from('he_refill_carryover')
          .update({ status: 'dropped', settled_at: now, settle_reason: reason, updated_at: now })
          .in('id', chunk)
          .eq('status', status)
          .select('id');
        if (error) throw new Error(error.message);
        out.dropped += (data ?? []).length;
      } catch (e) {
        note('двойники параллельной базы не сняты (этой ночью не берутся)', e);
      }
    }
  }

  const orphaned = candidates.filter((c) => !live.has(c.sourceBaseId)).map((c) => c.id);
  for (const ids of chunked(orphaned, HE_REFILL_CARRYOVER_ID_CHUNK)) {
    try {
      const { data, error } = await ctx.supabase
        .from('he_refill_carryover')
        .update({ status: 'dropped', settled_at: now, settle_reason: 'source_base_released', updated_at: now })
        .in('id', ids)
        .in('status', ['pending', 'claimed'])
        .select('id');
      if (error) throw new Error(error.message);
      out.dropped += (data ?? []).length;
    } catch (e) {
      note('компании ушедшей базы не сняты', e);
    }
  }

  const usable = candidates.filter((c) => live.has(c.sourceBaseId) && !conflicts.has(c.id));
  const taken = new Set<string>();
  for (const c of usable) {
    if (c.status === 'claimed') {
      taken.add(c.id);
      out.heldBefore.add(c.id);
    }
  }
  for (const ids of chunked(usable.filter((c) => c.status === 'pending').map((c) => c.id), HE_REFILL_CARRYOVER_ID_CHUNK)) {
    try {
      const { data, error } = await ctx.supabase
        .from('he_refill_carryover')
        .update({ status: 'claimed', claimed_base_id: input.baseId, claimed_at: now, updated_at: now })
        .in('id', ids)
        .eq('status', 'pending')
        .select('id');
      if (error) throw new Error(error.message);
      for (const row of (data ?? []) as Array<{ id?: unknown }>) {
        if (typeof row.id === 'string') taken.add(row.id);
      }
    } catch (e) {
      note('захват оборвался — берём то, что успели', e);
      break;
    }
  }
  out.companies = usable
    .filter((c) => taken.has(c.id))
    .map(({ id, sourceBaseId, companyKey, rows, columns }) => ({ id, sourceBaseId, companyKey, rows, columns }));
  return out;
}

/** Позиции пачки, которые могли дойти до провайдера: ушли в транспорт и не отклонены им явно. */
function refillReachedPositions(
  result: { attemptedIndexes: readonly number[]; deferredIndexes?: readonly number[] } | null,
): Set<number> {
  const out = new Set<number>();
  if (!result) return out;
  const refused = new Set(result.deferredIndexes ?? []);
  for (const index of result.attemptedIndexes) if (!refused.has(index)) out.add(index);
  return out;
}

interface HeRefillCarrySettle {
  sent: string[];
  returned: string[];
  dropped: Array<{ id: string; reason: string }>;
}

/**
 * Итог перенесённых компаний этой ночи (шаг 5 блока «ПЕРЕНОС») — по ВСЕМУ
 * набору исходов, чистая функция:
 *  - хотя бы один лид компании дошёл (или мог дойти) до провайдера → 'sent';
 *  - судьба неизвестна (`unknown`: бронь держал прошлый прогон этой же базы,
 *    а он мог эту компанию уже отправить) → 'dropped';
 *  - до чёрного списка не дошли (`inKept` = null: ночь упала раньше) или у
 *    компании остался лид после него → 'pending' (обратно в очередь);
 *  - у компании не осталось ни одного лида (весь адресный набор в чёрном
 *    списке владельца или ни один адрес не разобрался) → 'dropped'.
 */
function planHeRefillCarrySettle(input: {
  companies: readonly HeRefillCarryCompany[];
  ownerOf: ReadonlyMap<object, string>;
  inKept: ReadonlySet<string> | null;
  batch: readonly object[];
  reached: ReadonlySet<number>;
  unknown: ReadonlySet<string> | null;
}): HeRefillCarrySettle {
  const reachedIds = new Set<string>();
  for (const position of input.reached) {
    const lead = input.batch[position];
    const id = lead ? input.ownerOf.get(lead) : undefined;
    if (id) reachedIds.add(id);
  }
  const out: HeRefillCarrySettle = { sent: [], returned: [], dropped: [] };
  for (const company of input.companies) {
    if (reachedIds.has(company.id)) out.sent.push(company.id);
    else if (input.unknown?.has(company.id)) out.dropped.push({ id: company.id, reason: 'fate_unknown' });
    else if (input.inKept === null || input.inKept.has(company.id)) out.returned.push(company.id);
    else out.dropped.push({ id: company.id, reason: 'no_sendable_address' });
  }
  return out;
}

/**
 * Записать итог перенесённых компаний. Деньги, а не работа: 'sent' фиксирует
 * то, что провайдер уже принял, — поэтому клиентом без сигнала. Каждая запись
 * адресована «своим» захватом (status='claimed', claimed_base_id = эта база):
 * чужой итог она не перепишет. Никогда не бросает; false — что-то не легло, и
 * эти компании следующая ночь снимет как брошенные (без второго письма).
 */
async function settleHeRefillCarryover(
  ctx: HeStageContext,
  baseId: string,
  settle: HeRefillCarrySettle,
): Promise<boolean> {
  const db = paidCheckpointDb(ctx);
  const now = new Date().toISOString();
  let ok = true;
  const apply = async (ids: readonly string[], patch: Record<string, unknown>) => {
    for (const chunk of chunked(ids, HE_REFILL_CARRYOVER_ID_CHUNK)) {
      try {
        const { error } = await db
          .from('he_refill_carryover')
          .update(patch)
          .in('id', chunk)
          .eq('status', 'claimed')
          .eq('claimed_base_id', baseId);
        if (error) throw new Error(error.message);
      } catch (e) {
        ok = false;
        stageLog(
          ctx,
          `[base_collect] refill: итог переноса не записан для ${chunk.length} компаний ` +
            `(${e instanceof Error ? e.message : String(e)}) — следующая ночь снимет их как брошенные`,
        );
      }
    }
  };
  // 'sent' первым: из трёх записей только её потеря могла бы стоить письма,
  // если бы брошенный захват не снимался в 'dropped'.
  await apply(settle.sent, { status: 'sent', settled_at: now, settle_reason: null, updated_at: now });
  await apply(settle.returned, { status: 'pending', claimed_base_id: null, claimed_at: null, updated_at: now });
  const byReason = new Map<string, string[]>();
  for (const { id, reason } of settle.dropped) byReason.set(reason, [...(byReason.get(reason) ?? []), id]);
  for (const [reason, ids] of byReason) {
    await apply(ids, { status: 'dropped', settled_at: now, settle_reason: reason, updated_at: now });
  }
  return ok;
}

/**
 * Собственные компании ЭТОЙ ночи, которым не досталось ни одного письма (шаг 1
 * блока «ПЕРЕНОС»): после чёрного списка у компании остался лид, и ни один её
 * лид не дошёл до провайдера. Чистая функция. Строки компании — все её
 * допущенные строки (`rows` — leadRows ночи): чёрный список и вердикт следующая
 * ночь применит заново.
 *
 * Компания без ключа (ни имени, ни сайта) не переносится: отрез считает её
 * отдельной компанией по строке, а исключению сборок отпустить её по истечении
 * срока было бы не по чему.
 */
function ownUnsentRefillCompanies(input: {
  rows: readonly HeRefillCarryRow[];
  rowOf: ReadonlyMap<object, number>;
  kept: readonly object[];
  batch: readonly object[];
  reached: ReadonlySet<number>;
  columns: readonly string[];
}): Array<{ key: string; rows: HeRefillCarryRow[] }> {
  const keyOf = heRefillCarryKeyFn(input.columns);
  const keyOfLead = (lead: object | undefined): string => {
    const index = lead ? input.rowOf.get(lead) : undefined;
    const row = index === undefined ? undefined : input.rows[index];
    return row ? keyOf(row) : '';
  };
  const waiting = new Set<string>();
  for (const lead of input.kept) {
    const key = keyOfLead(lead);
    if (key) waiting.add(key);
  }
  for (const position of input.reached) {
    const key = keyOfLead(input.batch[position]);
    if (key) waiting.delete(key);
  }
  if (waiting.size === 0) return [];
  const byKey = new Map<string, HeRefillCarryRow[]>();
  for (const row of input.rows) {
    const key = keyOf(row);
    if (!waiting.has(key)) continue;
    const list = byKey.get(key);
    if (list) list.push(row);
    else byKey.set(key, [row]);
  }
  return [...byKey.entries()].map(([key, rows]) => ({ key, rows }));
}

/** Что ночь кладёт в he_refill_carryover: записи и их счёт для воронки. */
interface HeRefillCarryQueuePlan {
  records: Array<Record<string, unknown>>;
  /** Компаний, которые ждут ('pending'). */
  queued: number;
  /** Компаний, отпущенных сразу (крючок найма не доживёт свежим, heRefillCarryExpiry). */
  releasedHiring: number;
}

/**
 * Записи очереди для собственных компаний ночи. Чистая функция: счёт нужен
 * воронке ДО терминальных записей, а сама запись — после (или, у ночи без
 * бюджета, до) них. Срок каждой компании — heRefillCarryExpiry: компания, чей
 * крючок найма не доживёт до отправки свежим, пишется сразу 'released' —
 * исключение сборок её больше не держит (loadHeRefillReleasedCompanies), а
 * захват её не предложит.
 */
function planHeRefillCarryQueue(input: {
  projectId: string;
  verticalId: string;
  baseId: string;
  columns: string[];
  companies: Array<{ key: string; rows: HeRefillCarryRow[] }>;
  nowMs: number;
}): HeRefillCarryQueuePlan {
  const preparedAt = new Date(input.nowMs).toISOString();
  let queued = 0;
  let releasedHiring = 0;
  const records = input.companies.map((company) => {
    const expiry = heRefillCarryExpiry(company.rows, input.nowMs);
    if (expiry.release) releasedHiring += 1;
    else queued += 1;
    return {
      project_id: input.projectId,
      vertical_id: input.verticalId,
      source_base_id: input.baseId,
      company_key: company.key,
      lead_rows: company.rows,
      lead_columns: input.columns,
      prepared_at: preparedAt,
      expires_at: new Date(expiry.expiresAtMs).toISOString(),
      // Ключи одинаковые у КАЖДОЙ записи: пакетный upsert заполняет
      // отсутствующий ключ NULL'ом, а не DEFAULT'ом колонки (status NOT NULL).
      status: expiry.release ? 'released' : 'pending',
      settled_at: expiry.release ? preparedAt : null,
      settle_reason: expiry.release,
    };
  });
  return { records, queued, releasedHiring };
}

/**
 * Положить собственные компании ночи в очередь. Деньги: подготовка уже
 * оплачена, а повтор джобы эту запись не воспроизведёт. ОДИН запрос на всю
 * ночь (≤ HE_AUTO_REFILL_ROWS_LIMIT компаний): либо легли все, либо ни одной —
 * у ночи без бюджета от этого зависит, переносить или возвращать в пул (см.
 * runHeRefillAppend). Идемпотентна по (source_base_id, company_key). Никогда не
 * бросает; false — не легло: у успешной ночи и отказа после доставки компании
 * остаются исключёнными, как до переноса, у ночи без бюджета — уходят в пул.
 */
async function writeHeRefillCarryQueue(ctx: HeStageContext, plan: HeRefillCarryQueuePlan): Promise<boolean> {
  if (plan.records.length === 0) return true;
  try {
    const { error } = await paidCheckpointDb(ctx)
      .from('he_refill_carryover')
      .upsert(plan.records, { onConflict: 'source_base_id,company_key', ignoreDuplicates: true });
    if (error) throw new Error(error.message);
    return true;
  } catch (e) {
    stageLog(
      ctx,
      `[base_collect] refill: очередь переноса не записана ` +
        `(${e instanceof Error ? e.message : String(e)}) — компании ночи без письма в неё не попали`,
    );
    return false;
  }
}

/**
 * Отпущенные компании очереди проекта — для исключения сборок
 * (loadOtherBaseExclusionKeys в stages/baseCollect.ts, только market='us'):
 * база-источник → ключи компаний, которые больше не исключаются. Отпущена =
 * 'released' либо 'pending' с прошедшим сроком (шаг 6 блока «ПЕРЕНОС»).
 *
 * Не бросает: не прочиталось — пустая карта, то есть истёкшие компании
 * остаются исключёнными, как до переноса. Это безопасная сторона — потерянная
 * компания, а не вторая подготовка.
 */
export async function loadHeRefillReleasedCompanies(
  ctx: HeStageContext,
  projectId: string,
): Promise<Map<string, Set<string>>> {
  const out = new Map<string, Set<string>>();
  try {
    const nowMs = Date.now();
    const { data, error } = await ctx.supabase
      .from('he_refill_carryover')
      .select('source_base_id, company_key, status, expires_at')
      .eq('project_id', projectId)
      .in('status', ['pending', 'released']);
    if (error) throw new Error(error.message);
    for (const raw of (data ?? []) as Array<Record<string, unknown>>) {
      const baseId = raw.source_base_id;
      const key = raw.company_key;
      if (typeof baseId !== 'string' || typeof key !== 'string' || !key) continue;
      const released =
        raw.status === 'released'
        || (raw.status === 'pending' && typeof raw.expires_at === 'string' && Date.parse(raw.expires_at) <= nowMs);
      if (!released) continue;
      const keys = out.get(baseId);
      if (keys) keys.add(key);
      else out.set(baseId, new Set([key]));
    }
    return out;
  } catch (e) {
    stageLog(
      ctx,
      `[base_collect] перенос: отпущенные компании не прочитаны ` +
        `(${e instanceof Error ? e.message : String(e)}) — истёкшие остаются исключёнными`,
    );
    return new Map();
  }
}

/**
 * Долив собранной базы в запущенную кампанию (вызывается вместо финального
 * блока «analyzing + base_analyze»). Никогда не бросает refill-ошибки наружу
 * (см. шапку); бросает только ошибку финального апдейта самой базы — как
 * обычный путь стадии.
 *
 * У market='us' вместе со строками ночи уходят компании очереди переноса —
 * ПЕРВЫМИ (блок «ПЕРЕНОС» выше). `carryOnly` — ночь сборку не покупала:
 * собственных строк нет, отправляется только очередь.
 */
export async function runHeRefillAppend(args: {
  ctx: HeStageContext;
  job: HeJob;
  base: { id: string; project_id: string; vertical_id: string };
  info: HeCollectInfo;
  stats: HeCollectInfo['stats'];
  finalRows: HeUnifiedRow[];
  finalColumns: string[];
  /**
   * Вердикты валидации по индексам finalRows. null вместо массива (валидации
   * не было вовсе) или null в элементе (у строки вердикта нет) — такая строка
   * в долив НЕ идёт и попадает в stats.unverified, см. selectRefillLeadRows.
   */
  emailStatuses: Array<string | null> | null;
  usage: HeUsage;
  /**
   * Рынок проекта (стадия читает его так же, как для плана). Перенос работает
   * только при 'us'; не передан — переноса нет, долив ровно прежний.
   */
  market?: HeMarket;
  /** Ночь не покупала сборку: отправляется только очередь переноса. */
  carryOnly?: boolean;
}): Promise<HeStageResult> {
  const { ctx, job, base, info, stats, finalRows, finalColumns, emailStatuses, usage } = args;
  /** Перенос неотправленных компаний — только ENG (блок «ПЕРЕНОС»). */
  const carryEnabled = args.market === 'us';

  const done = (refill: HeRefillResult): HeStageResult => ({
    result: { base_id: base.id, rows: finalRows.length, refill },
    tokensUsed: usage.tokensUsed,
    costUsd: usage.costUsd,
  });

  const config = await loadRefillConfig(ctx, job.project_id);
  const dailyLeadsCap = config?.dailyLeadsCap ?? HE_AUTO_DEFAULT_DAILY_LEADS_CAP;
  // Кап адресов на компанию ЭТОЙ сборки: он же уехал конструктору в
  // step_config.cap_emails_per_company (collect_info.construct.contact_cap есть
  // всегда, в том числе там, где миграция 20260926_0001 не применена). Читаем
  // снапшот, а не колонку проекта: лимит мог измениться после постановки, а
  // оплачены пробы по тому, с которым сборка шла.
  const contactCap =
    normalizeHeMaxEmailsPerCompany(info.construct?.contact_cap) ?? HE_MAX_EMAILS_PER_COMPANY_DEFAULT;
  const companyTarget = heRefillCompanyTarget({ dailyLeadsCap, contactCap });
  const companyLimit =
    typeof info.limit === 'number' && Number.isFinite(info.limit) ? info.limit : null;
  // Сборка оплачена ДО этой ветки. Если её объём считали не из капа, лишние
  // краулы и SMTP-пробы уже потрачены: кап выбросит их строки, а компании
  // останутся выжженными (база уйдёт в 'analyzed'). Называем это вслух в
  // журнале сборки — иначе первый ночной счёт объяснять будет нечем. Строка
  // исчезнет сама, когда постановка начнёт считать объём в компаниях
  // (resolveHeRefillCollectCompanies).
  if (companyLimit !== null && companyLimit > companyTarget) {
    stageLog(
      ctx,
      `[base_collect] refill: сборка шла на ${companyLimit} компаний при капе ${dailyLeadsCap} ` +
        `лидов (хватило бы ${companyTarget}) — до ` +
        `${(companyLimit - companyTarget) * (contactCap + 1)} адресов проверено впустую; ` +
        'объём сборки должен считаться из капа (resolveHeRefillCollectCompanies)',
    );
  }
  /** Отдали ли строки провайдеру — решает судьбу компаний при отказе. */
  let providerTouched = false;
  /**
   * Кто именно увидел переполненный воркспейс — текст для причины паузы.
   * null = ёмкость не при чём. Живёт ВНЕ try, потому что оба исхода долива
   * (частичный приём и полный отказ) умеют упереться в ёмкость, а запись паузы
   * обязана идти ПОСЛЕ терминальных записей обоих.
   */
  let capacityPauseSource: string | null = null;
  /**
   * Бронь дневного бюджета этого прогона. Живёт ВНЕ try: закрыть её обязаны
   * оба исхода, иначе неиспользованный объём остался бы занятым до конца
   * UTC-суток и следующая вертикаль ночи не смогла бы его потратить.
   */
  let reservationId: string | null = null;
  /**
   * Состояние переноса, которое нужно ОБОИМ исходам (успех и catch): что взято
   * из очереди, какой лид чьей компании, кто пережил чёрный список, какая
   * пачка ушла провайдеру и что о ней известно. Объект лида переживает
   * blocklist и отрез без копирования (filterBlockedLeads и отрез фильтруют,
   * а не клонируют), поэтому лид служит ключом.
   */
  let carryClaim: HeRefillCarryClaim | null = null;
  const carriedLeadOwner = new Map<object, string>();
  /** null — до чёрного списка долив не дошёл. */
  let carriedInKept: Set<string> | null = null;
  /** Пачка, отданная провайдеру (позиции = индексы attempted/deferred). */
  let sentBatch: readonly object[] = [];
  /**
   * Собственные строки-кандидаты ночи (leadRows), какой свой лид из какой
   * строки и что пережило чёрный список — очередь собственных компаний нужна
   * и успешной ветке, и catch'у (ночь без бюджета, отказ после доставки).
   * `ownKept` null — до чёрного списка долив не дошёл, класть нечего.
   */
  let ownLeadRows: HeRefillCarryRow[] = [];
  const ownLeadRow = new Map<object, number>();
  let ownKept: readonly object[] | null = null;
  /** Результат долива, если appendLeads вернулся штатно. */
  let appendOutcome: { attemptedIndexes: readonly number[]; deferredIndexes?: readonly number[] } | null = null;
  const runStats: HeRefillStats = {
    collected: finalRows.length,
    with_email: 0,
    valid: 0,
    unverified: 0,
    appended: 0,
    skipped_blocklist: 0,
    skipped_instantly: 0,
    capped: 0,
    daily_cap: dailyLeadsCap,
    company_target: companyTarget,
    company_limit: companyLimit,
    ...(args.carryOnly ? { carry_only: true as const } : {}),
  };
  /**
   * Очередь собственных компаний ночи (шаг 1 блока «ПЕРЕНОС»): компании, у
   * которых после чёрного списка остался лид и ни один лид не дошёл до
   * провайдера (`reached` — позиции пачки, которые дошли или могли дойти).
   * null — класть нечего (не 'us', до чёрного списка не дошли, все охвачены).
   */
  const planOwnQueue = (reached: ReadonlySet<number>): HeRefillCarryQueuePlan | null => {
    if (!carryEnabled || ownKept === null) return null;
    const companies = ownUnsentRefillCompanies({
      rows: ownLeadRows,
      rowOf: ownLeadRow,
      kept: ownKept,
      batch: sentBatch,
      reached,
      columns: finalColumns,
    });
    if (companies.length === 0) return null;
    return planHeRefillCarryQueue({
      projectId: job.project_id,
      verticalId: base.vertical_id,
      baseId: base.id,
      columns: finalColumns,
      companies,
      nowMs: Date.now(),
    });
  };
  /** Счёт переноса этой ночи в воронку (HeRefillStats.carryover) — обе ветки. */
  const noteCarryStats = (settle: HeRefillCarrySettle | null, queue: HeRefillCarryQueuePlan | null): void => {
    const claim = carryClaim;
    const queued = queue?.queued ?? 0;
    const releasedHiring = queue?.releasedHiring ?? 0;
    const touched = (claim?.released ?? 0) + (claim?.dropped ?? 0) + queued + releasedHiring;
    if (!settle && touched === 0) return;
    runStats.carryover = {
      offered: claim?.companies.length ?? 0,
      sent: settle?.sent.length ?? 0,
      returned: settle?.returned.length ?? 0,
      dropped: (settle?.dropped.length ?? 0) + (claim?.dropped ?? 0),
      released: claim?.released ?? 0,
      queued,
      ...(releasedHiring > 0 ? { released_hiring: releasedHiring } : {}),
    };
  };

  try {
    // 1. Кампания и маппинг — из запущенного шаблона вертикали.
    const { data: templateRows, error: tErr } = await ctx.supabase
      .from('he_templates')
      .select('id, launch_info, personalization_plan, created_at')
      .eq('vertical_id', base.vertical_id)
      .not('launch_info', 'is', null);
    if (tErr) throw new Error(`he_templates read: ${tErr.message}`);
    const preferredCampaignId =
      typeof info.campaign_id === 'string' && info.campaign_id ? info.campaign_id : null;
    const pick = pickRefillTemplate((templateRows ?? []) as Array<Record<string, unknown>>, preferredCampaignId);
    if (!pick) {
      throw new Error('у вертикали нет запущенной кампании (he_templates.launch_info) — доливать некуда');
    }

    // 2. Владелец пресета — чей Instantly-аккаунт, blocklist и тариф (как у
    //    клиентского auto-pipeline: appendLeadsToClientCampaign по userId).
    if (!supabaseInstantly) {
      throw new Error('supabaseInstantly не сконфигурирован (INSTANTLY_SUPABASE_URL)');
    }
    const { data: presetRow, error: pErr } = await supabaseInstantly
      .from('client_campaign_presets')
      .select('client_user_id')
      .eq('id', pick.presetId)
      .maybeSingle();
    if (pErr) throw new Error(`client_campaign_presets read: ${pErr.message}`);
    const ownerUserId = (presetRow as { client_user_id?: unknown } | null)?.client_user_id;
    if (typeof ownerUserId !== 'string' || !ownerUserId) {
      throw new Error(`пресет ${pick.presetId} не найден — владелец кампании неизвестен`);
    }

    // 3. Лиды: email + допущенный вердикт валидации, маппинг колонок →
    //    переменные шаблона.
    const { leadRows, leadRowIndexes, withEmail, valid, unverified } =
      selectRefillLeadRows(finalRows, emailStatuses);
    runStats.with_email = withEmail;
    runStats.valid = valid;
    runStats.unverified = unverified;
    // Ни одного проверенного адреса, а непроверенные есть — валидация не
    // доработала. Уходим в общий отказ долива (catch ниже): прогон 'failed' с
    // причиной, компании возвращаются в пул по тому же правилу, что и у
    // недоставленного отказа, и завтрашняя сборка проверит их заново. Тихий
    // 'no_new' здесь означал бы «новых компаний нет» — отчёт, по которому
    // неделю неотправки не отличить от исчерпанного рынка.
    //
    // Статус фазы конструктора в тексте не для красоты: he_bases.error кабинет
    // сворачивает в машинный код причины (clientErrors.classifyHeClientError),
    // и по этой формулировке ENG-клиент получает «валидация почт не
    // доработала» вместо обобщённого технического сбоя. Переформулировать —
    // только сверившись с тем классификатором.
    if (valid === 0 && unverified > 0) {
      throw new Error(
        `валидация почт не дала вердиктов: ${unverified} стр. с адресом не проверено ` +
          `(конструктор завершился со статусом ${info.construct?.status ?? 'неизвестным'}) — ` +
          'долив остановлен',
      );
    }
    // Ни одного адреса вообще, и конструктор не доработал: джоба кончилась
    // failed/cancelled либо 'done' без данных (импорт ничего не принёс —
    // emails_found пишется только у импорта). Каталожные строки адресов не
    // несут, поэтому такая сетка — исходная выборка без единого адреса, и
    // правило выше её не ловит (непроверенных строк нет, раз нет адресов). Ноль
    // здесь — наш сбой, а не рынок: 'no_new' выжег бы оплаченный срез под
    // отчётом «отправлять нечего» и засчитал бы ночь сухой (scan_complete=true).
    // Уходим в общий отказ — компании вернутся в пул по правилу серии.
    //
    // Граница честная: ночь, где конструктор ДОРАБОТАЛ и не нашёл ни одного
    // адреса, остаётся 'no_new' (известное ограничение волны 6a), как и ночь,
    // где конструктор не запускался вовсе (гейт вычеркнул все строки — их
    // компании исключаются сознательно, см. allOffTarget в stages/baseCollect.ts).
    // Тексты — под тот же классификатор кабинета, что и выше ('enrichment').
    const construct = info.construct;
    const constructorUnfinished =
      !!construct?.bc_job_id && (construct.status !== 'done' || construct.emails_found === undefined);
    if (valid === 0 && withEmail === 0 && construct && constructorUnfinished) {
      throw new Error(
        construct.status === 'done'
          ? 'конструктор вернул пустые данные: в сетке нет ни одного адреса — долив остановлен'
          : `поиск адресов не доработал: в сетке нет ни одного адреса ` +
            `(конструктор завершился со статусом ${construct.status}) — долив остановлен`,
      );
    }
    const { leads, leadRowIndices: leadSourceRows } = mapBaseRowsToLeads({
      rows: leadRows,
      columns: finalColumns,
      operatorMapping: pick.operatorMapping,
      // Связь «доставленный лид → строка базы». Дальше значение подхватит
      // построчный журнал доставки (client_campaign_contact_ledger.source_row_id)
      // — второго журнала мы не заводим, а заполняем колонку, которая у ENG
      // стояла пустой.
      //
      // Ключ НЕ позиционный, и это принципиально: `persistRefillBase`
      // переписывает he_bases.data той же базы целиком, а повтор прогона
      // добирает строки от сдвинувшейся закладки каталога — под тем же
      // индексом завтра лежала бы ДРУГАЯ компания, и запись журнала,
      // сделанная умершим предшественником, показывала бы не на ту строку.
      // Нормализованное имя компании переживает переписывание: оно и есть то,
      // чем база опознаёт компанию в исключениях других баз проекта.
      // Индекс leadRowIndexes оставлен запасным ключом на случай пустого
      // имени (такие строки до отправки не доходят, но ключ обязан быть
      // определён хотя бы чем-то).
      sourceRowId: (index) => {
        const row = leadRows[index];
        const companyKey = row ? normalizeCompanyForDedup(row.company) : '';
        if (companyKey) return `${base.id}:${companyKey}`;
        const rowIndex = leadRowIndexes[index];
        return rowIndex === undefined ? null : `${base.id}:#${rowIndex}`;
      },
    });

    // 3b. ПЕРЕНОС (только market='us', блок «ПЕРЕНОС» выше): компании очереди
    //     вертикали — ПЕРВЫМИ в пачке. Берутся только после проверок своей
    //     сетки: ночь, которая всё равно уйдёт в отказ на шаге 3, очередь не
    //     трогает. Вердикт каждой перенесённой строки перепроверяется тем же
    //     selectRefillLeadRows (уходит только 'accepted', строки вне вертикали
    //     — нет), маппинг — колонками её базы-источника, а пометка доставки
    //     показывает на строку именно той базы, где компания лежит.
    //     Без очереди (или не 'us') пачка — ровно прежняя: те же лиды в том же
    //     порядке.
    let sendLeads = leads;
    let sendLeadSourceRows = leadSourceRows;
    let sendLeadRows: HeRefillCarryRow[] = leadRows;
    // Свой лид → индекс его строки в leadRows (очередь собственных компаний).
    ownLeadRows = leadRows;
    leads.forEach((lead, i) => ownLeadRow.set(lead, leadSourceRows[i]));
    /** Допущенных строк у перенесённых компаний — для исхода 'no_new' / 'appended'. */
    let carriedValid = 0;
    if (carryEnabled) {
      carryClaim = await claimHeRefillCarryover(ctx, {
        projectId: job.project_id,
        verticalId: base.vertical_id,
        baseId: base.id,
      });
      if (carryClaim.companies.length > 0) {
        const carriedRows: HeRefillCarryRow[] = [];
        const carriedLeads: typeof leads = [];
        const carriedSourceRows: number[] = [];
        for (const company of carryClaim.companies) {
          const picked = selectRefillLeadRows(
            company.rows,
            company.rows.map((row) => (typeof row._email_status === 'string' ? row._email_status : null)),
          );
          carriedValid += picked.valid;
          const offset = carriedRows.length;
          carriedRows.push(...picked.leadRows);
          const mapped = mapBaseRowsToLeads({
            rows: picked.leadRows,
            columns: company.columns,
            operatorMapping: pick.operatorMapping,
            sourceRowId: (index) => {
              const row = picked.leadRows[index];
              const companyKey = row ? normalizeCompanyForDedup(row.company) : '';
              return companyKey ? `${company.sourceBaseId}:${companyKey}` : null;
            },
          });
          mapped.leads.forEach((lead, i) => {
            carriedLeads.push(lead);
            carriedSourceRows.push(offset + mapped.leadRowIndices[i]);
            carriedLeadOwner.set(lead, company.id);
          });
        }
        // Один адрес — один лид: свой лид с адресом, который уже несёт
        // перенесённая компания, в пачку не идёт (провайдер отсеял бы его как
        // дубль, но решать это до отправки дешевле и честнее для воронки).
        const carriedEmails = new Set(carriedLeads.map((lead) => lead.email));
        sendLeads = [...carriedLeads];
        sendLeadSourceRows = [...carriedSourceRows];
        leads.forEach((lead, i) => {
          if (carriedEmails.has(lead.email)) return;
          sendLeads.push(lead);
          sendLeadSourceRows.push(carriedRows.length + leadSourceRows[i]);
        });
        sendLeadRows = [...carriedRows, ...leadRows];
      }
    }

    // 4. Blocklist владельца (сами считаем — число нужно в журнале;
    //    appendLeadsToClientCampaign продублирует фильтр внутри, это дёшево).
    const blockedSet = await getBlockedEmailSet(supabaseInstantly, ownerUserId);
    const { kept, blockedCount } = filterBlockedLeads(sendLeads, blockedSet);
    runStats.skipped_blocklist = blockedCount;
    ownKept = kept;
    if (carryClaim && carryClaim.companies.length > 0) {
      carriedInKept = new Set();
      for (const lead of kept) {
        const owner = carriedLeadOwner.get(lead);
        if (owner) carriedInKept.add(owner);
      }
    }

    // 4b. ЗАМЕР того, что прячет skipIfInCampaign (см. HeRefillSkipProbe).
    //     ВЫКЛЮЧЕН по умолчанию (HE_REFILL_SKIP_PROBE_REQUESTS): без него шаг
    //     не делает ни одного запроса и не пишет ни одного ключа.
    //     Только считает: ни одна строка отсюда не выпадает, и отказ замера
    //     ночь не роняет. Стоит до брони — это чтение, а бронь держит дневной
    //     объём проекта, и растягивать её на минуты чтения нельзя.
    const skipProbe = await measureRefillSkipExposure(ctx, {
      leads: kept,
      ownerUserId,
      campaignId: pick.campaignId,
    });
    if (skipProbe) {
      runStats.skip_probe = skipProbe;
      // Числа обязаны быть видны в логе прогона, а не только в jsonb: решение
      // по флагу принимается глазами, и «замер был, вот что он показал» должно
      // читаться без SQL.
      stageLog(
        ctx,
        `[base_collect] refill: замер skipIfInCampaign — спрошено ${skipProbe.probed} ` +
          `адресов из ${skipProbe.of}: в нашей кампании ${skipProbe.already_in_our_campaign}, ` +
          `в ЧУЖОЙ кампании воркспейса ${skipProbe.in_other_campaign}, ` +
          `в воркспейсе без кампании ${skipProbe.in_workspace_no_campaign}, ` +
          `нет в воркспейсе ${skipProbe.absent}, без вывода ${skipProbe.undecided} ` +
          `(${skipProbe.requests} запросов` +
          // «Оборвался» и «выборка» — разные вещи, и по числам их не отличить:
          // и то и другое даёт probed < of.
          `${skipProbe.stopped_early ? ', замер оборван: срок или отказ провайдера' : ''}; ` +
          'флаг НЕ менялся — это измерение)',
      );
    }

    // 5. Дневной кап проекта — БРОНЬ, взятая до первого запроса к рассыльщику.
    //    Кап заморожен за проектом на UTC-день, занятое считается под
    //    advisory-локом, поэтому два прогона одного проекта (в том числе два
    //    воркера на одной джобе после resetStuckJobs) не могут выдать друг
    //    другу один и тот же остаток. Ошибка брони — fail-closed: долив уходит
    //    в общий отказ, не отправив ни строки (см. reserveRefillDailyBudget).
    let toSend = kept;
    if (kept.length > 0) {
      const budget = await reserveRefillDailyBudget(ctx, {
        projectId: job.project_id,
        baseId: base.id,
        requested: kept.length,
      });
      reservationId = budget.id;
      if (budget.granted < kept.length && budget.granted > 0) {
        // Отрез ПО КОМПАНИЯМ, а не по порядку строк. После split_emails адреса
        // компании стоят подряд, и `kept.slice(0, granted)` отдавал весь кап
        // нескольким первым компаниям по всем их адресам, а остальные
        // оплаченные компании не получали ничего — и всё равно выжигались
        // (база 'analyzed'). Правило — то же, что у ручного запуска
        // (selectLeadsWithinLaunchCap, launchHandoff.ts): сначала по одному
        // адресу КАЖДОЙ компании, потом вторые адреса и т. д. При дефолтах
        // (кап 50, ~2 допущенных адреса на компанию из 100) письмо получают
        // ~50 компаний вместо ~25. appendLeads.ts не меняется.
        const cut = selectRefillLeadsByCompany({
          kept,
          leads: sendLeads,
          leadSourceRows: sendLeadSourceRows,
          leadRows: sendLeadRows,
          columns: finalColumns,
          granted: budget.granted,
        });
        toSend = cut.toSend;
        if (cut.companiesHeldBack > 0) runStats.capped_companies = cut.companiesHeldBack;
      } else {
        toSend = kept.slice(0, budget.granted);
      }
      runStats.reserved = budget.granted;
      runStats.budget_outcome = budget.outcome;
      if (budget.dailyCap !== null) runStats.daily_cap = budget.dailyCap;
      if (budget.spentBefore !== null && budget.dailyCap !== null) {
        runStats.daily_remaining = Math.max(0, budget.dailyCap - budget.spentBefore);
      }
      runStats.capped = kept.length - toSend.length;
      // Причина отреза — рядом с числом: воронка обязана отличать «бюджет
      // проекта на сутки» от брака адресов (unverified/отклонённые выше) и от
      // повтора прогона, у которого бюджет уже занят его первой попыткой.
      if (runStats.capped > 0) {
        runStats.capped_reason =
          budget.outcome === 'already_reserved' ? 'repeat_run' : 'daily_leads_cap';
      }
      if (budget.outcome === 'reclaimed') {
        // Перехват своей же брони: предшественник этой базы умер между
        // взятием брони и её закрытием (открыта дольше окна перехвата).
        // Молчать нельзя — это единственное место, где видно, что ночь
        // доедает чужой хвост, и что часть строк провайдер может отсеять как
        // уже принятые от предшественника.
        stageLog(
          ctx,
          `[base_collect] refill: бронь этой базы висела открытой дольше окна перехвата — ` +
            `забрали её себе (${budget.granted} стр. разрешено); строки, которые предыдущий ` +
            'прогон успел отдать, провайдер отсеет как дубли',
        );
      }
      // 5б. Бюджет не дал НИ ОДНОЙ строки — этот прогон провайдеру сегодня не
      //     отдаст ничего. Уходим в общий отказ (catch ниже). Прежнее
      //     поведение (тихий 'appended' с нулём) писало базу 'analyzed', и
      //     оплаченный срез выжигался из будущих сборок проекта навсегда.
      //     Судьба компаний в catch'е зависит от исхода брони
      //     (HeRefillBudgetOutcome): 'cap_exhausted' их не выжигает ВСЕГДА и в
      //     серию отказов не идёт — бюджет занят чужими базами, срез тут ни
      //     при чём: у market='us' компании уходят в очередь переноса, иначе
      //     в пул; 'already_reserved' их НЕ возвращает и не переносит — бронь
      //     держит прошлый прогон этой же базы, который мог уже отправить.
      //
      //     Текст причины разный у разных исходов и это не косметика: «кап
      //     проекта занят другими вертикалями» лечится капом, а «бронь этой
      //     базы моложе окна» — ничем, это ночь двойника. Общий якорь
      //     «дневной бюджет добора» — для разбора в journal/БД.
      if (toSend.length === 0) {
        throw new Error(
          budget.outcome === 'already_reserved'
            ? `дневной бюджет добора этой базы на сегодня уже забронирован её первым прогоном ` +
              `(${kept.length} стр. не отправлены) — долив остановлен`
            : `дневной бюджет добора проекта на сегодня занят целиком ` +
              `(${kept.length} стр. не отправлены, исход брони ${budget.outcome}) — долив остановлен`,
        );
      }
    } else {
      runStats.capped = 0;
    }

    // 6. Долив. valid===0 — 'no_new': сюда доходит только случай «вердикты
    //    есть, но ни один адрес не допущен» (или адресов не нашли вовсе, а
    //    конструктор доработал), то есть добор действительно нечего
    //    отправлять; непроверенные адреса и недоработавший конструктор
    //    отсеялись отказом на шаге 3. Валидные были, но всех съел blocklist —
    //    'appended' с appended=0 (воронка в stats): blocklist это решение
    //    ВЛАДЕЛЬЦА по конкретным адресам, а не отложенная ночь, и компании
    //    такой базы отработаны честно. Съел кап — уже не сюда: нулевой
    //    бюджет ушёл в отказ шагом 5б, а судьбу компаний решает исход брони.
    if (toSend.length > 0) {
      // Пачка запоминается ДО вызова: позиции в attempted/deferred (и в снимке
      // частичного отказа) — индексы именно этого массива, а итог переноса
      // обязан знать, чей лид на какой позиции, и в catch'е тоже.
      sentBatch = toSend;
      const appended = await appendLeadsToClientCampaign({
        userId: ownerUserId,
        campaignId: pick.campaignId,
        leads: toSend,
        contextLabel: `HE auto-refill · ${base.id}`,
        // Флаг ВОРКСПЕЙС-ШИРОКИЙ, а не кампания-широкий: Instantly отсеет
        // адрес, лежащий в ЛЮБОЙ кампании аккаунта, включая кампании других
        // клиентов студии. Мы за такой контакт уже заплатили сбором и не
        // отправим его никогда — при этом его компания уходит из будущих
        // сборок проекта вместе со всей базой ('analyzed').
        //
        // Почему он всё же остаётся true в этой волне. Во-первых, цена флага
        // до сих пор НЕ ИЗМЕРЕНА: ночной добор не запускался в production ни
        // разу, и «сколько адресов занято соседями» никто не считал — этим
        // занят шаг 4b выше (runStats.skip_probe), и решение принимается по
        // его числам, а не по ощущению. Во-вторых, семантику флага нельзя
        // подтвердить снаружи: единственное свидетельство — комментарий в
        // нашем же коде (clientLaunch/appendLeads.ts), API этого не описывает.
        //
        // Чего флаг НЕ держит (и почему его перевод в false не ломает
        // идемпотентность): повторный сбор тех же компаний исключён на сборке
        // (loadOtherBaseExclusionKeys), повторный прогон ТОЙ ЖЕ базы — стартовым
        // гейтом стадии ('collecting') и бронью дня ('repeat_run'), а
        // окончательность ночи даёт терминальная запись базы. Единственное, что
        // держит именно флаг, — второе письмо адресу, который уже в НАШЕЙ
        // кампании; при переводе в false этот отсев придётся делать самим,
        // чтением из lib/instantly/leadPresenceProbe, и «не знаю» тогда обязано
        // означать «не отправлять».
        //
        // ОДИН СЛУЧАЙ, ГДЕ ФЛАГ РАБОТАЕТ НЕ ЗАПАСНЫМ, А ЕДИНСТВЕННЫМ: перехват
        // своей брони ('reclaimed'). Предшественник этой базы умер, не записав
        // ни строки прогона, ни закрытия брони, но МОГ успеть отдать часть
        // пачки провайдеру; наследник шлёт её заново, и именно флаг делает так,
        // что второе письмо не уходит (эти строки вернутся как skipped, не
        // accepted). Поэтому перевод флага в false обязан идти вместе с
        // собственным отсевом — иначе перехват начнёт писать людям дважды.
        skipIfInCampaign: true,
        // Происхождение пачки в ОБЩЕМ построчном журнале доставки
        // (client_campaign_contact_ledger / client_campaign_append_batches).
        // Журнал пишется и без этого — но под дефолтным `campaign_append`,
        // в котором ночной добор ENG неотличим от ручной доливки RU-контура.
        // Своего ключа источника достаточно, чтобы строки ENG можно было найти
        // и сопоставить с he_jobs; ни одной строки RU это не меняет (журнал
        // скоупится client_user_id, а source_kind отчётность только проецирует,
        // см. lib/clientReports/exportSql.ts).
        ledgerSource: { kind: 'he_auto_refill', jobId: job.id },
        // Ночной долив — доверенный серверный оркестратор, а не браузер
        // клиента: объём уже срезан серверным `daily_leads_cap` (шаг 5 выше),
        // поэтому self-serve тарифный гейт к нему не применяется. Без этой
        // строки ENG-клиент получал 403 «Подписка не активна» ПОСЛЕ оплаченного
        // сбора (у него тариф неактивен или отсутствует), тогда как ручной
        // запуск ENG-кампании гейта не имеет вовсе. Ветка ENG-only по
        // построению: payload.refill ставит только крон autoPipeline, который
        // берёт лишь конфиги проектов he_projects.market='us'.
        //
        // Флаг снимает гейт ЦЕЛИКОМ (appendLeads.ts:245) — вместе с «подписка
        // не активна» отключаются удержание на прогреве почт, «оформлена, но
        // не оплачена» и тарифный лимит контактов. Для ENG это осознанно:
        // ящики, прогрев и расписание ведёт студия по договору, а не тариф
        // клиента; объём режет daily_leads_cap. НЕ затрагиваются (они вне
        // гейта): blocklist владельца, доменная политика, отказ Instantly по
        // лимитам воркспейса и журнал отправок. Вторая возможная опция —
        // `agency_managed` у ENG-пресета при провижининге, см. шапку
        // autoPipeline.ts.
        entitlementMode: 'managed_contract',
        // Кончилось место в воркспейсе — ПАУЗА, а не 402 поверх оплаченного
        // сбора: appendLeadsToClientCampaign грузит столько, сколько влезает,
        // и возвращает capacityBlocked вместо броска (и помечает не уехавшие
        // строки deferred, а не окончательно отсеянными). Ночной долив —
        // единственный ENG-путь, который упирается в ёмкость без человека
        // рядом, и разница «некуда грузить» против «адреса плохие» решает,
        // пересобирать базу или ждать места.
        pauseOnWorkspaceCapacity: true,
        // Признак жизни на КАЖДОЙ попытке отправки чанка (хук зовётся после
        // допуска лимитера, прямо перед HTTP). Без него ночной долив был
        // невидим для сторожа простоя стадии: blocklist, кап и загрузка идут
        // через supabaseInstantly и HTTP Instantly, то есть ни ctx.supabase, ни
        // ctx.log, ни ctx.onActivity не дёргаются, и медленная ночь провайдера
        // обрывалась аварийным выходом процесса ПОСРЕДИ загрузки: лиды уже
        // приняты, refill_result нет, строки журнала прогона нет, а повтор
        // грузит их заново — от дублей остаётся только skipIfInCampaign.
        //
        // Побочный эффект хука осознан (appendLeads.ts:380): вместе с ним
        // включаются timeoutMs=90_000 и timeoutIncludesBody=true — это нам и
        // нужно, иначе зависшее ЧТЕНИЕ ТЕЛА ответа не ограничено ничем, — и
        // выключается retryRateLimits, то есть 429 больше не пересиживается
        // внутри клиента (4+8+16 с). Обмен сознательный: отказ по 429 долив
        // ловит сам, пишет прогон 'failed' с причиной, ВОЗВРАЩАЕТ компании в пул
        // (429 доказывает, что строки не приняты — refillRateLimitRefusal) и его
        // повторит крон следующей ночью, тогда как аварийный выход посреди
        // загрузки не оставлял ни причины, ни журнала и приводил к повторной
        // отправке. Развязать три опции в appendLeads.ts было бы чище, но этот
        // файл общий с оплачиваемым RU-кабинетом — решение владельца.
        beforeProviderRequest: async () => {
          ctx.onActivity?.();
        },
      });
      appendOutcome = appended;
      runStats.appended = appended.accepted;
      runStats.skipped_instantly = appended.skipped;
      // Провайдер уже видел строки. Если дальше упадёт запись базы, компании
      // обратно в сборку отдавать нельзя (см. refillLeadsReachedProvider).
      // Попытки, которые провайдер сам отклонил по ёмкости (deferredIndexes),
      // доставкой не считаются — то же правило, что у отказа в catch'е: 200 с
      // нулём принятого и нулём места в воркспейсе раньше записывал ночь
      // 'appended' с нулём и выжигал её компании.
      providerTouched = appended.accepted > 0 || refillAttemptsNotProvenRefused(appended) > 0;
      if (appended.capacityBlocked === true) {
        // Воркспейс полон — это доказано ответом самого провайдера, а не
        // угадано. Причину запоминаем здесь, а пишем паузу после терминальных
        // записей (см. recordRefillCapacityPause). Команде сообщаем СРАЗУ, до
        // терминальных записей (alertRefillCapacityStop): кабинет напишет
        // клиенту «команда уже работает» по этой же ночи.
        capacityPauseSource = `долив базы ${base.id} (провайдер перестал принимать строки)`;
        alertRefillCapacityStop(ctx, job, base.id, capacityPauseSource);
        // Остаток пачки: принято + окончательно отсеяно ≤ отдано, разница —
        // строки, которым не хватило места (явный отказ на чанке + хвост,
        // который пауза не начала отправлять).
        const deferred = Math.max(0, toSend.length - appended.accepted - appended.skipped);
        if (deferred > 0) {
          runStats.deferred = deferred;
          runStats.deferred_reason = 'instantly_capacity';
        }
        if (!providerTouched) {
          // Провайдер не принял НИ ОДНОЙ строки — до запроса не дошло (ноль
          // места по предполёту appendLeads) либо он сам отказал по ёмкости
          // на каждой отданной строке. Это отказ, а не долив: уходим в общий
          // catch, чтобы база стала 'failed' и её компании вернулись в пул
          // (по тому же правилу серии отказов), а бронь закрылась нулём. Иначе ночь
          // записалась бы как 'appended' с нулём, а оплаченные компании
          // остались бы выжженными — при том что доливать было НЕКУДА и
          // завтрашняя ночь отправила бы их же, если место освободится.
          throw new Error(
            `${REFILL_CAPACITY_NOTE} — провайдер не принял ни одной строки из ${toSend.length}`,
          );
        }
        // Часть строк уехала: база остаётся 'analyzed' (компании отработаны),
        // остаток виден в stats.deferred. Durable-пауза ниже останавливает
        // ПРОЕКТ, а не хранит остаток; остаток хранит ПЕРЕНОС (только 'us'):
        // компании, ни один адрес которых не дошёл до провайдера, уходят в
        // очередь ниже и после снятия паузы идут первыми. Вторые адреса
        // компаний, получивших письмо, не досылаются — компания охвачена.
        stageLog(
          ctx,
          `[base_collect] refill: место в воркспейсе кончилось на доливе — ` +
            `принято ${appended.accepted}, не уехало ${deferred} стр. ` +
            (carryEnabled
              ? '(компании без единого письма уходят в очередь переноса и пойдут первыми после снятия паузы)'
              : '(эти строки не досылаются: пауза останавливает ночной добор проекта, а не хранит остаток)'),
        );
      }
    }
    // 'no_new' — только когда отправлять было нечего НИ из своей сетки, НИ из
    // очереди переноса: ночь, отправившая перенесённые компании, добавила
    // контакты, и правило сухой вертикали обязано это видеть.
    const outcome: HeRefillResult['status'] =
      valid === 0 && carriedValid === 0 ? 'no_new' : 'appended';

    // ПЕРЕНОС — решения считаются ДО терминальных записей (их числа уезжают в
    // refill_result и строку прогона), а пишутся ПОСЛЕ них (см. ниже).
    let carrySettle: HeRefillCarrySettle | null = null;
    let ownQueue: HeRefillCarryQueuePlan | null = null;
    if (carryEnabled && carryClaim) {
      const reached = refillReachedPositions(appendOutcome);
      if (carryClaim.companies.length > 0) {
        carrySettle = planHeRefillCarrySettle({
          companies: carryClaim.companies,
          ownerOf: carriedLeadOwner,
          inKept: carriedInKept,
          batch: sentBatch,
          reached,
          // Успешная ветка: бронь выдана этому прогону, неизвестных нет.
          unknown: null,
        });
      }
      ownQueue = planOwnQueue(reached);
      noteCarryStats(carrySettle, ownQueue);
    }

    const refillResult: HeRefillResult = {
      status: outcome,
      campaign_id: pick.campaignId,
      stats: runStats,
      // Тот же признак, что и у пустого harvest'а: 'no_new' здесь означает
      // «строки собрались, но допущенных адресов нет», и судить по такой ночи
      // о сухости можно только когда каталог дочитан. Пишется и при
      // 'appended' — форма строки прогона не должна зависеть от исхода.
      scan_complete: refillScanComplete(info),
      completed_at: new Date().toISOString(),
    };
    await persistRefillBase(ctx, base.id, {
      columns: finalColumns, rows: finalRows, info, stats, refillResult, status: 'analyzed',
    });
    // Бронь закрывается ПОСЛЕ терминальной записи базы: пока она открыта,
    // занятым считается весь выданный объём, и падение этой записи оставляет
    // бюджет занятым (недоотправка), а не свободным (отправка поверх капа).
    await finalizeRefillDailyBudget(ctx, {
      reservationId,
      baseId: base.id,
      consumed: runStats.appended,
    });
    await writeRefillRun(ctx, {
      configId: config?.id ?? null,
      projectId: job.project_id,
      verticalId: base.vertical_id,
      baseId: base.id,
      result: refillResult,
    });
    stageLog(
      ctx,
      `[base_collect] refill ${outcome}: кампания ${pick.campaignId}, лидов ${runStats.appended} ` +
        `(valid ${runStats.valid}, без вердикта ${runStats.unverified}, ` +
        `blocklist ${runStats.skipped_blocklist}, кап-отрез ${runStats.capped}` +
        // Причина отреза и сколько КОМПАНИЙ остались без письма — рядом с
        // числом строк: «отрезано 150» без них не отличает дневной кап от
        // повтора прогона и не говорит, сколько оплаченных компаний сгорело.
        (runStats.capped_reason ? ` (${runStats.capped_reason})` : '') +
        (runStats.capped_companies !== undefined
          ? `, компаний без письма ${runStats.capped_companies}`
          : '') +
        ' ' +
        // Остаток капа при нулевом отрезе — признак НЕДОбора: компаний собрали
        // меньше, чем нужно капу (см. HE_REFILL_ACCEPTED_PER_COMPANY). '?' —
        // остаток не измерен (брони не было либо она ничего не считала):
        // писать здесь ноль значило бы объявить бюджет исчерпанным.
        `при остатке ${runStats.daily_remaining ?? '?'} из ${runStats.daily_cap}` +
        // Исход брони и выданный объём — ЗДЕСЬ, а не только в jsonb прогона:
        // без них строка лога не отвечает, почему отправлено меньше, чем
        // допущено, и чем 'reclaimed'-ночь (доедаем хвост умершего прогона)
        // отличается от обычной. Ключей нет — бронь не бралась (отправлять
        // было нечего), и писать про неё нечего.
        `${runStats.budget_outcome === undefined
          ? ''
          : `, бронь ${runStats.budget_outcome} на ${runStats.reserved ?? 0} стр.`})`,
    );
    // ПЕРЕНОС — после терминальных записей: компании ночи ложатся в очередь,
    // только когда их база уже 'analyzed' (то есть держит их исключёнными), а
    // итог перенесённых — когда отправка этой ночи записана.
    if (carrySettle) await settleHeRefillCarryover(ctx, base.id, carrySettle);
    const ownQueued = ownQueue ? await writeHeRefillCarryQueue(ctx, ownQueue) : true;
    if (runStats.carryover) {
      const c = runStats.carryover;
      stageLog(
        ctx,
        `[base_collect] refill: перенос — из очереди предложено ${c.offered} компаний ` +
          `(ушли ${c.sent}, вернулись в очередь ${c.returned}, сняты ${c.dropped}, срок вышел ${c.released}); ` +
          `в очередь от этой ночи ${c.queued}` +
          (c.released_hiring ? `, сразу в пул (крючок найма не доживёт свежим) ${c.released_hiring}` : '') +
          (ownQueued ? '' : ' — ЗАПИСЬ НЕ ЛЕГЛА, эти компании остаются исключёнными') +
          (runStats.carry_only ? '; сборка этой ночью не покупалась' : ''),
      );
    }
    // Переполнение воркспейса переживает эту ночь: завтрашний тик проекту
    // сборку не купит, пока сотрудник не возобновит добор. Последним шагом —
    // все записи, фиксирующие потраченное, уже сделаны.
    if (capacityPauseSource) {
      await recordRefillCapacityPause(ctx, job.project_id, capacityPauseSource);
    }
    return done(refillResult);
  } catch (e) {
    // Ошибка долива НЕ валит джобу (см. шапку): база сохраняется с
    // refill_result.error, прогон журналируется 'failed'.
    //
    // Причина классифицируется рядом с текстом: отказ по ёмкости воркспейса —
    // не брак данных, а нехватка места у рассыльщика; он ставит durable-паузу
    // добора проекта (последний шаг этой ветки), и снимает её сотрудник —
    // сам по таймеру добор не возобновится. Маркер
    // REFILL_CAPACITY_NOTE дописывается в начало текста, чтобы причина читалась
    // и в he_bases.error (кабинет сворачивает его в машинный код), а не только
    // в машинном error_kind.
    //
    // ЧАСТИЧНЫЙ ПРИЁМ — отдельная ветка, и это деньги, а не отчётность.
    // AppendLeadsPartialError несёт СНИМОК результата: провайдер мог принять
    // часть пачки и упасть на следующем чанке или на записи журнала. Пока эту
    // ветку не разбирали, runStats.appended оставался нулём — то есть ночь,
    // отправившая настоящие письма, записывалась как не отправившая ничего:
    // дневной расход исчезал (refillAppendedToday его не видел), воронка
    // врала, а следующая вертикаль получала тот же объём второй раз.
    // Числа берём из снимка как есть; судьбу компаний решает не он, а
    // delivered ниже.
    const partial = e instanceof AppendLeadsPartialError ? e.partialResult : null;
    /**
     * Строк, ушедших в транспорт и НЕ отклонённых провайдером явно: их приём не
     * подтверждён и не опровергнут (refillAttemptsNotProvenRefused). Строки,
     * которые провайдер сам отказался взять по ёмкости, сюда не входят — они
     * точно не созданы.
     */
    let attempted = 0;
    if (partial) {
      runStats.appended = partial.accepted;
      runStats.skipped_instantly = partial.skipped;
      attempted = refillAttemptsNotProvenRefused(partial);
    }
    const capacityRefusal = refillCapacityRefusal(e);
    if (capacityRefusal) {
      runStats.error_kind = 'instantly_capacity';
      // Тот же доказанный факт, что и в успешной ветке: провайдер сам отказал
      // по ёмкости. Источник причины перезаписываем только если его ещё нет —
      // первым увидел тот, кто увидел раньше. Алерт команде — там же, где
      // источник впервые присвоен (успешная ветка уже отправила свой), и до
      // терминальных записей ниже.
      if (capacityPauseSource === null) {
        capacityPauseSource = `долив базы ${base.id} (провайдер отказал по ёмкости)`;
        alertRefillCapacityStop(ctx, job, base.id, capacityPauseSource);
      }
      // Строки, которые провайдер ОТКАЗАЛСЯ взять по ёмкости, он перечисляет
      // сам (deferredIndexes непустой только при pauseOnWorkspaceCapacity).
      // Хвост, до которого отправка не дошла, в это число не входит — считать
      // его тут нечем, а завышать воронку нельзя.
      const deferred = partial?.deferredIndexes?.length ?? 0;
      if (deferred > 0) {
        runStats.deferred = deferred;
        runStats.deferred_reason = 'instantly_capacity';
      }
    }
    // Отмена клиентом — не сбой среза (см. шапку файла, refillUserCancelled).
    const cancelled = refillUserCancelled(ctx);
    if (cancelled) runStats.cancelled = true;
    const rawMessage = e instanceof Error ? e.message : String(e);
    const message = (
      capacityRefusal && !rawMessage.includes(REFILL_CAPACITY_NOTE)
        ? `${REFILL_CAPACITY_NOTE} — ${rawMessage}`
        : rawMessage
    ).slice(0, 500);
    // Провайдер ничего не получил → база терминально 'failed', и её компании
    // остаются доступны следующей сборке проекта. Успел получить (или мы не
    // знаем наверняка) → прежнее 'analyzed': компании считаются отработанными,
    // второе письмо тому же лиду дороже потерянного лида.
    const delivered = providerTouched || refillLeadsReachedProvider(e);
    // РЕШЕНИЕ О КОМПАНИЯХ — по ВСЕМУ набору исходов отказа:
    //  1. доставлено (или не знаем) → 'analyzed'. У market='us' компании, до
    //     которых отправка не дошла (их срезал кап, отказ провайдера случился
    //     раньше их чанка), ложатся в очередь переноса — как у успешной ночи,
    //     ПОСЛЕ терминальной записи базы; кроме отмены клиентом;
    //  2. бронь держит прошлый прогон ЭТОЙ базы ('already_reserved': двойник
    //     при перекрытии деплоя либо умерший предшественник моложе окна
    //     перехвата) → 'analyzed', без очереди. Тот прогон мог уже отдать
    //     строки, а его приём нам не виден — это тот же случай «не знаем», что
    //     и п. 1, и любая повторная отправка могла бы стать вторым письмом;
    //  3. бюджет проекта не дал базе ни строки ('cap_exhausted'): провайдер от
    //     этой базы сегодня не получил ничего, причина — чужой расход капа.
    //     У market='us' (решение владельца 04.10.2026) — 'analyzed', а все её
    //     компании с лидом — в очередь переноса, ДО терминальной записи и одним
    //     запросом; очередь не легла (или класть нечего) — 'failed', прежний
    //     возврат в пул. Вне market='us' — 'failed' всегда. Серия отказов тут
    //     не спрашивается и сама ночь в неё не попадёт (refillStreakVerdict) —
    //     иначе вторая такая ночь подряд выжигала бы оплаченный срез без
    //     единого письма;
    //  4. отмена клиентом без доставки → 'failed' всегда: решение человека, а
    //     не свойство среза, в серию тоже не идёт;
    //  5. остальное (не дошло до провайдера по нашей или его причине) → серия
    //     отказов: возврат только первому подряд (REFILL_RELEASE_FAIL_STREAK_LIMIT),
    //     иначе ночной крон собирал бы тот же срез снова и снова.
    const predecessorHoldsBudget = !delivered && runStats.budget_outcome === 'already_reserved';
    const budgetSpentElsewhere = !delivered && runStats.budget_outcome === 'cap_exhausted';
    // Что дошло (или могло дойти) до провайдера — одно правило для своих и
    // перенесённых компаний (refillLeadsReachedProvider): явный 429 при
    // нулевом приёме доказывает, что не создано ничего.
    const reached = appendOutcome
      ? refillReachedPositions(appendOutcome)
      : partial && partial.accepted === 0 && refillRateLimitRefusal(e)
        ? new Set<number>()
        : refillReachedPositions(partial);
    // Очередь собственных компаний — только у п. 1 и п. 3 (market='us') и
    // только без отмены клиентом: отменённый прогон — решение человека, его
    // компании решает прежнее правило (п. 1 — исключены, п. 4 — в пул), и
    // следующие ночи не досылают за него то, что он не успел.
    const ownQueue = (delivered || budgetSpentElsewhere) && !cancelled ? planOwnQueue(reached) : null;
    /** null — серия решению не понадобилась и не читалась. */
    let failStreak: number | null = null;
    let released: boolean;
    /** П. 3 у market='us': очередь записана, база 'analyzed'. */
    let budgetStopCarried = false;
    if (delivered || predecessorHoldsBudget) {
      released = false;
    } else if (budgetSpentElsewhere && ownQueue && (await writeHeRefillCarryQueue(ctx, ownQueue))) {
      released = false;
      budgetStopCarried = true;
    } else if (budgetSpentElsewhere || cancelled) {
      released = true;
    } else {
      failStreak = await refillFailStreak(ctx, base.vertical_id, base.id);
      released = failStreak < REFILL_RELEASE_FAIL_STREAK_LIMIT;
    }
    // Перенесённые компании, которые провайдер не получил, возвращаются в
    // очередь со старым сроком, получившие — 'sent'. Исход 'already_reserved' —
    // единственный, где про перенесённую компанию НЕ известно, дошла ли она:
    // прошлый прогон ЭТОЙ базы, державший её захват, мог её отправить. Такие
    // (heldBefore) снимаются в 'dropped'; взятые из очереди только сейчас
    // прошлому прогону не доставались и возвращаются.
    let carrySettle: HeRefillCarrySettle | null = null;
    if (carryEnabled && carryClaim && carryClaim.companies.length > 0) {
      carrySettle = planHeRefillCarrySettle({
        companies: carryClaim.companies,
        ownerOf: carriedLeadOwner,
        inKept: carriedInKept,
        batch: sentBatch,
        reached,
        unknown: predecessorHoldsBudget ? carryClaim.heldBefore : null,
      });
    }
    // В воронку — только очередь, которая записана (п. 3) или будет записана
    // после терминальной записи (п. 1); у п. 3 с упавшей записью её нет.
    if (carryEnabled) noteCarryStats(carrySettle, delivered || budgetStopCarried ? ownQueue : null);
    // Текст базы у отмены — ровно тот, что пишет ENG-роут отмены: кабинет
    // сверяет его полным совпадением и показывает отмену, а не «шаг не успел»
    // (текст AbortError прочитанного после отмены запроса классифицировался
    // как 'timeout'). Строка прогона и журнал сохраняют настоящий текст.
    const baseError = cancelled ? REFILL_CANCELLED_ERROR : message;
    const refillResult: HeRefillResult = {
      status: 'failed',
      stats: runStats,
      error: message,
      ...(capacityRefusal ? { error_kind: 'instantly_capacity' as const } : {}),
      delivery_attempted: delivered,
      companies_released: released,
      ...(budgetStopCarried ? { companies_carried: true as const } : {}),
      // Серию пишем только когда от неё зависело решение: в остальных исходах
      // записанный здесь ноль был бы неизмеренным.
      ...(failStreak === null ? {} : { fail_streak: failStreak }),
      completed_at: new Date().toISOString(),
    };
    // Причина видна в карточке базы, а не только в журнале прогонов — только
    // вместе со статусом 'failed' (у 'analyzed'-базы error пустой, см.
    // persistRefillBase).
    await persistRefillBase(ctx, base.id, {
      columns: finalColumns,
      rows: finalRows,
      info,
      stats,
      refillResult,
      ...(released ? { status: 'failed' as const, error: baseError } : { status: 'analyzed' as const }),
    });
    // Расходом отказа считается ПОПЫТКА, а не подтверждённый приём: строки,
    // ушедшие в транспорт, могли быть созданы и при потерянном ответе, и
    // освобождать под них бюджет значило бы разрешить отправку сверх капа тем
    // же адресам. Исключение — строки, которые провайдер явно отклонил по
    // ёмкости (см. attempted выше): они не созданы, и держать под них бюджет
    // значило бы списать с дня отправку, которой не было. Отказ до первого
    // запроса освобождает бронь целиком (0) — и это важно: иначе одна
    // неудачная вертикаль съедала бы ночь всего проекта.
    await finalizeRefillDailyBudget(ctx, {
      reservationId,
      baseId: base.id,
      consumed: Math.max(runStats.appended, attempted),
    });
    await writeRefillRun(ctx, {
      configId: config?.id ?? null,
      projectId: job.project_id,
      verticalId: base.vertical_id,
      baseId: base.id,
      result: refillResult,
    });
    stageLog(
      ctx,
      `[base_collect] refill failed: ${message}` +
        // Тот же читатель полей брони, что и в успешной ветке: отказ после
        // выданной брони обязан показывать, сколько объёма было разрешено и
        // сколько оставалось от капа, — иначе по строке прогона не отличить
        // «бюджет не дал» от «дал, но упало». Ключа нет — бронь не бралась.
        (runStats.budget_outcome === undefined
          ? ''
          : ` [бронь ${runStats.budget_outcome} на ${runStats.reserved ?? 0} стр., ` +
            `остаток ${runStats.daily_remaining ?? '?'} из ${runStats.daily_cap}` +
            (runStats.capped > 0
              ? `, кап-отрез ${runStats.capped}${runStats.capped_reason ? ` (${runStats.capped_reason})` : ''}`
              : '') +
            ']') +
        (cancelled ? ' — отменено клиентом' : '') +
        (delivered
          ? ` — строки уже у провайдера (принято ${runStats.appended}, в транспорте ${attempted}), ` +
            'база остаётся analyzed'
          : predecessorHoldsBudget
            ? ' — бронь держит прошлый прогон этой базы, который мог уже отправить строки: ' +
              'база остаётся analyzed, компании не возвращаем'
            : budgetStopCarried
              ? ' — провайдер строк не получил, бюджет дня занят другими базами: компании ночи ' +
                'в очереди переноса (база analyzed), ночь в серию отказов не идёт'
            : released
              ? ' — провайдер строк не получил, база failed (компании не выжигаем)'
                + (budgetSpentElsewhere
                  ? ': бюджет дня занят другими базами, ночь в серию отказов не идёт'
                  : '')
                + (refillRateLimitRefusal(e) ? ': отказ по частоте запросов, приёма не было' : '')
              : ` — отказ ${(failStreak ?? 0) + 1}-й подряд, компании остаются исключёнными ` +
                '(база analyzed): иначе ночной прогон собрал бы тот же срез заново'),
    );
    // Итог перенесённых — после записей о потраченном, клиентом без сигнала.
    if (carrySettle) await settleHeRefillCarryover(ctx, base.id, carrySettle);
    // Отказ после доставки: база уже 'analyzed' и держит свои компании
    // исключёнными — теперь те, до кого отправка не дошла, ложатся в очередь
    // (как у успешной ночи). Очередь ночи без бюджета записана выше, до базы.
    const ownQueued = delivered && ownQueue ? await writeHeRefillCarryQueue(ctx, ownQueue) : true;
    if (runStats.carryover) {
      const c = runStats.carryover;
      stageLog(
        ctx,
        `[base_collect] refill: перенос в отказе — из очереди предложено ${c.offered} компаний ` +
          `(ушли ${c.sent}, вернулись в очередь ${c.returned}, сняты ${c.dropped}, срок вышел ${c.released}); ` +
          `в очередь от этой ночи ${c.queued}` +
          (c.released_hiring ? `, сразу в пул (крючок найма не доживёт свежим) ${c.released_hiring}` : '') +
          (ownQueued ? '' : ' — ЗАПИСЬ НЕ ЛЕГЛА, эти компании остаются исключёнными'),
      );
    }
    // Последним шагом, после всех записей о потраченном: отказ по ЁМКОСТИ
    // (и только он — 429, 402, сбой конструктора сюда не попадают, см.
    // refillCapacityRefusal) останавливает ночной добор проекта до явного
    // возобновления сотрудником.
    if (capacityPauseSource) {
      await recordRefillCapacityPause(ctx, job.project_id, capacityPauseSource);
    }
    return done(refillResult);
  }
}
