/**
 * Дочитан ли каталог этой ночью до конца.
 *
 * `true` — все задачи сборки закончили чтение сами: ни одна не встала по
 * потолку страниц (`hit_ceiling`), ни одна не оборвалась на середине
 * (`partial`), ни одна не упала. Только в этом случае «новых компаний нет»
 * говорит об ИСТОЧНИКЕ. Разбор состояний задачи — хендофф лейна расширения
 * плана: «встал по потолку» и «чтение оборвалось» не означают «сухо» никогда,
 * потому что непрочитанный хвост остался: у pdl повтор продолжает с закладки,
 * а живые фиды (funded, eng_hiring) закладки между сборками не держат и
 * читаются с начала среза, где уже собранные компании отсеиваются на выборке.
 *
 * `false` — читать осталось (потолок, обрыв, упавшая задача) ИЛИ задач не было
 * вовсе: у ночи без единой задачи нулевой результат говорит о плане, а не о
 * рынке. Оба случая одинаково не годятся как показание о сухости.
 *
 * Поле `exhausted` здесь НЕ участвует: оно про ОДИН срез («за закладкой под
 * эти фильтры пусто»), а правило судит ночь целиком, где срезов до четырёх и
 * перемешивает их interleaveTaskHarvests. Сухость источника и сухость среза —
 * разные факты, и путать их нельзя.
 */
function refillScanComplete(info: HeCollectInfo): boolean {
  const tasks = Array.isArray(info.tasks) ? info.tasks : [];
  if (tasks.length === 0) return false;
  return tasks.every(
    (t) => t.status === 'done' && t.hit_ceiling !== true && t.partial !== true && !t.error,
  );
}

/** Начало текущих UTC-суток — дневной бюджет daily_leads_cap считается по ним. */
function utcDayStart(now = new Date()): string {
  return new Date(Date.UTC(now.getUTCFullYear(), now.getUTCMonth(), now.getUTCDate())).toISOString();
}

/**
 * Сколько лидов ПРОЕКТ уже долил за текущие UTC-сутки (все его вертикали).
 *
 * Единственный потребитель — ПРЕДПОЛЁТ размера сборки
 * (resolveHeRefillCollectCompanies). Сам отрез по капу считает не это число, а
 * бронь (reserveRefillDailyBudget): там решение принимается под сериализацией,
 * здесь — оценка «сколько компаний покупать», и ошибаться ей можно только в
 * сторону недобора. Поэтому функция НИКОГДА не бросает: непрочитанная история —
 * ноль, то есть прежний (полный) объём сборки, а не «бюджет исчерпан».
 *
 * Три поправки к прежней арифметике, каждая закрывала свою дыру:
 *  * ключ — ПРОЕКТ, а не config_id. Кап объявлен «на проект в сутки», а
 *    he_auto_pipeline_configs может не быть вовсе (таблица пуста, refill
 *    поставлен руками) — тогда прежний расчёт не считал расход ВООБЩЕ и сборка
 *    шла по полному капу поверх уже отправленного. project_id есть у КАЖДОЙ
 *    строки прогона: её пишет либо крон при постановке, либо writeRefillRun;
 *  * учитываются и прогоны 'failed' с ненулевым `appended`. Долив, упавший
 *    ПОСЛЕ частичного приёма (AppendLeadsPartialError), отправил настоящих
 *    писем настоящим людям — считать такую ночь нулевой значило бы отдать этот
 *    объём следующей вертикали второй раз;
 *  * прогоны без завершения ('collecting') в сумму не идут: у них ещё нет
 *    ни приёма, ни числа. Открытая бронь такого прогона учтена в БРОНЯХ.
 *
 * Перерасход капа это число не сторожит и сторожить не обязано. Прежняя
 * редакция объясняла, что «многочанковый перерасход невозможен», потому что
 * HE_AUTO_REFILL_ROWS_LIMIT=200 меньше чанка отправки в 1000 — неверно дважды:
 * 200 — это КОМПАНИИ, а после split_emails строка — один адрес, и компания
 * даёт до contactCap строк (до 100), а daily_leads_cap сверху не ограничен,
 * так что пачка ночи бывает больше одного чанка. Настоящая граница другая:
 * toSend ≤ выданной брони ≤ остатку замороженного капа дня
 * (reserveRefillDailyBudget), а частичный приём на любом чанке приходит
 * снимком AppendLeadsPartialError и закрывает бронь принятым или попыткой —
 * объём сверх брони не уходит ни при каком числе чанков.
 */
async function refillAppendedToday(ctx: HeStageContext, projectId: string): Promise<number> {
  const { data, error } = await ctx.supabase
    .from('he_auto_pipeline_runs')
    .select('stats')
    .eq('project_id', projectId)
    .in('status', ['appended', 'failed'])
    .gte('completed_at', utcDayStart());
  if (error) throw new Error(`he_auto_pipeline_runs daily spent: ${error.message}`);
  let spent = 0;
  for (const row of data ?? []) {
    const appended = (row as { stats?: { appended?: unknown } }).stats?.appended;
    if (typeof appended === 'number' && Number.isFinite(appended) && appended > 0) {
      spent += appended;
    }
  }
  return spent;
}

/**
 * Конфиг auto-pipeline проекта. Best-effort: таблицы миграции может ещё не
 * быть на окружении (воркер выкатили раньше миграции) — тогда долив идёт с
 * дефолтным капом, а runs-запись пишется без config_id.
 */
async function loadRefillConfig(ctx: HeStageContext, projectId: string): Promise<RefillConfigRow | null> {
  try {
    const { data, error } = await ctx.supabase
      .from('he_auto_pipeline_configs')
      .select('id, daily_leads_cap')
      .eq('project_id', projectId)
      .maybeSingle();
    if (error) throw new Error(error.message);
    if (!data) return null;
    const row = data as { id?: unknown; daily_leads_cap?: unknown };
    const cap =
      typeof row.daily_leads_cap === 'number' && Number.isFinite(row.daily_leads_cap)
        ? row.daily_leads_cap
        : HE_AUTO_DEFAULT_DAILY_LEADS_CAP;
    return { id: String(row.id), dailyLeadsCap: cap };
  } catch (e) {
    stageLog(
      ctx,
      `[base_collect] refill: he_auto_pipeline_configs read: ${e instanceof Error ? e.message : String(e)} — кап по умолчанию`,
    );
    return null;
  }
}

/**
 * Исходы брони дневного бюджета — ВЕСЬ набор, который умеет вернуть
 * he_reserve_refill_daily_budget (миграция 20260930_0004). Перечислен здесь
 * целиком осознанно: ноль выданных строк бывает по трём разным причинам, и
 * воронка обязана их различать, иначе «повтор прогона» читался бы как
 * «исчерпан кап проекта» и лечился бы не тем.
 *
 * Выдали объём: 'granted' (новая бронь либо переоткрытие доказанно пустой) и
 * 'reclaimed' (ПЕРЕХВАТ своей же брони, открытой дольше окна перехвата, —
 * прогон-наследник умершего). Не выдали ничего: 'cap_exhausted' (кап проекта
 * занят другими бронями), 'already_reserved' (бронь этой базы моложе окна:
 * живой двойник) и 'nothing_requested' (спросили ноль — из этой ветки
 * недостижимо, бронь берётся только при kept.length > 0).
 *
 * Все нулевые исходы у долива значат одно: ЭТОТ прогон не отправит НИ ОДНОЙ
 * строки, и ночь кончается отказом (runHeRefillAppend, шаг 5б). Судьба
 * компаний у них РАЗНАЯ, потому что разное знание о доставке:
 *  - 'cap_exhausted' — у этой базы сегодня нет ни брони с расходом, ни
 *    открытой брони (иначе исход был бы 'already_reserved'), то есть провайдер
 *    от неё не получил ничего. Компании не выжигаются ВСЕГДА, вне серии
 *    отказов: у market='us' уходят в очередь переноса, иначе — в пул;
 *  - 'already_reserved' — бронь этой же базы держит её прошлый прогон: открытая
 *    (двойник или умерший предшественник моложе окна) либо закрытая с
 *    расходом. Тот прогон МОГ уже отдать строки провайдеру, поэтому компании
 *    остаются исключёнными ('analyzed'): второе письмо тому же лиду дороже
 *    потерянного лида;
 *  - 'nothing_requested' — недостижим (см. выше).
 */
export type HeRefillBudgetOutcome =
  | 'granted'
  | 'reclaimed'
  | 'cap_exhausted'
  | 'already_reserved'
  | 'nothing_requested';

interface HeRefillBudgetReservation {
  /** null — бронь не выдана (granted = 0). */
  id: string | null;
  granted: number;
  /** Кап, замороженный за проектом на этот UTC-день. */
  dailyCap: number | null;
  /** Занято другими бронями ДО этой. null — не считалось (бронь не выдавалась). */
  spentBefore: number | null;
  outcome: HeRefillBudgetOutcome;
}

/**
 * Занять дневной бюджет проекта ДО первого запроса к рассыльщику.
 *
 * Зачем бронь, а не разность двух чтений журнала. Прежний расчёт («сумма
 * stats.appended за сутки» минус кап) принимался в процессе воркера и ничем не
 * защищён от ВТОРОГО прогона той же джобы. У ENG этот повтор устроен так:
 * `resetStuckJobs()` (worker/hypothesisEngine.ts) на старте воркера закрывает
 * каждую оставшуюся 'running' джобу типизированным
 * HeJobInterruptionError('restart'), а writeJobFailure возвращает её в
 * 'pending' БЕСПЛАТНО — до HE_JOB_FREE_INTERRUPTIONS = 5 прерываний подряд.
 * То есть тот же сбор едет в Instantly ещё раз, и оба прогона видят одинаковый
 * остаток. Бронь решает это в БД: advisory-лок «проект + UTC-день»
 * сериализует решение, а сам кап берётся только с сервера — подменить его
 * вызовом нельзя.
 *
 * ЧЕМ ЭТОТ ПОВТОР НА САМОМ ДЕЛЕ ЯВЛЯЕТСЯ — и почему это меняет цену. Обычно он
 * ПОСЛЕДОВАТЕЛЬНЫЙ: процесс умер, новый его подобрал. Двумя ЖИВЫМИ прогонами
 * они становятся только при перекрытии деплоя (старый контейнер ещё работает,
 * когда стартует новый). Бесусловного bulk-апдейта «все running → pending», от
 * которого оборонялись бы всегда, у ENG нет с волны 3 — он остался у V2
 * (worker/verticalEngineV2.ts). Поэтому чаще всего бронь встречает не двойника,
 * а наследника.
 *
 * ОТЛИЧАЕТ ИХ ВОЗРАСТ ОТКРЫТОЙ БРОНИ, и это единственный доступный признак:
 * lease/heartbeat у ENG нет, а идентификатор джобы у наследника ТОТ ЖЕ (её
 * возвращает в 'pending' resetStuckJobs). Бронь моложе окна перехвата (два
 * часа, миграция 20260930_0004) — считаем, что двойник жив: 'already_reserved',
 * второй порции бюджета нет. Старше — предшественник мёртв: 'reclaimed', та же
 * база забирает свою бронь и досылает хвост, как досылала при прежней
 * арифметике двух чтений журнала (дубли по-прежнему отсекает
 * skipIfInCampaign). Два часа — примерно четырёхкратный запас к самому долгому
 * законному молчанию стадии (сторож простоя ≤ 30 мин + 2 мин на раскрутку,
 * worker/hypothesisEngine.ts), см. «ПОЧЕМУ ДВА ЧАСА» в миграции.
 *
 * ЦЕНА, КОТОРАЯ ОСТАЛАСЬ. Наследник, пришедший РАНЬШЕ окна (перезапуск воркера
 * через минуту — обычный случай), хвост не досылает, а незакрытая бронь до
 * конца UTC-суток держит объём для ОСТАЛЬНЫХ баз проекта: их вертикали в ту же
 * ночь получают 'cap_exhausted'. Освобождать чужой объём по возрасту нельзя —
 * у чужой базы другие адреса, и это была бы настоящая отправка поверх капа.
 * Компаний эти ночи не выжигают: 'cap_exhausted' при любой серии отказов
 * переносит компании своей базы в очередь (market='us'; шаг 5б ниже) либо
 * возвращает их в пул — тогда теряется оплаченная сборка ночи (её срез
 * следующая сборка купит заново), а не сами компании. Сам наследник ('already_reserved') компании своей базы НЕ
 * возвращает: предшественник мог успеть их отправить, а его приём наследнику
 * не виден — ни строкой прогона (её предшественник не дописал), ни бронью
 * (она открыта и держит весь выданный объём). Отсюда же недосчёт: принятое
 * предшественником не попадёт ни в stats.appended наследника, ни в
 * refillAppendedToday; кап это не ломает — открытая бронь держит объём до
 * конца суток, — но воронка ночи покажет ноль там, где письма могли уйти.
 *
 * FAIL-CLOSED, И ОТСЮДА ПОРЯДОК ВЫКАТА: СНАЧАЛА МИГРАЦИЯ 20260930_0004, ПОТОМ
 * ЭТОТ КОД. Любая ошибка вызова (нет миграции, нет прав, сбой БД) БРОСАЕТ, и
 * долив уходит в общий отказ, не отправив ни строки. Значит код, уехавший
 * раньше миграции, останавливает ночной добор ВСЕХ ENG-проектов целиком — это
 * не мягкая деградация, а ноль отправок при оплаченных сборах. Сторона выбрана
 * по цене ошибки: провайдер строк не видел → база 'failed' → её компании
 * возвращаются в пул при ПЕРВОМ отказе подряд (со второго их удерживает серия
 * отказов — сбой брони повторяется сам, пока не применена миграция), а
 * отправленное сверх капа не отзывается.
 */
async function reserveRefillDailyBudget(
  ctx: HeStageContext,
  input: { projectId: string; baseId: string; requested: number },
): Promise<HeRefillBudgetReservation> {
  const { data, error } = await ctx.supabase.rpc('he_reserve_refill_daily_budget', {
    p_project_id: input.projectId,
    p_base_id: input.baseId,
    p_requested: input.requested,
  });
  if (error) throw new Error(`he_refill daily budget reservation: ${error.message}`);
  const rows = Array.isArray(data) ? data : [];
  const row =
    rows.length === 1 && rows[0] && typeof rows[0] === 'object'
      ? (rows[0] as Record<string, unknown>)
      : null;
  const granted = row?.granted;
  const reservationId = row?.reservation_id;
  const raw = row?.outcome;
  const outcome: HeRefillBudgetOutcome | null =
    raw === 'granted' || raw === 'reclaimed' || raw === 'cap_exhausted'
      || raw === 'already_reserved' || raw === 'nothing_requested'
      ? raw
      : null;
  // Снимок проверяется целиком: половина ответа (например granted без брони)
  // означала бы, что мы отправим строки, за которые никто не расписался.
  if (
    outcome === null
    || typeof granted !== 'number'
    || !Number.isSafeInteger(granted)
    || granted < 0
    || granted > input.requested
    || (granted > 0 && (typeof reservationId !== 'string' || !reservationId))
    || (granted === 0 && reservationId !== null && reservationId !== undefined)
    // Объём выдают ровно два исхода, и наоборот: ненулевой granted без одного
    // из них означал бы, что мы отправим строки, за которые никто не расписался.
    || (outcome === 'granted' || outcome === 'reclaimed') !== (granted > 0)
  ) {
    throw new Error('he_refill daily budget reservation returned an invalid snapshot');
  }
  const asCount = (value: unknown): number | null =>
    typeof value === 'number' && Number.isSafeInteger(value) && value >= 0 ? value : null;
  return {
    id: granted > 0 ? (reservationId as string) : null,
    granted,
    dailyCap: asCount(row?.daily_cap),
    spentBefore: asCount(row?.spent_before),
    outcome,
  };
}

/**
 * Записать фактический расход брони и отпустить неиспользованное.
 *
 * НИКОГДА не бросает и никогда не валит долив: незавершённая бронь держит весь
 * свой объём до конца UTC-суток, то есть отказ этой записи даёт НЕДОотправку
 * (видна в воронке следующей ночи), а не отправку поверх капа. Обратная
 * сторона — тоже осознанная: «освободить» мы можем только то, что точно не
 * ушло, поэтому на неопределённом отказе (`AppendLeadsPartialError` с
 * попытками) расходом считается ПОПЫТКА, а не подтверждённый приём. Точно не
 * ушли строки, которые провайдер сам отклонил по ёмкости (deferredIndexes —
 * «безопасно повторить» по контракту appendLeads): их бронь отпускает.
 *
 * Идёт клиентом СТАДИЙ (а не paidCheckpointDb): запись только УМЕНЬШАЕТ
 * занятое, и её отказ после abort'а безопасен — в отличие от терминальной
 * записи базы и строки прогона, которые фиксируют уже потраченные деньги.
 */
async function finalizeRefillDailyBudget(
  ctx: HeStageContext,
  input: { reservationId: string | null; baseId: string; consumed: number },
): Promise<void> {
  if (!input.reservationId) return;
  try {
    const { error } = await ctx.supabase.rpc('he_finalize_refill_daily_budget', {
      p_reservation_id: input.reservationId,
      p_base_id: input.baseId,
      p_consumed: input.consumed,
    });
    if (error) throw new Error(error.message);
  } catch (e) {
    stageLog(
      ctx,
      `[base_collect] refill: бронь дневного бюджета не закрыта ` +
        `(${e instanceof Error ? e.message : String(e)}) — остаток занят до конца UTC-суток`,
    );
  }
}

/**
 * Финал прогона в he_auto_pipeline_runs: крон пишет строку 'collecting' при
 * постановке — обновляем её по base_id; не нашли (refill поставлен вручную) —
 * вставляем финальную строку целиком. Best-effort: журнал — аудит, падение
 * записи не должно валить стадию после уже случившегося долива.
 *
 * Запись — ДЕНЬГИ, а не аудит, и поэтому идёт клиентом БЕЗ сигнала джобы
 * (paidCheckpointDb): в `stats.appended` лежит число лидов, которых Instantly УЖЕ
 * принял. Отправку сверх капа эта строка НЕ сторожит — прежняя редакция
 * утверждала обратное («следующая ночь видит бюджет нетронутым и отправляет
 * поверх капа»), но с брони дневного бюджета (he_refill_daily_reservations,
 * миграция 20260930_0004) кап держит бронь в БД, и потерю этой строки она не
 * замечает; к тому же кап — на UTC-сутки, и «следующая ночь» живёт уже с новым.
 * Что стоит потерянная строка на самом деле:
 *  - ПРЕДПОЛЁТНЫЙ размер сборки (refillAppendedToday) не видит расход этого
 *    прогона и в те же сутки покупает компании, чьи строки бронь потом
 *    выбросит;
 *  - лента кабинета и воронка ночей не видят эту ночь (строка остаётся
 *    'collecting');
 *  - серия отказов вертикали (refillFailStreak) и правило сухой вертикали
 *    читают журнал; зависшую 'collecting' строку серия отказов разбирает по
 *    статусу её базы, а правило сухой вертикали пропускает.
 *
 * ЧТЕНИЯ здесь нет СОЗНАТЕЛЬНО. Раньше строку сначала искали `select('id')`, и
 * это чтение — клиентом стадий, потому что через клиент чекпойнта чтения не идут
 * — после аборта отвергалось, уводя весь вызов в catch: строка не появлялась
 * именно в том прогоне, ради которого запись и освобождали от сигнала. Поэтому
 * апдейт сам адресуется по (base_id, status='collecting') и возвращает
 * затронутые id, а вставка нужна только когда не затронуто ничего. Дублей это не
 * добавляет: барьер `status='collecting'` тот же, что стоял в поиске, — повтор
 * стадии поверх уже завершённой строки не попадает в апдейт и, как и раньше,
 * вставляет отдельную строку прогона.
 */
async function writeRefillRun(
  ctx: HeStageContext,
  write: {
    configId: string | null;
    projectId: string;
    verticalId: string;
    baseId: string;
    result: HeRefillResult;
  },
): Promise<void> {
  const patch = {
    status: write.result.status,
    // `scan_complete` подмешивается в тот же jsonb, что и воронка: у правила
    // сухой вертикали есть только строка прогона, а различать «источник пуст»
    // и «мы не дочитали» оно обязано (см. HeRefillResult.scan_complete).
    // Ключ пишется ТОЛЬКО когда он известен: его отсутствие — это «не знаем»,
    // и правило трактует такую ночь как непригодную для приговора.
    stats: {
      ...((write.result.stats ?? {}) as Record<string, unknown>),
      ...(write.result.scan_complete === undefined
        ? {}
        : { scan_complete: write.result.scan_complete }),
    },
    error: write.result.error ?? null,
    completed_at: write.result.completed_at,
  };
  const db = paidCheckpointDb(ctx);
  try {
    const { data: updated, error: updErr } = await db
      .from('he_auto_pipeline_runs')
      .update(patch)
      .eq('base_id', write.baseId)
      .eq('status', 'collecting')
      .select('id');
    if (updErr) throw new Error(updErr.message);
    if (!updated || updated.length === 0) {
      const { error } = await db.from('he_auto_pipeline_runs').insert({
        config_id: write.configId,
        project_id: write.projectId,
        vertical_id: write.verticalId,
        base_id: write.baseId,
        ...patch,
      });
      if (error) throw new Error(error.message);
    }
  } catch (e) {
    stageLog(
      ctx,
      `[base_collect] refill: запись he_auto_pipeline_runs не удалась: ${e instanceof Error ? e.message : String(e)}`,
    );
  }
}

/**
 * Терминальный апдейт refill-базы: строки как в обычном пути, статус —
 * 'analyzed' при доливе и 'failed' у недоставленного отказа, компании
 * которого возвращаются в пул (см. runHeRefillAppend).
 * Строки сохраняются в любом случае: отчёт и разбор причины идут по ним.
 *
 * he_bases.error пишется ВСЕГДА, а не «когда передали»: у 'failed' — причина, у
 * 'analyzed' — пусто. Пустое у 'analyzed' не формальность: cancel-роут мог
 * успеть записать базе 'Cancelled by user' (он переводит 'collecting' в
 * 'failed' по проекту целиком), а долив, уже отдавший строки провайдеру, всё
 * равно пишет базе 'analyzed' — и отмена на отработанной базе читалась бы
 * кабинетом как остановленный шаг, а у 'analyzed'-базы непустой error — как
 * сломанная база.
 *
 * Идёт клиентом БЕЗ сигнала джобы (paidCheckpointDb) — это запись ДЕНЕГ, и самых
 * дорогих в движке: к обоим её вызовам Instantly мог УЖЕ принять лидов в живую
 * кампанию, а приём не отменяется. Она же несёт решение о судьбе компаний
 * (`companies_released`). Пока запись была привязана к сигналу, abort (отмена
 * клиентом или сторож простоя) отвергал её ОБА раза — сначала в успешной ветке,
 * потом в catch'е, — и стадия падала наружу, оставив базу в 'collecting': лиды в
 * кампании есть, базы, воронки и решения нет. Дальше финальный фейл джобы уводил
 * такую базу в 'failed' (repairBaseAfterCollectFinalFail), а 'failed'-база
 * выпадает из кросс-базового исключения (loadOtherBaseExclusionKeys) — то есть
 * УЖЕ НАПИСАННЫЕ компании объявлялись несобранными, и ночной крон пересобирал их
 * за деньги (второе письмо спасал только skipIfInCampaign, оплаченный краул и
 * SMTP-пробы — нет).
 */
async function persistRefillBase(
  ctx: HeStageContext,
  baseId: string,
  args: {
    columns: string[];
    rows: HeUnifiedRow[];
    info: HeCollectInfo;
    stats: HeCollectInfo['stats'];
    refillResult: HeRefillResult;
  } & (
    | { status: 'analyzed' }
    | {
        status: 'failed';
        /** Текст в he_bases.error (кабинет сворачивает его в машинный код). */
        error: string;
      }
  ),
): Promise<void> {
  const { error } = await paidCheckpointDb(ctx)
    .from('he_bases')
    .update({
      columns: args.columns,
      sample_rows: args.rows.slice(0, SAMPLE_ROWS),
      data: args.rows,
      row_count: args.rows.length,
      status: args.status,
      error: args.status === 'failed' ? args.error : null,
      collect_info: { ...args.info, stats: args.stats, refill_result: args.refillResult },
      updated_at: new Date().toISOString(),
    })
    .eq('id', baseId);
  if (error) throw new Error(`he_bases refill update: ${error.message}`);
}

/**
 * Дошла ли до провайдера хотя бы одна строка упавшего долива.
 *
 * Зачем: loadOtherBaseExclusionKeys (stages/baseCollect.ts) исключает из
 * будущих сборок проекта компании всех баз, КРОМЕ 'failed'. Пока упавший
 * долив сохранялся в 'analyzed', его компании выжигались навсегда: сбор
 * оплачен, письма не ушли, второй раз эти компании не соберутся. Отдавать их
 * обратно в сборку можно только когда Instantly точно ничего не получил —
 * повторное письмо уже написанному лиду хуже потерянного лида.
 *
 * AppendLeadsPartialError несёт снимок результата; attemptedIndexes
 * заполняется в onRequestAttempt ПЕРЕД HTTP-запросом, поэтому непустой
 * список означает «запрос мог долететь, даже если ответ потерян». Остальные
 * отказы долива (нет кампании или пресета, сменившийся воркспейс, blocklist,
 * нулевая ёмкость по ПРЕДПОЛЁТУ appendLeads) бросаются до первого запроса в
 * Instantly. Исчерпанный лимит контактов воркспейса бывает и ОТВЕТОМ на
 * запрос — о нём ниже.
 *
 * Два исключения из «попытка = возможно доставлено» — оба про строки, которые
 * провайдер ЯВНО отклонил сам:
 *  - отказ по частоте запросов (429): запрос «отклонён целиком», и при нулевом
 *    accepted строки гарантированно не приняты (см. refillRateLimitRefusal);
 *  - отказ по ёмкости воркспейса: appendLeads (pauseOnWorkspaceCapacity)
 *    кладёт такие строки в deferredIndexes — по его контракту это «точные
 *    отказы провайдера, которые безопасно повторить», — и в 4xx «лимит
 *    контактов» (весь чанк), и в 200 с leads_uploaded=0 при нуле остатка
 *    (refillAttemptsNotProvenRefused). Попытка, попавшая в deferred, доставкой
 *    не считается.
 * Считать такую ночь доставленной значило бы выжигать оплаченный срез из-за
 * паузы провайдера. Ответ с частичным приёмом (accepted > 0) по-прежнему
 * доставка: он решается ВЫШЕ обоих исключений, даже если следующий чанк получил
 * отказ. Попытка БЕЗ явного ответа (сорванный сокет, истёкший срок) — по-прежнему
 * «возможно, долетел».
 *
 * Отсюда инвариант: доставленная база НИКОГДА не уходит в 'failed' решением
 * ЭТОГО прогона, поэтому в released-базе не может быть компании, которой уже
 * писал он сам (её собственный сбор исключал все не-'failed' базы проекта, а
 * доставленные базы остаются 'analyzed'). Прогон, который сам не отправлял, но
 * чью базу мог отправить ДРУГОЙ прогон той же джобы — живой двойник при
 * перекрытии деплоя или наследник умершего предшественника, — получает от
 * брони 'already_reserved' и компании тоже не возвращает (runHeRefillAppend):
 * доставку предшественника он не видит, а «не знаем» — это 'analyzed'.
 * Путей, где база с доставкой всё же может стать 'failed', два, и оба — когда
 * терминальная запись ЭТОГО прогона (persistRefillBase, оба вызова) не дошла:
 *   - ремонт воркера после ФИНАЛЬНОГО фейла base_collect — на первом отказе
 *     подряд либо когда сам ремонт сорвался до записи базы (тогда прежний
 *     'failed'); со второго подряд база уходит в 'analyzed' со строками среза
 *     (closeHeRefillBaseUndelivered, CAS по 'collecting');
 *   - отмена клиентом, пришедшая во время долива: cancel-роут пишет
 *     'collecting'-базе 'failed', и переписать её 'analyzed' было некому.
 * Второе письмо в обоих случаях не уходит: долив идёт со skipIfInCampaign=true
 * (Instantly отсеет лида, который уже в кампании), а start-guard стадии
 * (`status !== 'collecting'` → throw) не даёт повторно собрать базу с
 * терминальным статусом. Цена — деньги сбора: компании вернутся в пул и будут
 * собраны ещё раз.
 */
function refillLeadsReachedProvider(e: unknown): boolean {
  if (!(e instanceof AppendLeadsPartialError)) return false;
  const partial = e.partialResult;
  if (partial.accepted > 0) return true;
  // Провайдер ОТВЕТИЛ «слишком часто» — это доказательство НЕприёма: запрос
  // отклонён целиком, лидов он не создал. Неопределённость (сорванный сокет,
  // истёкший срок, потерянный ответ) сюда не попадает — только явный HTTP-код.
  if (refillRateLimitRefusal(e)) return false;
  return refillAttemptsNotProvenRefused(partial) > 0;
}

/**
 * Сколько строк ушло в транспорт и НЕ отклонено провайдером явно.
 *
 * attemptedIndexes — «запрос мог долететь», deferredIndexes — строки, которые
 * провайдер сам отказался взять по ёмкости (явный 4xx на чанке либо 200 с
 * нулём остатка, где все пропуски не объяснены окончательными причинами;
 * appendLeads заполняет его только при pauseOnWorkspaceCapacity). Разница —
 * строки, чей приём не подтверждён и не опровергнут: именно они делают ночь
 * «возможно, доставленной» и именно их бронь не вправе отпустить. Строки,
 * окончательно отсеянные провайдером (дубль кампании, невалидный адрес), в
 * deferred не попадают и остаются здесь: провайдер их видел.
 */
function refillAttemptsNotProvenRefused(result: {
  attemptedIndexes: readonly number[];
  deferredIndexes?: readonly number[];
}): number {
  const refused = new Set(result.deferredIndexes ?? []);
  let open = 0;
  for (const index of result.attemptedIndexes) if (!refused.has(index)) open += 1;
  return open;
}

/**
 * Явный отказ Instantly по частоте запросов (HTTP 429).
 *
 * Зачем отдельно: хук beforeProviderRequest (признак жизни для сторожа простоя)
 * в appendLeads.ts связан ОДНОЙ строкой с двумя другими опциями — таймаут 90 с
 * с чтением тела и `retryRateLimits: false`. То есть, взяв видимость для
 * сторожа, ночной долив потерял пересиживание 429 внутри клиента Instantly
 * (4+8+16 с), и 429 на ПЕРВОМ чанке стал прилетать сюда как отказ. А
 * attemptedIndexes заполняются в onRequestAttempt ДО HTTP-запроса — значит без
 * этого предиката разовый 429 читался бы как «провайдер строки получил»: база
 * сохранялась 'analyzed' с нулём доставленных лидов, а её компании исключались
 * из ВСЕХ будущих сборок проекта (loadOtherBaseExclusionKeys). Оплаченный краул
 * и SMTP-пробы сгорали из-за паузы провайдера на минуту.
 *
 * Разбор по тексту здесь — не выбор, а следствие: AppendLeadsPartialError
 * переносит наружу только `message` исходной ошибки (ни `cause`, ни статуса), а
 * appendLeads.ts делит файл с ОПЛАЧИВАЕМЫМ RU-кабинетом и обязан остаться
 * байт-в-байт. Поэтому класс читается напрямую, когда ошибка дошла не
 * завёрнутой, и по стабильному префиксу сообщения клиента Instantly
 * (`Instantly API <код>: …`, lib/instantly/client.ts) — когда завёрнутой.
 * Чистое решение — развязать три опции в appendLeads и дать ошибке `cause`;
 * это правка общего с платящим контуром файла и требует решения владельца.
 */
function refillRateLimitRefusal(e: unknown): boolean {
  if (e instanceof InstantlyApiError) return e.status === 429;
  return e instanceof Error && /^Instantly API 429\b/.test(e.message);
}

/**
 * Текст отказа «у рассыльщика не осталось места под контакты».
 *
 * Пишется в he_bases.error и refill_result.error рядом с машинным
 * error_kind='instantly_capacity'. Формулировка стабильная НАМЕРЕННО: по ней
 * клиентский классификатор (clientErrors.classifyHeClientError) отличает
 * «некуда грузить» от «данные плохие». Менять — только вместе с его правилом.
 */
const REFILL_CAPACITY_NOTE = 'Instantly: лимит контактов воркспейса исчерпан';

/**
 * Отказ долива про ёмкость воркспейса?
 *
 * Своего разбора текстов нет: capacityBlocked ставит внутри
 * appendLeadsToClientCampaign тот самый предикат isInstantlyContactCapacityError
 * (он же проверяется здесь напрямую — отказ мог прилететь и не завёрнутым), а
 * третья ветка узнаёт наш собственный отказ «провайдер не принял ни строки»,
 * который эта стадия бросает сама (см. долив ниже).
 */
function refillCapacityRefusal(e: unknown): boolean {
  if (isInstantlyContactCapacityError(e)) return true;
  if (e instanceof AppendLeadsPartialError && e.partialResult.capacityBlocked === true) return true;
  return e instanceof Error && e.message.includes(REFILL_CAPACITY_NOTE);
}

/**
 * Остановить ночной добор ПРОЕКТА durable-паузой: воркспейс рассыльщика полон,
 * и это знание обязано пережить текущую ночь.
 *
 * ЗАЧЕМ ИМЕННО ОТСЮДА. Предполёт ёмкости в кроне спрашивает
 * /workspace-billing/plan-details, и без scope на биллинг ответ у него —
 * «не знаем» (getWorkspaceContactCapacity отдаёт null на 403). Тогда
 * единственное доказательство переполнения — отказ провайдера на /leads/add,
 * то есть ЭТО МЕСТО. Оно же — требуемая деградация «ответ импорта
 * авторитетен»: предполёт молчит, импорт отвечает, решение принимается по
 * ответу импорта.
 *
 * ЦЕНА НОЧИ, КОТОРУЮ ЭТО ЭКОНОМИТ, УЖЕ ЗАПЛАЧЕНА. Пауза не возвращает деньги
 * текущей ночи и сама stats.deferred не досылает — она отменяет СЛЕДУЮЩУЮ
 * покупку сборки, которую некуда отправить. Отложенные компании успешной ночи
 * хранит перенос (he_refill_carryover): после снятия паузы они идут первыми,
 * если их срок ещё не вышел.
 *
 * Команде об этой паузе сообщает НЕ эта функция, а alertRefillCapacityStop —
 * в момент, когда причина паузы стала известна, то есть ДО терминальных
 * записей: abort посреди них не должен оставить кабинет с фразой «команда уже
 * работает» без алерта.
 *
 * ЗАПИСЬ BEST-EFFORT И ПОСЛЕДНЯЯ В ПОРЯДКЕ. Она идёт ПОСЛЕ терминальной записи
 * базы, закрытия брони и строки прогона: те фиксируют уже потраченные деньги и
 * обязаны состояться в любом случае, а пауза — про завтра. Клиент стадии здесь
 * ОБЫЧНЫЙ (ctx.supabase, с сигналом джобы), а не paidCheckpointDb: критерий
 * того исключения — «запись фиксирует УЖЕ СДЕЛАННУЮ оплату», и пауза под него
 * не подходит. Плата за это названа прямо: прогон, прерванный abort'ом ровно
 * здесь, паузу не запишет, и следующая ночь купит одну сборку, которую
 * отказ провайдера остановит снова — уже с паузой.
 *
 * Конфига у проекта может не быть (таблица пуста, refill поставлен руками) —
 * тогда пауза не ставится, и это верно: ночного тика у такого проекта нет.
 */
async function recordRefillCapacityPause(
  ctx: HeStageContext,
  projectId: string,
  source: string,
): Promise<void> {
  const paused = await pauseHeAutoPipelineRefill(
    ctx.supabase,
    projectId,
    buildHeCapacityPauseReason(source),
  );
  stageLog(
    ctx,
    paused
      ? '[base_collect] refill: ночной добор проекта остановлен по ёмкости воркспейса — '
        + 'вернуть его может только сотрудник (Движок вертикалей → карточка проекта)'
      : '[base_collect] refill: durable-пауза по ёмкости НЕ записана '
        + '(пауза уже стояла, конфига добора нет либо колонок паузы нет) — '
        + 'ночной тик решает как раньше',
  );
}

/**
 * Алерт команде: долив этой ночи упёрся в ёмкость рассыльщика, ночной добор
 * проекта встаёт на паузу. Контракт лейна алертов (opsAlert.ts) — ровно эти
 * поля.
 *
 * ЗАЧЕМ ИМЕННО ЗДЕСЬ. Кабинет ENG показывает клиенту на карточке базы, в ленте
 * («M not sent», «refill stopped») и в Command Center одну и ту же фразу
 * HE_TEAM_ON_IT_EN — «временная проблема на нашей стороне, команда уже
 * работает» (components/client-eng/clientFailureText.ts). Вторая её половина
 * правдива, только пока этот вызов стоит: убрать его можно только вместе с
 * фразой.
 *
 * Зовётся там, где ПРИСВАИВАЕТСЯ capacityPauseSource — и в успешной ветке, и в
 * catch'е, — то есть раньше терминальной записи базы, строки прогона и самой
 * паузы, и независимо от того, ляжет ли пауза потом (нет конфига, нет колонок):
 * карточка базы и лента показывают фразу в любом случае. Повтор того же
 * проекта в течение 6 ч гасит дедупликация opsAlert.
 *
 * `void`: воркер долгоживущий, ждать Telegram ему незачем; функция не бросает
 * никогда и сама ограничена 15 с. Пачку, отложенную в свёртку, воркер шлёт при
 * штатной остановке (flushHeOpsAlerts в worker/hypothesisEngine.ts).
 * Рынок — ctx.market: refill бывает только у market='us', а не-'us' opsAlert
 * отбрасывает сам, в одном месте.
 */
function alertRefillCapacityStop(ctx: HeStageContext, job: HeJob, baseId: string, source: string): void {
  void notifyHeClientStop({
    projectId: job.project_id,
    market: ctx.market ?? null,
    stage: 'base_collect (refill)',
    kind: 'capacity_pause',
    provider: 'sending',
    reason: source,
    jobId: job.id,
    baseId,
  });
}

/**
 * Как строка журнала прогонов решает серию отказов (refillFailStreak):
 * 'failure' — отказ среза, 'success' — серию обрывает, 'skip' — серию не
 * решает вовсе (ни отказ, ни успех).
 *
 * ВЕСЬ набор состояний строки he_auto_pipeline_runs с base_id:
 *  - 'appended' / 'no_new' → 'success';
 *  - 'failed':
 *      · stats.cancelled — отмена клиентом → 'skip' (решение человека);
 *      · stats.budget_outcome 'cap_exhausted' — бюджет проекта не дал базе ни
 *        строки, её компании вне серии ушли в очередь переноса (market='us')
 *        или вернулись в пул → 'skip';
 *      · stats.budget_outcome 'already_reserved' — бронь держал прошлый прогон
 *        той же базы, который мог отправить; итог ночи неизвестен → 'skip';
 *      · остальное → 'failure';
 *  - 'collecting' ЧУЖОЙ базы — строку никто не закрыл: процесс умер между
 *    записью базы и строки, запись строки упала, ремонт воркера сорвался до
 *    своего терминала и закрыл базу прежним 'failed', либо ночь закрыта кодом
 *    до closeHeRefillBaseUndelivered (тогда таймаут конструктора и ремонт
 *    писали базу сами, без строки прогона). Итог ночи тогда — СТАТУС ЕЁ
 *    БАЗЫ:
 *      · 'failed' с текстом отмены → 'skip';
 *      · 'failed' иначе → 'failure' (компании вернулись в пул — ровно тот
 *        случай, ради которого серия заведена);
 *      · 'analyzed' → 'success': компании базы исключены, повторной покупки
 *        этого среза не будет, то есть звеном цикла возвратов ночь не была;
 *      · базы нет или статус другой ('collecting' чужой базы той же
 *        вертикали невозможен — he_bases_one_collecting_per_vertical) → 'skip';
 *  - любой другой статус → 'skip'.
 */
type RefillStreakVerdict = 'failure' | 'success' | 'skip';

function refillStreakVerdict(
  run: { status?: unknown; stats?: unknown },
  base: { status?: unknown; error?: unknown } | undefined,
): RefillStreakVerdict {
  if (run.status === 'appended' || run.status === 'no_new') return 'success';
  if (run.status === 'failed') {
    const stats = (run.stats && typeof run.stats === 'object' ? run.stats : {}) as {
      cancelled?: unknown;
      budget_outcome?: unknown;
    };
    if (stats.cancelled === true) return 'skip';
    if (stats.budget_outcome === 'cap_exhausted' || stats.budget_outcome === 'already_reserved') {
      return 'skip';
    }
    return 'failure';
  }
  if (run.status === 'collecting') {
    if (!base) return 'skip';
    if (base.status === 'analyzed') return 'success';
    if (base.status !== 'failed') return 'skip';
    const text = typeof base.error === 'string' ? base.error.trim().toLowerCase() : '';
    return REFILL_CANCEL_MARKERS.has(text) ? 'skip' : 'failure';
  }
  return 'skip';
}

/**
 * Сколько refill-прогонов этой вертикали упало ПОДРЯД перед текущим.
 *
 * Журнал he_auto_pipeline_runs: строку 'collecting' пишет крон при постановке,
 * финал — эта стадия по base_id. Считаем строки ДРУГИХ баз вертикали (своя
 * сейчас ещё 'collecting'), от свежей к старой, и каждую разбираем
 * refillStreakVerdict: отказ растит серию, успех обрывает, «не решает»
 * пропускается. Строки без base_id — отказы САМОЙ постановки крона (сбора не
 * было), они про срез ничего не говорят и в окно не попадают.
 *
 * Зависшие 'collecting' строки чужих баз раньше отсекались запросом — и это
 * была дыра: ночь, которую закрыл не долив (таймаут конструктора, ремонт
 * воркера, смерть процесса, упавшая запись строки), в серии не значилась вовсе,
 * и каждая следующая выглядела «первым отказом». Теперь такая строка решается
 * по статусу её базы (одно доп. чтение he_bases по id). Порядок — по created_at:
 * у зависшей строки completed_at нет, а created_at есть у всех (у ночной —
 * момент постановки, у вставленной стадией — момент финала).
 *
 * Никогда не бросает: вызывается из catch-ветки долива, где падать нельзя
 * (см. шапку файла), и из closeHeRefillBaseUndelivered. Непрочитанная
 * история = 0, то есть отказ считается
 * разовым и компании возвращаются в пул — из двух исходов это обратимый:
 * вернуть срез можно ещё раз, а выжженный назад не достать.
 *
 * Возвращаемое число ограничено: решение бинарное («серия достигла лимита или
 * нет»), счёт останавливается на LIMIT + 1, а читается не больше
 * REFILL_FAIL_STREAK_WINDOW строк.
 */
async function refillFailStreak(
  ctx: HeStageContext,
  verticalId: string,
  currentBaseId: string,
): Promise<number> {
  try {
    const { data, error } = await ctx.supabase
      .from('he_auto_pipeline_runs')
      .select('base_id, status, stats')
      .eq('vertical_id', verticalId)
      // base_id IS NULL отсекает и сам neq (SQL: NULL <> id → NULL), условие
      // оставлено явным — оно про смысл строки, а не про трёхзначную логику.
      .not('base_id', 'is', null)
      .neq('base_id', currentBaseId)
      .order('created_at', { ascending: false })
      .limit(REFILL_FAIL_STREAK_WINDOW);
    if (error) throw new Error(error.message);
    const runs = (data ?? []) as Array<{ base_id?: unknown; status?: unknown; stats?: unknown }>;

    const staleBaseIds = [
      ...new Set(
        runs
          .filter((run) => run.status === 'collecting' && typeof run.base_id === 'string')
          .map((run) => run.base_id as string),
      ),
    ];
    const baseById = new Map<string, { status?: unknown; error?: unknown }>();
    if (staleBaseIds.length > 0) {
      const { data: bases, error: bErr } = await ctx.supabase
        .from('he_bases')
        .select('id, status, error')
        .in('id', staleBaseIds);
      if (bErr) throw new Error(`he_bases: ${bErr.message}`);
      for (const b of (bases ?? []) as Array<{ id?: unknown; status?: unknown; error?: unknown }>) {
        if (typeof b.id === 'string') baseById.set(b.id, b);
      }
    }

    let streak = 0;
    for (const run of runs) {
      const verdict = refillStreakVerdict(
        run,
        typeof run.base_id === 'string' ? baseById.get(run.base_id) : undefined,
      );
      if (verdict === 'success') break;
      if (verdict === 'skip') continue;
      streak += 1;
      // LIMIT подряд упавших прогонов уже запрещают возврат, +1 отличает
      // «серия ровно на лимите» от «длиннее» в журнале.
      if (streak > REFILL_RELEASE_FAIL_STREAK_LIMIT) break;
    }
    return streak;
  } catch (e) {
    stageLog(
      ctx,
      `[base_collect] refill: he_auto_pipeline_runs серия отказов не прочитана: ` +
        `${e instanceof Error ? e.message : String(e)} — считаем отказ разовым`,
    );
    return 0;
  }
}

interface RefillTemplatePick {
  campaignId: string;
  presetId: string;
  operatorMapping: HeOperatorMapping[] | undefined;
}

/**
 * Шаблон для долива: среди шаблонов вертикали с launch_info — точное
 * совпадение по campaign_id из collect_info (снапшот постановки), иначе
 * последний по дате запуска (force-перезапуск создаёт НОВУЮ кампанию и
 * перезаписывает launch_info — доливать надо в неё).
 */
export function pickRefillTemplate(
  templates: Array<Record<string, unknown>>,
  preferredCampaignId: string | null,
): RefillTemplatePick | null {
  const launched = templates
    .map((t) => {
      const launch = parseLaunchInfo(t.launch_info);
      if (!launch) return null;
      const plan = t.personalization_plan as { operator_mapping?: HeOperatorMapping[] } | null;
      const ts =
        Date.parse(launch.created_at) ||
        Date.parse(typeof t.created_at === 'string' ? t.created_at : '') ||
        0;
      return { launch, operatorMapping: plan?.operator_mapping, ts };
    })
    .filter((t): t is NonNullable<typeof t> => t !== null);
  if (launched.length === 0) return null;

  const toPick = (t: (typeof launched)[number]): RefillTemplatePick | null => {
    // При сплите запуска по сегментам доливаем ТОЛЬКО в основную кампанию
    // (segment=null): новые лиды refill не классифицированы по сегментам.
    // Сплит без основной кампании (все лиды попали в сегменты) → доливать
    // некуда: null, а не фолбэк на сегментную.
    if (t.launch.campaigns?.length) {
      const main = t.launch.campaigns.find((c) => c.segment === null);
      if (!main) return null;
      return { campaignId: main.campaign_id, presetId: t.launch.preset_id, operatorMapping: t.operatorMapping };
    }
    return {
      campaignId: t.launch.campaign_id,
      presetId: t.launch.preset_id,
      operatorMapping: t.operatorMapping,
    };
  };

  if (preferredCampaignId) {
    const exact = launched.find(
      (t) =>
        t.launch.campaign_id === preferredCampaignId ||
        (t.launch.campaigns ?? []).some((c) => c.campaign_id === preferredCampaignId),
    );
    if (exact) {
      const picked = toPick(exact);
      if (picked) return picked;
    }
  }
  for (const t of launched.slice().sort((a, b) => b.ts - a.ts)) {
    const picked = toPick(t);
    if (picked) return picked;
  }
  return null;
}

/**
 * Строки-кандидаты в лиды: непустой email И вердикт валидации 'accepted'.
 *
 * Вердикт считает heLaunchEmailVerdict (launchHandoff.ts) — тот же список
 * допущенных статусов, что у ручного запуска шаблона, и тот же разбор
 * регистра/пробелов. Здесь он НЕ переписан осознанно: два пути допуска
 * адресов, которые можно поправить по отдельности, рано или поздно разойдутся,
 * а расхождение видно только по баунсам, то есть уже по репутации доменов.
 * Почему catch_all не допущен — в докблоке HE_LAUNCH_ACCEPTED_EMAIL_STATUSES.
 *
 * 'missing' (вердикта нет вовсе) отклоняется, как и 'rejected', но считается
 * отдельно: ночной долив идёт без человека рядом, и «валидация не доработала»
 * обязано быть видно в воронке, а не выглядеть как «адреса плохие».
 */
export function selectRefillLeadRows(
  rows: HeUnifiedRow[],
  emailStatuses: Array<string | null> | null,
): {
  leadRows: HeUnifiedRow[];
  /**
   * Позиция каждой отобранной строки в ИСХОДНОМ массиве (он же he_bases.data
   * после persistRefillBase). Нужна пометке доставки: лиду проставляется
   * `source_row_id`, и без этого массива запасной индекс был бы
   * номером внутри отфильтрованного среза, то есть указывал бы не на ту строку.
   */
  leadRowIndexes: number[];
  withEmail: number;
  valid: number;
  unverified: number;
} {
  const leadRows: HeUnifiedRow[] = [];
  const leadRowIndexes: number[] = [];
  let withEmail = 0;
  let unverified = 0;
  for (let i = 0; i < rows.length; i += 1) {
    const row = rows[i];
    if (row.email.trim() === '') continue;
    // Строки вне вертикали (релевант-гейт base_collect) в долив не идут.
    if ((row as { _low_relevance?: boolean })._low_relevance === true) continue;
    withEmail += 1;
    const verdict = heLaunchEmailVerdict(emailStatuses?.[i] ?? null);
    if (verdict === 'missing') unverified += 1;
    if (verdict !== 'accepted') continue;
    leadRows.push(row);
    leadRowIndexes.push(i);
  }
  return { leadRows, leadRowIndexes, withEmail, valid: leadRows.length, unverified };
}

/**
 * Какие лиды пачки уезжают, когда бронь дневного бюджета выдала меньше строк,
 * чем есть: отрез по КОМПАНИЯМ правилом ручного запуска
 * (selectLeadsWithinLaunchCap) — сначала по одному адресу каждой компании,
 * потом вторые и т. д.; порядок компаний — порядок строк базы.
 *
 * `kept` — лиды после blocklist'а: тот же объект лида, что в `leads`
 * (filterBlockedLeads фильтрует, не копируя), поэтому строка базы лида
 * находится по позиции в `leads` → `leadSourceRows` (индекс в `leadRows`).
 * Лид, строку которого найти не удалось, считается отдельной компанией —
 * деградация к поштучному отрезу, а не потеря лида.
 *
 * Вердикт внутри компании роли не играет: в долив доходят только допущенные
 * адреса, и порядок адресов компании — порядок её строк.
 */
function selectRefillLeadsByCompany<L extends object>(input: {
  kept: readonly L[];
  leads: readonly L[];
  leadSourceRows: readonly number[];
  leadRows: HeUnifiedRow[];
  columns: string[];
  granted: number;
}): { toSend: L[]; companiesHeldBack: number } {
  const positionOf = new Map<L, number>();
  input.leads.forEach((lead, position) => positionOf.set(lead, position));
  const keptRowIndices = input.kept.map((lead) => {
    const position = positionOf.get(lead);
    return position === undefined ? -1 : input.leadSourceRows[position] ?? -1;
  });
  const selection = selectLeadsWithinLaunchCap({
    rows: input.leadRows,
    columns: input.columns,
    leadRowIndices: keptRowIndices,
    limit: input.granted,
  });
  return {
    toSend: selection.keptLeadPositions.map((position) => input.kept[position]),
    companiesHeldBack: selection.companiesHeldBack,
  };
}

/**
 * Пустой harvest refill-сборки — штатный «no_new»: база в терминальный
 * 'analyzed' (НЕ failed), прогон 'no_new', джоба завершится успешно.
 *
 * Эта запись базы — РАБОТА, а не деньги, и поэтому остаётся на КЛИЕНТЕ СТАДИЙ (в
 * отличие от persistRefillBase ниже). Провайдер здесь не видел ни строки:
 * доливать было нечего, ни один лид не принят, отменять нечего. Её отказ по
 * abort'у стоит повтора сборки — а повтор ночного добора по пустому сегменту
 * штатно упирается в то же «новых компаний нет» и ничего у провайдера не
 * покупает. Расширять освобождение от сигнала на неё значило бы платить
 * размытием границы за то, чего abort не ломает; критерий — у paidCheckpointDb.
 * Строка прогона ниже под освобождение попадает (writeRefillRun), но до неё
 * отвергнутая запись базы всё равно не доходит — и это правильный порядок:
 * прогон 'no_new' без терминальной базы был бы отчётом о том, чего не случилось.
 */
export async function completeHeRefillNoNew(args: {
  ctx: HeStageContext;
  job: HeJob;
  baseId: string;
  verticalId: string;
  info: HeCollectInfo;
  stats: HeCollectInfo['stats'];
}): Promise<HeRefillResult> {
  const { ctx, job, baseId, verticalId, info, stats } = args;
  const refillResult: HeRefillResult = {
    status: 'no_new',
    // Пустой harvest — ещё не показание о сухости: та же пустота бывает у ночи,
    // вставшей по потолку страниц. Признак пишется ЗДЕСЬ, потому что дальше
    // (в строке прогона) задач уже не видно.
    scan_complete: refillScanComplete(info),
    completed_at: new Date().toISOString(),
  };

  const { error } = await ctx.supabase
    .from('he_bases')
    .update({
      status: 'analyzed',
      collect_info: { ...info, stats, refill_result: refillResult },
      updated_at: new Date().toISOString(),
    })
    .eq('id', baseId);
  if (error) throw new Error(`he_bases refill no_new update: ${error.message}`);

  const config = await loadRefillConfig(ctx, job.project_id);
  await writeRefillRun(ctx, {
    configId: config?.id ?? null,
    projectId: job.project_id,
    verticalId,
    baseId,
    result: refillResult,
  });
  stageLog(ctx, '[base_collect] refill: новых компаний нет — прогон no_new, база analyzed');
  return refillResult;
}

/**
 * ОТКАЗ REFILL-БАЗЫ, ЗАКРЫТЫЙ НЕ ВЕТКОЙ ДОЛИВА. Писателей у него два:
 *  - таймаут ожидания конструктора 6 ч (stages/baseCollect.ts, фаза CONSTRUCT);
 *  - ремонт воркера после ФИНАЛЬНОГО фейла base_collect, пока база ещё
 *    'collecting' (worker/hypothesisEngine.ts: repairBaseAfterCollectFinalFail
 *    → closeHeRefillBaseAfterFinalFail в stages/baseCollect.ts).
 * Раньше оба писали базе 'failed' сами, мимо серии отказов, а строку прогона
 * оставляли 'collecting'. Пока общая очередь конструктора забита, каждая ночь
 * поэтому заново покупала тот же возвращённый срез — гейт релевантности и ещё
 * одну джобу конструктора, — и так без предела.
 *
 * Решение о компаниях — то же, что у отказа долива (runHeRefillAppend, п. 5),
 * плюс один исход, которого у долива не бывает (там срез всегда куплен):
 *  - срез не куплен (`slice` = null: ни суда гейта, ни джобы конструктора) →
 *    компании возвращаются, серия не читается. Повторная сборка купит здесь
 *    только бесплатные чтения каталога, а выжечь некупленное — потерять
 *    компании даром;
 *  - срез куплен → refillFailStreak: первый отказ подряд возвращает компании
 *    (база 'failed', как и раньше), со второго база 'analyzed', а строки среза
 *    ложатся в её `data`. Без строк 'analyzed' не исключила бы ничего:
 *    исключение будущих сборок читает именно `data` не-'failed' баз
 *    (loadOtherBaseExclusionKeys), а у собирающейся базы она пуста;
 *  - строк среза не получить (`slice()` бросил) или их ноль → возврат: из двух
 *    ошибок обратимая, как у непрочитанной серии.
 *
 * Запись базы — КЛИЕНТОМ СТАДИИ и с CAS по 'collecting'. Это работа, а не
 * деньги (провайдер строк не получал), и её потеря оставляет базу
 * 'collecting': повтор доходит до того же решения бесплатно. Отмена клиентом,
 * легшая раньше, выигрывает — CAS не перепишет её 'failed'. Строку прогона
 * пишет writeRefillRun со статусом 'failed', и refillStreakVerdict читает её как
 * обычный отказ.
 *
 * Возвращает итог (он же collect_info.refill_result) или null, если базу уже
 * закрыл кто-то другой и CAS ничего не задел — тогда не пишется ничего.
 */
export async function closeHeRefillBaseUndelivered(args: {
  ctx: HeStageContext;
  projectId: string;
  base: { id: string; vertical_id: string };
  /** Причина: he_bases.error у 'failed', refill_result.error и error строки прогона. */
  reason: string;
  /** collect_info базы уже без рабочего состояния (dropCollectWorkState). */
  info: HeCollectInfo;
  /** Воронка сборки, если вызывающий её посчитал. */
  stats?: HeCollectInfo['stats'];
  /** Строки купленного среза — только если серия велит их оставить; null — срез не куплен. */
  slice: (() => Promise<{ rows: HeUnifiedRow[]; columns: string[] }>) | null;
}): Promise<HeRefillResult | null> {
  const { ctx, projectId, base, reason, info, stats, slice } = args;
  /** null — серия решению не понадобилась и не читалась. */
  let failStreak: number | null = null;
  let kept: { rows: HeUnifiedRow[]; columns: string[] } | null = null;
  if (slice) {
    failStreak = await refillFailStreak(ctx, base.vertical_id, base.id);
    if (failStreak >= REFILL_RELEASE_FAIL_STREAK_LIMIT) {
      try {
        const bought = await slice();
        if (bought.rows.length > 0) kept = bought;
      } catch (e) {
        stageLog(
          ctx,
          `[base_collect] refill: строки купленного среза не получены ` +
            `(${e instanceof Error ? e.message : String(e)}) — компании возвращаются в пул`,
        );
      }
    }
  }
  const message = reason.slice(0, 500);
  const refillResult: HeRefillResult = {
    status: 'failed',
    error: message,
    companies_released: kept === null,
    ...(failStreak === null ? {} : { fail_streak: failStreak }),
    completed_at: new Date().toISOString(),
  };
  const collectInfo: HeCollectInfo = { ...info, ...(stats ? { stats } : {}), refill_result: refillResult };
  const now = new Date().toISOString();
  const patch = kept
    ? {
        columns: kept.columns,
        sample_rows: kept.rows.slice(0, SAMPLE_ROWS),
        data: kept.rows,
        row_count: kept.rows.length,
        status: 'analyzed',
        error: null,
        collect_info: collectInfo,
        updated_at: now,
      }
    : { status: 'failed', error: message, collect_info: collectInfo, updated_at: now };
  const { data: landed, error } = await ctx.supabase
    .from('he_bases')
    .update(patch)
    .eq('id', base.id)
    .eq('status', 'collecting')
    .select('id');
  if (error) throw new Error(`he_bases refill close: ${error.message}`);
  if (!landed || landed.length === 0) {
    stageLog(ctx, `[base_collect] refill: база ${base.id} уже не 'collecting' — её закрыли без нас, решение не пишем`);
    return null;
  }
  const config = await loadRefillConfig(ctx, projectId);
  await writeRefillRun(ctx, {
    configId: config?.id ?? null,
    projectId,
    verticalId: base.vertical_id,
    baseId: base.id,
    result: refillResult,
  });
  stageLog(
    ctx,
    `[base_collect] refill failed до долива: ${message} — ` +
      (kept
        ? `отказ ${(failStreak ?? 0) + 1}-й подряд, компании остаются исключёнными ` +
          `(база analyzed, ${kept.rows.length} строк): иначе ночной прогон собрал бы тот же срез заново`
        : failStreak === null
          ? 'срез не куплен, база failed (компании в пул)'
          : failStreak < REFILL_RELEASE_FAIL_STREAK_LIMIT
            ? 'первый отказ подряд, база failed (компании в пул)'
            : 'строк среза нет, база failed (компании в пул)'),
  );
  return refillResult;
}

/**
 * Потолок замера skipIfInCampaign (шаг 4b) в ЗАПРОСАХ к провайдеру за прогон.
 *
 * ПО УМОЛЧАНИЮ ЗАМЕР ВЫКЛЮЧЕН (0), и это не осторожность, а правило: лимитер
 * Instantly общий на весь воркспейс (~10–15 RPM, lib/instantly/rateLimiter.ts),
 * в котором ЖИВАЯ RU-рассылка отправляет письма за деньги. Измерение не имеет
 * права занимать её минуты само по себе — включать его должен человек, который
 * в этот момент собирается принять решение по флагу. Цена включённого замера
 * названа числом: ≤ 30 запросов на ПРОГОН, то есть ≤ 30 × verticals_per_run за
 * ночь (при дефолтных трёх вертикалях — до 90 запросов, 6–9 минут общего
 * лимитера); выключенного — ноль запросов и ни одного ключа в воронке.
 *
 * Как включить на несколько ночей: HE_REFILL_SKIP_PROBE_REQUESTS=30 в env
 * воркера. Замер выдержит любое число до HE_REFILL_SKIP_PROBE_MAX, но тридцати
 * адресов хватает на решение, ради которого он заводится: «половина пачки
 * занята соседями» и «не занят никто» на такой выборке различаются с запасом;
 * бухгалтерией замер не является и не притворяется. Пустая строка и 0 —
 * выключено.
 */
const HE_REFILL_SKIP_PROBE_DEFAULT = 0;
/** Потолок на случай опечатки в переменной окружения (пачка ночи и так ≤ 200). */
const HE_REFILL_SKIP_PROBE_MAX = 200;

function refillSkipProbeBudget(): number {
  const raw = process.env.HE_REFILL_SKIP_PROBE_REQUESTS;
  if (raw === undefined || raw.trim() === '') return HE_REFILL_SKIP_PROBE_DEFAULT;
  const value = Number(raw);
  if (!Number.isFinite(value) || value <= 0) return 0;
  return Math.min(Math.floor(value), HE_REFILL_SKIP_PROBE_MAX);
}

/**
 * Выборка адресов для замера: РАВНОМЕРНО по пачке, а не первые N.
 *
 * Пачка упорядочена сборкой (компании идут группами, у компании — её адреса),
 * поэтому первые N — это первые компании среза, а не срез. Шаг по всей длине
 * даёт выборку, по которой можно судить о пачке; случайности здесь нет
 * намеренно — прогон должен воспроизводиться по тем же данным.
 */
function refillSkipProbeSample(leads: readonly { email: string }[], budget: number): string[] {
  if (budget <= 0 || leads.length === 0) return [];
  if (leads.length <= budget) return leads.map((lead) => lead.email);
  const step = leads.length / budget;
  const out: string[] = [];
  for (let i = 0; i < budget; i += 1) out.push(leads[Math.floor(i * step)].email);
  return out;
}

/**
 * Шаг 4b: СКОЛЬКО контактов пачки прячет флаг skipIfInCampaign и на каком
 * основании. Подробности значения полей — у HeRefillSkipProbe.
 *
 * Никогда не бросает и ничего не меняет: замер не имеет права уронить ночь,
 * ради которой уже оплачены краул и SMTP-пробы. Любой отказ (нет кампании, нет
 * доступа к провайдеру, сорванный запрос) — это просто отсутствие ключа
 * `skip_probe` или его `undecided`, и долив идёт дальше ровно как без замера.
 *
 * Стоит ПЕРЕД бронью дневного бюджета: замер — чтение, а бронь держит объём
 * проекта до конца UTC-суток, и расширять её окно минутами чтения нельзя.
 * Поэтому мерится `kept` (пачка после blocklist'а), а не `toSend` (после
 * дневного капа): для вопроса «лежат ли эти адреса в чужих кампаниях» это та
 * же популяция, зато бронь остаётся такой же короткой, как была.
 */
async function measureRefillSkipExposure(
  ctx: HeStageContext,
  args: { leads: readonly { email: string }[]; ownerUserId: string; campaignId: string },
): Promise<HeRefillSkipProbe | undefined> {
  const budget = refillSkipProbeBudget();
  if (budget <= 0 || args.leads.length === 0 || !args.campaignId) return undefined;
  try {
    // Тот же резолв аккаунта, что у долива (пресет владельца кампании): читать
    // надо В ТОТ воркспейс, в который грузим, иначе замер расскажет про чужой.
    const requestOptions = await resolveClientInstantlyRequestOptions(args.ownerUserId);
    const probe = await probeLeadPresence({
      emails: refillSkipProbeSample(args.leads, budget),
      ownCampaignId: args.campaignId,
      requestBudget: budget,
      // Срок на весь замер. Число запросов само по себе времени не ограничивает:
      // медленный провайдер растянет тридцать чтений на сколько угодно, а долив
      // ждать не должен. Две минуты — потолок, после которого замер отдаёт ночь.
      budgetMs: 120_000,
      requestOptions: {
        ...requestOptions,
        // Замер виден в почасовых счётчиках отдельной строкой: его цена — это
        // запросы, отнятые у общего лимита воркспейса, и она обязана быть
        // видимой ДО того, как кто-то решит поднять бюджет.
        consumer: 'he_refill_skip_probe',
        timeoutMs: 20_000,
        timeoutIncludesBody: true,
        // Замер УСТУПАЕТ дорогу. Пересиживать 429 внутри клиента (4+8+16 с) он
        // не имеет права: воркспейс общий с RU-контурами, и если провайдер уже
        // говорит «слишком часто», правильный ответ измерения — прекратиться,
        // а не встать в очередь впереди работы. Отказ здесь просто обрывает
        // замер (см. probeLeadPresence), долив идёт дальше.
        retryRateLimits: false,
      },
      // Признак жизни сторожу простоя стадии: замер идёт по HTTP мимо
      // ctx.supabase, и без этого хука десятки запросов выглядели бы молчанием.
      onRequest: () => ctx.onActivity?.(),
      // Отменённая (или прерванная сторожем) джоба замер прекращает сразу:
      // доедать общий лимит воркспейса ради числа, которого никто не прочтёт,
      // нельзя. Сам долив на этом не падает — прерывание он встретит на
      // следующем чтении клиентом стадий, как и до правки.
      shouldStop: () => ctx.signal?.aborted === true,
    });
    if (probe.probed === 0) return undefined;
    return {
      probed: probe.probed,
      of: args.leads.length,
      already_in_our_campaign: probe.counts.own_campaign,
      in_other_campaign: probe.counts.other_campaign,
      in_workspace_no_campaign: probe.counts.no_campaign,
      absent: probe.counts.absent,
      undecided: probe.counts.undecided,
      requests: probe.requests,
      stopped_early: probe.stoppedEarly,
    };
  } catch (e) {
    stageLog(
      ctx,
      `[base_collect] refill: замер skipIfInCampaign не состоялся — ` +
        `${e instanceof Error ? e.message : String(e)} (на долив не влияет)`,
    );
    return undefined;
  }
}

/* ─── ПЕРЕНОС НЕОТПРАВЛЕННЫХ КОМПАНИЙ ─────────────────────────────────────
 *
 * Решение владельца 04.10.2026: компании, которым ночь не отправила ни одного
 * письма, не выбрасываются. Только market='us' — ночной долив и так бывает
 * только у него, но каждое место ниже проверяет рынок само, и RU-инструмент
 * этот код не исполняет ни в одной ветке.
 *
 * ПОЧЕМУ ПЕРЕНОС, А НЕ ВОЗВРАТ В ПУЛ. Возврат (компания перестаёт исключаться,
 * следующая сборка готовит её заново) покупал бы подготовку второй раз: гейт
 * релевантности — платный вызов модели на каждые 50 строк, краул сайта и
 * SMTP-проба — трафик прокси и время воркера, плюс место в общей очереди
 * конструктора. При дефолтах (кап 50 строк, пол сборки 100 компаний, оценка
 * HE_REFILL_ACCEPTED_PER_COMPANY = 2 допущенных адреса на компанию) ночь
 * отправляет первые адреса 50 компаний и оставляет без письма остальные 50:
 * возврат — это 100 подготовленных компаний на 50 охваченных КАЖДУЮ ночь (как
 * и сегодня, только без потери), перенос — 100 подготовленных на 100
 * охваченных за две ночи, потому что вторая ночь отправляет очередь и сборку
 * не покупает. Перенос безопасен: строки очереди хранят адрес, вердикт
 * валидации и всё, что нужно маппингу в лиды, а сама компания всё это время
 * лежит в `data` своей базы и исключена из новых сборок — подготовить её
 * второй раз некому.
 *
 * ЖИЗНЕННЫЙ ЦИКЛ строки he_refill_carryover (миграция 20261004_0001):
 *  1. КЛАДЁТ ночь вертикали собственные компании, у которых после чёрного
 *     списка остался хоть один лид и ни один лид не дошёл до провайдера
 *     (ownUnsentRefillCompanies). ИСХОДЫ НОЧИ — ВЕСЬ НАБОР:
 *       · 'appended' — кладёт: их срезал кап, провайдер отказал по ёмкости,
 *         отправка до них не дошла. Пишет ПОСЛЕ терминальной записи базы;
 *       · отказ ПОСЛЕ доставки (delivered: принято > 0, попытка без явного
 *         отказа или сбой записи после приёма) — кладёт так же: база и так
 *         'analyzed', а компании, до которых отправка не дошла, иначе остались
 *         бы исключёнными навсегда. Пишет ПОСЛЕ терминальной записи базы.
 *         Отменённый клиентом прогон не кладёт (ни здесь, ни ниже): его
 *         компании решает прежнее правило;
 *       · отказ 'cap_exhausted' (бюджет дня не дал ни строки) — кладёт ВСЕ
 *         свои компании с лидом, и база становится 'analyzed', а не 'failed'
 *         (решение владельца 04.10.2026). Пишет ДО терминальной записи базы,
 *         одним запросом: не легла очередь — база 'failed', прежний возврат в
 *         пул, то есть хуже, чем до переноса, не бывает;
 *       · отказ 'already_reserved' — НЕ кладёт и не возвращает: прошлый прогон
 *         этой же базы мог отправить её компании, и любая повторная отправка
 *         могла бы стать вторым письмом;
 *       · отказ, не дошедший до провайдера по другой причине (сбой долива, 429,
 *         ёмкость при нулевом приёме, отмена клиентом), — НЕ кладёт: компании
 *         решает прежнее правило возврата (первый отказ подряд — в пул, со
 *         второго — исключены, отмена — в пул).
 *     Компания, чей крючок найма не доживёт до отправки свежим, не ждёт, а
 *     сразу отпускается в пул ('released', см. heRefillCarryExpiry).
 *  2. СЧИТАЕТ следующая ночь вертикали на тике плана
 *     (resolveHeRefillCollectCompanies): компаний очереди хватает на остаток
 *     дня — сборку не покупает. Тик крона (autoPipeline.ts) той же арифметикой
 *     по проекту не ставит сборку вертикалям без очереди, пока очередь
 *     проекта покрывает день.
 *  3. БЕРЁТ ночь вертикали в доливе (claimHeRefillCarryover): 'pending' →
 *     'claimed' с id своей базы. Конкурентов нет: собирающаяся база у вертикали
 *     одна (he_bases_one_collecting_per_vertical), поэтому чужой 'claimed' —
 *     всегда брошенный (его ночь умерла до записи итога) и уходит в 'dropped':
 *     был ли он отправлен, неизвестно, а второе письмо дороже потерянной
 *     компании. Перед захватом компания сверяется с ПАРАЛЛЕЛЬНЫМИ базами
 *     проекта (heRefillCarryPeerConflicts): сборки разных вертикалей одной ночи
 *     не видят строк друг друга (у собирающейся базы `data` пуст), и одна
 *     компания может оказаться в двух базах. Её копия в чужой базе, которая
 *     могла уйти письмом, снимает нашу ('prepared_elsewhere'); из двух копий в
 *     очереди остаётся одна — базы с меньшим id.
 *  4. ОТПРАВЛЯЕТ тем же путём, что и свои строки: вердикт перепроверяется
 *     (selectRefillLeadRows → heLaunchEmailVerdict, отправляется только
 *     'accepted'), чёрный список, бронь дня, отрез по компаниям — перенесённые
 *     компании стоят в пачке ПЕРВЫМИ, поэтому их первые адреса идут раньше
 *     первых адресов новых компаний.
 *  5. ЗАКРЫВАЕТ (settleHeRefillCarryover) по тому, что известно о пачке:
 *     адрес дошёл до провайдера (или мог дойти) → 'sent'; не дошёл → обратно
 *     'pending' со СТАРЫМ сроком; отправлять нечего (всё в чёрном списке) или
 *     судьба неизвестна (бронь держал прошлый прогон этой же базы) →
 *     'dropped'.
 *  6. СРОК — HE_REFILL_CARRYOVER_MAX_AGE_DAYS от подготовки, а у компании с
 *     крючком найма — не позже момента, когда фид последний раз видел её
 *     вакансию, плюс ENG_HIRING_FEED_FRESH_DAYS (heRefillCarryExpiry). Истёкшая
 *     'pending' не предлагается и считается отпущенной ('released'):
 *     исключение сборок перестаёт её видеть (loadHeRefillReleasedCompanies,
 *     читает stages/baseCollect.ts), и компанию можно подготовить заново. В
 *     'released' уходит только то, что НИ РАЗУ не дошло до провайдера, —
 *     второго письма этот путь не даёт.
 *
 * ПОЧЕМУ КОМПАНИЯ ОЧЕРЕДИ НЕ ЛЕЖИТ В ПУЛЕ. Пул — это то, что может собрать
 * следующая сборка, а исключение сборок (loadOtherBaseExclusionKeys) читает
 * `data` каждой не-'failed' базы проекта. Строка очереди живёт, только пока
 * её база-источник не 'failed' (иначе захват снимает её в 'dropped'), а
 * пропуск исключения (loadHeRefillReleasedCompanies) даётся ровно паре «база +
 * компания» и ровно отпущенной строке ('released' или 'pending' с прошедшим
 * сроком), которую захват уже не предложит: граница срока у обоих одна —
 * `expires_at <= now`. То есть в каждый момент компания либо в очереди, либо
 * в пуле, но не там и там сразу.
 *
 * ЧТЕНИЯ — клиентом стадий и best-effort: не прочиталось — очереди нет, то
 * есть поведение до переноса. ЗАПИСИ итога и очереди — клиентом без сигнала
 * (paidCheckpointDb): итог фиксирует то, что провайдер уже принял, а очередь —
 * оплаченную подготовку, которую повтор джобы не воспроизведёт (база ночи к
 * этому моменту терминальна, и стадия на ней больше не запустится). Потеря
 * любой из них стоит не больше, чем стоило до переноса: незаписанная очередь —
 * компании остаются исключёнными (у ночи без бюджета — возвращаются в пул),
 * незаписанный итог — захват станет брошенным и уйдёт в 'dropped'. Второго
 * письма не даёт ни одна.
 */

/**
 * Сколько суток перенесённая компания ждёт отправки, считая от подготовки.
 *
 * В норме очередь пустеет за одну-две ночи (ночь, которой хватает очереди,
 * отправляет только её), и дольше она живёт, только когда отправка стоит:
 * пауза по ёмкости до снятия сотрудником, снятая кампания, отказы подряд.
 * Неделя покрывает такой простой вместе с выходными. Дольше держать нельзя из-за
 * свежести: вердикт SMTP-пробы стареет медленно, а крючок «hiring X» из ленты
 * найма — быстрее, поэтому у компании с таким крючком срок ещё короче (см.
 * heRefillCarryExpiry). После срока — шаг 6 блока выше.
 */
export const HE_REFILL_CARRYOVER_MAX_AGE_DAYS = 7;

const DAY_MS = 86_400_000;

/**
 * Срок строки очереди (шаг 6 блока «ПЕРЕНОС») — по ВСЕМУ набору форм строк
 * компании. Чистая функция.
 *
 * Решение владельца 04.10.2026: вакансия в письме не старше окна
 * ENG_HIRING_FEED_FRESH_DAYS (14 суток). Крючок найма — непустая ячейка
 * `vacancy_title`: именно она уезжает в переменную письма, и у market='us' её
 * даёт только фид найма (mapEngHiringRow). Без границы компания, собранная с
 * вакансией, виденной 14 суток назад, ждала бы в очереди ещё до 7 суток, и
 * крючок доезжал бы до письма в возрасте до 21 суток.
 *  - крючка нет ни у одной строки → обычный срок: подготовка + 7 суток;
 *  - у каждой строки с крючком есть `_hiring_seen_at` → срок = минимум из
 *    обычного и `_hiring_seen_at` + окно;
 *  - хоть у одной строки с крючком даты нет (база собрана до этой правки или
 *    дата не пережила сетку конструктора) → возраст крючка неизвестен, и
 *    компания НЕ ПЕРЕНОСИТСЯ, а сразу отпускается в пул
 *    ('hiring_post_age_unknown'). Почему не «снять крючок и перенести»:
 *    переменная письма опустела бы или ушла бы в фолбэк, а текст шаблона
 *    вертикали, собранной по найму, может говорить о найме и без переменной —
 *    письмо утверждало бы то, что мы больше не можем проверить. Почему не
 *    «оставить исключённой»: это и есть выброшенная компания, которую владелец
 *    запретил. В пуле её снова найдёт следующая сборка, и фид пропустит её
 *    только со свежей вакансией;
 *  - граница уже прошла к моменту записи → тоже сразу в пул
 *    ('hiring_post_stale'). Граница в будущем, но раньше обычного срока —
 *    строка ждёт до неё, а дальше её отпускает захват, как любую истёкшую.
 */
export function heRefillCarryExpiry(
  rows: ReadonlyArray<HeUnifiedRow & HeHiringSeenRow>,
  preparedAtMs: number,
): { expiresAtMs: number; release: null | 'hiring_post_age_unknown' | 'hiring_post_stale' } {
  let expiresAtMs = preparedAtMs + HE_REFILL_CARRYOVER_MAX_AGE_DAYS * DAY_MS;
  for (const row of rows) {
    if (String(row.vacancy_title ?? '').trim() === '') continue;
    const seenMs = typeof row._hiring_seen_at === 'string' ? Date.parse(row._hiring_seen_at) : NaN;
    if (!Number.isFinite(seenMs)) return { expiresAtMs: preparedAtMs, release: 'hiring_post_age_unknown' };
    expiresAtMs = Math.min(expiresAtMs, seenMs + ENG_HIRING_FEED_FRESH_DAYS * DAY_MS);
  }
  if (expiresAtMs <= preparedAtMs) return { expiresAtMs, release: 'hiring_post_stale' };
  return { expiresAtMs, release: null };
}

