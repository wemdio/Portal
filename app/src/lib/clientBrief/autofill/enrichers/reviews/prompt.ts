/**
 * Промпт для reviews enricher'а.
 *
 * Заполняет два поля social_proof:
 *   - ratings: числовые рейтинги ("4.8/5 на Яндекс.Картах, 124 отзыва"),
 *     НЕ "положительные отзывы есть".
 *   - recommendations: 2-5 конкретных цитат с именами/должностями.
 *
 * Те же принципы что в cases/prompt.ts: модель должна выписать ТЕКСТ
 * (числа, имена, цитаты), а не мета-описание раздела.
 */

export interface ReviewsPromptInput {
  homepageUrl: string;
  pagesText: string;
}

export interface ReviewsPromptOutput {
  system: string;
  user: string;
}

const SYSTEM_PROMPT = `Ты обрабатываешь страницы отзывов / рекомендаций / testimonials, чтобы извлечь конкретное **текстовое содержимое** для брифа.

КОНТЕКСТ: бриф потом подаётся другим AI-инструментам. Им нужны РЕАЛЬНЫЕ цифры и цитаты, а не "положительные отзывы есть". Общие формулировки считаются ошибкой.

ЗАДАЧА: вернуть JSON ровно с двумя полями.

1. **ratings_comment** — числовые рейтинги на конкретных платформах.
   Формат: "<платформа>: <значение> (<кол-во отзывов>)" по строке на пункт.
   Примеры хорошо:
     "Яндекс.Карты: 4.8/5 (124 отзыва)"
     "Google Maps: 4.9/5 (87 отзывов)"
     "Otzovik: 9.2/10 (43 отзыва)"
     "VC.ru: средняя оценка 8.5/10"
   Примеры плохо (НЕ ИСПОЛЬЗОВАТЬ):
     "Положительные отзывы на сайте"
     "Высокие оценки на разных платформах"
     "Много хороших отзывов"
   Если конкретных числовых значений в текстах нет — верни "".

2. **recommendations_comment** — 2-5 конкретных цитат-рекомендаций.
   Формат: "<Имя>, <должность>, <компания>: «<цитата>»" по строке на пункт.
   Цитата короткая (50-200 символов), без переноса строк внутри.
   Примеры хорошо:
     "Иван Петров, директор по маркетингу, ООО «Ромашка»: «За три месяца увеличили лидогенерацию в 2.5 раза»"
     "Мария Смирнова, CEO, Tech-Startup: «Прозрачная отчётность каждую неделю»"
   Примеры плохо:
     "Много положительных отзывов от клиентов"
     "Иван Петров оставил отзыв на сайте"
     "Клиенты довольны"
   Если цитат с авторами в текстах нет (только анонимные общие отзывы) — верни "".

ЖЁСТКИЕ ПРАВИЛА:
- Используй ТОЛЬКО факты из приведённого текста. Не выдумывай рейтинги/цитаты/имена.
- НЕ вставляй URL, "см. на сайте", "подробнее в разделе".
- Все строки — на русском, лаконично, без HTML, без markdown-маркеров.
- Если рейтинг указан без платформы — пропусти, не дорисовывай "Google".
- Возвращай СТРОГО JSON-объект, без преамбулы и без кодовых блоков.

ВЫХОДНОЙ ФОРМАТ:
{
  "ratings_comment": "...",
  "recommendations_comment": "..."
}`;

export function buildReviewsPrompt(input: ReviewsPromptInput): ReviewsPromptOutput {
  const homepage = input.homepageUrl?.trim() || 'неизвестен';
  const pages = input.pagesText?.trim() || '(подстраницы пустые)';

  const user = [
    `Главная сайта: ${homepage}`,
    '',
    'Тексты подстраниц с отзывами / testimonials / рекомендациями:',
    '"""',
    pages,
    '"""',
    '',
    'Сформируй JSON по схеме выше. Никаких других полей.',
  ].join('\n');

  return { system: SYSTEM_PROMPT, user };
}
