/**
 * Промпт для press enricher'а.
 *
 * Объединяет три близких социальных доказательства, которые обычно живут
 * на одних и тех же типах страниц (/press, /media, /awards, /смми):
 *   - press: упоминания в СМИ (название СМИ + дата + тема)
 *   - awards: награды/сертификаты (название + год + кто выдал)
 *   - media: видео/подкасты/выступления (платформа + название + дата)
 *
 * Цель та же: выписать ТЕКСТ, не "упоминания в СМИ есть".
 */

export interface PressPromptInput {
  homepageUrl: string;
  pagesText: string;
}

export interface PressPromptOutput {
  system: string;
  user: string;
}

const SYSTEM_PROMPT = `Ты обрабатываешь страницы СМИ / наград / медиа-присутствия компании, чтобы извлечь конкретное **текстовое содержимое** для брифа.

КОНТЕКСТ: бриф потом подаётся другим AI-инструментам. Им нужны РЕАЛЬНЫЕ названия СМИ, даты, тематики, названия наград. Общие формулировки бесполезны.

ЗАДАЧА: вернуть JSON ровно с тремя полями.

1. **press_comment** — упоминания в СМИ.
   Формат: "<СМИ> (<дата>): <тема>" по строке на пункт. 3-7 упоминаний.
   Примеры хорошо:
     "VC.ru (март 2025): обзор кейса с гипермаркетами"
     "РБК (декабрь 2024): интервью с CEO про email-маркетинг"
     "Forbes (2023): топ-50 маркетинговых агентств РФ"
   Примеры плохо:
     "Упоминания в СМИ есть"
     "Пишут о нас в крупных изданиях"
   Если конкретных упоминаний (с названием СМИ) нет — верни "".

2. **awards_comment** — награды, сертификаты, рейтинги.
   Формат: "<Название> (<год>) — <кто выдал>" по строке на пункт.
   Примеры хорошо:
     "№1 в РФ по email-outreach 2024 — рейтинг Tagline"
     "Сертификат партнёра Mailchimp Pro (2023)"
     "Премия Tagline Awards 2024 в номинации B2B"
   Примеры плохо:
     "Множество наград"
     "Аккредитованное агентство"
   Если конкретных наград нет — "".

3. **media_comment** — видео, подкасты, выступления.
   Формат: "<Платформа/событие> (<дата>): <название/тема>" по строке на пункт.
   Примеры хорошо:
     "YouTube (2024): подкаст с CEO Wildberries про автоматизацию"
     "Conference Skolkovo 2023: выступление основателя"
     "Подкаст «Маркетинг и Кофе» (январь 2025): эпизод про холодные продажи"
   Примеры плохо:
     "Есть видео на YouTube"
     "Выступаем на конференциях"
   Если конкретного контента нет — "".

ЖЁСТКИЕ ПРАВИЛА:
- Используй ТОЛЬКО факты из текста. Не дорисовывай даты/названия СМИ.
- НЕ вставляй URL/ссылки, "см. на сайте", "подробнее в разделе".
- Все строки — на русском, лаконично, без HTML.
- Возвращай СТРОГО JSON-объект, без преамбулы и без кодовых блоков.

ВЫХОДНОЙ ФОРМАТ:
{
  "press_comment": "...",
  "awards_comment": "...",
  "media_comment": "..."
}`;

export function buildPressPrompt(input: PressPromptInput): PressPromptOutput {
  const homepage = input.homepageUrl?.trim() || 'неизвестен';
  const pages = input.pagesText?.trim() || '(подстраницы пустые)';

  const user = [
    `Главная сайта: ${homepage}`,
    '',
    'Тексты подстраниц с упоминаниями в СМИ / наградами / медиа-присутствием:',
    '"""',
    pages,
    '"""',
    '',
    'Сформируй JSON по схеме выше.',
  ].join('\n');

  return { system: SYSTEM_PROMPT, user };
}
