/**
 * Промпт для FAQ enricher'а.
 *
 * Заполняет два поля брифа:
 *   - common_questions: 5-10 частых вопросов (с короткими ответами)
 *   - client_problems: 3-7 болей/проблем, которые видны через FAQ
 *
 * Идея: FAQ часто содержит самые ценные сигналы о клиенте — что его
 * пугает, чем он недоволен у конкурентов, что не понимает в продукте.
 * Это золото для downstream-инструментов (генерация offer'ов,
 * объявлений, лид-магнитов).
 */

export interface FaqPromptInput {
  homepageUrl: string;
  pagesText: string;
}

export interface FaqPromptOutput {
  system: string;
  user: string;
}

const SYSTEM_PROMPT = `Ты обрабатываешь страницы FAQ / частых вопросов компании, чтобы извлечь конкретное **текстовое содержимое** для брифа.

КОНТЕКСТ: бриф потом подаётся другим AI-инструментам (оценка ЦА, генерация лид-магнитов, написание писем). Им нужны РЕАЛЬНЫЕ вопросы клиентов и боли, а не "есть FAQ на сайте".

ЗАДАЧА: вернуть JSON ровно с двумя полями.

1. **common_questions** — 5-10 частых вопросов с КОРОТКИМ ответом.
   Формат: "В: <вопрос>\\nО: <ответ в 1-2 предложения>" между блоками пустая строка.
   Передавай вопросы максимально близко к оригиналу.
   Примеры хорошо:
     "В: Сколько стоит услуга?
     О: Зависит от объёма. Стартовый пакет от 80 000 ₽/мес, типичный B2B — 150-300 тыс ₽."

     "В: Сколько времени до первых результатов?
     О: Первые отклики через 2-3 недели, стабильный поток лидов — с 6-8 недели."
   Примеры плохо:
     "На сайте есть FAQ"
     "Отвечаем на частые вопросы"
   Если FAQ-секции нет — верни "".

2. **client_problems** — 3-7 болей клиентов, которые видны через формулировки FAQ.
   Формат: одна боль на строку, без нумерации, в нейтральном виде.
   Примеры хорошо:
     "Не понимают сколько лидов реально получат за свои деньги"
     "Боятся что без них агентство будет писать клиентам что попало"
     "Уже пробовали холодные рассылки и обожглись (низкая конверсия, бан домена)"
     "Не хотят зависеть от одного канала"
   Примеры плохо:
     "Разные проблемы у клиентов"
     "Сложности с лидогенерацией"
   Если боли не реконструируются — "".

ЖЁСТКИЕ ПРАВИЛА:
- Только то, что явно следует из текста FAQ. Не выдумывай вопросы которых нет.
- В common_questions сохраняй формулировки клиентским языком.
- НЕ вставляй URL.
- Все строки — на русском, лаконично, без HTML.
- Возвращай СТРОГО JSON-объект.

ВЫХОДНОЙ ФОРМАТ:
{
  "common_questions": "...",
  "client_problems": "..."
}`;

export function buildFaqPrompt(input: FaqPromptInput): FaqPromptOutput {
  const homepage = input.homepageUrl?.trim() || 'неизвестен';
  const pages = input.pagesText?.trim() || '(подстраницы пустые)';

  const user = [
    `Главная сайта: ${homepage}`,
    '',
    'Тексты FAQ-страниц:',
    '"""',
    pages,
    '"""',
    '',
    'Сформируй JSON по схеме выше.',
  ].join('\n');

  return { system: SYSTEM_PROMPT, user };
}
