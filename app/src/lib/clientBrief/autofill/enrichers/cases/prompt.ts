/**
 * Промпт для cases enricher'а.
 *
 * Главная цель — заставить модель выписать **текстовое содержимое кейсов**,
 * а не мета-описание вроде "Есть раздел кейсов на сайте". Последующие
 * AI-инструменты (Оценка ЦА, гипотезы) работают с этим текстом как с
 * контекстом, и от "есть на сайте" им никакой пользы.
 *
 * Поэтому промпт жёстко структурирован: формат каждого кейса задан явно
 * (клиент → задача → результат с цифрами), плюс антипаттерны перечислены.
 */

export interface CasesPromptInput {
  /** Основной URL сайта (для контекста). */
  homepageUrl: string;
  /** Куски с подстраниц в формате "## URL\nТекст". */
  pagesText: string;
}

export interface CasesPromptOutput {
  system: string;
  user: string;
}

const SYSTEM_PROMPT = `Ты обрабатываешь страницы кейсов / портфолио / проектов компании, чтобы извлечь конкретное **текстовое содержимое** для брифа.

КОНТЕКСТ: бриф потом подаётся другим AI-инструментам (оценка целевой аудитории, генерация гипотез по сбору базы). Им нужны РЕАЛЬНЫЕ описания кейсов — клиент, задача, результат, цифры. Фраза «есть раздел кейсов на сайте» бесполезна и считается ошибкой.

ЗАДАЧА: вернуть JSON ровно с тремя полями:

1. **cases_comment** — 3-7 кейсов в формате:
   "<клиент или сегмент> — <задача / что делали> — <результат с цифрами или конкретикой>"
   Каждый кейс с новой строки. Если на сайте есть отраслевая разбивка — отрази её.
   Примеры хорошо:
     "Сеть строительных гипермаркетов «Петрович» — внедрили email-outreach по B2B-клиентам — 142 лида за 3 месяца, +18% к конверсии"
     "IT-интегратор уровня enterprise — настройка холодных писем в LinkedIn — выручка +28 млн ₽ за квартал"
   Примеры плохо (НЕ ИСПОЛЬЗОВАТЬ такие формулировки):
     "На сайте есть кейсы"
     "85+ проектов с разными клиентами"
     "Раздел кейсов: https://example.com/cases"
     "Успешные кейсы есть в портфолио"
   Если в текстах ни одного полного кейса не получается реконструировать — верни пустую строку "".

2. **impressive_results** — крупные количественные результаты, не привязанные к одному кейсу:
   "выручка клиентов выросла на X%", "собрали Y баз по Z отраслям", "средний ROI Q×".
   По строке на пункт. Если цифр нет — "".

3. **existing_clients** — перечисление узнаваемых клиентов/брендов (так как они написаны).
   Можно через запятую или построчно. Если клиенты не названы поимённо — "".

ЖЁСТКИЕ ПРАВИЛА:
- Используй ТОЛЬКО факты из приведённого текста. Никаких догадок, никаких "обычно у таких компаний".
- НЕ вставляй URL, "см. /cases", "подробнее на сайте". Это не помогает downstream-инструментам.
- Все строки — на русском, лаконично, без HTML, без markdown-маркеров вроде "• " или "- ".
- Не выдумывай цифры. Если результат описан без цифр — оставь его без цифр, не дорисовывай.
- Возвращай СТРОГО JSON-объект, без преамбулы и без кодовых блоков.

ВЫХОДНОЙ ФОРМАТ:
{
  "cases_comment": "...",
  "impressive_results": "...",
  "existing_clients": "..."
}`;

export function buildCasesPrompt(input: CasesPromptInput): CasesPromptOutput {
  const homepage = input.homepageUrl?.trim() || 'неизвестен';
  const pages = input.pagesText?.trim() || '(подстраницы пустые)';

  const user = [
    `Главная сайта: ${homepage}`,
    '',
    'Тексты подстраниц с кейсами / портфолио / проектами:',
    '"""',
    pages,
    '"""',
    '',
    'Сформируй JSON по схеме выше. Никаких других полей.',
  ].join('\n');

  return { system: SYSTEM_PROMPT, user };
}
