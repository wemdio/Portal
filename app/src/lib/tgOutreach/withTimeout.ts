/**
 * Ограничение по времени для запросов к Telegram.
 *
 * gramJS не таймаутит вызовы сам. Мобильный прокси меняет IP в любой момент, в
 * том числе посреди уже установленного соединения: сокет остаётся «живым» с
 * точки зрения библиотеки, запрос уходит в никуда и не возвращается никогда.
 * Такой зависший await не будит даже разрыв соединений снаружи.
 *
 * Цена этого — не одна потерянная переписка: цикл кампании перестаёт подавать
 * признаки жизни, сторожевой таймер воркера через 15 минут пытается погасить
 * кампанию, ещё через 3 минуты роняет весь процесс, и вместе с ним умирают все
 * остальные кампании. Ровно это произошло 06.08.2026 с прогревом ATOL-1.
 *
 * Поэтому каждый сетевой вызов оборачиваем: лучше упавшая переписка, чем
 * повисший воркер.
 */

/**
 * `signal` необязателен и добавлен для прогрева на едином жизненном цикле:
 * минутный таймаут спасает от повисшего запроса, но при остановке воркера
 * ждать эту минуту незачем — деплой даёт контейнеру считанные секунды, а после
 * перехвата прогона соседом наш вызов вообще идёт за чужой счёт. С сигналом
 * ожидание обрывается сразу, сам сетевой вызов при этом продолжает жить (гасить
 * gramJS изнутри нечем) — его добьёт разрыв соединений на выходе из цикла.
 *
 * Ошибка отмены намеренно НЕ отличается по типу от таймаутной: решение
 * «остановка или настоящий сбой» принимается по `signal.aborted` у вызывающего,
 * а не по разбору текста и имени ошибки.
 */
export function withTimeout<T>(
  promise: Promise<T>,
  ms: number,
  what: string,
  signal?: AbortSignal,
): Promise<T> {
  let timer: ReturnType<typeof setTimeout> | undefined;
  let onAbort: (() => void) | undefined;
  const guard = new Promise<never>((_, reject) => {
    timer = setTimeout(
      () => reject(new Error(`${what}: нет ответа за ${Math.round(ms / 1000)}с`)),
      ms,
    );
    if (signal) {
      if (signal.aborted) reject(new Error(`${what}: прервано остановкой`));
      onAbort = () => reject(new Error(`${what}: прервано остановкой`));
      signal.addEventListener('abort', onAbort, { once: true });
    }
  });
  return Promise.race([promise, guard]).finally(() => {
    clearTimeout(timer);
    if (signal && onAbort) signal.removeEventListener('abort', onAbort);
  });
}
