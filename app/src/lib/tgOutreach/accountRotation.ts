/**
 * В каком порядке круг берёт аккаунты.
 *
 * Раньше порядок был один и тот же всегда — как аккаунты пришли из базы. Пока
 * воркер живёт часами, это неважно: круг всё равно доходит до каждого. Но
 * 28.08.2026 воркер падал по три раза в день, а пауза между аккаунтами — до
 * десяти минут. Каждый новый процесс начинал список сначала, успевал обработать
 * два-три аккаунта и умирал. Хвост списка не работал НИКОГДА: у кампании ATOL-1
 * из двенадцати аккаунтов реально писали двое, а свежая база на триста
 * контактов сутки стояла с нулём отправок.
 *
 * Лечится порядком: первым берём того, до кого дольше всех не доходили. Тогда
 * каждый следующий запуск подхватывает эстафету с места обрыва, а не топчется
 * по началу списка. Падения от этого не исчезают — их надо искать отдельно, —
 * но перестают выжигать хвост.
 *
 * Позицию не храним отдельным полем: «когда до аккаунта дошли в последний раз»
 * и есть позиция, и она же переживает перезапуск, переезд на другой воркер и
 * добавление новых аккаунтов в середину списка. Новый аккаунт с пустой меткой
 * встаёт первым — это верно и по смыслу: до него не доходили никогда.
 */

export interface RotatableAccount {
  id: string;
  /** Когда круг в последний раз брал этот аккаунт в работу. */
  last_cycle_at?: string | null;
  /** Тай-брейк, чтобы порядок был устойчивым, а не случайным. */
  created_at?: string;
}

function ts(value: string | null | undefined): number | null {
  if (!value) return null;
  const t = new Date(value).getTime();
  return Number.isFinite(t) ? t : null;
}

/**
 * Отсортировать аккаунты «кого дольше всех не брали — тот первый».
 *
 * Не мутирует вход: список аккаунтов дальше используется и для других вещей
 * (сверка своих tg_user_id, счётчики), и менять его порядок под ними — способ
 * получить неочевидную ошибку через полгода.
 *
 * Аккаунты, до которых не доходили ни разу, идут перед всеми остальными.
 * Порядок между ними — по дате добавления: так партия, залитая утром, пойдёт
 * в том же порядке, в каком её загрузили, а не вперемешку.
 */
export function orderByStaleness<T extends RotatableAccount>(accounts: T[]): T[] {
  return [...accounts].sort((a, b) => {
    const aAt = ts(a.last_cycle_at);
    const bAt = ts(b.last_cycle_at);

    if (aAt === null && bAt === null) {
      return (ts(a.created_at) ?? 0) - (ts(b.created_at) ?? 0);
    }
    // Никогда не бравшийся — самый «застоявшийся», он важнее всех.
    if (aAt === null) return -1;
    if (bAt === null) return 1;
    if (aAt !== bAt) return aAt - bAt;
    return (ts(a.created_at) ?? 0) - (ts(b.created_at) ?? 0);
  });
}
