/**
 * Спинтакс в тексте первого касания: `{Привет|Здравствуйте|Добрый день}`.
 *
 * Текст первого касания лежит в самом контакте — его кладут при загрузке базы,
 * один и тот же на всю базу с подстановкой имени. В переписках это видно
 * невооружённым глазом: три сотни человек получают дословно одинаковый абзац,
 * отличающийся только обращением. Для Telegram одинаковые исходящие с разных
 * аккаунтов — прямой признак рассылки, а для получателя — признак того, что
 * писал не человек.
 *
 * Рандомизация текста синонимами — стандартный приём и отдельная рекомендация
 * руководства TgNinja. Делаем именно так, а не перефразированием моделью:
 * текст первого касания согласован с клиентом, и отдавать его на переписывание
 * нейросети значит каждый раз рисковать смыслом и платить за каждый контакт. К
 * тому же счёт за ИИ уже кончался, а рассылка от него зависеть не должна.
 *
 * Варианты пишет оператор, поэтому разбор нарочно снисходителен: незакрытая
 * скобка или пустой вариант не должны ронять отправку — в худшем случае уйдёт
 * текст как есть.
 */

/** Максимальная вложенность: защита от `{{{{...}}}}` в присланном файле. */
const MAX_DEPTH = 5;

/**
 * Развернуть спинтакс, выбрав по одному варианту из каждой группы.
 *
 * Разбираем изнутри наружу: вложенная группа `{а|{б|в}}` должна схлопнуться до
 * `{а|б}` прежде, чем выбирать во внешней, иначе во внешний вариант попадут
 * фигурные скобки как обычный текст.
 *
 * `pick` подменяется в тестах и при предпросмотре — оператору полезно увидеть
 * несколько разных развёрток одного текста, а не гадать по описанию.
 */
export function expandSpintax(
  text: string,
  pick: (options: string[]) => string = (options) => options[Math.floor(Math.random() * options.length)],
): string {
  let result = text ?? '';
  for (let depth = 0; depth < MAX_DEPTH; depth += 1) {
    // Группа без вложенных скобок — самая внутренняя из оставшихся.
    const innermost = /\{([^{}]*)\}/;
    if (!innermost.test(result)) break;
    result = result.replace(new RegExp(innermost, 'g'), (whole, body: string) => {
      const options = body.split('|');
      // Одиночная скобка без разделителя — не спинтакс, а просто текст в
      // скобках. Трогать его нельзя: в письмах встречается «(3 000 ₽)».
      if (options.length < 2) return whole;
      const cleaned = options.map((o) => o.trim()).filter((o) => o.length > 0);
      if (!cleaned.length) return '';
      return pick(cleaned);
    });
  }
  return result;
}

/** Есть ли в тексте хоть одна группа вариантов. */
export function hasSpintax(text: string): boolean {
  return /\{[^{}]*\|[^{}]*\}/.test(text ?? '');
}

/**
 * Сколько разных сообщений даёт текст.
 *
 * Число нужно оператору на загрузке базы: «вариантов 1» на трёхсот контактах
 * означает, что рандомизации нет вовсе, и лучше узнать это до отправки, а не из
 * переписок неделю спустя.
 *
 * Перемножаем размеры групп; вложенность считается тем же обходом изнутри.
 */
export function countSpintaxVariants(text: string): number {
  let total = 1;
  let result = text ?? '';
  for (let depth = 0; depth < MAX_DEPTH; depth += 1) {
    const innermost = /\{([^{}]*)\}/;
    if (!innermost.test(result)) break;
    result = result.replace(new RegExp(innermost, 'g'), (whole, body: string) => {
      const options = body.split('|').map((o) => o.trim()).filter((o) => o.length > 0);
      if (options.length < 2) return whole;
      total *= options.length;
      // Оставляем первый вариант: он может содержать скобки внешней группы.
      return options[0];
    });
  }
  return total;
}
