/**
 * Какие сообщения диалога уходят менеджеру при срабатывании триггера.
 *
 * gramJS отдаёт историю свежими сообщениями вперёд — на это опирается и
 * `[...history].reverse()` в `handleChat` перед сборкой контекста для модели.
 * Прежний код брал `history.slice(-forward_limit)`, то есть хвост списка,
 * упорядоченного от новых к старым, — а это САМЫЕ СТАРЫЕ сообщения окна. При
 * настройках «Сообщений в контексте GPT» 20 и «Сообщений в пересылке» 5
 * менеджер получал начало переписки вместо разбега перед «передаю ваш контакт».
 *
 * На коротких диалогах ошибка не видна: пока сообщений не больше лимита
 * пересылки, хвост и голова — это один и тот же список целиком. Поэтому она и
 * дожила до длинных переписок.
 */

export interface ForwardCandidate {
  id: number;
}

export function pickForwardIds(
  /** История из gramJS: новые сообщения первыми. */
  history: ForwardCandidate[],
  /** Сколько последних сообщений диалога пересылать («Сообщений в пересылке»). */
  forwardLimit: number,
  /** Только что отправленный ответ — тот самый, в котором сработал триггер. */
  sentId: number,
): number[] {
  const limit = Number.isFinite(forwardLimit) ? Math.max(0, Math.floor(forwardLimit)) : 0;
  const recent = history.slice(0, limit).map((m) => m.id);

  // Сообщение с триггером идёт всегда, даже при лимите ноль: без него пересылка
  // не отвечает на вопрос «почему это лид».
  const ids = new Set<number>([...recent, sentId]);

  // По возрастанию id: Telegram кладёт пересланное в чат-приёмник в этом
  // порядке, и переписка читается сверху вниз, а не задом наперёд.
  return [...ids].sort((a, b) => a - b);
}
