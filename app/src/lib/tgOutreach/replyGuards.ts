import { isRepeatOfOurs as isRepeatOfOursShared, normalizeForRepeatCheck } from '../outreachRepeatGuard';
import type { DialogMessage } from './types';

/**
 * Проверки перед отправкой сгенерированного ответа.
 *
 * Отдельным модулем от `campaignLoop`: это чистые функции над текстом, их
 * нужно уметь прогонять тестами, не поднимая весь цикл кампании.
 */

const normalize = normalizeForRepeatCheck;

/**
 * Мы уже отправляли этот текст в этом диалоге.
 *
 * Зачем: в тупике разговора («Хорошо.» — «Спасибо.») модели нечего сказать, и
 * она слово в слово повторяет собственную прощальную реплику. Для человека это
 * выглядит как сломанный бот, а для Telegram одинаковые сообщения — прямой
 * признак спам-рассылки и повод забанить аккаунт.
 *
 * Сама проверка — в `outreachRepeatGuard`: тот же вопрос решает LinkedIn-раннер,
 * где два запуска на пересекающихся лидах дублировали людям абзацы.
 */
export function isRepeatOfOurs(reply: string, history: DialogMessage[]): boolean {
  return isRepeatOfOursShared(reply, history);
}

/**
 * Благодарность и прощание. Отвечать на них нечего ни при каких условиях:
 * разговор закончен, и любая реплика сверху — лишний шум.
 */
const CLOSERS = new Set([
  'спасибо', 'спасибо большое', 'большое спасибо', 'спс', 'благодарю',
  'пока', 'до свидания', 'всего доброго', 'всего хорошего', 'удачи',
  'понятно', 'ясно', 'принято',
]);

/**
 * Согласие-подтверждение. Смысл зависит от того, спрашивали ли мы:
 * «Да» после «могу прислать условия?» — это согласие, а «Да» после нашего
 * прощания — вежливая точка.
 */
const ACKS = new Set([
  'да', 'ок', 'окей', 'ok', 'хорошо', 'ага', 'угу', 'добро', 'договорились',
]);

/**
 * Реплика, на которую предстоит ответить, — то есть последнее сообщение в
 * диалоге, и только если оно от собеседника. Искать последнее входящее где-то
 * в глубине истории было бы неверно: если после него мы уже что-то написали,
 * отвечать не на что, и решать тут нечего.
 */
function lastIncoming(history: DialogMessage[]): string | null {
  const last = (history ?? [])[(history ?? []).length - 1];
  return last?.role === 'user' ? (last.content ?? '') : null;
}

/** Последнее наше сообщение. */
function lastOutgoing(history: DialogMessage[]): string | null {
  for (let i = (history ?? []).length - 1; i >= 0; i -= 1) {
    const m = history[i];
    if (m?.role === 'assistant') return m.content ?? '';
  }
  return null;
}

/**
 * Отвечать не нужно: собеседник поставил вежливую точку.
 *
 * Зачем: на «Спасибо.» мы дописывали ещё одну реплику, и разговор тянулся
 * дольше, чем у него был смысл. Для Telegram это лишние исходящие в диалоге,
 * который уже закончился, — тот же спам-сигнал, что и дословные повторы.
 *
 * Осторожность с согласием. Триггер на лид срабатывает по НАШЕМУ ответу
 * (`detectTrigger`), поэтому промолчать — значит не распознать лида в этот ход.
 * Для благодарности и прощания это безопасно: лида там нет. А вот «Да» и «Ок»
 * двусмысленны — после нашего вопроса это согласие, и молчать нельзя. Поэтому
 * их глушим только тогда, когда мы ни о чём не спрашивали.
 *
 * Длинные сообщения не трогаем вообще: «Спасибо, пришлите в понедельник» — не
 * точка, а просьба.
 */
export function shouldStaySilent(history: DialogMessage[]): boolean {
  const incoming = lastIncoming(history);
  if (incoming === null) return false;

  const text = normalize(incoming);
  if (!text) return false;
  // Больше трёх слов — уже не «вежливая точка», а содержание.
  if (text.split(' ').length > 3) return false;

  if (CLOSERS.has(text)) return true;
  if (!ACKS.has(text)) return false;

  const ours = lastOutgoing(history);
  // Мы спрашивали — «Да» отвечает на вопрос, и промолчать значит бросить
  // согласившегося человека без ответа.
  return !(ours ?? '').trim().endsWith('?');
}
