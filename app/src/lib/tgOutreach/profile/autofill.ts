const TRANSLIT: Record<string, string> = {
  а: 'a', б: 'b', в: 'v', г: 'g', д: 'd', е: 'e', ё: 'e', ж: 'zh', з: 'z',
  и: 'i', й: 'y', к: 'k', л: 'l', м: 'm', н: 'n', о: 'o', п: 'p', р: 'r',
  с: 's', т: 't', у: 'u', ф: 'f', х: 'h', ц: 'ts', ч: 'ch', ш: 'sh',
  щ: 'sch', ъ: '', ы: 'y', ь: '', э: 'e', ю: 'yu', я: 'ya',
};

/** Кириллица → латиница по одному правилу на букву. */
export function translit(value: string): string {
  return (value ?? '')
    .toLowerCase()
    .split('')
    .map((ch) => (ch in TRANSLIT ? TRANSLIT[ch] : ch))
    .join('')
    .replace(/[^a-z0-9_]/g, '');
}

export interface Identity {
  firstName: string;
  lastName: string;
}

function pick<T>(list: T[]): T {
  return list[Math.floor(Math.random() * list.length)];
}

/** Случайные имя и фамилия. */
export function pickIdentity(): Identity {
  return { firstName: pick(FIRST_NAMES), lastName: pick(LAST_NAMES) };
}

/**
 * Ник по правилам Telegram: 5–32 символа, латиница, цифры и `_`, начинается с
 * буквы и не заканчивается подчёркиванием.
 *
 * Обрезаем до 32 ДО удаления хвостового `_`, иначе обрезка сама может оставить
 * его последним символом и вернуть невалидный ник.
 */
export function normalizeUsername(value: string): string {
  let name = (value ?? '').toLowerCase().replace(/[^a-z0-9_]/g, '').replace(/_+/g, '_');
  name = name.replace(/^[^a-z]+/, '').slice(0, 32).replace(/_+$/, '');
  return name;
}

export function isValidUsername(value: string): boolean {
  return /^[a-z][a-z0-9_]{3,30}[a-z0-9]$/.test(value ?? '');
}

/**
 * Варианты ника от самого «человеческого» к самому случайному.
 *
 * Порядок и есть суть: `ivan_petrov` выглядит как живой человек, `ivanp8421` —
 * как регистрация ради регистрации. Занятыми окажутся как раз первые, поэтому
 * список длинный, но вырождается постепенно, а не сразу в цифры.
 */
export function usernameCandidates(identity: Identity): string[] {
  const first = translit(identity.firstName);
  const last = translit(identity.lastName);
  const raw = [
    `${first}_${last}`,
    `${first}${last}`,
    `${first}_${last}${Math.floor(Math.random() * 90) + 10}`,
    `${first}${last[0]}${Math.floor(Math.random() * 9000) + 1000}`,
    `${first}_${last}_${Math.floor(Math.random() * 900) + 100}`,
    `${last}_${first}`,
    `${first}${Math.floor(Math.random() * 90000) + 10000}`,
    `${first}_${last}${Math.floor(Math.random() * 9000) + 1000}`,
  ];
  return raw.map(normalizeUsername).filter(isValidUsername);
}

/**
 * Описание профиля.
 *
 * Одна строка про роль и компанию — этого достаточно: длинное описание у
 * человека, который пишет первым, выглядит как реклама. Компания приходит из
 * настроек кампании, потому что аккаунты одной кампании представляют одного
 * клиента.
 */
export function buildBio(company: string | null | undefined): string {
  const name = (company ?? '').trim();
  return name ? `Менеджер компании ${name}` : 'Менеджер';
}

/**
 * Название компании для описания: настройка кампании, а если её нет — имя самой
 * кампании без технического хвоста вроде «-1» или «_Старые аккаунты».
 */
export function companyFromCampaign(
  settingsCompany: string | null | undefined,
  campaignName: string | null | undefined,
): string {
  const explicit = (settingsCompany ?? '').trim();
  if (explicit) return explicit;
  const raw = (campaignName ?? '').trim();
  if (!raw) return '';
  return raw.split(/[_\-–]/)[0].trim();
}
