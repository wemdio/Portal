/**
 * Отлёжка аккаунта TG-аутрича: после загрузки на портал и после смены имени,
 * ника или аватарки аккаунт какое-то время не идёт в боевую рассылку
 * (поле tg_outreach_accounts.profile_rest_until).
 *
 * Правило из руководства TgNinja: свежий аккаунт или свежепереименованный,
 * тут же ушедший писать незнакомым, — характерный признак подготовки к
 * рассылке, и платим за это бюджетом в тридцать писем.
 *
 * Отлёжка запрещает боевую рассылку, но НЕ прогрев: греться между своими
 * аккаунтами в эти часы можно и нужно — именно этим пауза и наполняется.
 *
 * Три часа — решение 07.10.2026 (было 12 часов и только после смены профиля):
 * купленную партию загружают и настраивают в тот же день, и полсуток простоя
 * на каждый шаг стоили рабочего дня. Переопределяется
 * TG_OUTREACH_PROFILE_REST_HOURS.
 */
export const ACCOUNT_REST_HOURS = Number(process.env.TG_OUTREACH_PROFILE_REST_HOURS) || 3;

/** До какого момента отлёживается аккаунт, начавший отлёжку сейчас. */
export function accountRestUntilIso(now: number = Date.now()): string {
  return new Date(now + ACCOUNT_REST_HOURS * 3_600_000).toISOString();
}
