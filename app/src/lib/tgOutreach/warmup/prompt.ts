/**
 * Прогрев: генерация реплик.
 *
 * Промпт намеренно НЕ продающий. Боевой системный промпт кампании сюда не
 * годится: он тянет разговор к офферу, а прогреву нужен бытовой фон — по нему
 * Telegram видит живого человека, а не рабочий инструмент.
 */
import type { OpenAISettings } from '../types';

const WARMUP_SYSTEM_PROMPT = `Ты пишешь в мессенджере обычному приятелю. Пиши как живой человек: коротко, на русском, без формальностей и без деловых тем.

Правила:
- одно сообщение — одна-две фразы, не длиннее 15 слов;
- бытовые темы: погода, планы на вечер, еда, дорога, сериалы, спорт, усталость после работы;
- никаких продаж, услуг, предложений, ссылок, приглашений и обсуждения работы;
- не представляйся и не спрашивай «кто это»: вы давно знакомы;
- не повторяй дословно то, что уже было в переписке;
- иногда отвечай вопросом, иногда просто реагируй;
- эмодзи изредка, не в каждом сообщении.

Верни только текст сообщения, без кавычек и пояснений.`;

/**
 * Промпт публичных ответов — отдельный и заметно строже бытового.
 *
 * Разница не в тоне, а в цене ошибки. Реплику в личке видит один свой же
 * аккаунт; ответ в публичном чате читают админы и антиспам-боты, и неудачный
 * оборачивается жалобой на всю партию.
 *
 * Два правила заслуживают отдельного объяснения:
 *
 * Запрет на встречные вопросы. Заданный вопрос обязывает отвечать на ответ, а
 * аккаунт этого не сделает — план дня уже составлен. Повисший вопрос виден
 * всему чату и выглядит хуже, чем отсутствие реплики.
 *
 * Право промолчать. На спорной теме любой ответ хуже молчания, поэтому модели
 * прямо разрешено вернуть пустоту: активность просто пропускается. Это не
 * страховка от ошибок модели, а осознанный отказ отвечать там, где не надо.
 */
const PUBLIC_REPLY_SYSTEM_PROMPT = `Ты обычный участник публичного чата в Telegram. Тебе показывают чужое сообщение, ответь на него коротко и по-человечески.

Правила:
- одна фраза, не длиннее 12 слов, на русском;
- по теме сообщения, спокойно и доброжелательно;
- НЕ задавай вопросов собеседнику: отвечать на ответ ты не будешь;
- никаких ссылок, услуг, предложений, рекламы и упоминаний работы;
- не представляйся, не обращайся по имени, не упоминай, что ты недавно в чате;
- эмодзи максимум один и не всегда.

Если сообщение про политику, религию, конфликт, спор, оскорбления, продажу чего-либо, деньги, здоровье или любую чувствительную тему — верни пустую строку и ничего не пиши. Молчание лучше неудачного ответа.

Верни только текст ответа или пустую строку.`;

/** Настройки генерации реплик прогрева для openaiGenerate. */
export function warmupOpenAISettings(): OpenAISettings {
  return {
    system_prompt: WARMUP_SYSTEM_PROMPT,
    project_name: '',
    trigger_phrases_positive: '',
    trigger_phrases_negative: '',
    target_chats_positive: '',
    target_chats_negative: '',
    use_fallback_on_fail: false,
    fallback_text: '',
  };
}

/**
 * Настройки генерации публичного ответа.
 *
 * Запасной реплики здесь намеренно нет. В переписке между своими банальное
 * «ага, понял» лучше оборванного диалога, а в чужом чате такая отписка не в
 * тему выглядит именно тем, чем является, — ботом. Не сгенерировали ответ —
 * пропускаем активность.
 */
export function publicReplyOpenAISettings(): OpenAISettings {
  return {
    system_prompt: PUBLIC_REPLY_SYSTEM_PROMPT,
    project_name: '',
    trigger_phrases_positive: '',
    trigger_phrases_negative: '',
    target_chats_positive: '',
    target_chats_negative: '',
    use_fallback_on_fail: false,
    fallback_text: '',
  };
}

/**
 * Запасные реплики на случай, когда GPT недоступен. Из-за одного сбойного
 * запроса прогрев останавливаться не должен, но и молчать в середине
 * переписки нельзя — оборванный на полуслове диалог выглядит хуже банальной
 * фразы.
 */
const FALLBACKS = [
  'ага, понял',
  'ну ок, тогда так и сделаем',
  'да, примерно так же',
  'слушай, давай попозже обсудим',
  'угу, согласен',
  'ладно, тогда до связи',
  'ясно, спасибо',
  'да нормально всё',
];

export function fallbackReply(index: number): string {
  return FALLBACKS[Math.abs(index) % FALLBACKS.length];
}
