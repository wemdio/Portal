/**
 * Эвристический детектор отраслей клиентов в кейс-странице сайта.
 *
 * Что делает: берёт plain-текст со страницы /cases (или того что найдено
 * как cases-подстраница), нормализует регистр и считает упоминания
 * ключевых слов по каждой из ~15 базовых B2B-отраслей. Возвращает
 * массив отраслей с порогом ≥2 упоминания, отсортированный по частоте,
 * не более 5 первых.
 *
 * Зачем: counter `cases_count` и список `customers` (логотипы) ничего
 * не говорят о ТОМ, в каких отраслях работают клиенты компании. А именно
 * это нужно для outreach-захода вида «вижу у вас кейсы в ритейле — у нас
 * 50+ ритейлеров с такой же болью». Идея: после прогона sales-специалист
 * фильтрует базу по «Отрасли в кейсах содержит "ритейл"» и пишет
 * прицельные письма.
 *
 * Точность: ~80%. Промахи: false positive («магазин приложений» = ритейл),
 * пропуск редких ниш (нет в словаре). Для топ-100 целевых аккаунтов лучше
 * прогнать LLM-extractor; для массовых прогонов (1000+ доменов) эвристика
 * закрывает 80% задач бесплатно — не вызываем модель за каждый домен.
 *
 * Пороги подобраны консервативно: одно случайное слово не делает
 * отрасль (порог = 2), а слова длиной ≥5 символов снижают шанс
 * collision'ов между языками и контекстами.
 */

interface IndustryRule {
  /** Канонический ярлык для вывода (попадает в колонку «Отрасли в кейсах»). */
  name: string;
  /** Подстроки в lowercase. Учитываем суффиксы — для русского достаточно. */
  keywords: string[];
}

