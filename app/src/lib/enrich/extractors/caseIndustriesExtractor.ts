const MIN_MENTIONS = 2;
const MAX_INDUSTRIES = 5;

function escapeRegex(s: string): string {
  return s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
}

function countAllOccurrences(text: string, needle: string): number {
  // text и needle уже lowercased вызывающим. Использование regex /g + match —
  // чище чем indexOf-loop и не ломается на multibyte UTF-8.
  const re = new RegExp(escapeRegex(needle), 'g');
  const matches = text.match(re);
  return matches ? matches.length : 0;
}

export function extractCaseIndustries(html: string): string[] {
  if (!html) return [];

  const $ = cheerio.load(html);
  // Снимаем шум: nav/footer/header часто содержат списки разделов и адресов,
  // которые сбивают счётчик («строительство» в адресе соседнего ЖК и т.п.).
  $('nav, footer, header, script, style, noscript').remove();
  const text = $('body').text().toLowerCase();
  if (!text || text.length < 50) return [];

  const counts: { name: string; count: number }[] = [];
  for (const rule of INDUSTRY_DICT) {
    let total = 0;
    for (const kw of rule.keywords) total += countAllOccurrences(text, kw);
    if (total >= MIN_MENTIONS) counts.push({ name: rule.name, count: total });
  }

  counts.sort((a, b) => b.count - a.count);
  return counts.slice(0, MAX_INDUSTRIES).map((c) => c.name);
}
