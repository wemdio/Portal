type Segment = 'it' | 'marketing' | 'suppliers' | 'general';

const IT_KEYWORDS = ['it', 'saas', 'fintech', 'edtech', 'hr tech', 'hrtech', 'разработк', 'software', 'платформ', 'ai ', 'ml ', 'devops', 'облач', 'cloud', 'data', 'аналитик', 'cybersec', 'информацион'];
const MARKETING_KEYWORDS = ['маркетинг', 'реклам', 'digital', 'pr ', 'smm', 'seo', 'брендинг', 'креатив', 'медиа', 'коммуникаци', 'event', 'ивент', 'btl', 'performance'];
const SUPPLIER_KEYWORDS = ['производств', 'поставк', 'поставщик', 'логистик', 'строительств', 'оборудован', 'торговл', 'дистрибуц', 'оптов', 'промышлен', 'склад', 'транспорт', 'металл', 'пищев', 'упаковк', 'сырь'];

function detectSegment(niche: string, description: string): Segment {
  const text = `${niche} ${description}`.toLowerCase();
  if (MARKETING_KEYWORDS.some((kw) => text.includes(kw))) return 'marketing';
  if (IT_KEYWORDS.some((kw) => text.includes(kw))) return 'it';
  if (SUPPLIER_KEYWORDS.some((kw) => text.includes(kw))) return 'suppliers';
  return 'general';
}

