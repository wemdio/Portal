/**
 * Политика защиты НЕСОХРАНЁННЫХ правок открытого письма при выходе из редактора
 * цепочки (email-sequence-v2, шаг «Письма»).
 *
 * Вынесено из EmailSequenceV2View в чистую функцию, чтобы:
 *  - все точки выхода (переключение письма, добавление, отправка в рассылку,
 *    уход со шага) шли через ОДНУ политику, а не расходились по хендлерам;
 *  - класс регрессий «новый путь навигации забыл про реестр грязных писем»
 *    ловился юнит-тестом, а не только глазами ревьюера.
 *
 * Решение зависит от намерения (intent) и от того, есть ли несохранённые правки.
 */

export type LetterExitIntent =
  /** Клик по другому письму в списке — редактор заменится другим. */
  | 'switchLetter'
  /** «+ Добавить письмо» — следом loadRun перезагрузит список писем. */
  | 'addLetter'
  /** «Отправить в рассылку» — уходит СЕРВЕРНОЕ состояние писем. */
  | 'sendToLaunch'
  /** Уход со шага «Письма» (кнопка «Назад» или клик по кружку степпера). */
  | 'leaveStep';

export interface LetterExitDecision {
  /** Показать window.confirm перед действием (и дать отменить). */
  confirm: boolean;
  /** Очистить реестр грязных писем после (подтверждённого/тихого) выхода. */
  clear: boolean;
}

/**
 * Политика ПРИ наличии несохранённых правок. Разведение confirm/clear:
 *  - switchLetter: редактор заменится другим письмом, loadRun НЕ следует →
 *    спрашиваем и чистим сами.
 *  - addLetter: следом loadRun перезагрузит список и сам очистит реестр →
 *    спрашиваем, но не чистим здесь (иначе двойная очистка).
 *  - sendToLaunch: уходит серверное состояние, редактор ОСТАЁТСЯ на экране →
 *    спрашиваем, но флаг НЕ трогаем, чтобы предупреждение не пропало для
 *    последующих действий с тем же несохранённым письмом.
 *  - leaveStep: редактор размонтируется, его локальные правки теряются →
 *    не спрашиваем (контракт кнопки «Назад» — тихий сброс), но чистим реестр,
 *    иначе флаг протухнет и при возврате даст ложное предупреждение.
 */
const POLICY: Record<LetterExitIntent, LetterExitDecision> = {
  switchLetter: { confirm: true, clear: true },
  addLetter: { confirm: true, clear: false },
  sendToLaunch: { confirm: true, clear: false },
  leaveStep: { confirm: false, clear: true },
};

/** Текст подтверждения для интентов, требующих confirm. `leaveStep` — пустой. */
export const LETTER_EXIT_MESSAGE: Record<LetterExitIntent, string> = {
  switchLetter: 'В открытом письме есть несохранённые правки. Переключиться без сохранения?',
  addLetter: 'В открытом письме есть несохранённые правки. Продолжить без сохранения?',
  sendToLaunch:
    'В письме есть несохранённые правки — они не попадут в рассылку. Сначала сохраните письмо. Продолжить без них?',
  leaveStep: '',
};

/**
 * Что делать при выходе из редактора письма с учётом несохранённых правок.
 * Если несохранённого нет — ничего спрашивать и чистить не нужно.
 */
export function decideLetterExit(
  intent: LetterExitIntent,
  hasUnsaved: boolean,
): LetterExitDecision {
  if (!hasUnsaved) return { confirm: false, clear: false };
  return POLICY[intent];
}
