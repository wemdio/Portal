/** Временный код: почта ещё пытается доставить, отказ не окончательный. */
export function isTemporaryBounceCode(code: string | null): boolean {
  return code !== null && code.startsWith('4');
}

export function describeBounceCode(code: string | null): string {
  if (code === null) return 'Код не найден в ответе сервера';
  if (EXACT[code]) return EXACT[code];
  return BY_CLASS.find(([re]) => re.test(code))?.[1] ?? 'Ответ сервера без пояснения';
}
