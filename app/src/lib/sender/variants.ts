/**
 * А/Б-тест письма: у шага цепочки бывает несколько вариантов текста, и база
 * делится между ними поровну.
 *
 * Вариант считается от id получателя, а не бросается монеткой при каждой
 * постановке письма. Иначе один и тот же лид после паузы, повтора или
 * пересчёта шага мог бы получить follow-up из другого варианта, а в
 * результатах теста его ответ приписался бы не тому письму.
 *
 * Правило общее для планировщика (кому что уедет) и для предпросмотра (что
 * показать по конкретному адресу), поэтому живёт отдельно от обоих.
 */

/** Больше четырёх вариантов — это уже не тест: на каждый не хватит базы. */
export const MAX_VARIANTS = 4;

/**
 * Сколько получателей на вариант нужно, чтобы разнице в ответах можно было
 * верить. Меньше — это разброс, а не победа одного текста над другим.
 */
export const MIN_RECIPIENTS_PER_VARIANT = 200;

const LABELS = ['А', 'Б', 'В', 'Г'];

/** Человеческое имя варианта: 1 → «А». */
export function variantLabel(variantNo: number): string {
  return LABELS[variantNo - 1] ?? String(variantNo);
}

/** FNV-1a: короткий устойчивый хеш строки, одинаковый на сервере и в браузере. */
function hash(text: string): number {
  let value = 0x811c9dc5;
  for (let i = 0; i < text.length; i += 1) {
    value ^= text.charCodeAt(i);
    value = Math.imul(value, 0x01000193) >>> 0;
  }
  return value;
}

/**
 * Какой вариант шага достанется этому получателю (1..count).
 *
 * Шаг входит в хеш: варианты первого и второго письма делят базу независимо,
 * иначе «вариант Б первого» всегда ехал бы вместе с «вариантом Б второго», и
 * понять, какое из двух писем сработало, было бы нельзя.
 */
export function pickVariant(recipientId: string, stepNo: number, count: number): number {
  if (count <= 1) return 1;
  return (hash(`${recipientId}:${stepNo}`) % count) + 1;
}
