/**
 * Process-wide «мы останавливаемся» флаг, общий для воркер-скриптов
 * (`app/worker/*.ts`) и библиотечного кода, который они выполняют
 * (`app/src/lib/**`).
 *
 * Зачем (инцидент 11.08.2026, деплой 15:10): воркер на SIGTERM отдаёт свои
 * задачи соседней реплике, но сами job'ы продолжают крутиться весь docker stop
 * grace, и их heartbeat — `updateJobProgress` — писал `started_at = now()`.
 * Тогда это отменяло передачу задачи (она шла через backdate той же колонки), и
 * все три job'а деплоя прождали 15 минут, подняв алерт «Долго висит» за секунду
 * до самоподбора.
 *
 * Сегодня передача идёт через аренду (`lease_until`, lib/jobs/lifecycle.ts), и
 * heartbeat её не трогает — но флаг нужен по-прежнему, уже ради читателей
 * `started_at`: монитора здоровья и порога простоя. Останавливающийся процесс,
 * который пишет «я жив» до самого SIGKILL, прячет простой задачи и от монитора,
 * и от библиотеки.
 *
 * Контракт: флаг односторонний. Процесс, получивший SIGTERM, не «оживает» —
 * поэтому сбрасывать его в проде незачем и нельзя (иначе heartbeat снова
 * начнёт врать).
 */

let shuttingDown = false;

/** Вызывается из SIGTERM/SIGINT-хэндлера воркера ДО любой async-работы. */
export function markShuttingDown(): void {
  shuttingDown = true;
}

/**
 * true — процесс получил сигнал остановки. Код, который пишет heartbeat'ы,
 * обязан это проверять: писать «я жив» во время shutdown — враньё, из-за
 * которого работа простаивает до stale-порога.
 */
export function isShuttingDown(): boolean {
  return shuttingDown;
}

/** @internal — только для тестов; в проде флаг односторонний. */
export function __resetShutdownStateForTests(): void {
  shuttingDown = false;
}
