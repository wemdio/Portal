function collectAllCodes(node: OkvedNode): string[] {
  const codes = [node.code];
  if (node.children) {
    for (const child of node.children) {
      codes.push(...collectAllCodes(child));
    }
  }
  return codes;
}

export function getAllDescendantCodes(tree: OkvedNode[], code: string): string[] {
  for (const node of tree) {
    if (node.code === code) {
      return collectAllCodes(node).filter((c) => c !== code);
    }
    if (node.children) {
      const found = getAllDescendantCodes(node.children, code);
      if (found.length > 0) return found;
    }
  }
  return [];
}

function collectLeafCodes(node: OkvedNode): string[] {
  if (!node.children || node.children.length === 0) return [node.code];
  const codes: string[] = [];
  for (const child of node.children) {
    codes.push(...collectLeafCodes(child));
  }
  return codes;
}

export function getLeafCodes(tree: OkvedNode[], code: string): string[] {
  for (const node of tree) {
    if (node.code === code) return collectLeafCodes(node);
    if (node.children) {
      const found = getLeafCodes(node.children, code);
      if (found.length > 0) return found;
    }
  }
  return [];
}

export function flattenTree(nodes: OkvedNode[]): { code: string; name: string }[] {
  const result: { code: string; name: string }[] = [];
  for (const node of nodes) {
    result.push({ code: node.code, name: node.name });
    if (node.children) result.push(...flattenTree(node.children));
  }
  return result;
}
