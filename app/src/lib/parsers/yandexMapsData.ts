export function generateSearchUrls(cities: string[], rubrics: string[]): string[] {
  const urls: string[] = [];
  for (const city of cities) {
    for (const rubric of rubrics) {
      const query = `${city} ${rubric}`.trim();
      const encoded = encodeURIComponent(query);
      urls.push(`https://yandex.ru/maps/?text=${encoded}`);
    }
  }
  return urls;
}

