/**
 * Ensure a code appears in the list. Used to preserve values that came
 * from a resumed job but aren't in our curated list (custom locale).
 */
export function ensureLocaleOption(list: LocaleOption[], code: string): LocaleOption[] {
  if (!code) return list;
  if (list.some((o) => o.code === code)) return list;
  return [{ code, label: code }, ...list];
}
