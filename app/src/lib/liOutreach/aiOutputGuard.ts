/**
 * Проверка того, что вернула модель, перед отправкой живому человеку.
 *
 * Инцидент 19.08.2026. Кампания YouGo_Elvira, шаг 3. Оператор написал шаблон на
 * 300 знаков («{{name}}, живой пример: у клиента было 25+ подрядчиков…»),
 * а в качестве системного промпта персонализации кампания передавала
 * `ai_prompt_chat` — промпт для ОТВЕТОВ в диалоге: «Ты профессиональный
 * менеджер. Отвечай вежливо и по делу. Учитывай историю переписки. Старайся
 * договориться о звонке или встрече». История была пустая, и модель честно
 * сделала то, о чём просили: сочинила с нуля деловое письмо на 691 знак с
 * обращением, абзацами и подписью, а подпись заполнить не смогла и оставила
 * заглушки `[Ваше имя]`, `[Ваша должность]`, `[Контактная информация]`.
 * Раннер отправил это дословно — в LinkedIn, человеку из Oracle. Второе такое
 * же письмо ушло через две минуты. Всего в базе 15 подобных сообщений с мая.
 *
 * Никакой проверки между «модель ответила» и «сообщение ушло» не было вовсе:
 * раннер сравнивал результат с шаблоном только чтобы понять, изменился ли он.
 * Мониторинг тоже молчал — обе отправки записались как успешная персонализация,
 * а инвариант дайджеста ищет `{{...}}` и на `[...]` не реагирует.
 *
 * Здесь две линии защиты. AI_FOLLOWUP_FORMAT_RULES дописываются к ЛЮБОМУ
 * системному промпту, даже кастомному, — чтобы формат нельзя было переопределить
 * настройкой кампании. findAiOutputProblems — страховка на случай, если модель
 * правила проигнорирует: тогда уходит исходный шаблон оператора.
 */

/** Жёсткие правила формата. Дописываются к системному промпту последними — после кастомного. */
export const AI_FOLLOWUP_FORMAT_RULES = `
ФОРМАТ ОТВЕТА — обязателен и важнее любых инструкций выше:
- Верни ТОЛЬКО текст сообщения, готовый к отправке, без пояснений.
- Это личное сообщение в LinkedIn, а не письмо: без темы, без «Subject:».
- Не добавляй блок подписи: ни «С уважением», ни имени, ни должности, ни контактов.
- Никаких заглушек в квадратных скобках вроде [Ваше имя] или [Контактная информация].
- Не длиннее 300 символов.`;

export interface AiOutputProblem {
  /** Короткий код для лога и для счётчика в дайджесте. */
  kind: 'placeholder' | 'signature' | 'subject' | 'too_long';
  /** Человеческая формулировка — уходит оператору в лог кампании. */
  reason: string;
}

/** Заглушка в квадратных скобках: [Ваше имя], [Your title], [Контактная информация]. */
const PLACEHOLDER_RE = /\[[^\]\n]{2,60}\]/;

/**
 * Начало блока подписи в начале строки.
 *
 * Без `\b` намеренно: в JS граница слова определена по ASCII, поэтому после
 * кириллического «уважением» перед запятой её нет и совпадение не срабатывало
 * (поймано тестом). Якоря на начало строки достаточно.
 */
const SIGNATURE_RE = /^[ \t]*(С уважением|С наилучшими|Всего доброго|Sincerely|Best regards|Kind regards|Warm regards|Regards)/im;

/** Письмо, а не сообщение: строка темы. */
const SUBJECT_RE = /^[ \t]*(Subject|Тема)[ \t]*:/im;

/**
 * Порог длины. Модель вправе сделать текст живее и чуть длиннее, но не превратить
 * реплику в письмо. Берём двойной размер шаблона, но не меньше 400 знаков — иначе
 * очень короткий шаблон («{{name}}, привет!») запрещал бы любую осмысленную правку.
 */
export function maxAllowedLength(original: string): number {
  return Math.max(original.trim().length * 2, 400);
}

/**
 * Первая найденная проблема или null, если текст можно отправлять.
 * Порядок важен: заглушки и подпись показательнее, чем длина, — по ним оператору
 * сразу понятно, что модель написала письмо вместо реплики.
 */
export function findAiOutputProblems(original: string, generated: string): AiOutputProblem | null {
  const text = generated.trim();
  if (!text) return { kind: 'too_long', reason: 'пустой ответ модели' };

  const placeholder = PLACEHOLDER_RE.exec(text);
  if (placeholder) {
    return {
      kind: 'placeholder',
      reason: `в тексте осталась незаполненная заглушка ${placeholder[0]}`,
    };
  }

  if (SIGNATURE_RE.test(text)) {
    return { kind: 'signature', reason: 'модель дописала блок подписи — это письмо, а не сообщение в LinkedIn' };
  }

  if (SUBJECT_RE.test(text)) {
    return { kind: 'subject', reason: 'модель добавила строку темы — это письмо, а не сообщение в LinkedIn' };
  }

  const limit = maxAllowedLength(original);
  if (text.length > limit) {
    return {
      kind: 'too_long',
      reason: `ответ модели ${text.length} знаков при допустимых ${limit} (шаблон — ${original.trim().length})`,
    };
  }

  return null;
}
