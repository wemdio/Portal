import type { ClientNavMode } from '@/lib/clientNav';

/**
 * Показываем ли клиенту метрики открытий писем.
 *
 * Трекинг открытий перестал быть достоверным: пиксель режут Apple Mail Privacy
 * и прокси картинок Gmail, а боты защитных шлюзов, наоборот, открывают письмо
 * за получателя (в проде уникальных открытий ~50% от отправок — цифра заведомо
 * завышенная). Показывать её клиенту как метрику качества рассылки нельзя,
 * поэтому из обычного кабинета открытия убраны целиком: и число, и процент.
 *
 * Исключение — auto-режим (кастомный кабинет Mailganer): там метрику считают
 * иначе, её переделывают отдельно. Пока отдаём как было.
 *
 * Клиентский (браузерный) предикат: страницы берут mode из
 * ClientPortalContext. Серверный аналог — resolveClientPortalMode в
 * lib/clientPortalMode.ts (он server-only, в компоненты не импортируется).
 */
export function shouldShowOpenMetrics(mode: ClientNavMode): boolean {
  return mode === 'auto';
}
