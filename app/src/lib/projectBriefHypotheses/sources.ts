function tokenizeRu(text: string): string[] {
  return (text.toLowerCase().match(/[\p{L}\p{N}]+/gu) ?? []).filter(
    (t) => t.length >= 4 && !RUSSIAN_STOPWORDS.has(t),
  );
}

// Лёгкий стемминг: префикс из STEM_LEN символов. Русские словоформы отличаются
// окончаниями (клиники↔клиник, строительные↔строительство, медицинских↔
// медицинские) — точное равенство токенов их теряло, и реально релевантные базы
// уходили в no-match. Префикс почти не даёт ложных совпадений (автомобиль ≠
// автоматизация уже на 6 символах). Синонимы с РАЗНЫМ корнем (стоматология ↔
// медицина) это НЕ ловит — для них нужен отдельный словарь.
const STEM_LEN = 6;
function stemRu(t: string): string {
  return t.slice(0, STEM_LEN);
}

const TOP_PRIORITY: ExportBaseCategory[] = ['ТОП', 'Рубрика', 'Тип компании'];

/**
 * Сужает каталог до топ-N записей, наиболее релевантных тексту брифа,
 * по простому keyword-overlap (количество общих токенов >=4 символов).
 * Если бриф пуст или нет совпадений — возвращает первые N "TOП"-категорий.
 */
export function selectRelevantCatalog(
  briefText: string,
  catalog: ExportBaseCatalogItem[],
  limit: number,
): ExportBaseCatalogItem[] {
  const safeLimit = Math.max(1, Math.floor(limit));
  const briefTokens = new Set(tokenizeRu(briefText));

  if (briefTokens.size === 0) {
    return catalog.filter((i) => TOP_PRIORITY.includes(i.category)).slice(0, safeLimit);
  }

  // Стеммы токенов брифа — для матча по словоформам (см. stemRu).
  const briefStems = new Set([...briefTokens].map(stemRu));

  const scored = catalog
    .map((item) => {
      const tokens = tokenizeRu(item.name);
      let score = 0;
      for (const t of tokens) {
        if (briefTokens.has(t)) {
          score += 1; // точное совпадение токена
        } else if (t.length >= STEM_LEN && briefStems.has(stemRu(t))) {
          score += 0.7; // совпадение по словоформе (клиники↔клиник), вес меньше
        }
      }
      // Без буста ТОП-категорий: он тащил «универсальные» базы (продавцы WB/OZON,
      // госзакупки, интернет-магазины) наверх почти на любой бриф, из-за чего
      // разным клиентам предлагались одни и те же категории. Теперь ранжируем
      // чисто по keyword-релевантности к брифу.
      return { item, score };
    })
    .filter((entry) => entry.score > 0)
    .sort((a, b) => b.score - a.score);

  if (scored.length === 0) {
    // Бриф есть, но НИ ОДНА категория не совпала по ключевым словам → НЕ
    // подставляем «универсальный» grab-bag (WB/OZON, госзакупки, интернет-
    // магазины). Он противоречил бы инструкции «не добивай общими категориями»
    // и как раз давал одинаковые источники разным клиентам. Пусто: модель
    // опирается на LEAD_SOURCES в системном промпте + ICP-инструкцию.
    return [];
  }

  // защита от дублей по URL
  const seen = new Set<string>();
  const result: ExportBaseCatalogItem[] = [];
  for (const { item } of scored) {
    if (seen.has(item.url)) continue;
    seen.add(item.url);
    result.push(item);
    if (result.length >= safeLimit) break;
  }
  return result;
}

