/**
 * Когда шаг конструктора баз сохраняет промежуточный результат.
 *
 * Чекпоинт был привязан только к числу обработанных строк — раз в 250. На
 * бумаге это «~17 записей на базу в 4297 строк», на практике даёт вечный цикл:
 * если задача умирает раньше 250-й строки, чекпоинт не пишется НИ РАЗУ, resume
 * начинает шаг с нуля, доходит до того же места и умирает снова.
 *
 * Именно это случилось 12.08.2026 на базе в 6602 строки: 250 строк — это 3.8%,
 * а задача падала на 3%. Прогресс полз до трёх процентов, сбрасывался в ноль и
 * шёл по новой, и так бесконечно — при том что механизм resume работал
 * исправно, ему просто нечего было восстанавливать.
 *
 * Чем больше база, тем позже первый чекпоинт по счётчику строк, — то есть
 * защита слабеет ровно там, где нужнее. Поэтому добавлено время: чекпоинт
 * пишется и по счётчику, и по таймеру, что наступит раньше. Теперь любой сбой
 * стоит не больше минуты работы, а не всего шага.
 */

/** Раз во сколько строк писать чекпоинт (как было). */
export const DEFAULT_CHECKPOINT_EVERY_ROWS = 250;
/**
 * Раз в сколько миллисекунд писать чекпоинт независимо от числа строк.
 *
 * Минута — цена одного сбоя. Запись чекпоинта на большой базе стоит ~4 МБ
 * jsonb: раз в минуту это заметно дешевле, чем терять шаг целиком, и заметно
 * реже, чем «на каждой строке».
 */
export const DEFAULT_CHECKPOINT_INTERVAL_MS = 60_000;

export interface CheckpointGateOptions {
  everyRows?: number;
  intervalMs?: number;
  /** Часы — параметром, чтобы поведение гейта можно было проверить тестом. */
  now?: () => number;
}

/**
 * Возвращает функцию-решатель: пора ли писать чекпоинт.
 *
 * Вызывается после каждой обработанной строки. Сама ничего не пишет — только
 * отвечает «да/нет» и запоминает момент последнего «да».
 */
export function makeCheckpointGate(options: CheckpointGateOptions = {}) {
  const everyRows = Math.max(1, options.everyRows ?? DEFAULT_CHECKPOINT_EVERY_ROWS);
  const intervalMs = Math.max(1_000, options.intervalMs ?? DEFAULT_CHECKPOINT_INTERVAL_MS);
  const now = options.now ?? (() => Date.now());

  let lastAt = now();

  return function shouldCheckpoint(done: number, isLast: boolean): boolean {
    // Последнюю строку сохраняем всегда: следующего шанса не будет.
    if (isLast) {
      lastAt = now();
      return true;
    }
    const byRows = done > 0 && done % everyRows === 0;
    const byTime = now() - lastAt >= intervalMs;
    if (!byRows && !byTime) return false;
    lastAt = now();
    return true;
  };
}
