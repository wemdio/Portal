/**
 * Предмет обсуждения ({{предмет}}) — что мы предлагаем обсудить именно этой
 * компании: «Хочу обсудить поиск корпоративных клиентов на поставки
 * автомобильных запчастей и компонентов». Утверждённые тексты 09.10.2026
 * ставят его в письма 1 и 2 внутри предложения.
 *
 * Пишет его дешёвая модель разбора по тому, что компания продаёт, — как
 * связку (bridge.ts), доли цента на компанию. Ответ проверяет topicLineOf; не
 * прошёл или модель молчит — запасная фраза FALLBACK_TOPIC: стоит внутри
 * предложения, пустой быть не может.
 */

import { wordCount } from '../evidence';
import { asString, callJson } from '../llm';

export const FALLBACK_TOPIC = 'поиск новых корпоративных клиентов для вашей компании';

const SYSTEM = `Ты помогаешь написать холодное письмо от Polza Agency. Polza находит компаниям новых B2B-клиентов: подбирает целевые компании и пишет им письма.
В письме стоит фраза «Хочу обсудить …». Допиши её конец: что именно мы предлагаем обсудить этой компании — поиск клиентов для того, что она продаёт.
Верни СТРОГИЙ JSON: {"topic": string}

Правила:
- 5–15 слов, с маленькой буквы, без точки в конце; начинается со слова «поиск» или «привлечение»;
- назови, каких клиентов и на что: «поиск корпоративных клиентов на …», «привлечение застройщиков и подрядчиков к …»;
- исходи только из того, что компания продаёт; не выдумывай отрасли и продукты;
- без цифр, названий компаний, кавычек, вопросов; не упоминай Polza, рассылки и письма;
- если непонятно, что компания продаёт, верни {"topic": ""}.

Примеры (не копируй их):
Продаёт: автозапчасти и компоненты оптом для СТО и автопарков.
{"topic": "поиск корпоративных клиентов на поставки автомобильных запчастей и компонентов"}
Продаёт: внедрение и доработку Битрикс24 для бизнеса.
{"topic": "привлечение компаний, которым нужно внедрение и доработка Битрикс24"}`;

const TOPIC_FORBIDDEN = /polza|польз[аы]\s+agency|рассылк|письм|аутрич|outreach|гарант|срочн|уникальн/i;

/** Предмет обсуждения от модели — или null, если не годится в письмо как есть. */
export function topicLineOf(value: unknown): string | null {
  const text = asString(value).replace(/\s+/g, ' ').trim().replace(/[.;,]+$/, '');
  if (!text) return null;
  const words = wordCount(text);
  if (words < 4 || words > 18) return null;
  if (/\d|[«»"{}?!]/.test(text)) return null;
  if (TOPIC_FORBIDDEN.test(text)) return null;
  if (!/^(поиск|привлечени)/.test(text)) return null;
  return text;
}

/**
 * Предмет обсуждения дешёвой моделью. Модель не ответила или ответ не годится —
 * null (вызывающий ставит FALLBACK_TOPIC). Лимит на ИИ и ключ летят дальше:
 * они про весь запуск.
 */
export async function buildTopic(productSummary: string | null, options: { timeoutMs?: number } = {}): Promise<string | null> {
  if (!productSummary?.trim()) return null;
  const raw = await callJson(
    SYSTEM,
    `ПРОДАЁТ: ${productSummary}`,
    'topic',
    200,
    (r) => typeof r.topic === 'string',
    options.timeoutMs,
  );
  return topicLineOf(raw.topic);
}
