/**
 * Образцы цепочек по продуктам каскада (спека
 * 2026-10-28-outreach-three-products-cascade-design.md, «Три продукта»): СДР,
 * классика РФ/СНГ, классика за рубеж, автоаутрич. С 29.10.2026 шаблон
 * пишется на продукт, и это образец писателя (templateWriter.ts); с
 * USE_FIXED_TEMPLATES они же идут в письма как есть, под компанию меняются
 * только плейсхолдеры (renderTemplate.ts).
 *
 * Тексты подготовлены по КП без утверждения продаж (решение владельца
 * 28.10.2026). Правила — те же, что проверяет runTemplateQa: свой текст письма
 * не длиннее 200 символов, один вопрос, без цен, цифр (кроме «15 минут» и
 * «2–3 сегмента»), корня «гарант» и слов «аутрич» / «лидогенерация»; повод и
 * связка — отдельными абзацами в письме 1, гипотеза — в письме 3 без кейса.
 * Письмо 4 не называет себя последним: после паузы компании предложат
 * следующий продукт. Каждое письмо продаёт только свой продукт: гарантия по
 * заявкам — только у классики РФ/СНГ, «система» — только у автоаутрича.
 */

import type { Product } from '../cascade';
import { senderFirstName, type SenderProfile } from '../libraries';
import { TEMPLATE_PLACEHOLDERS, TEMPLATE_SIGN_OFF, type ChainTemplateLetters } from '../types';

const P = TEMPLATE_PLACEHOLDERS;
const B = `«${P.brand}»`;

function letter(...paragraphs: string[]): string {
  return ['Добрый день!', ...paragraphs, TEMPLATE_SIGN_OFF].join('\n\n');
}

/** Версия текстов — в модель шаблона в базе, чтобы отличать от писем Gemini. */
export const FIXED_TEMPLATES_MODEL = 'fixed:products@2026-10-29';

/** Письмо 1 «перешлите ответственному»: суть продукта, предмет и просьба переслать. */
function routing(offer: string): string {
  return letter(P.opening, P.bridge, `${offer} Хочу обсудить ${P.topic}. Перешлёте письмо тому, кто в компании ${B} отвечает за продажи?`);
}

/** Письмо 4: мягкое закрытие и один вопрос продукта. */
function closing(question: string): string {
  return letter(`Если тема сейчас не ко времени, так и напишите — вернусь позже. Если этим занимается коллега, подскажите, к кому обратиться. ${question}`);
}

export function fixedTemplate(product: Product, sender: SenderProfile): ChainTemplateLetters {
  const me = `${senderFirstName(sender)}, ${sender.company_name}.`;
  switch (product) {
    case 'sdr':
      // Зовём к менеджеру: он возьмёт задачу и назовёт результат и стоимость.
      // Список компаний не просим — тогда ждут конкретики в ответ (Андрей Сальнов).
      return {
        subject: `выход на крупных клиентов для ${B}`,
        bodyDirect: letter(
          P.opening,
          P.bridge,
          'Наша команда вручную находит тех, кто принимает решения в нужных вам компаниях, и выходит на них от вашего имени. Удобно созвониться на 15 минут с нашим менеджером?',
        ),
        bodyRouting: routing('Наша команда вручную выходит на тех, кто принимает решения в нужных вам компаниях.'),
        letter2: letter(
          `${me} К крупным клиентам в узкой нише нужен личный выход. Наш менеджер разберёт вашу задачу и назовёт результат и стоимость — созвонимся на 15 минут?`,
        ),
        bodyWithCase: letter(`${me} Для примера: ${P.case}`, 'Так же можем выйти и на нужные вам компании. Обсудим вашу задачу с менеджером?'),
        bodyWithoutCase: letter(
          `${me} Коротко о том, как мы работаем.`,
          P.hypothesis,
          'Находим в нужных вам компаниях ответственных, выходим на них вручную и передаём ответы вашему менеджеру с перепиской. Обсудим вашу задачу?',
        ),
        letter4: closing('Поговорить с нашим менеджером сейчас актуально?'),
      };
    case 'classic':
      // Команда ведёт кампанию; обязательства по заявкам — в договоре (корень «гарант» нельзя).
      return {
        subject: `новые B2B-клиенты для ${B}`,
        bodyDirect: letter(
          P.opening,
          P.bridge,
          'Наша команда ведёт поиск клиентов за вас: выбирает сегменты, собирает базу и выходит на тех, кто принимает решения. Созвонимся на 15 минут и прикинем, сколько заявок это может дать?',
        ),
        bodyRouting: routing('Наша команда ведёт поиск B2B-клиентов за вас: сегменты, база и выход на тех, кто принимает решения.'),
        letter2: letter(
          `${me} Письма уходят не всем подряд: у каждого сегмента свой повод и свой текст. Обязательства по заявкам прописываем в договоре. Прикинем за 15 минут, с каких сегментов начать?`,
        ),
        bodyWithCase: letter(`${me} Для примера: ${P.case}`, 'Прикинем похожий план для вас за 15 минут?'),
        bodyWithoutCase: letter(
          `${me} Как выглядит первый тест.`,
          P.hypothesis,
          'Берём 2–3 сегмента, собираем компании и тех, кто принимает решения, и по ответам видим, какие сегменты расширять. Прислать короткий план теста?',
        ),
        letter4: closing('Новые клиенты сейчас в приоритете?'),
      };
    case 'classic_abroad':
      // Зарубежные рынки, почта и LinkedIn; обязательств по заявкам здесь нет — не обещаем.
      return {
        subject: `клиенты за рубежом для ${B}`,
        bodyDirect: letter(
          P.opening,
          P.bridge,
          'Наша команда находит клиентов на зарубежных рынках: собирает базу и пишет тем, кто принимает решения, по почте и в LinkedIn от вашего имени. Созвонимся на 15 минут?',
        ),
        bodyRouting: routing('Наша команда находит B2B-клиентов за рубежом: по почте и в LinkedIn выходит на тех, кто принимает решения.'),
        letter2: letter(
          `${me} Страны и сегменты проверяем небольшими тестами, а ответы с интересом передаём вашему менеджеру с перепиской. Прикинем за 15 минут, какие рынки проверить первыми?`,
        ),
        bodyWithCase: letter(`${me} Для примера: ${P.case}`, 'Обсудим, как сделать так же на зарубежных рынках?'),
        bodyWithoutCase: letter(
          `${me} Как выглядит первый тест.`,
          P.hypothesis,
          'Берём 2–3 сегмента на одном рынке, пишем по почте и в LinkedIn и по ответам видим, где есть спрос. Прислать короткий план теста?',
        ),
        letter4: closing('Продажи за рубежом сейчас актуальны?'),
      };
    case 'auto':
      // Система сама находит и пишет, заявки каждый месяц без найма; ведение включено.
      return {
        subject: `новые заявки каждый месяц для ${B}`,
        bodyDirect: letter(
          P.opening,
          P.bridge,
          'Мы настраиваем систему, которая каждый день сама находит подходящие компании и пишет им от вашего имени. Заявки приходят каждый месяц без найма команды. Созвонимся на 15 минут?',
        ),
        bodyRouting: routing('Наша система сама находит подходящие компании и пишет им — заявки приходят каждый месяц без найма команды.'),
        letter2: letter(
          `${me} Настройку и ведение берём на себя, а ответы с интересом получает ваш менеджер. Прикинем за 15 минут, сколько подходящих компаний на вашем рынке и какой темп реален?`,
        ),
        bodyWithCase: letter(`${me} Для примера: ${P.case}`, 'Прикинем, какой темп реален для вас?'),
        bodyWithoutCase: letter(
          `${me} Как это выглядит.`,
          P.hypothesis,
          'Система каждый день находит компании с поводом для письма и пишет им, а ответы с интересом получает ваш менеджер. Прислать короткий план запуска?',
        ),
        letter4: closing('Постоянный поток заявок сейчас актуален?'),
      };
  }
}
