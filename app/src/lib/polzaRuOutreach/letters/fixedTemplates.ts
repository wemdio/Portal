/**
 * Утверждённые тексты писем RU автоаутрича (документ «Оффер для Автоаутрича»,
 * 09.10.2026, вкладка с цепочкой для hh.ru). С этого дня шаблон оффера не
 * пишет Gemini: письма идут ровно в утверждённой формулировке, под компанию
 * меняются только плейсхолдеры (renderTemplate.ts).
 *
 * Две цепочки: «найм» (вакансия на hh) и общая — для всех остальных поводов;
 * повод (выставка, Директ, рост, возврат) встаёт строкой в письмо 1.
 * Письмо 1: «А» — лично ЛПР (bodyDirect), «В» — общая почта (bodyRouting).
 *
 * Отступления от документа, чтобы письма проходили автопроверку (runQa) и
 * читались по-русски:
 * - название компании с родовым словом: «в компании «…»» — в кавычках оно не
 *   склоняется (решение 28.09.2026);
 * - в письме 4 первый вопрос стал утверждением: вопрос в письме один;
 * - письмо 3 без подходящего кейса начинается сразу с механики — фраза
 *   «покажу реальные результаты» без кейса была бы обещанием без содержания;
 * - после повода в письме 1 «А» — связка (просьба CEO 02.10.2026).
 */

import { senderFirstName, type SenderProfile } from '../libraries';
import { TEMPLATE_PLACEHOLDERS, TEMPLATE_SIGN_OFF, type ChainTemplateLetters, type ChainType } from '../types';

const P = TEMPLATE_PLACEHOLDERS;
const B = `«${P.brand}»`;

function letter(...paragraphs: string[]): string {
  return [...paragraphs, TEMPLATE_SIGN_OFF].join('\n\n');
}

/** Версия текстов — в модель шаблона в базе, чтобы отличать от писем Gemini. */
export const FIXED_TEMPLATES_MODEL = 'fixed:offer-doc@2026-10-09';

export function fixedTemplate(chain: ChainType, sender: SenderProfile): ChainTemplateLetters {
  const me = `${senderFirstName(sender)}, ${sender.company_name}.`;
  const hiring = chain === 'hiring';

  const bodyDirect = letter(
    `Добрый день, я очень коротко по поводу ${B})`,
    P.opening,
    P.bridge,
    `Я из ${sender.company_name}. Помогаем B2B-компаниям получать новые заявки каждый месяц через email-outreach: сами подбираем целевые компании, находим ЛПР и пишем им от вашего лица.`,
    'Самое трудоемкое берем на себя – от технической настройки до первичного прогрева холодного лида, а вашему менеджеру передаем уже готовый заинтересованный ответ вместе с перепиской.',
    `Какие нам шаги сделать, чтобы попробовать это на ${B}?)`,
  );

  const bodyRouting = hiring
    ? letter(
      'Добрый день!',
      `Обратил внимание, что в компании ${B} сейчас открыта вакансия ${P.position}. В связи с этим есть предложение обсудить ${P.topic}.`,
      'Подскажите, пожалуйста, кто у вас отвечает за развитие этого направления? Буду благодарен, если поделитесь контактом или перешлете письмо.',
    )
    : letter(
      'Добрый день!',
      P.opening,
      `Подскажите, пожалуйста, кто в компании ${B} отвечает за продажи и привлечение клиентов?`,
      `Хочу обсудить ${P.topic}.`,
      'Буду благодарен, если передадите письмо ответственному сотруднику или подскажете его контакт.',
    );

  const letter2 = letter(
    'Добрый день!',
    `${me} Писал вам на днях про ${P.topic} – дополню детали, по которым обычно принимается решение.`,
    ...(hiring
      ? [`Сейчас вы ищете ${P.position}, но найм начнёт приносить сделки только через пару месяцев. Наш email-outreach закрывает эту паузу: первые заинтересованные ответы придут уже на 2–3 неделе.`]
      : []),
    P.hypothesis,
    'На практике это выглядит так: мы собираем и верифицируем базу под ваши услуги, выделяем 2–3 приоритетных сегмента и пишем компаниям точечно, опираясь на их бизнес-сигналы, а не общий спам.',
    'Всю техническую настройку, защиту от спам-фильтров и первый контакт мы берем на себя. Вашему менеджеру передаем уже квалифицированных лидов с историей переписки и понятным интересом.',
    'Что важно знать заранее: KPI по лидам фиксируем в договоре: если лидов не будет – вернём деньги. Раз в неделю присылаем отчёт: отправки, ответы, лиды в работе.',
    `Чтобы вы могли оценить подход под свою нишу, давайте созвонимся минут на 15: разберём 2–3 кейса из смежных отраслей и наметим группы клиентов, с которых стоит начать для ${B}. Когда вам будет удобно?`,
  );

  const mechanism = 'мы анализируем рынок и выходим на целевые компании на основе коммерческих сигналов – например, когда у них открывается нужная вакансия, расширяется отдел или запускается новое направление. Вы первыми предлагаете решение горячему сегменту, пока до него не дотянулись конкуренты.';
  const economics = `Предлагаю за 15 минут прикинуть экономику email-outreach для ${B}: объём доступной базы, реалистичный диапазон лидов и окупаемость при вашем среднем чеке. Когда удобно созвониться?`;
  const bodyWithCase = letter(
    'Добрый день!',
    'Чтобы было понятнее, какую отдачу email-outreach дает в вашей нише, покажу реальные результаты из релевантной для вас ниши:',
    P.case,
    `Суть в том, что ${mechanism}`,
    economics,
  );
  const bodyWithoutCase = letter(
    'Добрый день!',
    `Чтобы было понятнее, какую отдачу email-outreach может дать в вашей нише, расскажу, как мы работаем: ${mechanism}`,
    'Так первые ответы приходят от компаний, у которых задача есть прямо сейчас, а не от тех, кто просто получил очередное письмо.',
    economics,
  );

  const letter4 = letter(
    'Добрый день!',
    `${me} Понимаю, что сейчас, возможно, не до этого – поэтому всего один короткий вопрос.`,
    'Возможно, у вас есть на примете компании, которым идеально подходят ваш продукт, услуги или экспертный опыт, но пока не получилось выйти на нужного человека. Можно начать развитие продаж именно с них.',
    'Я изучу, какие задачи они сейчас решают, что запускают и где ваша команда или решения могут принести им максимальную пользу. Поводом для обращения станет конкретная бизнес-задача клиента и ваш подходящий кейс, а не просто предложение познакомиться.',
    'Какие 3–5 компаний вы больше всего хотели бы видеть среди своих клиентов?',
  );

  return {
    subject: hiring ? `Вопрос по привлечению клиентов в ${B}` : `новые b2b-клиенты для ${B}`,
    subjectsRouting: hiring ? [B] : [`по поводу роста продаж в ${B}`, `вопрос по лидогенерации в ${B}`],
    bodyDirect,
    bodyRouting,
    letter2,
    bodyWithCase,
    bodyWithoutCase,
    letter4,
  };
}
