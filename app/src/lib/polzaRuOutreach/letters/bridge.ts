/**
 * Связка повода с предложением ({{связка}}) — одна фраза письма 1 сразу после
 * {{повод}}. Замечание CEO 02.10.2026: «Увидел новость …», а следом
 * пересказ сайта — повод висит сам по себе. Связка объясняет, при чём тут
 * новые клиенты: «когда ставки высокие, заказчиков приходится искать самим».
 *
 * Пишет её дешёвая модель разбора, одна фраза на компанию (доли цента): шаблон
 * писателя один на оффер и связать с ним чужую новость не может. Ответ
 * проверяет bridgeLineOf; не прошёл или модель молчит — запасная фраза по
 * поводу и продукту (fallbackBridge), письмо без связки не уходит.
 *
 * С 29.10.2026 модель знает продукт шага каскада: связка ведёт к тому, на что
 * отвечает именно он, — иначе письмо СДР получило бы связку про рассылки
 * (анти-цель спеки каскада: обещание из КП другого продукта).
 */

