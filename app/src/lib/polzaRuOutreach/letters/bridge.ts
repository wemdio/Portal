/**
 * Запасная связка повода с продуктом — когда модель не ответила или ответ не
 * прошёл проверку. У возврата повод — прошлый разговор: связывать нечего,
 * письмо дальше говорит само. «Автоматизация» старых строк — связка её
 * исходной цепочки (вызывающий передаёт её вместо `automation`).
 */
export function fallbackBridge(chain: ChainType, product: Product): string | null {
  if (chain === 'reactivation' || chain === 'automation') return null;
  const bridges = FALLBACK_BRIDGES[chain];
  return bridges[product] ?? bridges.base;
}

export interface BridgeRequest {
  chain: ChainType;
  baseChain?: ChainType;
  /** Продукт шага каскада: к нему ведёт связка. */
  product: Product;
  brand: string;
  /** Фраза-повод, уже подставленная в письмо (openingSentence). */
  opening: string;
  productSummary: string | null;
}

/**
 * Связка дешёвой моделью. Модель не ответила или ответ не годится — null
 * (вызывающий ставит fallbackBridge). Лимит на ИИ и ключ летят дальше: они
 * про весь запуск.
 */
export async function buildBridge(req: BridgeRequest, options: { timeoutMs?: number } = {}): Promise<string | null> {
  const prompt = bridgePrompt(req);
  const raw = await callJson(
    prompt.system,
    prompt.user,
    'bridge',
    200,
    (r) => typeof r.bridge === 'string',
    options.timeoutMs,
  );
  return bridgeLineOf(raw.bridge);
}
