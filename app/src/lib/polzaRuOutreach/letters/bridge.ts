/**
 * Связка повода с предложением ({{связка}}) — одна фраза письма 1 сразу после
 * {{повод}}. Замечание CEO 02.10.2026: «Увидел новость …», а следом
 * пересказ сайта — повод висит сам по себе. Связка объясняет, при чём тут
 * новые клиенты: «когда ставки высокие, заказчиков приходится искать самим».
 *
 * Пишет её дешёвая модель разбора, одна фраза на компанию (доли цента): шаблон
 * писателя один на оффер и связать с ним чужую новость не может. Ответ
 * проверяет bridgeLineOf; не прошёл или модель молчит — запасная фраза по
 * офферу (fallbackBridge), письмо без связки не уходит.
 */

import { wordCount } from '../evidence';
import { asString, callJson } from '../llm';
import type { ChainType } from '../types';

const SYSTEM = `Ты помогаешь написать холодное письмо от Polza Agency. Polza настраивает компаниям автоматические рассылки писем на почты их будущих клиентов — так у компании появляются новые заявки.
Письмо начинается с повода — факта о компании-получателе. Напиши ОДНУ фразу, которая идёт сразу после повода и связывает его с тем, что компании нужны новые клиенты или заявки.
Верни СТРОГИЙ JSON: {"bridge": string}

Правила:
- одно предложение, 10–30 слов, обращение на «вы», простой разговорный язык, в конце точка;
- исходи из повода и того, что компания продаёт; не повторяй повод своими словами;
- говори осторожно, как наблюдение: «обычно», «в такие моменты», «когда …, важно …» — не ставь компании диагноз и не утверждай её планы и проблемы;
- без цифр, названий компаний, кавычек, вопросов, восклицаний, обещаний результата; не упоминай Polza, рассылки и письма — о них скажет следующий абзац;
- если повод никак не связать с поиском клиентов, верни {"bridge": ""}.

Примеры (не копируй их):
Повод: «Увидел, что вы ищете «Менеджер по продажам».» Продаёт: упаковку для пищевых производств.
{"bridge": "Новому менеджеру с первого дня понадобятся контакты, а входящих заявок на всех обычно не хватает."}
Повод: «Увидел новость: «Ставки по кредитам для застройщиков снова выросли».» Продаёт: бетон и нерудные материалы.
{"bridge": "Когда стройка замедляется, поставщикам приходится самим искать новых заказчиков, а не ждать, пока те позвонят."}
Повод: «Увидел, что у вас появилась новая точка: Казань, ул. Баумана.» Продаёт: ремонт грузовой техники.
{"bridge": "Новой точке нужен свой поток клиентов, и чем раньше он появится, тем быстрее она выйдет в плюс."}`;

/** Слова, которых в связке быть не должно: о Polza и рассылках говорит шаблон, выдумки — нельзя. */
const BRIDGE_FORBIDDEN = /polza|польз[аы]\s+agency|рассылк|письм|аутрич|outreach|гарант|срочн|уникальн|процент|десятк|сотн|тысяч|вдвое|втрое/i;

/** Связка от модели — или null, если не годится в письмо как есть. */
export function bridgeLineOf(value: unknown): string | null {
  const text = asString(value).replace(/\s+/g, ' ').trim();
  if (!text) return null;
  const words = wordCount(text);
  if (words < 8 || words > 35) return null;
  if (/\d|[«»"{}?!]/.test(text)) return null;
  if (BRIDGE_FORBIDDEN.test(text)) return null;
  // Одно предложение с точкой в конце: вторая фраза — уже пересказ.
  if (!/[.]$/.test(text) || /[.…]\s+\S/.test(text.slice(0, -1))) return null;
  if (!/^[А-ЯЁ]/.test(text)) return null;
  return text;
}

/** Запасная связка по офферу — когда модель не ответила или ответ не прошёл проверку. */
export function fallbackBridge(chain: ChainType, baseChain?: ChainType): string | null {
  switch (chain) {
    case 'hiring':
      return 'Новым людям в продажах с первого дня понадобятся контакты, а входящих заявок на всех обычно не хватает.';
    case 'ad_budget':
      return 'Реклама приводит тех, кто уже ищет, а многие подходящие вам компании пока ничего не ищут — до них можно дойти напрямую.';
    case 'event':
      return 'Выставка — хороший повод самим выйти на компании, с которыми вы хотели бы работать, а не ждать их у стенда.';
    case 'growth_event':
      return 'Когда компания растёт, новых заказов нужно больше, чем приносят рекомендации и входящие заявки.';
    case 'icp_only':
      return 'Таким компаниям новые клиенты обычно приходят по рекомендациям, а этот поток трудно ускорить.';
    case 'reactivation':
      // Повод — прошлый разговор: связывать нечего, письмо дальше говорит само.
      return null;
    case 'automation':
      return baseChain && baseChain !== 'automation' ? fallbackBridge(baseChain) : null;
  }
}

export interface BridgeRequest {
  chain: ChainType;
  baseChain?: ChainType;
  brand: string;
  /** Фраза-повод, уже подставленная в письмо (openingSentence). */
  opening: string;
  productSummary: string | null;
}

/**
 * Связка дешёвой моделью. Модель не ответила или ответ не годится — null
 * (вызывающий ставит fallbackBridge). Лимит на ИИ и ключ летят дальше: они
 * про весь запуск.
 */
export async function buildBridge(req: BridgeRequest, options: { timeoutMs?: number } = {}): Promise<string | null> {
  const raw = await callJson(
    SYSTEM,
    [`ПОВОД: «${req.opening}»`, `ПРОДАЁТ: ${req.productSummary ?? 'не указано'}`].join('\n'),
    'bridge',
    200,
    (r) => typeof r.bridge === 'string',
    options.timeoutMs,
  );
  return bridgeLineOf(raw.bridge);
}
