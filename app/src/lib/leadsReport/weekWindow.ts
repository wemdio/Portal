const MSK_OFFSET_MS = 3 * 60 * 60 * 1000;
const DAY_MS = 24 * 60 * 60 * 1000;
const HOUR_MS = 60 * 60 * 1000;

/**
 * Отчётное окно продаж: [прошлая пятница 18:00:00 МСК, эта пятница 18:00:00 МСК).
 * Ровно 7 суток от отчёта до отчёта. Дальше по расписанию: в 18:05 бежит синк
 * AMO, в 18:15 уходит отчёт. Синк стоит ПОСЛЕ отсечки специально — тогда всё,
 * что попало в окно, к его старту уже создано и заведомо окажется в базе.
 *
 * Договорённость с продажами (Александр, 08.09.2026): неделя считается
 * «с субботы по пятницу на 18:00». Окно при этом начинается не в субботу
 * 00:00, а на шесть часов раньше — в пятницу в 18:00, — и это не описка.
 * Отчёт уходит в 18:05, то есть всё, что заведено в пятницу после 18:00, в
 * текущий отчёт попасть уже не может физически. Начнись следующее окно в
 * субботу, вечер пятницы не попал бы и в него — сделка исчезала бы навсегда,
 * ровно как `@bass_dmitry` (35041989) 04.09.2026. Поэтому окна стыкуются
 * встык, а `labelStart` показывает продажам привычную субботу.
 *
 * Правило `end`: ближайшая ПЯТНИЦА 18:00 МСК на этой календарной неделе
 * (не в будущем через воскресенье). Если сегодня пт — сегодня 18:00;
 * если пн-чт — прошедшая пятница; если сб-вс — прошедшая пятница. Ручной
 * запуск в пятницу ДО 18:00 поэтому даёт окно, которое ещё не закрылось —
 * так же, как и раньше; для штатного крона это неважно.
 */
export function currentMskWeekWindow(now: Date): {
  start: Date;
  end: Date;
  /**
   * Дата, с которой отчёт подписан в шапке — суббота 00:00 МСК, то есть
   * `start` плюс шесть часов. Ручной отчёт продаж подписан так же
   * («с 29.08 по 4.09»), и совпадение шапок — единственное, что позволяет
   * сверять два отчёта построчно. На то, что считается, не влияет.
   */
  labelStart: Date;
} {
  const nowMsk = new Date(now.getTime() + MSK_OFFSET_MS);
  const dow = nowMsk.getUTCDay(); // 0 = вс, 5 = пт
  // Сколько дней назад ближайшая пятница (сегодня если пт).
  const daysBackToFriday = dow === 5 ? 0 : (dow - 5 + 7) % 7;

  const endMskMs = Date.UTC(
    nowMsk.getUTCFullYear(),
    nowMsk.getUTCMonth(),
    nowMsk.getUTCDate() - daysBackToFriday,
    18, 0, 0, 0,
  );
  // Вычитаем ровно 7 суток, а не «семь дней календаря»: в МСК нет перевода
  // часов, поэтому арифметика по миллисекундам здесь точна и не зависит от
  // того, на какое число выпала пятница.
  const startMskMs = endMskMs - 7 * DAY_MS;

  return {
    start: new Date(startMskMs - MSK_OFFSET_MS),
    end: new Date(endMskMs - MSK_OFFSET_MS),
    labelStart: new Date(startMskMs + 6 * HOUR_MS - MSK_OFFSET_MS),
  };
}

export function shortMskDate(date: Date): string {
  const msk = new Date(date.getTime() + MSK_OFFSET_MS);
  const day = String(msk.getUTCDate()).padStart(2, '0');
  const month = String(msk.getUTCMonth() + 1).padStart(2, '0');
  return `${day}.${month}`;
}
