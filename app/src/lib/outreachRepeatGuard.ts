/**
 * «Мы это уже отправляли» — общая проверка для всех каналов аутрича.
 *
 * Живёт отдельным модулем, потому что нужна двум независимым движкам:
 *
 *  - Telegram (`tgOutreach/replyGuards`): в тупике разговора («Хорошо.» —
 *    «Спасибо.») модели нечего сказать, и она слово в слово повторяет
 *    собственную прощальную реплику;
 *  - LinkedIn (`liOutreach/campaignRunner`): две running-кампании на
 *    пересекающихся лидах шлют в один и тот же чат человека, потому что гард от
 *    повтора стоял только на шаге invite. Так 15–17.08.2026 четыре человека
 *    получили один и тот же абзац дважды, а 20.08 пересечение вернулось на 153
 *    лидах после перезапуска остановленной кампании.
 *
 * Причины разные, а вопрос один и тот же: уходил ли этот текст этому человеку.
 * Для получателя оба случая выглядят одинаково — собеседник дважды прислал
 * одно и то же, — и оба одинаково читаются платформой как признак рассылки.
 */

/** Минимальная форма записи истории: подходит и TG-диалогу, и LinkedIn-переписке. */
export interface RepeatCheckMessage {
  role?: string | null;
  content?: string | null;
}

/**
 * Нормализация для сравнения текстов: регистр, пунктуация и пробелы значения
 * не имеют. «Хорошо.» и «хорошо!» — одно и то же сообщение для получателя, и
 * для платформы, которая ищет одинаковые рассылки, тоже.
 */
export function normalizeForRepeatCheck(text: string): string {
  return text
    .toLowerCase()
    .replace(/ё/g, 'е')
    .replace(/[^\p{L}\p{N}\s]/gu, ' ')
    .replace(/\s+/g, ' ')
    .trim();
}

/**
 * Мы уже отправляли этот текст в этой переписке.
 *
 * Сравнение строгое, по нормализованному тексту целиком. Похожие, но не
 * совпадающие тексты («Хорошо, вернёмся» против «Хорошо, вернёмся позже») этой
 * проверкой НЕ ловятся: подобие пришлось бы мерить порогом, а неверно
 * выбранный порог глушил бы осмысленные сообщения. Точное совпадение — то, что
 * действительно наблюдается в боевых диалогах, и у него нет ложных
 * срабатываний.
 *
 * Роль обязательна: тот же текст, присланный собеседником (он нас
 * процитировал), не должен блокировать нашу отправку.
 */
export function isRepeatOfOurs(text: string, history: RepeatCheckMessage[] | null | undefined): boolean {
  const candidate = normalizeForRepeatCheck(text);
  if (!candidate) return false;
  return (history ?? []).some(
    (m) => m?.role === 'assistant' && normalizeForRepeatCheck(m.content ?? '') === candidate,
  );
}
