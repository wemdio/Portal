/**
 * B2C/ИП/гос отсев ПО КОМПАНИИ (название + домен) — только OutreachOS пайплайн.
 *
 * Классификация выборки первого live-прогона (217 из 868, воркфлоу 05.07)
 * показала ~74% чистого B2B и ~20% шума, причём шум СТРУКТУРНЫЙ: B2C-ритейл,
 * онлайн-школы, отели/медиа, ИП-частники с ФИО-названиями на tilda. Половина
 * шума ловится дёшево по названию/домену — эти правила здесь. Вторая половина
 * (онлайн-школа с нормальным доменом в IT-индустрии) структурно неотличима от
 * B2B и осознанно НЕ ловится (ta_scoring выключен by design).
 *
 * Принцип: precision > recall. Каждое правило должно почти не задевать B2B —
 * лучше пропустить B2C-компанию, чем выкинуть живого покупателя. Поэтому:
 * нет generic-правил вроде «host содержит sale» (убило бы salebot/salesforce).
 *
 * Чистые функции без зависимостей (изоляция от Mailganer сохранена).
 * Известный неохваченный хвост: ФИО с редким именем вне FIRST_NAMES
 * («Лоикова Зулия») — его добирает LLM-рубеж (classifyCompanies.ts).
 */

/**
 * Частые русские имена для эвристики «название = ФИО из 2 слов».
 * Матчится ТОЛЬКО в паре с фамильным суффиксом второго слова (см. isPersonName)
 * — само по себе имя компанию не исключает («Виктория Транс» остаётся).
 */
const FIRST_NAMES: ReadonlySet<string> = new Set([
  'александр', 'александра', 'алексей', 'алина', 'анастасия', 'андрей', 'анна',
  'антон', 'артем', 'артём', 'валентина', 'валерий', 'василий', 'вера', 'виктор',
  'виктория', 'владимир', 'владислав', 'галина', 'дарья', 'денис', 'дмитрий',
  'евгений', 'евгения', 'егор', 'екатерина', 'елена', 'иван', 'игорь', 'илья',
  'ирина', 'кирилл', 'константин', 'ксения', 'лариса', 'лидия', 'любовь',
  'людмила', 'максим', 'марина', 'мария', 'михаил', 'надежда', 'наталия',
  'наталья', 'никита', 'николай', 'нина', 'оксана', 'олег', 'ольга', 'павел',
  'петр', 'пётр', 'полина', 'роман', 'светлана', 'сергей', 'софья', 'станислав',
  'тамара', 'татьяна', 'фёдор', 'федор', 'юлия', 'юрий', 'яна',
]);

/**
 * Отчество: Павлович, Сергеевна, Ильинична. Голого `ич$` НЕТ намеренно —
 * иначе «...Кирпич» в трёхсловном названии ложно матчится как ФИО.
 */
const PATRONYMIC_RE = /(?:ович|евич|ьич|овна|евна|ична)$/;

/** Фамильный суффикс: Смагина, Венглинский, Кутергина, Петров, Ильин... */
const SURNAME_RE = /(?:ов|ова|ев|ева|ёв|ёва|ин|ина|ын|ына|ский|ская|цкий|цкая|ич|ко|ук|юк|енко)$/;

/**
 * true, если название компании — ФИО человека (ИП/частник, не юрлицо-бренд).
 *
 * Два паттерна с высокой точностью:
 *  - 3 кириллических слова, последнее — отчество («Ильин Александр Павлович»);
 *  - 2 кириллических слова: одно — частое имя, другое — с фамильным суффиксом
 *    («Смагина Наталья», «Венглинский Александр»). Оба условия сразу, иначе
 *    «Красный дельфин» / «Рабочие Руки» ложно бы срабатывали.
 */
export function isPersonName(nameRaw: string): boolean {
  const words = (nameRaw ?? '').trim().toLowerCase().split(/\s+/);
  if (words.some((w) => !/^[а-яё-]+$/.test(w))) return false;
  // Для 3 слов среднее ОБЯЗАНО быть именем: иначе бренды типа «Строительный
  // Двор Петрович» ложно матчились бы по одному лишь суффиксу «-ович».
  if (words.length === 3) return FIRST_NAMES.has(words[1]) && PATRONYMIC_RE.test(words[2]);
  if (words.length === 2) {
    const [a, b] = words;
    return (
      (FIRST_NAMES.has(a) && SURNAME_RE.test(b)) ||
      (FIRST_NAMES.has(b) && SURNAME_RE.test(a))
    );
  }
  return false;
}

/**
 * Стоп-токены в НАЗВАНИИ (lowercase-подстрока или regex с ручными границами —
 * \b в JS не работает с кириллицей). Каждый токен = наблюдённый паттерн шума
 * из классификации либо однозначно-B2C категория.
 */
const NAME_STOP_RULES: readonly { rule: string; re: RegExp }[] = [
  { rule: 'name:ип', re: /(?:^|\s)ип(?:\s|$)/ },
  { rule: 'name:ип', re: /индивидуальный предприниматель/ },
  // (?!ь): «школьная карта»/«мосшкольснаб» (B2B-поставщики ДЛЯ школ) не матчатся,
  // сами школы («школа», «онлайн-школа», «автошкола») — матчатся.
  { rule: 'name:школа', re: /школ(?!ь)/ },
  // Граница перед «отел» обязательна: иначе «котельное оборудование» (B2B) матчится.
  // Латинского hotel в NAME-правиле НЕТ намеренно: «The Hotels Network»/Hotellab —
  // B2B-вендоры ДЛЯ отелей; реальные отели ловятся кириллицей и host:hotel.
  { rule: 'name:отель', re: /(?:^|[^а-яё])отел[ьия]|гостиниц|хостел/ },
  { rule: 'name:фотостудия', re: /фотостуд|фотограф/ },
  // Только полное «футбольн»: голое «фк» = чаще фарм/фин компания (ФК ПУЛЬС,
  // Банк ФК Открытие) — ревью подтвердило ложные срабатывания на топ-B2B.
  { rule: 'name:футбольный клуб', re: /футбольн/ },
  // Правил «издательство» и «коллегия адвокатов» НЕТ намеренно: по ground truth
  // сессии 05.07 большинство их киллов — B2B (издательства продают тиражи оптом
  // сетям: ИД Питер, Мозаика-Синтез; коллегия = корп-юрфирма tp-law). Реально
  // B2C-издательства (Детская Литература) ловит LLM-рубеж с рефьютом.
  // Lookbehind: «коммерческая недвижимость» = B2B (CRE), остальное — физлицам.
  { rule: 'name:недвижимость', re: /(?<!коммерческ(?:ая|ой) )недвижимост|риэлт|риелт/ },
  { rule: 'name:банкротство физлиц', re: /банкротств[оа]? физ/ },
  // Прилагательные — B2B-поставщики В вертикаль, не сама вертикаль: «ресторанный
  // консалтинг», «Ресторан-Сервис», «кофейное оборудование», «пекарное …» — не
  // матчатся ((?!н), (?![ыо]), (?![ -]сервис)). «Кофейня»/«Пекарня X» — матчатся.
  { rule: 'name:общепит', re: /ресторан(?!н)(?![ -]сервис)|(?:^|[^а-яё])кафе(?:[^а-яё]|$)|кофейн(?![ыо])|пекарн(?![ыо])/ },
  { rule: 'name:красота/фитнес', re: /салон красоты|барбершоп|фитнес[ -]?(?:клуб|центр)|спа[ -]салон/ },
  { rule: 'name:туризм', re: /турагент|туроператор|туристическ(?:ое|ая) (?:агентство|компания|фирма)/ },
  { rule: 'name:ломбард', re: /ломбард/ },
  // Off-ICP B2B (владелец 07.07): технически B2B, но НЕ покупатели cold-email
  // инструмента. Только высокоточные термины, не задевающие IT/ИБ/агентства.
  // Физохрана: ЧОП/ЧОО + «охранное агентство/организация», «частная охранная».
  // НЕ матчит «информационная безопасность», «Security Vision», «РОСОХРАНА»
  // (эти — либо целевой ИБ, либо ловит LLM-рубеж).
  { rule: 'icp:чоп', re: /(?:^|[^а-яё])чо[оп](?:[^а-яё]|$)|охранн(?:ое|ая|ой) (?:агентство|организаци|предприяти|фирм)|частн(?:ое|ая|ой) охранн/ },
  // ЖКХ/коммуналка — однозначные термины (НЕ голое «управляющая компания» — то B2B-холдинги).
  { rule: 'icp:жкх', re: /(?:^|[^а-яё])жкх(?:[^а-яё]|$)|жилищно-коммунальн|(?:^|[^а-яё])тсж(?:[^а-яё]|$)|водоканал|теплосет|горэлектросет|домоуправлен/ },
  // Госпредприятия: ФГУП/ГУП/МУП («группа» не содержит «гуп» — безопасно).
  { rule: 'icp:госпредприятие', re: /(?:^|[^а-яё])(?:фгуп|гуп|муп)(?:[^а-яё]|$)/ },
];

/**
 * Стоп-правила по ХОСТУ сайта (или домена почты). Только высокоточные:
 * B2C-TLD, конструкторы частных лендингов, «магазин/школа» в домене.
 */
const HOST_STOP_RULES: readonly { rule: string; test: (host: string) => boolean }[] = [
  { rule: 'host:.shop', test: (h) => h.endsWith('.shop') || h.endsWith('.store') },
  { rule: 'host:tilda', test: (h) => h.endsWith('tilda.ws') || h.endsWith('taplink.cc') },
  { rule: 'host:school', test: (h) => h.includes('school') || h.includes('shkola') },
  // Только сегментная граница: hotellab.io / thehotelsnetwork.com (B2B-вендоры
  // ДЛЯ отелей) не матчатся; navigator-hotel.ru — матчится.
  { rule: 'host:hotel', test: (h) => /(?:^|[.-])(?:hotel|hostel)s?(?:[.-]|$)/.test(h) },
  // (?!e): 'magazine' (B2B trade-медиа, profashion-magazine) ≠ 'magazin' (магазин).
  { rule: 'host:magazin', test: (h) => /magazin(?!e)/.test(h) },
];

/** Хост из URL (без протокола/www/пути), lowercase. '' если не парсится. */
function hostOf(url: string): string {
  if (!url) return '';
  try {
    const u = new URL(url.startsWith('http') ? url : `https://${url}`);
    return u.hostname.replace(/^www\./, '').toLowerCase();
  } catch {
    return '';
  }
}

/**
 * Проверяет компанию по всем структурным правилам.
 * Возвращает имя сработавшего правила (для логов/отчёта очистки) или null.
 */
export function matchOutreachOsB2cRule(
  name: string,
  websiteUrl: string,
  emailDomain?: string,
): string | null {
  const lowered = (name ?? '').trim().toLowerCase();
  if (lowered) {
    if (isPersonName(lowered)) return 'name:фио';
    for (const { rule, re } of NAME_STOP_RULES) {
      if (re.test(lowered)) return rule;
    }
  }
  const hosts = [hostOf(websiteUrl ?? ''), (emailDomain ?? '').trim().toLowerCase()];
  for (const host of hosts) {
    if (!host) continue;
    for (const { rule, test } of HOST_STOP_RULES) {
      if (test(host)) return rule;
    }
  }
  return null;
}

/** true, если компанию в OutreachOS-лиды не берём (B2C/ИП/гос по структурным правилам). */
export function isOutreachOsB2cCompany(name: string, websiteUrl: string, emailDomain?: string): boolean {
  return matchOutreachOsB2cRule(name, websiteUrl, emailDomain) !== null;
}
