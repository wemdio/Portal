function toolPage(toolId: ToolId): GuidePageDoc {
  const config = TOOLS_CONFIG[toolId];
  const isTelegramFlowTool = toolId === 'tg-parser' || toolId === 'tg-outreach';
  return {
    title: config.title,
    route: config.href,
    purpose: config.description,
    controls: [
      { name: 'Карточка инструмента', description: 'На странице /tools открывает экран инструмента по нажатию "Открыть".' },
      { name: 'Основные кнопки экрана', description: 'Запуск, фильтрация, сохранение, экспорт, удаление или остановка задач.' },
      { name: 'Поля ввода и селекты', description: 'Параметры поиска, условия обработки, диапазоны, режимы и источники.' },
      { name: 'Таблицы/списки результатов', description: 'Просмотр строк, сортировка, фильтрация, действия по строке.' },
      ...(isTelegramFlowTool
        ? [{ name: 'Блоки аккаунтов и прокси', description: 'Подготовка аккаунтов, настройка лимитов и при необходимости привязка прокси перед запуском.' }]
        : []),
    ],
    subchapters: toolSubchapters[toolId],
    pipeline: toolPipeline,
    states: toolStates,
    typicalIssues: [
      ...toolIssues,
      ...(isTelegramFlowTool
        ? ['Перед запуском проверьте, что аккаунт активен и не находится в кулдауне; при сетевых сбоях используйте корректный прокси.']
        : []),
    ],
  };
}

