/**
 * Промпт стадии site_profile: текст сайта клиента → структурированный профиль.
 * Профиль — фундамент всего downstream-пайплайна (конкуренты, гипотезы,
 * цепочки), поэтому промпт запрещает додумывать факты, но требует выводов,
 * прямо следующих из текста.
 */

import type { LLMMessage } from '../llm';

const SYSTEM = `Ты — senior B2B-стратег агентства performance-аутрича Polza. По тексту сайта клиента ты восстанавливаешь его бизнес-профиль: что продаёт, кому, по какой цене, как именно покупают.

От твоего профиля зависит качество всего дальнейшего ресёрча (конкуренты, гипотезы рынков, цепочки писем), поэтому:
- опирайся ТОЛЬКО на текст сайта — не додумывай факты;
- делай разумные выводы там, где они прямо следуют из текста (например, «работаем с крупным бизнесом» + кейсы с банками → price_tier enterprise);
- если информации нет — честно возвращай "unknown"/пустую строку/пустой массив.

Отвечай строго на русском.`;

export interface SiteProfilePromptInput {
  websiteUrl: string;
  siteText: string;
}

export function buildSiteProfileMessages(input: SiteProfilePromptInput): LLMMessage[] {
  const user = `Сайт клиента: ${input.websiteUrl}

ТЕКСТ САЙТА (главная + страница «о компании», может быть обрезан парсером):
"""
${input.siteText}
"""

Собери профиль компании и верни ТОЛЬКО JSON строго такого вида (без markdown-фенсов и пояснений):
{
  "company_name": string,      // название компании/бренда как на сайте
  "product_summary": string,   // ЧТО продаёт: продукт/услуга, 2-4 предложения, конкретно — человек, не видевший сайт, должен понять оффер за 10 секунд
  "usp": string[],             // 3-7 УТП/отличий: как заявлены на сайте или прямо следуют из него
  "price_tier": "low"|"medium"|"high"|"enterprise"|"unknown",
  "deal_cycle": string,        // как покупают: самообслуживание / короткий цикл / длинные переговоры и тендеры; "" если непонятно
  "target_audience": string,   // кто заявлен клиентом: роли, типы компаний, размер бизнеса
  "current_clients": string[], // типы/названия клиентов, РЕАЛЬНО упомянутые на сайте (кейсы, логотипы, отзывы)
  "cases": string[],           // конкретные кейсы/результаты с цифрами, если есть на сайте
  "geo": string,               // география работы (страны/города, если следует из текста)
  "business_model": string     // b2b-услуги / SaaS / продакшн / агентство / e-commerce и т.п.
}

Жёсткие правила:
- current_clients и cases — только то, что буквально есть в тексте сайта.
- Не перевирай оффер: если продают несколько разных продуктов, опиши основной и упомяни остальные в product_summary.
- Никакого текста вне JSON.`;

  return [
    { role: 'system', content: SYSTEM },
    { role: 'user', content: user },
  ];
}

/* ─────────────────── Извлечение кейсов клиента ─────────────────── */

const CASES_SYSTEM = `Ты — аналитик B2B-кейсов агентства Polza. По тексту сайта клиента ты извлекаешь его доказательные кейсы в кейс-банк: они пойдут в холодные письма как доказательство, поэтому точность критична.

Жёсткие правила:
- бери ТОЛЬКО кейсы с конкретным содержанием: понятно, кто клиент (индустрия/тип), какая была задача и что получилось; маркетинговые общие фразы («мы помогли многим компаниям») — НЕ кейсы;
- ничего не додумывай: metrics заполняй только числами, которые буквально есть в тексте (нет цифр — пустой объект); имена клиентов — только реально названные;
- если на сайте нет ни одного конкретного кейса — честно верни пустой массив, это норма, а не ошибка.

Отвечай строго на русском.`;

export interface SiteCaseExtractionPromptInput {
  websiteUrl: string;
  /** Текст главной/«о компании» (тот же, что ушёл в профиль). */
  siteText: string;
  /** Дополнительные страницы (кейсы/проекты/отзывы), до 3 штук. */
  extraPages?: Array<{ url: string; text: string }>;
}

export function buildSiteCaseExtractionMessages(input: SiteCaseExtractionPromptInput): LLMMessage[] {
  const extra = (input.extraPages ?? [])
    .map((p) => `ДОПОЛНИТЕЛЬНАЯ СТРАНИЦА ${p.url}:\n"""\n${p.text}\n"""`)
    .join('\n\n');

  const user = `Сайт клиента: ${input.websiteUrl}

ТЕКСТ САЙТА (главная + страница «о компании», может быть обрезан парсером):
"""
${input.siteText}
"""
${extra ? `\n${extra}\n` : ''}
Извлеки до 8 кейсов клиента и верни ТОЛЬКО JSON строго такого вида (без markdown-фенсов и пояснений):
{
  "cases": [
    {
      "industry": string,     // индустрия/отрасль клиента из кейса (как названа на сайте)
      "client_type": string,  // тип/размер клиента (напр. «сеть кофеен, 40 точек», «enterprise-банк»)
      "task": string,         // задача клиента, 1 предложение
      "metrics": object,      // свободный json: ТОЛЬКО конкретные цифры из текста, напр. {"рост_конверсии": "+32%", "срок": "2 месяца"}; нет цифр — {}
      "result": string,       // достигнутый результат, 1 предложение, с опорой на цифры из текста, если они есть
      "text": string          // краткое содержание кейса: 2–3 предложения (кто клиент, что сделали, что получили)
    }
  ]
}

Если конкретных кейсов нет — верни {"cases": []}. Никакого текста вне JSON.`;

  return [
    { role: 'system', content: CASES_SYSTEM },
    { role: 'user', content: user },
  ];
}
