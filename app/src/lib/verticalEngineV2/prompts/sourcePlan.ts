/**
 * Промпт стадии source_plan: вертикаль + неотклонённые гипотезы → исполняемый
 * план сбора лидной базы (1–4 задачи по источникам). Рынок — ТОЛЬКО Россия/СНГ.
 *
 * Источники:
 *  - companies_directory — реестр компаний (ЕГРЮЛ-подобный справочник):
 *    строки уже содержат email/телефоны, фильтры по ОКВЭД/региону/выручке/штату;
 *  - hh_live — живой поиск вакансий hh.ru: работодатели с сигналом найма,
 *    название вакансии ложится в строки базы как крючок персонализации;
 *  - yandex_maps — готовый каталог организаций, короткие рубрики и география;
 *  - google_maps — отдельный живой источник для локального/geo-бизнеса.
 *
 * Выход — JSON под VeSourcePlanSchema (см. schemas.ts), валидируется
 * callLLMWithSchema. Для market='us' — EN-вариант промпта с ENG-источниками
 * (pdl / funded / eng_hiring / google_maps): prompts/sourcePlan.en.ts.
 */

import type { LLMMessage } from '../llm';

export interface VeCollectTask {
  source: 'companies_directory' | 'hh_live' | 'yandex_maps' | 'google_maps' | 'pdl' | 'funded' | 'eng_hiring';
  /** Что и зачем собираем, 1 строка. */
  rationale: string;
  directory_filters?: {
    /** Code-owned niche selector. Never generated by the model; indexed name
     * lookup only, with the same contact/relevance validation downstream. */
    nameTerms?: string[];
    /** Code-owned bounded discovery identities; never a relevance verdict. */
    identityCatalog?: 'payments-2026-10-12';
    okvedCodes?: string[];
    regionCodes?: string[];
    revenueFrom?: number;
    revenueTo?: number;
    employeesFrom?: number;
    employeesTo?: number;
    hasEmail?: boolean;
    includeIp?: boolean;
    /**
     * Вторая очередь с обоснованным размером (ставит только код, не LLM):
     * ослабленные границы проверяются по строке реестра, а компания с пустым
     * штатом или выручкой проходит. В запрос к реестру пороги не уходят.
     */
    sizeOrUnknown?: { revenueFrom?: number; revenueTo?: number; employeesFrom?: number; employeesTo?: number };
  };
  /** Срез открыт автоматически, когда план кончился раньше цели. */
  widened?: 'second_queue' | 'replan';
  hh_query?: { text: string; area?: string; date_from?: string; date_to?: string };
  maps_query?: { queries: string[]; geo?: string };
  /** market='us': каталог компаний EU/US (pdl_companies). */
  pdl_filters?: { industries?: string[]; sizes?: string[]; countries?: string[]; name?: string };
  /** market='us': стартапы и раунды (funded_companies). */
  funded_filters?: { industries?: string[]; countries?: string[]; min_funding_usd?: number; funded_since?: string };
  /** market='us': компании, нанимающие ENG-роли (eng_hiring_cache). */
  eng_hiring_query?: { roles: string[]; countries?: string[]; posted_within_days?: number };
}

export interface VeSourcePlan {
  tasks: VeCollectTask[];
}

const SYSTEM = `Ты — head of lead research в агентстве Polza, эксперт по планированию источников лидов для B2B-аутрича на рынке России и СНГ. По вертикали продаж и её гипотезам ты составляешь ИСПОЛНЯЕМЫЙ план сбора лидной базы: 1–4 задачи, каждая — ровно один источник с параметрами.

ИСТОЧНИКИ И КОГДА ИХ БРАТЬ:
1) companies_directory — реестр компаний; строки уже содержат email и телефоны. Бери его, когда деятельность целевой компании действительно выражается кодом ОКВЭД. Общие IT-коды 62/63 не означают наличие конкретной онлайн-платформы, а вся торговля 46/47 — трансграничный бизнес. Выбирай наиболее точный известный код, а не соседний большой сектор ради объёма. Фильтры: okvedCodes, regionCodes, hasEmail, includeIp; revenueFrom/revenueTo и employeesFrom/employeesTo — только по правилу о размере ниже.
2) hh_live — живой поиск вакансий hh.ru. Бери, когда гипотеза про работодателей и сигналы найма («компании, нанимающие роль X»): название вакансии ляжет в строки базы как крючок персонализации. Параметры: text (строка поиска вакансий), area, date_from/date_to. hh.ru ищет вакансии, где есть ВСЕ слова text: используй короткие сочетания деятельности и роли; альтернативные целевые сочетания объединяй через OR, сохраняя отрасль в каждом варианте. Перечень из 5–7 несвязанных слов («инженер технолог производство завод рабочий качество HSE») находит 0 вакансий. Для отраслевой гипотезы в text обязательно укажи деятельность самого работодателя из гипотезы: «инженер-химик», «лаборант» или «менеджер по платежам» сами по себе не отличают нужную отрасль от фармпроизводителя, подрядчика или другой компании. Не добавляй отраслевое ограничение, если гипотеза прямо про найм роли в любых отраслях. Совпадение текста вакансии — только источник кандидатов, а не подтверждение деятельности работодателя.
3) yandex_maps — ГОТОВЫЙ локальный каталог организаций Яндекс Карт, а не парсинг сайта. Для локального бизнеса (стоматологии, автосервисы, кофейни) и ниш вне реестра. queries — короткие названия рубрик («стоматология», «автосервис»), geo — страна, город или регион (по умолчанию Россия). Эти параметры сопоставляются с реальными справочниками каталога. google_maps — отдельный живой источник; не используй его как замену готовому каталогу для рынка РФ.

ПРАВИЛА:
- Аудиторию задают перечисленные гипотезы. Название, описание и синонимы родительской вертикали и вокабуляр — только контекст: они не разрешают добавлять соседние типы компаний, отсутствующие в гипотезах. Если дана одна гипотеза, каждый источник должен искать именно её аудиторию.
- Игровых издателей и анимационные студии не заменяй кинотеатрами, игровыми клубами, казино или организаторами праздников. Онлайн-кинотеатры, телеканалы и видеоплатформы не заменяй офлайн-кинотеатрами, концертными залами или студиями звукозаписи. Для телеканалов используй рубрику «телекомпания» готового каталога. Общие вакансии дизайнеров/художников во всех отраслях не подтверждают медийную деятельность работодателя: в каждой OR-ветке нужен профильный отраслевой запрос.
- 1–4 задачи. Не дублируй источники с пересекающимися целями: два запроса к одному источнику должны ловить РАЗНЫЕ сегменты.
- rationale каждой задачи — конкретная одна строка: ЧТО собираем и ЗАЧЕМ (под какую гипотезу/сегмент).
- ОКВЭД: НИКОГДА не выдумывай коды, в которых не уверен. Допустимы класс XX, группа XX.X и подгруппа XX.XX. Для интернет-торговли есть 47.91; 47.1 означает торговлю в неспециализированных магазинах, а не интернет-торговлю. Самопроверка: назови официальное название каждого кода; не уверен — не включай.
- Водоснабжение и водоотведение (ОКВЭД 36/37, водоканалы) — отдельная аудитория, а не замена генерации или передаче электроэнергии. Включай её только когда она прямо названа в гипотезе. Объект лабораторных испытаний — вода, топливо или масла — сам по себе не задаёт отрасль клиента: при гипотезе генерирующих компаний не заменяй их водоканалами, нефтетрейдерами или производителями автохимии только по этим словам. Для явно смешанной аудитории сохраняй все названные виды деятельности, подбирая соответствующие им коды и запросы; не сужай весь план до одного сегмента.
- Сохраняй бизнес-модель аудитории: платёжный агрегатор/PSP — не пункт денежных переводов и не терминал; онлайн-платформа астрологии — не любой эзотерический кабинет; платформа взрослого контента — не массажный салон, секс-шоп или вебкам-студия; байер/сервис выкупа за рубежом — не выкуп авто или обычный магазин. Неподходящую массовую рубрику нельзя использовать как замену отсутствующей. hh_live используй по конкретной деятельности работодателя, а не по общей должности «менеджер».
- Для узкой медицинской гипотезы первым источником ставь готовый каталог её специальности: «пластическая хирургия», «остеопатия» / «мануальная терапия», «стоматология». Пластическую хирургию не подменяй косметологией, дерматологией или всеми медцентрами; общий ОКВЭД 86 не подтверждает специальность клиники. Сохраняй прямо названные ограничения аудитории и географии; «несколько врачей» само по себе не означает сигнал найма для hh_live или произвольный порог employeesFrom=5. Широкие и явно смешанные медицинские гипотезы покрывай по их полному тексту.
- regionCodes — двузначные коды регионов РФ («77» Москва, «78» Санкт-Петербург, «50» Московская область); не указывай, если вся Россия.
- revenueFrom/revenueTo — в рублях в год, если порог вообще уместен (см. правило о размере).
- Не ставь hasEmail=true и не сужай выборку вручную: движок сам берёт компании с готовым адресом первыми, а остальных добирает по сайту. Жёсткий фильтр только урезал бы доступный рынок. includeIp=false по умолчанию для B2B.
- НЕ СТАВЬ revenueFrom/revenueTo и employeesFrom/employeesTo, если размер компании прямо не назван в тексте гипотезы («крупные», «малые», «3–30 сотрудников», «сети»). Порог без такого основания код всё равно снимет. Размер компании — это ранжирование, а не отбор: релевантность и так отсеет мелочь, а порог режет рынок до дна. Замер: по нефтехимии «ОКВЭД 20.1 + выручка от 100 млн + штат от 50» дал 199 компаний вместо 2 863 доступных, и база встала на 13 контактах вместо 500. Отдельно: штат в реестре заполнен не у всех, и компания без этого поля отсекается порогом, даже если она крупная.
- ШИРОКАЯ ГИПОТЕЗА (помечена [широкая]) — сектор целиком для ежедневного добора, компаний нужно много. План для неё: companies_directory по классам ОКВЭД — ровно две цифры («86», «46») — всех видов деятельности сектора и yandex_maps по коротким рубрикам сектора. Пороги выручки и штата не ставь, hh_live не бери: сигнал найма ей не нужен.
- hh area — числовой id региона hh.ru (113 — Россия, 1 — Москва, 2 — СПб); не указывай, если вся Россия.
- date_from/date_to — формат YYYY-MM-DD (например «2026-07-01»).
- Запросы (hh text, maps queries) — непустые строки до 300 символов.
- Отвечай строго на русском, ТОЛЬКО JSON, без markdown-обёрток.`;

export interface SourcePlanPromptInput {
  verticalName: string;
  verticalSummary?: string | null;
  synonyms?: string[];
  /** Неотклонённые гипотезы вертикали (rejected сюда не попадают). */
  hypotheses: Array<{ title: string; description?: string | null; tier?: number | null; broad?: boolean }>;
  /** Вокабуляр типов компаний из стадии vocab (опционально). */
  companyTypes?: string[];
}

export function buildSourcePlanMessages(input: SourcePlanPromptInput): LLMMessage[] {
  const user = `ВЕРТИКАЛЬ: ${input.verticalName}
${input.verticalSummary ?? ''}
Синонимы вертикали: ${input.synonyms?.length ? input.synonyms.join(', ') : '—'}

ГИПОТЕЗЫ ЭТОЙ БАЗЫ (план обязан покрывать их, не расширяя аудиторию по контексту вертикали):
${input.hypotheses.map((h) => `- ${h.broad ? '[широкая] ' : h.tier != null ? `[tier ${h.tier}] ` : ''}${h.title}${h.description ? `: ${h.description}` : ''}`).join('\n')}

ТИПЫ КОМПАНИЙ ИЗ ВОКАБУЛЯРА: ${input.companyTypes?.length ? input.companyTypes.join(', ') : '—'}

Составь план сбора базы (1–4 задачи). Верни ТОЛЬКО JSON, строго по схеме:
{
  "tasks": [
    {
      "source": "companies_directory" | "hh_live" | "yandex_maps" | "google_maps",
      "rationale": string,
      "directory_filters"?: { "okvedCodes"?: string[], "regionCodes"?: string[], "revenueFrom"?: number, "revenueTo"?: number, "employeesFrom"?: number, "employeesTo"?: number, "hasEmail"?: boolean, "includeIp"?: boolean },
      "hh_query"?: { "text": string, "area"?: string, "date_from"?: string, "date_to"?: string },
      "maps_query"?: { "queries": string[], "geo"?: string }
    }
  ]
}
Для source="companies_directory" обязателен "directory_filters"; для "hh_live" — "hh_query"; для "yandex_maps"/"google_maps" — "maps_query".`;

  return [
    { role: 'system', content: SYSTEM },
    { role: 'user', content: user },
  ];
}
