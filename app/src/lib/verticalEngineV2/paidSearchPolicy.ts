/**
 * Рубильник платного поиска сайтов — самой дорогой статьи сбора.
 *
 * Замер 21.09.2026 по 15 базам: поиск заканчивается подтверждённым сайтом в
 * 2.8% записей, а весь сбор стоит 5.2 кредита за готовый контакт. То есть
 * поиск — кандидат на самый неэффективный участок, но доказать это можно
 * только опытом: выключить на несколько часов и сравнить и кредиты, и
 * прирост контактов.
 *
 * Выключение безопасно и обратимо: компания не теряется и не отклоняется, она
 * получает существующий штатный статус «поиск отложен» и вернётся к проверке,
 * как только рубильник снова включат. Ровно так же ведёт себя бесплатная фаза
 * сбора, которая работает с первого дня.
 *
 * Пустая переменная или любое иное значение — поиск разрешён, как раньше.
 */
export function isVePaidWebsiteSearchEnabled(): boolean {
  return (process.env.VE_PAID_WEBSITE_SEARCH ?? '').trim().toLowerCase() !== 'off';
}
