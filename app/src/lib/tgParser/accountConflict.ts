/**
 * Один Telegram-аккаунт — одно место работы одновременно.
 *
 * Инцидент 19.08.2026. Три из четырёх аккаунтов парсера оказались теми же
 * номерами, что крутятся в работающей аутрич-кампании TG_VBI. Аутрич-воркер
 * держит эти сессии открытыми круглосуточно, поэтому запуск парсера тем же
 * аккаунтом Телеграм расценивает как угон и обрывает подключение:
 * `406: AUTH_KEY_DUPLICATED (caused by InvokeWithLayer)`. Задача падала за доли
 * секунды, а оператор видел «парсер лёг» без единого намёка на причину.
 *
 * Хуже, что это не просто неудобство: после такого конфликта Телеграм
 * аннулирует ключ, и аккаунт приходится переавторизовывать заново — так и вышло
 * с четвёртым номером, который в аутриче не занят, но чью сессию сожгло раньше.
 *
 * Ничто не мешало завести один и тот же номер в оба инструмента: система не
 * предупреждала и спокойно запускала задачу. Проверка ниже ловит это ДО
 * подключения, чтобы вместо кода Телеграма оператор получил внятную причину.
 */

/** Только цифры: номера в двух таблицах записаны в разных форматах (+7…, 7…, 8…). */
export function normalizePhone(raw: string | null | undefined): string {
  return (raw ?? '').replace(/\D/g, '');
}

export interface OutreachAccountRef {
  phone: string | null;
  campaignName: string;
}

/**
 * Имя работающей аутрич-кампании, которая занимает этот номер, или null.
 *
 * Сравниваем по цифрам номера, а не по id: в парсере и аутриче это разные
 * таблицы со своими записями, общего ключа между ними нет — единственное, что
 * достоверно связывает их с одним живым аккаунтом Телеграма, это телефон.
 */
export function findOutreachConflict(
  parserPhone: string | null | undefined,
  outreachAccounts: OutreachAccountRef[],
): string | null {
  const phone = normalizePhone(parserPhone);
  if (!phone) return null;

  for (const acc of outreachAccounts) {
    if (normalizePhone(acc.phone) === phone) return acc.campaignName;
  }
  return null;
}

/** Текст для оператора: что случилось и что с этим делать. */
export function outreachConflictMessage(phone: string, campaignName: string): string {
  return (
    `Аккаунт ${phone} сейчас занят аутрич-кампанией «${campaignName}». ` +
    `Телеграм не разрешает одну сессию в двух местах: запуск парсера оборвал бы её ` +
    `и мог разлогинить аккаунт совсем. Остановите кампанию либо заведите для парсера отдельный номер.`
  );
}
