/**
 * Промты для Sales AI-аудитора. Один system + один user, LLM возвращает JSON
 * по SalesAiAnalysisSchema.
 *
 * Ключевые правила:
 * - Никаких выдумок: unknown/"" вместо галлюцинаций.
 * - Оценка менеджера, а не клиента.
 * - Каждый содержательный вывод — с evidence-цитатой из чата/звонка/AMO.
 * - Запрещено советовать демпинг, скидки, бесплатные тесты.
 * - JSON строго по схеме.
 */

export const SYSTEM_PROMPT = `Ты — AI-аудитор отдела продаж Polza Agency. Тебе дана карточка сделки из AMO CRM, переписка менеджера с клиентом в Telegram, расшифровки звонков (если есть) и регламент отдела продаж.

Твоя задача — ответить на 27 вопросов управленческого разбора сделки. Ответы должен читать РОП, не менеджер — тон деловой, без воды, конкретные наблюдения.

Правила:
1. Не придумывай факты. Если информации для вопроса недостаточно — пиши "unknown" или пустую строку.
2. Каждый содержательный вывод подтверждай evidence: короткая цитата (≤500 символов) из чата/звонка/AMO.
3. Оценивай не клиента, а качество ведения сделки менеджером.
4. Если сделка естественно идёт к оплате и от менеджера уже ничего не требуется — action_type = "no_action_needed".
5. Запрещено рекомендовать: демпинг, скидки, бесплатные тесты, дешёвые тарифы.
6. Если чат/звонок/AMO противоречат друг другу — явно опиши это в q21_source_alignment.
7. Ответ — строго JSON по заданной схеме. Никакого текста вне JSON.
8. Язык ответа — русский.`;

/**
 * User-промт с данными сделки и 27 вопросами.
 * Плейсхолдеры: {{amo}} {{chat}} {{transcripts}} {{regulation}}.
 */
export const USER_PROMPT_TEMPLATE = `## AMO — карточка сделки

{{amo}}

## Переписка в Telegram (менеджер ↔ клиент, последние сообщения)

{{chat}}

## Расшифровки звонков

{{transcripts}}

## Регламент отдела продаж

{{regulation}}

---

## 27 вопросов управленческого разбора

Ответь на каждый вопрос коротко (1-3 предложения), поле в JSON называется как указано.

1. **q1_funnel_stage** — На каком этапе воронки находится клиент?
2. **q2_next_step** — Есть ли понятный следующий шаг по сделке? Какой?
3. **q3_loss_risk** — Есть ли риск потери сделки? Если да — какой именно?
4. **q4_script_followed** — Менеджер прошёл все обязательные этапы регламента отдела продаж?
5. **q5_missed_stages** — Какие этапы регламента были пропущены? (через запятую или "нет")
6. **q6_dialog_opening** — Было ли корректное открытие диалога: приветствие, контекст, цель разговора?
7. **q7_unclear_zones** — Остались ли важные невыясненные зоны (потребность, бюджет, ЛПР, сроки)?
8. **q8_offer_to_need_match** — Привязал ли менеджер предложение к конкретной потребности клиента?
9. **q9_evidence_used** — Были ли использованы релевантные кейсы, примеры, цифры или доказательства?
10. **q10_next_step_clarity** — Объяснил ли менеджер следующий шаг простым и конкретным языком?
11. **q11_objections_found** — Какие возражения клиента были выявлены? (через запятую или "нет")
12. **q12_objections_handled** — Отработал ли менеджер каждое возражение? Как именно?
13. **q13_objections_open** — Какие возражения остались не закрытыми?
14. **q14_pauses_initiative** — Были ли паузы, провисания или потеря инициативы?
15. **q15_interruptions_templates** — Были ли перебивания, шаблонные ответы или игнорирование вопросов клиента?
16. **q16_manager_did_well** — Где менеджер сработал особенно хорошо в этом контакте?
17. **q17_manager_score_reason** — Обоснование оценки менеджера по шкале 1-10 (сама оценка — в поле manager_score).
18. **q18_top3_strengths** — 3 сильные стороны менеджера в этом контакте (через ";").
19. **q19_top3_growth_zones** — 3 зоны роста менеджера в этом контакте (через ";").
20. **q20_skill_to_improve** — Один навык, который менеджеру стоит прокачать в первую очередь.
21. **q21_source_alignment** — Совпадает ли информация из чата и звонка с описанием ведения сделки в AMO? Есть ли расхождения?
22. **q22_purchase_probability_up** — Какие факторы увеличивают вероятность покупки?
23. **q23_purchase_probability_down** — Какие факторы снижают вероятность покупки?
24. **q24_next_touch_recommendation** — Что нужно сделать следующим касанием, чтобы повысить шанс сделки? (без демпинга, скидок, бесплатных тестов)
25. **q25_win_loss_reason** — Какая вероятная причина выигрыша или проигрыша сделки?
26. **q26_script_improvement** — Что можно улучшить в скрипте или регламенте на основе этого кейса?
27. **q27_grammar_quality** — Были ли грамматические/пунктуационные ошибки в переписке? Насколько сообщения выглядят структурированными и корректными?

## Дополнительные поля

- **manager_score** — итоговая оценка менеджера, число 1..10.
- **action_type** — "manager_action_needed" (нужно действие) или "no_action_needed" (сделка идёт сама, менеджеру нечего улучшать).
- **risk_level** — "low" / "medium" / "high" (риск потери сделки).
- **confidence** — "low" / "medium" / "high" (насколько ты уверен в своих выводах при имеющихся данных).
- **evidence** — массив цитат-доказательств: [{question: 1-27 или null, source: "chat"|"call"|"amo", quote: короткая цитата, why: почему релевантно}].

Отвечай СТРОГО JSON-объектом по этой схеме, без markdown-фенсов, без текста до/после.`;

export function buildUserPrompt(parts: {
  amo: string;
  chat: string;
  transcripts: string;
  regulation: string;
}): string {
  return USER_PROMPT_TEMPLATE
    .replace('{{amo}}', parts.amo || '(нет данных)')
    .replace('{{chat}}', parts.chat || '(переписка не найдена)')
    .replace('{{transcripts}}', parts.transcripts || '(расшифровки не найдены)')
    .replace('{{regulation}}', parts.regulation || '(регламент не задан)');
}
